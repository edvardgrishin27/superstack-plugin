def gate_suite() -> dict:
    """Красное без имени — не диагноз.

    Строка «упало 1 из 1939» за одну ночь встретилась дважды, и оба раза набор
    приходилось гонять заново только затем, чтобы узнать, ЧТО упало. Имена
    берутся из вывода того же прогона — второй раз спрашивать не о чем.
    """
    code, passed, failed, tail, names = _suite()
    if code == 0 and passed:
        return {"status": "pass", "detail": f"{passed} тестов зелёные"}
    if code in НЕ_СОСТОЯЛСЯ:
        return {"status": "unknown", "detail": tail.strip()[:300]}
    detail = f"упало {failed} из {passed + failed}"
    показаны = names[:_NAMES_SHOWN]
    if показаны:
        # Пусто бывает честно: набор упал не на тесте (ошибка сбора, обрыв),
        # и выдумывать имя тут нечем — тогда остаётся число и хвост вывода.
        detail += ": " + ", ".join(показаны)
        if len(names) > len(показаны):
            detail += f" и ещё {len(names) - len(показаны)}"
    return {"status": "fail", "detail": detail, "output": tail,
            "failed_tests": names}


def _занято_чужим(что: str) -> "dict | None":
    """Вердикт ворот, когда дерево держит чужой ЖИВОЙ прогон, — либо None.

    Ворота герметичности краснели строкой «при разном HOME собрано разное:
    2435+0 против 2434+1». Читается это как ответ на их собственный вопрос —
    и было неправдой: рядом шёл ВТОРОЙ прогон планки по тому же дереву, тот
    же тест падал у того, кому не достался замок мутаций, и разница в один
    тест приезжала в вердикт как зависимость от домашнего каталога.

    Доказано журналом попыток взять замок: 13:35:27 замок взял прогон набора
    соседней планки, через 1,7 секунды другому отказано, отпущен через
    59 секунд. Один прогон на свободном дереве зелёный; два — красные оба.

    Цена ошибки не в ложном красном, а в подменённом смысле: ворота, которые
    краснеют от шума, перестают читать — вместе с настоящей зависимостью от
    HOME, ради которой они и написаны. Поэтому здесь «не смог измерить» с
    названным виновником, а не вердикт о HOME.
    """
    чужой = _чужой_замок()
    if not чужой:
        return None
    return {"status": "unknown",
            "detail": (f"рядом меряет чужой прогон: процесс {чужой['pid']} "
                       f"({чужой['кто']}) держит дерево — {что}"),
            "lock": _пометка_замка(чужой),
            "next": "дождаться чужого прогона и померить заново — числа, "
                    "собранные рядом с ним, не говорят о HOME"}


def gate_hermetic() -> dict:
    """Одно и то же число тестов при разном HOME.

    Набор читал настоящий ~/.claude и за одну сессию уехал с 260 на 282 теста
    БЕЗ единой правки кода. Такое «зелено» — свойство машины, а не кода, и
    отчитываться им нельзя.

    Дерево на время обоих прогонов объявляется занятым: пока ворота мерили
    молча, две планки спокойно уходили в один набор и портили измерения друг
    другу — ровно та болезнь, ради которой замок заведён этажом ниже.
    """
    занято = _занято_чужим("два харнесса на одном дереве меряют друг друга, "
                           "а не код")
    if занято:
        return занято
    беда_замка = acquire_lock()
    if беда_замка:
        return {"status": "unknown", "detail": беда_замка}
    рядом = None
    try:
        with tempfile.TemporaryDirectory() as a, tempfile.TemporaryDirectory() as b:
            ca, pa, fa, _, _ = _suite({"HOME": a})
            # Замок сняли под нами (руками или чужим `release`) — числа
            # второго прогона уже нельзя относить на HOME.
            рядом = _занято_чужим("числа собирались, пока дерево держал не "
                                  "этот прогон")
            cb, pb, fb, _, _ = _suite({"HOME": b})
            рядом = рядом or _занято_чужим("числа собирались, пока дерево "
                                           "держал не этот прогон")
    finally:
        release_lock()
    if 124 in (ca, cb):
        return {"status": "unknown", "detail": "прогон не завершился"}
    расхождение = pa != pb or fa != fb
    if (расхождение or fa) and рядом:
        return рядом
    if расхождение:
        return {"status": "fail",
                "detail": f"при разном HOME собрано разное: {pa}+{fa} против {pb}+{fb}"}
    if fa:
        return {"status": "fail", "detail": f"герметично, но красное: {fa} падений"}
    return {"status": "pass", "detail": f"{pa} тестов при любом HOME"}


def gate_mutations() -> dict:
    """Зарегистрированная поломка обязана ронять набор.

    Единственные ворота, которые доказывают, что тесты держат смысл, а не
    форму. Выжившая мутация означает: механизм можно удалить, и никто не
    заметит. Прошлая проверка дала 7 выживших из 10.
    """
    src = PLUG / "tests" / "mutations.json"
    if not src.is_file():
        return {"status": "unknown", "detail": f"нет набора мутаций: {src}"}
    try:
        muts = json.loads(src.read_text("utf-8"))["mutations"]
    except (ValueError, KeyError) as e:
        return {"status": "unknown", "detail": f"набор мутаций не разобран: {e}"}

    total = len(muts)
    доля = None
    if SHARD is not None:
        доля = SHARD
        muts = shard_of(muts, *SHARD)
    picked = None
    if ONLY_MUTATIONS:
        known = {m["id"] for m in muts}
        unknown = sorted(ONLY_MUTATIONS - known)
        if unknown:
            # Опечатка в имени иначе даёт «все пойманы», не проверив ничего —
            # то есть самый убедительный из возможных зелёных отчётов.
            return {"status": "unknown",
                    "detail": "нет таких мутаций: " + ", ".join(unknown)}
        picked = [m for m in muts if m["id"] in ONLY_MUTATIONS]
        muts = picked

    чужой = _чужой_замок()
    if чужой:
        # Отказ по занятому дереву помечен ПОЛЕМ: вызывающий отличает «мерить
        # нечем, дерево держит другой» от «механизм сломан», не разбирая прозу.
        return {"status": "unknown", "detail": чужой["беда"],
                "lock": _пометка_замка(чужой)}
    held = acquire_lock()
    if held:
        return {"status": "unknown", "detail": held}
    копия = None
    try:
        # Одноразовая копия целиком: 25 МБ и секунда времени против того, что
        # обрыв прогона больше не оставляет сломанный файл в рабочем дереве и
        # не мешает ни редактировать, ни выкладывать, пока идёт измерение.
        копия = Path(tempfile.mkdtemp(prefix="superstack-мутации-"))/ "дерево"
        shutil.copytree(PLUG, копия, ignore=shutil.ignore_patterns(
            "__pycache__", "*.pyc", ".pytest_cache", ".mutation-backup",
            ".mutation-lock"))
        v = _mutate_all(muts, копия, реестр=total)
    except OSError as e:
        v = {"status": "unknown", "detail": f"копию сделать не удалось: {e}"}
    finally:
        release_lock()
        if копия is not None:
            shutil.rmtree(копия.parent, ignore_errors=True)

    # Число ВСЕГО набора, а не своё: без него сумму выполненных по долям не с
    # чем сравнивать, и пятнадцать долей из шестнадцати складываются в зелёный
    # итог, не назвав недостачу.
    v["registry_total"] = total
    пометка = None
    if доля is not None:
        v["shard"] = {"index": доля[0], "of": доля[1]}
        пометка = (f"ДОЛЯ {доля[0]} из {доля[1]}: {len(muts)} поломок из "
                   f"{total}, остальные — в других долях")
    elif picked is not None:
        пометка = f"ВЫБОРКА {len(picked)} из {total}, остальные не проверялись"
    if пометка:
        # Подмножество не имеет права выглядеть взятой планкой: «проверено 3»
        # и «проверены все» — разные утверждения, и второе тут не доказано.
        v["subset"] = True
        v["detail"] = f"{v['detail']} — {пометка}"
        if v["status"] == "pass":
            # Пометки в detail не хватало: код возврата её не читает. Полный
            # прогон с `--mutation X` возвращал ноль, проверив одну поломку из
            # пятисот, и это неотличимо от взятой планки. «partial» — не провал
            # и не пропуск: проверенное проверено, но планка на нём не берётся.
            # Выборка, которая УПАЛА, остаётся провалом: там доказано большее.
            v["status"] = "partial"
    # Итог доли ложится поверх промежуточного: сведение отличает законченную
    # долю от снятой по признаку `status`, а не по тому, что файл существует.
    _write_progress({"gate": "мутации", **v})
    return v


def merge_shards(файлы: list) -> dict:
    """Свести доли в ОДИН вердикт. Зелено только когда сходятся числа.

    Ради этой функции всё разбиение и затевалось. Доля доказывает свою долю
    набора и ничего сверх неё; «пятнадцать заданий из шестнадцати зелёные» —
    не «набор проверен», и разница обязана быть красной, а не незаметной.

    Три способа получить ложное зелёное, каждый закрыт отдельно: доля пропала
    (артефакт не доехал), доля оборвалась на середине (задание сняли), доля
    отчиталась, не проверив своё (протух якорь, не состоялся прогон). Первые
    два видны по номерам и статусу, третий — только по сумме выполненных.
    """
    доли, битые = [], []
    for f in sorted(файлы, key=str):
        try:
            доли.append(json.loads(Path(f).read_text("utf-8")))
        except (OSError, ValueError) as e:
            битые.append(f"{Path(f).name}: {e}")
    if битые:
        return {"status": "unknown",
                "detail": "доля не прочитана: " + "; ".join(битые[:_NAMES_SHOWN]),
                "next": "перезапустить эти доли — сводить нечего"}
    if not доли:
        return {"status": "unknown", "detail": "долей не найдено — сводить нечего",
                "next": "проверить, что задания долей выгрузили артефакты"}

    реестры = {d.get("registry_total") for d in доли}
    if None in реестры or len(реестры) != 1:
        # Доли с разных коммитов складывать нельзя: сумма сойдётся, а проверен
        # будет не тот набор.
        return {"status": "fail",
                "detail": "доли мерили разные наборы поломок: "
                          + ", ".join(sorted(str(r) for r in реестры))}
    реестр = реестры.pop()

    номера = [(d.get("shard") or {}).get("index") for d in доли]
    сколько = {(d.get("shard") or {}).get("of") for d in доли}
    if None in номера or None in сколько or len(сколько) != 1:
        return {"status": "fail",
                "detail": "доля не назвала свой номер — сведение не с чем сверить"}
    из = сколько.pop()
    if not isinstance(из, int) or not 1 <= из <= 1024:
        # Битое число долей иначе уводит перебор в вечность на строке ниже:
        # сведение обязано отказать, а не зависнуть молча.
        return {"status": "fail",
                "detail": f"доля объявила невозможное разбиение: из {из}"}
    пропали = [i for i in range(1, из + 1) if i not in номера]
    дубли = sorted({i for i in номера if номера.count(i) > 1})

    оборванные = [{"shard": d["shard"]["index"], "current": d.get("current"),
                   "executed": d.get("executed") or 0}
                  for d in доли if d.get("status") == "running"]
    выжили = [s for d in доли for s in (d.get("survived") or [])]
    несостоявшиеся = [s for d in доли for s in (d.get("inconclusive") or [])]
    выполнено = sum(int(d.get("executed") or 0) for d in доли)
    поймано = выполнено - len(выжили)
    числа = (f"долей {len(доли)} из {из}, зарегистрировано {реестр}, "
             f"выполнено {выполнено}, поймано {поймано}, "
             f"неизвестно {len(несостоявшиеся)}")
    итог = {"shards": из, "reported": len(доли), "registry_total": реестр,
            "executed": выполнено, "caught": поймано, "survived": выжили,
            "inconclusive": несостоявшиеся, "torn": оборванные,
            "missing_shards": пропали}

    if пропали:
        return {"status": "fail",
                "detail": f"долей не хватает: нет {', '.join(map(str, пропали))} "
                          f"из {из} — остальные прошли, но набор не проверен; "
                          + числа, **итог}
    if дубли:
        return {"status": "fail",
                "detail": f"доля посчитана дважды: {', '.join(map(str, дубли))}",
                **итог}
    if выжили:
        return {"status": "fail",
                "detail": f"выжило {len(выжили)}: "
                          + ", ".join(s["id"] for s in выжили[:_NAMES_SHOWN])
                          + f"; {числа}", **итог}
    if оборванные:
        имена = ", ".join(
            f"{o['shard']} (встала на {o['current'] or 'базовом прогоне'})"
            for o in оборванные[:_NAMES_SHOWN])
        return {"status": "fail",
                "detail": f"доля оборвана: {имена}; {числа}", **итог}
    if несостоявшиеся:
        # Не «поймана» и не «выжила»: прогон не состоялся, и сказать по нему
        # нечего. Причина называется раньше общих чисел — по числам «прогон не
        # состоялся» неотличим от «поломка поймана».
        return {"status": "unknown",
                "detail": числа + " — прогон не состоялся у "
                          + ", ".join(x["id"] for x in несостоявшиеся[:_NAMES_SHOWN]),
                **итог}
    красные = [d for d in доли if d.get("status") in ("fail", "unknown")]
    if красные:
        return {"status": красные[0]["status"],
                "detail": f"доля {красные[0]['shard']['index']}: "
                          + str(красные[0].get("detail", ""))[:200], **итог}
    if выполнено != реестр:
        return {"status": "fail",
                "detail": f"проверено не всё: {числа}", **итог}
    return {"status": "pass", "detail": числа, **итог}


def gate_policy(v: dict, путь: Path = None) -> dict:
    """Перевести отчёт планки в вердикт сборки по списку обязательных ворот.

    Две вещи, которых тут быть не должно. Первая — обязательные ворота, чьё
    «не смог проверить» стало предупреждением: четыре ночных прогона честно
    писали, что схему официальным инструментом хоста проверить не удалось и
    карту с планом сверить не удалось, — и заканчивались зелёными, потому что
    падали только на `fail`.

    Вторая опаснее: НОВЫЕ ворота, молча попавшие в мягкую корзину. Список, в
    который можно не дописывать, устаревает тише, чем портится, — поэтому
    ворота, не названные ни обязательными, ни справочными, роняют политику
    сами по себе.
    """
    src = Path(путь) if путь else PLUG / ПОЛИТИКА
    try:
        свод = json.loads(Path(src).read_text("utf-8"))
        обязательные = {g["gate"] for g in свод["required"]}
        справочные = {g["gate"] for g in свод["advisory"]}
    except (OSError, ValueError, KeyError, TypeError) as e:
        return {"status": "unknown", "errors": [], "warnings": [],
                "detail": f"список обязательных ворот не прочитан: {e}"}

    названы = обязательные | справочные
    не_названы = sorted({g["gate"] for g in v.get("gates") or []} - названы)
    if не_названы:
        return {"status": "fail",
                "detail": "ворота не названы ни обязательными, ни справочными: "
                          + ", ".join(не_названы),
                "errors": [f"нет в {ПОЛИТИКА}: {g} — решить, провал это или "
                           "оговорка, и записать вместе с причиной"
                           for g in не_названы],
                "warnings": []}

    ошибки, оговорки = [], []
    for g in v.get("gates") or []:
        if g["status"] == "fail":
            ошибки.append(f'{g["gate"]}: {g["detail"]}')
        elif g["status"] == "unknown":
            (ошибки if g["gate"] in обязательные else оговорки).append(
                f'{g["gate"]}: не смог проверить — {g["detail"]}')
        elif g["status"] in ("skipped", "partial"):
            оговорки.append(f'{g["gate"]}: {g["detail"]}')
    if ошибки:
        return {"status": "fail", "errors": ошибки, "warnings": оговорки,
                "detail": f"провалов и непроверенного обязательного: "
                          f"{len(ошибки)}"}
    return {"status": "pass", "errors": [], "warnings": оговорки,
            "detail": f"обязательные ворота пройдены, оговорок {len(оговорки)}"}


