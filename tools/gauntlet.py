def parse_shard(текст: str) -> tuple:
    """Разобрать «i/n». Мусор — отказ, а не молчаливая единственная доля.

    Опечатка вида `--shard 1-16` иначе даёт «1 из 1», то есть полный прогон
    под именем доли: задание уходит в тот же таймаут, что и до разбиения, и
    отчитывается как одна из шестнадцати.
    """
    m = re.fullmatch(r"\s*(\d+)\s*/\s*(\d+)\s*", текст)
    if not m:
        raise ValueError(f"доля пишется как i/n, а не «{текст}»")
    i, n = int(m.group(1)), int(m.group(2))
    if n < 1 or not 1 <= i <= n:
        raise ValueError(f"доли {i} из {n} не бывает")
    return i, n


def shard_of(muts: list, index: int, of: int) -> list:
    """Доля index из of — круговой раздачей по отсортированным id.

    Три свойства, ради которых это код, а не деление на глаз: доли не
    пересекаются, вместе дают ВЕСЬ набор и получаются примерно равными.
    Четвёртое — сортировка: без неё перестановка строк в `mutations.json`
    тихо перекраивает разбиение, и «доля 3» вчера и сегодня перестают быть
    одним и тем же множеством.
    """
    порядок = sorted(muts, key=lambda m: m["id"])
    return [m for k, m in enumerate(порядок) if k % of == index - 1]


def _write_progress(состояние: dict) -> None:
    """Записать промежуточное — ПОДМЕНОЙ ФАЙЛА ЦЕЛИКОМ.

    Запись поверх оставила бы обрезанный JSON ровно в тот момент, ради
    которого отчёт и пишется: задание снимают посреди работы, и читать его
    остаток будет сведение, а не человек.
    """
    if PROGRESS is None:
        return
    try:
        PROGRESS.parent.mkdir(parents=True, exist_ok=True)
        tmp = PROGRESS.with_name(PROGRESS.name + ".tmp")
        tmp.write_text(json.dumps(состояние, ensure_ascii=False, indent=1),
                       encoding="utf-8")
        tmp.replace(PROGRESS)
    except OSError as e:
        print(f"    промежуточный отчёт не записан: {e}",
              file=sys.stderr, flush=True)


_TRIPLE = re.compile(r'"""[\s\S]*?"""' + r"|'''[\s\S]*?'''")


def executable_text(path: Path) -> str:
    """Текст файла БЕЗ комментариев и докстрингов.

    Ворота «план» искали улику простым вхождением подстроки в файл. Внешняя
    проверка выпотрошила четыре механизма, оставив их названия в докстрингах, —
    и ворота отчитались «на месте» по всем четырём. Улика, живущая в прозе,
    доказывает, что кто-то написал про механизм, а не что механизм есть.

    Для .py и .sh проза вырезается. Для .md и .json — нет: там текст И ЕСТЬ
    артефакт, вырезать нечего, и это ограничение названо, а не замаскировано.

    Направление ошибки выбрано намеренно: вырезав лишнее, ворота объявят
    механизм отсутствующим и заставят перепривязать улику. Обратная ошибка —
    засчитать пустышку — тише и дороже.
    """
    text = path.read_text("utf-8", errors="replace")
    suffix = path.suffix.lower()
    if suffix == ".py":
        try:
            text = _blank_prose(text)
        except Exception:                            # noqa: BLE001
            # Файл не разбирается — вырезаем хотя бы очевидное. Молчаливый
            # возврат сырого текста вернул бы ровно ту дыру, что чиним.
            text = _TRIPLE.sub(" ", re.sub(r"(?m)^\s*#.*$", "", text))
    elif suffix == ".sh":
        text = re.sub(r"(?m)^\s*#.*$", "", text)
    return text


def _blank_prose(text: str) -> str:
    """Затереть комментарии и докстринги ПРОБЕЛАМИ, не трогая остальное.

    Именно затереть, а не выбросить: перестроение файла из токенов рвёт
    соседство слов — `def probe_runtime` превращается в `def\\nprobe_runtime`,
    и улика перестаёт находиться в коде, который на месте. Пробелы сохраняют
    все смещения, поэтому вхождение подстроки остаётся тем же вопросом.

    Тройная кавычка в этом проекте — всегда докстринг или длинный комментарий.
    Обычные строковые литералы не трогаем: `"proven-local"` — настоящий код
    и законная улика.
    """
    import io
    import tokenize

    lines = text.splitlines(keepends=True)
    starts = [0]
    for ln in lines:
        starts.append(starts[-1] + len(ln))

    def offset(row: int, col: int) -> int:
        return starts[row - 1] + col

    spans = []
    for tok in tokenize.generate_tokens(io.StringIO(text).readline):
        prose = tok.type == tokenize.COMMENT or (
            tok.type == tokenize.STRING and tok.string.lstrip("rbuRBUf")[:3]
            in ('"""', "'''"))
        if prose:
            spans.append((offset(*tok.start), offset(*tok.end)))

    out = list(text)
    for a, b in spans:
        for i in range(a, min(b, len(out))):
            if out[i] != "\n":                       # переводы строк сохраняем
                out[i] = " "
    return "".join(out)


def _looks_applied(text: str, find: str, replace: str) -> bool:
    """Применена ли эта мутация к тексту прямо сейчас.

    Наивное правило «замена есть, оригинала нет» ложно молчит, когда искомое
    является ПОДСТРОКОЙ заменяющего. Живой случай: `tools: Read, Grep, Glob`
    против `tools: Read, Grep, Glob, Task`. В мутированном файле оригинал
    формально присутствует — внутри замены, — и сторож рапортовал «застрявших 0»
    на файле с оставшейся поломкой. Именно так `Task` пережил убитый прогон,
    и красным это стало не у сторожа, а у набора тестов.

    Разбираем три случая отдельно, потому что они и различаются по-разному:
      · искомое внутри заменяющего (добавление) — судим только по заменяющему;
      · заменяющее внутри искомого (удаление) — наличие искомого значит оригинал;
      · непересекающиеся — прежнее правило верно.

    Ошибка склоняется в сторону «застряла»: лишний отказ мерить стоит одного
    прогона, пропущенная поломка отравляет все последующие.
    """
    if find in replace:
        return replace in text
    if replace in find:
        return find not in text and replace in text
    return replace in text and find not in text


def purge_bytecode() -> int:
    """Снести кэш байткода. Не гигиена, а условие правильности измерения.

    Python признаёт кэш устаревшим по паре (mtime, размер). Мутация и её
    восстановление часто совпадают в РАЗМЕРЕ («GATE» -> «AUTO», `_key=_key` ->
    `_key=None`) и укладываются в ОДНУ секунду — тогда пара совпадает, и
    интерпретатор берёт старый .pyc. Ворота при этом честно докладывают исход
    прогона, который шёл по другому коду: мутация объявляется выжившей, ни разу
    не исполнившись, — либо, что хуже, пойманной.

    Воспроизводится за три строки, поэтому лечится не рассуждением, а чисткой.
    """
    killed = 0
    for d in PLUG.rglob("__pycache__"):
        try:
            shutil.rmtree(d)
            killed += 1
        except OSError:
            pass
    return killed


def _lock() -> Path:
    return PLUG / ".mutation-lock"


def _alive(pid: int) -> bool:
    """Жив ли процесс. Сомнение решается в сторону «жив».

    Ошибиться в эту сторону стоит одного отказа мерить; в обратную — двух
    харнессов, мутирующих одно дерево, и это уже было трижды.
    """
    if os.name == "nt":
        # На Windows сигнала 0 нет: `os.kill` там убивает процесс по-настоящему.
        # Спросить «жив ли он» нечем, и выбор направления ошибки здесь не
        # технический, а по цене: счесть чужой замок мёртвым значит сломать
        # дерево тому, кто как раз меряет. Поэтому «не знаю» = «жив».
        return True
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except (PermissionError, OSError):
        return True
    return True


def _чей_прогон() -> str:
    """Чей это прогон — одной строкой, которая ляжет в файл замка.

    Номер держателя — не улика. Ворота герметичности краснели строкой «набор
    зависит от HOME», а настоящей причиной был отказ по замку: «дерево уже
    мутирует процесс 27713». Установить, ЧЕЙ это процесс, не удалось вовсе:
    к моменту чтения отчёта его в `ps` уже нет, а в файле замка, кроме числа,
    не лежало ничего. Улика, за которой некого спросить, — не улика.

    Строка одна и без переносов: первая строка файла замка разбирается как
    «номер, дальше описание», и второй строкой описание потерялось бы у всех,
    кто читает `.split()[0]`.
    """
    тест = os.environ.get("PYTEST_CURRENT_TEST")
    if тест:
        return "набор: " + тест.split(" ")[0][-110:]
    if os.environ.get("SUPERSTACK_MUTATION_RUN") == "1":
        return "прогон мутаций"
    хвост = " ".join(sys.argv[1:])[:110]
    return "планка: " + (хвост or "без флагов")


def _чужой_замок() -> "dict | None":
    """Чужой ЖИВОЙ держатель дерева: номер, чей прогон и готовая беда.

    Разбор замка живёт в ОДНОМ месте: об одном и том же файле спрашивают
    трое — сам замок, ворота мутаций и ворота герметичности. Разошедшиеся
    копии разбора ответили бы по-разному на один и тот же файл, и разошлись
    бы молча.
    """
    p = _lock()
    try:
        первая = p.read_text("utf-8").splitlines()[0]
    except (OSError, ValueError, IndexError):
        # ValueError ловит и битую кодировку: нечитаемый замок — это «некому
        # мешать», а не вечная блокировка. Ошибаться тут можно только в эту
        # сторону, обратная — отказ мерить навсегда.
        return None
    поля = первая.split(None, 1)
    try:
        pid = int(поля[0])
    except (ValueError, IndexError):
        return None
    if pid <= 0 or pid == os.getpid() or not _alive(pid):
        return None
    # Замок от прежней версии несёт только номер. Это «прогон не назвался»,
    # а не повод выдумать за него имя.
    кто = поля[1].strip() if len(поля) > 1 else "прогон не назвался"
    return {"pid": pid, "кто": кто,
            "беда": (f"дерево уже мутирует процесс {pid} ({кто}) — второй "
                     "харнесс увидит чужую поломку и отнесёт её на свой счёт; "
                     f"дождись первого или сними {p}")}


def _пометка_замка(чужой: dict) -> dict:
    """Признак «дерево держит чужой прогон» ПОЛЕМ, а не формулировкой.

    «Не смог измерить, потому что дерево занято» и «механизм сломан» —
    разные утверждения, а в отчёте оба выглядели одинаково: unknown и текст.
    Вызывающему (в том числе тесту) приходилось разбирать прозу, то есть
    договариваться о словах вместо поля; слова же меняются при первой правке.
    """
    return {"pid": чужой["pid"], "кто": чужой["кто"]}


def acquire_lock() -> "str | None":
    """Занять исключительное право мутировать дерево. Беда либо None.

    Зачем замок. Два процесса, мутирующих одно дерево, портят измерения друг
    друга молча: каждый видит чужую поломку и относит её на счёт своей. За одну
    сессию это случилось трижды, и в третий раз — когда я сам запустил починку
    поверх идущей проверки. Механизм без замка не защищает даже от автора.

    Мёртвый замок снимается сам: процесс, убитый по SIGKILL, файл за собой не
    уберёт, и вечная блокировка от прошлого прогона — это отказ мерить навсегда.
    """
    p = _lock()
    чужой = _чужой_замок()
    if чужой:
        return чужой["беда"]
    try:
        p.write_text(f"{os.getpid()} {_чей_прогон()}\n", encoding="utf-8")
    except OSError as e:
        return f"замок не поставлен ({e}) — мутировать вслепую нельзя"
    return None


def release_lock() -> None:
    try:
        _lock().unlink()
    except OSError:
        pass


def _sh(cmd: list, timeout: int, env: dict = None, cwd: Path = None) -> tuple:
    try:
        p = subprocess.run(cmd, cwd=str(cwd or PLUG), capture_output=True,
                           text=True, timeout=timeout,
                           # Не писать .pyc вовсе: то, чего нет, не может
                           # устареть и подменить измеряемый код.
                           env={**os.environ, "SUPERSTACK_IGNORE_PAUSE": "1",
                                "NO_COLOR": "1", "PYTHONDONTWRITEBYTECODE": "1",
                                **(env or {})})
        return p.returncode, (p.stdout or "") + (p.stderr or "")
    except subprocess.TimeoutExpired:
        return 124, f"не завершилось за {timeout} с"
    except OSError as e:
        return 127, str(e)


_COUNT = re.compile(r"(\d+) passed")
_FAILED = re.compile(r"(\d+) failed")
_FAILED_LINE = re.compile(r"^FAILED (\S+)", re.MULTILINE)

#: Сколько имён упавших тестов попадает в строку ворот. Пять — потолок ради
#: читаемости строки; остальные не исчезают, а называются числом.
_NAMES_SHOWN = 5


def _failed_names(out: str) -> list:
    """Имена упавших тестов из строк «FAILED tests/...::...» вывода pytest.

    Считается по ПОЛНОМУ выводу, а не по хвосту, который уходит в `output`:
    сводка pytest печатается последней, но пять длинных имён в срез уже не
    влезают, и имя пропало бы ровно тогда, когда упало не одно.
    """
    names = []
    for m in _FAILED_LINE.finditer(out):
        if m.group(1) not in names:
            names.append(m.group(1))
    return names


def _suite(env: dict = None) -> tuple:
    """(код, сколько прошло, сколько упало, хвост вывода, имена упавших)."""
    code, out = _sh([sys.executable, "-m", "pytest", "tests/", "-q"],
                    SUITE_TIMEOUT, env)
    passed = int(_COUNT.search(out).group(1)) if _COUNT.search(out) else 0
    failed = int(_FAILED.search(out).group(1)) if _FAILED.search(out) else 0
    return code, passed, failed, out[-1500:], _failed_names(out)


