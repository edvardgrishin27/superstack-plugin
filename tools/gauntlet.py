#: Хуки перечислены по `*.py`, и это не косметика. Хуки переехали на Python,
#: `hooks.json` зовёт только `.py`, а оставшиеся рядом `.sh` — обёртки в одну
#: строку, которые продукт не запускает ниоткуда. Считая входом обёртку,
#: ворота мерили достижимость от мёртвой точки: то, что держалось на ней
#: одной, числилось подключённым и не запускалось никогда.
ENTRY_GLOBS = ("*/skills/**/*.md", "*/hooks/*.py", "*/hooks/*.json",
               "*/agents/*.md", "*/commands/*.md")


def gate_reconciled(карта_путь: Path = None) -> dict:
    """Карта сверялась с ПЛАНОМ, и после сверки план не менялся.

    Все остальные ворота проверяют соответствие КАРТЕ. Полнота самой карты им
    невидима: её пишет та же модель, которая по ней строит, и однажды «34 из
    34» горело зелёным поверх 14 групп пропусков. Нашла их независимая сверка,
    после которой карта выросла до 137 механизмов.

    Та сверка осталась разовой. Здесь считается единственное, что тут вообще
    можно посчитать кодом, — отпечаток плана, с которым карту сверяли.

    Чем эти ворота НЕ являются, и это важнее: они не доказывают, что карта
    полна. Полноту устанавливает чтение плана другой моделью, а отметку ставит
    человек, и врать ей можно. Ворота не дают расхождению пройти МОЛЧА — это
    другое утверждение, более слабое и единственное честное.
    """
    src = карта_путь or (PLUG / "data" / "plan-coverage.json")
    try:
        карта = json.loads(Path(src).read_text("utf-8"))
    except (OSError, ValueError) as e:
        return {"status": "unknown", "detail": f"карта не прочитана: {e}"}

    отметка = карта.get("reconciled") or {}
    if not отметка.get("digest"):
        return {"status": "unknown",
                "detail": "карта ни разу не сверялась с планом — полноту её "
                          "механизмов не проверял никто",
                "next": "прочитать план другой моделью, дополнить карту и "
                        "отметить сверку: tools/plan_stamp.py --by <кто>"}

    # Переносимый снимок лежит РЯДОМ С КАРТОЙ. До него эта проверка упиралась
    # в личный файл в домашнем каталоге автора: независимый клон его не
    # содержит, ворота честно отвечали «не смог» — и ответ уезжал в зелёный
    # итог сборки, потому что тот падал только на `fail`.
    снимок = plan_stamp.read_snapshot(Path(src).parent / plan_stamp.SNAPSHOT_NAME)
    if not снимок["ok"]:
        return {"status": "unknown",
                "detail": снимок["why"] + " — сверку нельзя воспроизвести "
                          "нигде, кроме машины автора",
                "next": "пересобрать снимок рядом с картой: "
                        "tools/plan_stamp.py --snapshot"}
    if снимок["snapshot"]["plan_digest"] != отметка["digest"]:
        return {"status": "unknown",
                "detail": "снимок рядом с картой относится к другому плану, "
                          "чем отметка о сверке",
                "next": "переотметить сверку: tools/plan_stamp.py --by <кто>"}

    p = plan_stamp.plan_path()
    по_снимку = not p.is_file()
    if not по_снимку and plan_stamp.digest(p) != отметка["digest"]:
        нынешние = {r["digest"] for r in plan_stamp.build_snapshot(p)["sections"]}
        было = [r["digest"] for r in снимок["snapshot"]["sections"]]
        разошлись = [i for i, d in enumerate(было, 1) if d not in нынешние]
        где = (f"; разделов изменилось {len(разошлись)} — "
               + ", ".join(map(str, разошлись[:_NAMES_SHOWN]))) if разошлись else ""
        return {"status": "unknown",
                "detail": "план правился после сверки — полнота карты снова "
                          "неизвестна" + где,
                "reconciled": {k: отметка.get(k)
                               for k in ("date", "by", "mechanisms")},
                "changed_sections": разошлись,
                "next": "перечитать изменившееся, дополнить карту и "
                        "переотметить: tools/plan_stamp.py --by <кто>"}

    # Сверка нашла не только пропуски карты, но и механизмы, которых нет в
    # КОДЕ. Держать их вне карты и звать это «сверено» — то же враньё
    # умолчанием, ради которого ворота и заводились: «156 из 156» горело бы
    # зелёным поверх двадцати трёх невыполненных обещаний плана.
    дыры = Path(src).parent / "plan-gaps.json"
    if дыры.is_file():
        try:
            список = json.loads(дыры.read_text("utf-8")).get("gaps") or []
        except (OSError, ValueError) as e:
            return {"status": "unknown", "detail": f"список дыр не разобран: {e}"}
        if список:
            return {"status": "unknown",
                    "detail": f"карта сверена {отметка.get('date')} "
                              f"({отметка.get('by')}), но {len(список)} механизмов "
                              "плана не построено",
                    "gaps": [g["plan_line"] for g in список],
                    "next": "построить их или отказаться от них В ПЛАНЕ — "
                            "молча удалить запись значит вернуть ту самую дыру"}

    # Что именно доказано, говорится вслух. С планом на месте — что он не
    # менялся после сверки. Без него — что отметка и переносимый снимок
    # говорят об одном плане. Второе слабее первого, и подменять одно другим
    # молча значило бы повторить ту же болезнь этажом выше.
    как = ("плана нет в этом дереве — сверено по переносимому снимку рядом "
           "с картой" if по_снимку else "план на месте и с тех пор не менялся")
    return {"status": "pass", "by_snapshot": по_снимку,
            "detail": f"карта сверена с планом {отметка.get('date')} "
                      f"({отметка.get('by')}), механизмов на тот момент "
                      f"{отметка.get('mechanisms')}; {как}"}


#: Столько байт скилла грузится ДО первого решения. Рынок держит 1–3 тысячи
#: токенов; для русского текста это примерно 4 байта на токен, отсюда потолок.
#: Число тут не священное — священно то, что оно ЕСТЬ: правило без числа не
#: нарушается никогда.
ВЕС_ПОТОЛОК = 12_000

#: Пометка в SKILL.md рядом с вынесенной фазой. Фаза, читаемая всегда, ничего
#: не экономит: текст переехал в другой файл и грузится тем же весом. Поэтому
#: она входит в вес загрузки, а не выпадает из него.
ЧИТАЕТСЯ_ВСЕГДА = "читается всегда"


def gate_weight() -> dict:
    """Вес скилла на загрузке — тем же прибором, каким мы меряем чужое.

    Продукт считает конституцию человека и зовёт находкой всё, что толще
    двухсот строк. Свой главный скилл не считал никто, и он вырос до
    тридцати трёх килобайт — вчетверо выше того потолка, который мы ставим
    другим. Прибор для чужих и не для себя — это и есть та асимметрия,
    которую ловят все остальные ворота, только этажом выше.

    Считается СТАРТОВЫЙ вес: `SKILL.md` плюс те вынесенные фазы, которые
    помечены как читаемые всегда. Условные фазы не считаются — их читают,
    дойдя до них, и в дешёвом прогоне они не грузятся вовсе.
    """
    skills = sorted((PLUG / "plugins").glob("*/skills/*"))
    if not skills:
        return {"status": "unknown", "detail": "скиллов не найдено"}

    тяжёлые, всего = [], {}
    for s in skills:
        f = s / "SKILL.md"
        if not f.is_file():
            continue
        текст = f.read_text("utf-8", errors="replace")
        старт = len(текст.encode("utf-8"))
        максимум = старт
        for ф in sorted(s.glob("phases/*.md")):
            байт = len(ф.read_text("utf-8", errors="replace").encode("utf-8"))
            максимум += байт
            место = текст.find(f"phases/{ф.name}")
            рядом = текст[max(0, место - 400):место] if место >= 0 else ""
            if ЧИТАЕТСЯ_ВСЕГДА in рядом:
                старт += байт
        всего[s.name] = {"старт": старт, "максимум": максимум}
        if старт > ВЕС_ПОТОЛОК:
            тяжёлые.append({"skill": s.name, "старт": старт,
                            "сверх": старт - ВЕС_ПОТОЛОК})

    detail = "; ".join(f"{имя} {v['старт']}" for имя, v in sorted(всего.items()))
    if тяжёлые:
        return {"status": "fail", "weights": всего, "over": тяжёлые,
                "detail": f"сверх потолка {ВЕС_ПОТОЛОК}: " +
                          ", ".join(f"{x['skill']} на {x['сверх']}" for x in тяжёлые),
                "next": "вынести в phases/ то, что не нужно до первого решения, "
                        "и назвать условие чтения — иначе фаза считается "
                        "читаемой всегда и веса не снимает"}
    return {"status": "pass", "weights": всего,
            "detail": f"все скиллы под потолком {ВЕС_ПОТОЛОК}: {detail}"}


def gate_wiring() -> dict:
    """Инструмент обязан быть ДОСТИЖИМ, а не просто существовать.

    Единственные ворота, которые ловят болезнь этого проекта в его собственном
    исходнике. Она уже случалась трижды, и каждый раз выглядела построенной
    системой: `hooks.json` объявлял 34 хука при девяти подключённых; `learn.py`
    был написан целиком — планка из трёх условий, маршрутизация, слияние — и не
    вызывался НИКЕМ; в один заход сюда добавилось шесть инструментов, до
    которых не дотягивался ни один скилл.

    Механизм, который не с чего запустить, неотличим от отсутствующего — и хуже
    его, потому что занимает место в отчёте и в голове. Тесты его не ловят:
    файл на месте, функции работают, набор зелёный.

    Достижимость считается транзитивно от точек входа: скилл зовёт инструмент,
    тот зовёт следующий. Инструмент, который человек запускает сам, — законный
    случай, но он обязан быть НАЗВАН в `data/entrypoints.json` вместе с
    причиной. Разница между «решили так» и «забыли» должна быть записана, иначе
    через месяц её не отличить.
    """
    tools = sorted(PLUG.glob("plugins/*/tools/*.py"))
    if not tools:
        return {"status": "unknown", "detail": "инструментов не найдено"}

    entries = []
    for g in ENTRY_GLOBS:
        entries += list(PLUG.glob("plugins/" + g))

    declared, why = set(), {}
    ep = PLUG / "data" / "entrypoints.json"
    if ep.is_file():
        try:
            for e in json.loads(ep.read_text("utf-8"))["entrypoints"]:
                declared.add(e["tool"])
                why[e["tool"]] = e.get("why", "")
        except (ValueError, KeyError, TypeError) as e:
            return {"status": "unknown",
                    "detail": f"список точек входа не разобран: {e}"}

    # Проза вырезается тем же прибором, что у ворот «план». Упоминание имени
    # в комментарии или докстринге доказывает, что про инструмент НАПИСАЛИ, а
    # не что его откуда-то зовут. Живой случай: `lint_rules.py` встречался в
    # пакете ровно один раз — в докстринге соседнего инструмента — и ворота
    # считали его достижимым. Для .md вырезать нечего: там текст и есть
    # артефакт, и это ограничение названо, а не замаскировано.
    text = {}
    for f in entries + tools:
        try:
            text[f] = executable_text(f)
        except OSError:
            text[f] = ""

    by_name = {t.name: t for t in tools}

    def зовёт(где: str, имя: str) -> bool:
        """Вызов инструмента — это и путь к файлу, и питоновский импорт.

        Проверка только по «имя.py» пропускает `import derive_phase`: модуль
        пишется без расширения, и на глаз разницы нет. Один такой инструмент
        уже числился достижимым по ложной причине — его имя встречалось в
        карте владельцев внутри резолвера, то есть в строке справочника, а не
        в вызове. Слияние удалило резолвер, маска слетела, и ворота показали
        мёртвым инструмент, который на самом деле работает каждый прогон.

        Обратная ошибка тоже возможна и хуже: искать голое имя без границ
        значило бы считать вызовом любое упоминание в комментарии. Поэтому
        импорт распознаётся формой оператора, а не подстрокой.

        Ровно эта обратная ошибка тут и стояла: путь искался вхождением
        `имя in где`, и `doctor.py` числился достижимым, потому что входит в
        `project_doctor.py`. Граница берётся с обеих сторон. Слева `/` — это
        разделитель пути, и `tools/learn.py` остаётся вызовом; буква, `_`,
        `-` и точка слева означают уже другое имя.
        """
        мод = имя[:-3]
        if re.search(rf"(?<![\w.-]){re.escape(имя)}(?![\w-])", где):
            return True
        return re.search(rf"^\s*(?:import|from)\s+{re.escape(мод)}\b",
                         где, re.M) is not None

    # Достижимое от точек входа, потом транзитивно через сами инструменты.
    reached = {n for n in by_name
               if any(зовёт(text[e], n) for e in entries) or n in declared}
    for _ in range(len(by_name) + 1):
        grown = set(reached)
        for n, t in by_name.items():
            if n in reached:
                continue
            if any(зовёт(text[by_name[r]], n) for r in reached if r in by_name):
                grown.add(n)
        if grown == reached:
            break
        reached = grown

    dead = sorted(n for n in by_name if n not in reached)
    stale = sorted(d for d in declared if d not in by_name)

    # Второй отказ этих же ворот, и он тише первого. `${CLAUDE_PLUGIN_ROOT}`
    # разворачивается в корень ТОГО плагина, чей скилл исполняется. Скилл,
    # зовущий `$CLAUDE_PLUGIN_ROOT/tools/verify.py` из пакета, где verify.py
    # нет, выглядит подключённым и падает «нет такого файла» — то есть как
    # поломка окружения, а не как опечатка в пути. Так и было: оба вызова
    # единственного сборочного скилла указывали в пустоту несколько заходов.
    wrong = []
    for e in entries:
        plug = e.relative_to(PLUG / "plugins").parts[0]
        for m in re.finditer(r"\$\{?CLAUDE_PLUGIN_ROOT\}?/tools/([\w.]+\.py)",
                             text[e]):
            if not (PLUG / "plugins" / plug / "tools" / m.group(1)).is_file():
                wrong.append(f"{plug}: зовёт {m.group(1)} через свой корень, "
                             f"а его там нет")
    if wrong:
        return {"status": "fail",
                "detail": f"пути в пустоту: {len(wrong)} — {wrong[0]}",
                "wrong_paths": sorted(set(wrong)),
                "next": "поправить имя инструмента: все они лежат в "
                        "plugins/superstack/tools, и путь от корня пакета верен"}

    if dead:
        return {"status": "fail",
                "detail": f"инструментов не достать ниоткуда: {len(dead)} из "
                          f"{len(tools)} — {', '.join(dead[:6])}",
                "dead": [str(by_name[d].relative_to(PLUG)) for d in dead],
                "next": "подключить к скиллу, хуку или агенту — либо записать "
                        "в data/entrypoints.json с причиной, почему инструмент "
                        "запускает человек"}
    if stale:
        return {"status": "unknown",
                "detail": f"в списке точек входа названы несуществующие "
                          f"инструменты: {', '.join(stale[:5])}"}
    return {"status": "pass",
            "detail": f"все {len(tools)} инструментов достижимы"
                      + (f" ({len(declared)} — вручную, с причиной)" if declared else "")}


