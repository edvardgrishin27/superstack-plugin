def stash(mid: str, target: Path, original: bytes) -> None:
    """Отложить оригинал ДО внесения поломки.

    Восстановление обратной заменой — угадывание, и оно уже испортило файл:
    поломка `crew.missing-stamps-read-as-clean` заменяла блок на строку
    `continue`, а такая строка в файле не одна. Обратная замена вернула блок в
    ПЕРВОЕ вхождение — в другую ветку. Файл остался синтаксически валидным и
    стал семантически неверным, `--unstick` отчитался «вернул 1», и увидели это
    только десять упавших тестов.

    Байты, отложенные заранее, снимают вопрос целиком: возвращать нечего
    искать. Живёт рядом с замком и переживает убийство процесса — ровно тот
    случай, ради которого всё это и нужно.
    """
    d = _backup_dir()
    d.mkdir(parents=True, exist_ok=True)
    safe = re.sub(r"[^\w.-]", "_", mid)
    (d / f"{safe}.bak").write_bytes(original)
    (d / f"{safe}.json").write_text(json.dumps(
        {"id": mid, "file": str(target.relative_to(PLUG)),
         "sha256": hashlib.sha256(original).hexdigest()}, ensure_ascii=False),
        encoding="utf-8")


def _stashed(mid: str) -> "bytes | None":
    """Отложенный оригинал этой поломки, если он есть."""
    safe = re.sub(r"[^\w.-]", "_", mid)
    p = _backup_dir() / f"{safe}.bak"
    try:
        return p.read_bytes()
    except OSError:
        return None


def unstash(mid: str) -> None:
    safe = re.sub(r"[^\w.-]", "_", mid)
    for suf in (".bak", ".json"):
        try:
            (_backup_dir() / f"{safe}{suf}").unlink()
        except OSError:
            pass


def _внутри_набора() -> bool:
    """Ворота крутятся ВНУТРИ чужого прогона набора.

    Базовый прогон — это прогон ВСЕГО набора, а в наборе есть тесты, которые
    зовут эти самые ворота: вложенный базовый прогон не сходится, каждый круг
    запускает следующий. Признак берётся из среды: `PYTEST_CURRENT_TEST`
    ставит сам pytest, `SUPERSTACK_MUTATION_RUN` — прогон мутаций.

    Планка запускается отдельным процессом, где нет ни того, ни другого: в
    продукте базовый прогон идёт ВСЕГДА. Пропуск при этом называется в
    отчёте ворот (поле `baseline`), а не молчит, и заперт тестами, которые
    снимают признак нарочно, — молча выключенная проверка отвечает «всё
    чисто» и этим хуже отсутствующей.
    """
    return bool(os.environ.get("PYTEST_CURRENT_TEST")
                or os.environ.get("SUPERSTACK_MUTATION_RUN") == "1")


def _baseline(корень: Path) -> "str | None":
    """Набор ДО первой подмены: причина, по которой исходы читать нельзя, или None.

    Красный набор делает «пойманными» все мутации разом — он падал и без
    подмены. По числам отчёта такой прогон неотличим от честного, и это самый
    дешёвый способ получить «все пойманы», не проверив ничего.

    Прогон идёт тем же способом, что и прогоны с подменой: та же команда, тот
    же флаг сторожа, тот же корень. Единственная разница между базовым и
    остальными — сама подмена, иначе разницу исходов не на что относить.
    """
    code, out = _sh([sys.executable, "-m", "pytest", "tests/", "-q", "-x"],
                    SUITE_TIMEOUT, cwd=корень,
                    env={"SUPERSTACK_MUTATION_RUN": "1"})
    if code == 0:
        return None
    if code in НЕ_СОСТОЯЛСЯ:
        return f"базовый прогон не состоялся (код {code}): {out.strip()[-200:]}"
    имена = ", ".join(_failed_names(out)[:_NAMES_SHOWN])
    return "набор красный ДО поломок: " + (имена or out.strip()[-200:])


def _mutate_all(muts: list, корень: Path = None, реестр: int = None) -> dict:
    # Корень подаётся снаружи: ломается ОДНОРАЗОВАЯ копия, а не
    # рабочее дерево человека. Прежде ломалось живое, и дважды
    # прерванный прогон оставлял в нём `if False:` — восемь красных
    # тестов в четырёх файлах, ни один из которых не был дефектом.
    в_копии = корень is not None
    корень = корень or PLUG
    survived, checked, broken, вне, неясные = [], 0, [], [], []
    всего = len(muts)
    # `всего` — сколько досталось ЭТОМУ прогону, `реестр` — сколько поломок
    # зарегистрировано вообще. У полного прогона это одно число, у доли — два
    # разных, и путать их значит терять недостачу при сложении.
    реестр = всего if реестр is None else реестр
    доля = {"index": SHARD[0], "of": SHARD[1]} if SHARD else None

    def снимок(текущая: "str | None") -> dict:
        """Что уже проверено и на чём стоим прямо сейчас."""
        сделано = checked - len(неясные)
        return {"status": "running", "current": текущая, "shard": доля,
                "registry_total": реестр, "registered": всего,
                "executed": сделано, "caught": сделано - len(survived),
                "survived": survived, "inconclusive": неясные}
    # Первая запись — ДО базового прогона. Он сам идёт минутами, и доля,
    # снятая на нём, иначе не оставляет вообще ничего: сведение видит
    # пропавший артефакт вместо «встала на базовом прогоне».
    _write_progress(снимок(None))
    # Базовый прогон ДО первой подмены: см. `_baseline`. Пропуск (ворота
    # вызваны изнутри набора) НАЗЫВАЕТСЯ в отчёте, а не подразумевается.
    if _внутри_набора():
        база = "не гонялся: ворота вызваны изнутри прогона набора"
    else:
        причина = _baseline(корень)
        if причина:
            return {"status": "unknown",
                    "detail": f"исходы поломок не читаются — {причина}",
                    "survived": [], "inconclusive": [], "registered": всего,
                    "registry_total": реестр, "executed": 0, "caught": 0,
                    "baseline": причина}
        база = "зелёный"
    т0 = time.monotonic()
    for n, m in enumerate(muts, 1):
        # Признак жизни. Без него прогон на 45 минут снаружи неотличим от
        # зависшего: судить можно было только по смене дочерних процессов в
        # `ps`. Это ровно тот отказ, который ворота ловят у других — механизм,
        # о работе которого нельзя узнать, — и он был у самой планки.
        #
        # В stderr, а не в stdout: stdout занят машиночитаемым отчётом, и
        # строка прогресса в нём сломала бы разбор у того, кто читает JSON.
        прошло = time.monotonic() - т0
        осталось = (прошло / (n - 1) * (всего - n + 1)) if n > 1 else 0
        print(f"  мутация {n}/{всего}  {m['id'][:44]:<44}"
              + (f"  ещё ~{осталось / 60:.0f} мин" if n > 1 else ""),
              file=sys.stderr, flush=True)
        # Отчёт ложится ДО прогона: имя поломки, на которой встали, известно
        # только пока она идёт. После — узнавать его будет некому.
        _write_progress(снимок(m["id"]))
        target = корень / m["file"]
        if not target.is_file():
            # Поставка — ПОДМНОЖЕСТВО репозитория: `research/` остаётся у
            # разработки и в публичное дерево не едет. Мутация на такой файл
            # там неисполнима — но это «не проверялась», а не «поймана» и не
            # «якорь протух». Разница обязана быть объявлена в самой записи и
            # названа в отчёте: молчаливый пропуск превратил бы отсутствующий
            # механизм в зелёную строку.
            if m.get("вне_поставки"):
                вне.append(m["id"])
                continue
            broken.append(f"{m['id']}: нет файла {m['file']}")
            continue
        original = target.read_bytes()
        text = original.decode("utf-8")
        if m["find"] not in text:
            broken.append(f"{m['id']}: якорь не найден в {m['file']}")
            continue
        if not в_копии:
            stash(m["id"], target, original)
        try:
            target.write_text(text.replace(m["find"], m["replace"], 1), encoding="utf-8")
            # Кэш байткода сносится ПЕРЕД каждым прогоном, а не один раз на
            # ворота: замена того же размера в ту же секунду неотличима для
            # инвалидации, и без чистки прогон пошёл бы по старому .pyc —
            # то есть измерял бы не ту мутацию, о которой отчитывается.
            purge_bytecode()
            # -x: первое падение и есть ответ «поймана». Гонять весь набор до
            # конца на заведомо сломанном коде — платить минутами за то, что
            # уже известно.
            code, _ = _sh([sys.executable, "-m", "pytest", "tests/", "-q", "-x"],
                          MUTATION_TIMEOUT, cwd=корень,
                          # Сторож в conftest обязан молчать ИМЕННО здесь. Он
                          # обрывает набор, увидев мутацию в дереве, — а тут она
                          # применена намеренно. Без этого флага pytest вышел бы
                          # с ненулевым кодом до единого теста, ворота прочли бы
                          # это как «мутация поймана», и весь набор мутаций
                          # отчитался бы пойманным, не проверив ни одной.
                          env={"SUPERSTACK_MUTATION_RUN": "1"})
            if code in НЕ_СОСТОЯЛСЯ:
                # Таймаут (124) и незапустившийся процесс (127) — авария
                # ОКРУЖЕНИЯ, а не ответ набора. Пока обе засчитывались за
                # пойманную поломку, короткий таймаут давал «все мутации
                # пойманы», не выполнив ни одного прогона.
                исход = "inconclusive"
                print(f"    НЕ ВЫШЛО: {m['id']} — прогон не состоялся "
                      f"(код {code})", file=sys.stderr, flush=True)
            elif code == 0:
                исход = "survived"
                # Выжившая — единственная новость, ради которой стоит
                # прерывать поток строк. Печатается сразу: узнать о ней через
                # сорок минут значит сорок минут считать, что всё в порядке.
                print(f"    ВЫЖИЛА: {m['id']} — {m['why'][:100]}",
                      file=sys.stderr, flush=True)
            else:
                исход = "caught"
        finally:
            # Восстановление байт-в-байт и ДО любой другой работы: мутация,
            # пережившая прогон в файле, отравит все следующие ворота.
            target.write_bytes(original)
            # Отложенное снимается только ПОСЛЕ удачного возврата: пока файл не
            # восстановлен, единственная целая копия — эта.
            if not в_копии:
                unstash(m["id"])
        checked += 1
        if исход == "survived":
            survived.append({"id": m["id"], "why": m["why"]})
        elif исход == "inconclusive":
            неясные.append({"id": m["id"], "code": code,
                            "why": ("не уложился в таймаут" if code == 124
                                    else "процесс не запустился")})

    # Четыре числа вместо одного громкого. «Все пойманы» не различает
    # «набор покраснел на подмене» и «прогон не состоялся», а разница между
    # ними — это разница между проверкой и её видимостью.
    выполнено = checked - len(неясные)
    поймано = выполнено - len(survived)
    числа = (f"зарегистрировано {всего}, выполнено {выполнено}, "
             f"поймано {поймано}, неизвестно {len(неясные)}")
    итог = {"survived": survived, "inconclusive": неясные,
            "registered": всего, "registry_total": реестр,
            "executed": выполнено, "caught": поймано, "baseline": база}
    if broken:
        return {"status": "unknown",
                "detail": "мутации не применились: " + "; ".join(broken[:5]),
                **итог}
    if survived:
        return {"status": "fail",
                "detail": f"выжило {len(survived)} из {выполнено}; {числа}",
                **итог}
    if неясные:
        # Не «поймана» и не «выжила»: прогон не состоялся, и сказать по нему
        # нечего. Чистый pass тут был бы тем самым враньём умолчанием.
        return {"status": "unknown",
                "detail": числа + " — прогон не состоялся у "
                          + ", ".join(x["id"] for x in неясные[:_NAMES_SHOWN]),
                **итог}
    хвост = (f" — ещё {len(вне)} не проверялись: файла нет в этом дереве "
             "(объявлено вне поставки)") if вне else ""
    return {"status": "pass", "detail": числа + хвост, "вне_дерева": вне,
            **итог}


def gate_rules() -> dict:
    # Каталоги правил перечисляются глобом, а не именем: линт по одному
    # каталогу молча проверял бы часть файлов и печатал «правила целы» — то
    # есть врал бы ровно тем способом, против которого написан.
    linter = PLUG / "plugins" / "superstack" / "tools" / "lint_rules.py"
    globs = [str(d / "*.json") for d in sorted((PLUG / "plugins").glob("*/rules"))]
    if not globs:
        return {"status": "unknown", "detail": "ни одного каталога правил не найдено"}
    code, out = _sh([sys.executable, str(linter)] + globs, 300)
    if code == 0:
        return {"status": "pass", "detail": out.strip().splitlines()[-1][:200] if out.strip() else "правила целы"}
    return {"status": "fail", "detail": out.strip()[-500:]}


def marketplace_crosscheck() -> dict:
    """Объявленное против существующего — в обе стороны, без подпроцессов.

    Ворота подписались строкой «плагин ставится, а не только лежит», а
    проверяли один файл из восьми: `claude plugin validate .` валидирует
    ТОЛЬКО `marketplace.json` и молчит о том, существует ли каталог из
    `source`. Живой случай: манифест объявлял `./plugins/superstack`, каталога
    не было, семь настоящих пакетов не были объявлены вовсе — и ворота были
    зелёными. Продукт не устанавливался с момента разделения на семь, и
    заметить это было нечем.

    Проверка нарочно НЕ зовёт `claude`: на машине без него сильная половина
    ворот иначе исчезала бы молча.

    Третье множество — сирота — обязательно. Каталог, потерявший свой
    `plugin.json`, выпадает из обеих разностей сразу, и проверка зеленеет на
    пустоте.
    """
    mk = PLUG / ".claude-plugin" / "marketplace.json"
    if not mk.is_file():
        return {"status": "unknown", "detail": f"нет манифеста маркетплейса: {mk}"}
    try:
        entries = json.loads(mk.read_text("utf-8"))["plugins"]
    except (ValueError, KeyError) as e:
        return {"status": "unknown", "detail": f"манифест не разобран: {e}"}

    pkgs, orphans = {}, []
    for d in sorted((PLUG / "plugins").glob("*")):
        if not d.is_dir():
            continue
        pj = d / ".claude-plugin" / "plugin.json"
        if not pj.is_file():
            orphans.append(d.name)
            continue
        try:
            pkgs[d.name] = json.loads(pj.read_text("utf-8"))
        except ValueError as e:
            orphans.append(f"{d.name} (манифест не разобран: {e})")

    bad, seen = [], set()
    for e in entries:
        name, src = e.get("name", ""), (e.get("source") or "")
        if name in seen:
            bad.append(f"{name}: объявлен дважды — ключ установки перестаёт "
                       "указывать на одно")
        seen.add(name)
        d = PLUG / src.lstrip("./") if isinstance(src, str) else None
        if d is None or not d.is_dir():
            bad.append(f"{name}: source `{src}` не существует — запись в пустоту")
            continue
        pj = d / ".claude-plugin" / "plugin.json"
        if not pj.is_file():
            bad.append(f"{name}: в `{src}` нет .claude-plugin/plugin.json")
            continue
        p = pkgs.get(d.name, {})
        if p.get("name") != name:
            bad.append(f"{name}: пакет представляется как «{p.get('name')}» — "
                       "ключ установки указывал бы не на тот пакет")
        if e.get("version") != p.get("version"):
            bad.append(f"{name}: версия записи {e.get('version')} ≠ версии "
                       f"пакета {p.get('version')} — semver удовлетворяется "
                       "не тем кодом, а имя каталога установки берётся отсюда")

    for n in sorted(set(pkgs) - seen):
        bad.append(f"{n}: пакет есть, записи в маркетплейсе нет — не поставится")

    # Объявленное поле ГАСИТ каталог: движок берёт дефолтный каталог только
    # когда поля нет. Файл, лежащий рядом и не названный, не грузится никогда,
    # и ошибки при этом нет. Так уже потерялся агент слепой приёмки.
    for n, p in sorted(pkgs.items()):
        for field, sub in (("agents", "agents"), ("skills", "skills"),
                           ("commands", "commands")):
            declared = p.get(field)
            if not isinstance(declared, list):
                continue
            named = {Path(x).name for x in declared if isinstance(x, str)}
            on_disk = {f.name for f in (PLUG / "plugins" / n / sub).glob("*.md")}
            missed = sorted(on_disk - named)
            if missed and not any(str(x).rstrip("/").endswith(sub) for x in declared):
                bad.append(f"{n}: в `{sub}/` лежит незаявленное — {', '.join(missed[:3])}; "
                           "объявленное поле гасит каталог, и это не грузится молча")

    if bad:
        return {"status": "fail", "detail": f"{len(bad)} расхождений: {bad[0]}",
                "mismatches": bad}
    if orphans:
        return {"status": "unknown",
                "detail": "каталоги без манифеста: " + ", ".join(orphans[:5])}
    return {"status": "pass",
            "detail": f"{len(entries)} записей = {len(pkgs)} пакетов, версии сходятся"}


def gate_manifest() -> dict:
    cross = marketplace_crosscheck()
    if cross["status"] == "fail":
        return cross
    if not shutil.which("claude"):
        return {"status": "unknown",
                "detail": "сверка прошла, но схему проверить нечем: claude не найден"}
    env = {k: v for k, v in os.environ.items()
           if k not in ("CLAUDECODE", "CLAUDE_CODE_ENTRYPOINT")}
    try:
        p = subprocess.run(["claude", "plugin", "validate", "."],
                           cwd=str(PLUG), capture_output=True,
                           text=True, timeout=180, env=env)
    except (OSError, subprocess.TimeoutExpired) as e:
        return {"status": "unknown", "detail": str(e)[:200]}
    if p.returncode != 0:
        return {"status": "fail",
                "detail": "корневой манифест: "
                          + ((p.stdout or "") + (p.stderr or ""))[-300:]}

    # Каждый пакет — отдельно. Раньше валидировался только корень, и шесть
    # манифестов из семи были невалидны при зелёных воротах: движок 2.1.42
    # отвергает ключ `dependencies`, а узнать об этом было неоткуда.
    broken = []
    for d in sorted((PLUG / "plugins").glob("*")):
        if not (d / ".claude-plugin" / "plugin.json").is_file():
            continue
        r = subprocess.run(["claude", "plugin", "validate", str(d)],
                           cwd=str(PLUG), capture_output=True, text=True,
                           timeout=180, env=env)
        if r.returncode != 0:
            tail = ((r.stdout or "") + (r.stderr or "")).strip().splitlines()
            broken.append(f"{d.name}: {tail[-1][:120] if tail else 'провал'}")
    if broken:
        return {"status": "fail",
                "detail": f"невалидных пакетов {len(broken)}: {broken[0]}",
                "packages": broken}
    return {"status": "pass",
            "detail": f"{cross['detail']}; схема валидна у корня и всех пакетов"}


def gate_plan() -> dict:
    """Механизмы плана — счётным списком, а не на глаз.

    План — 928 строк прозы. Пока «построено» проверяется чтением, ответ
    зависит от того, кто читал. Здесь у каждого механизма есть улика: файл и
    строка, которая обязана в нём быть.
    """
    src = PLUG / "data" / "plan-coverage.json"
    if not src.is_file():
        return {"status": "unknown", "detail": f"нет карты плана: {src}"}
    try:
        items = json.loads(src.read_text("utf-8"))["mechanisms"]
    except (ValueError, KeyError) as e:
        return {"status": "unknown", "detail": f"карта плана не разобрана: {e}"}

    present, missing, weak = [], [], []
    for it in items:
        ev = it["evidence"]
        # Улика без `contains` удовлетворяется ПУСТЫМ ФАЙЛОМ. Это не мелкая
        # неточность, а дыра в самом приборе: `touch tools/что_угодно.py`
        # засчитывался за построенный механизм, и «N из N» горело зелёным
        # поверх пустоты. Такая запись — не «пройдена» и не «провалена», она
        # НЕПРОВЕРЯЕМА, и ворота обязаны сказать это отдельным словом.
        if not ev.get("contains"):
            weak.append(it)
            continue
        f = PLUG / ev["file"]
        ok = f.is_file()
        if ok:
            try:
                ok = ev["contains"] in executable_text(f)
            except OSError:
                ok = False
        (present if ok else missing).append(it)

    # Улика «в файле есть подстрока» доказывает НАЛИЧИЕ, а не работу. Это
    # известно и записано, но в отчёте всё равно горело одно громкое число —
    # и читалось как «226 механизмов работают». Поэтому чисел теперь два.
    #
    # Оговорка названа вслух: связь считается ПО ФАЙЛУ, а не по строке.
    # Поломка в том же файле не обязана ломать именно этот механизм — она
    # лишь означает, что файл кто-то проверял на слом. Более точной связи в
    # данных нет, и выдумывать её значило бы снова считать желаемое.
    сломанные = set()
    src_m = PLUG / "tests" / "mutations.json"
    if src_m.is_file():
        try:
            сломанные = {m["file"] for m in
                         json.loads(src_m.read_text("utf-8"))["mutations"]}
        except (ValueError, KeyError, TypeError):
            сломанные = set()
    подтверждено = [it for it in present
                    if it["evidence"]["file"] in сломанные]

    detail = (f"{len(present)} из {len(items)} на месте; "
              f"из них поломкой проверено {len(подтверждено)}, "
              f"только подстрокой {len(present) - len(подтверждено)}")
    if weak:
        detail += f"; {len(weak)} записей без проверяемой улики"
    out = {"detail": detail, "proved_by_mutation": len(подтверждено),
           "substring_only": len(present) - len(подтверждено)}
    if missing:
        out["missing"] = [{"id": m["id"], "layer": m["layer"],
                           "mechanism": m["mechanism"],
                           "file": m["evidence"]["file"]} for m in missing]
    if weak:
        out["unverifiable"] = [{"id": m["id"], "layer": m["layer"],
                                "mechanism": m["mechanism"],
                                "file": m["evidence"]["file"],
                                "why": "нет поля contains: пустой файл прошёл бы"}
                               for m in weak]
    if missing:
        return {"status": "fail", **out}
    if weak:
        # Не «провалено» — «не смог проверить». Отдельный статус держит код 2
        # и не даёт объявить планку взятой, но и не обвиняет в отсутствии того,
        # что, возможно, на месте.
        return {"status": "unknown", **out}
    return {"status": "pass", **out}


