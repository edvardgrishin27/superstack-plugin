#!/usr/bin/env python3
"""SUPERSTACK — передача таска исполнителю. Промпт собирает код, а не добрая воля.

Зачем это скрипт, а не абзац в инструкции.

Самое острое наблюдение AutoPilot звучит так: «правило, живущее только в этом
файле, не существует». Фазовые файлы читает оркестратор, а код пишет субагент,
который их никогда не увидит. Всё, что исполнитель обязан соблюдать, обязано
доехать В ЕГО ПРОМПТЕ — и там же сказано, что чаще всего теряется тестовый
контракт, потому что он читается как совет, а не как вход.

Это ровно тот класс, который у нас превращается в механизм. Пока промпт
собирает модель, дисциплина держится на её внимании к концу третьего часа.
Здесь промпт собирает скрипт: обязательные куски вложены им, а не вспомнены,
и неполный промпт не собирается вовсе — вместо него код возврата и список
того, чего не хватает.

Что делает передачу невозможной (код 1), а не просто неудобной:

  · таск не служит ни одному требованию — работа, которую никто не заказывал;
  · нет критериев приёмки — исполнитель не узнает, когда закончил;
  · нет команды тестов — «зелёный прогон» будет означать «я не запускал»;
  · пустой interfaces.md не у первого таска — тогда архитектуру задаст тот,
    кто увидел одну восьмую задачи, а остальные будут её обходить;
  · названы разделы спеки, которых в спеке нет;
  · проект объявил каталог архитектурных решений, а передача идёт без него —
    тогда исполнитель писал бы в зоне, чьё решение принято и записано, не
    увидев его, и «забыл флаг» означало бы то же, что «решения нет».

Решения, правящие зоной таска, вкладываются в промпт ЗДЕСЬ. У AutoPilot про
ADR сказано «прочитай, когда решение вот-вот отменят» — то есть вспомни о папке
ровно тогда, когда уверен, что она не нужна. Здесь решение приходит вместе с
заданием, и не увидеть его нельзя.

  python3 handoff.py <состояние.json> <id> --interfaces X.md [--spec Y.md]
                     [--test-cmd "npm test"] [--adr docs/adr] [--json]

  код 0 — промпт собран, 1 — передавать нечего, 2 — не смог, 3 — вызов
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

#: Тестовый контракт. Уходит в промпт ДОСЛОВНО и целиком — не пересказом.
#: Пересказ и есть способ, которым правило перестаёт доезжать: каждый пересказ
#: короче предыдущего, и первым выпадает то, что выглядит наименее срочным, —
#: а это как раз строка про источник ожидаемого значения.
TESTING_CONTRACT = """Тесты пиши только на швах, названных в приложенных разделах спецификации.
Не тестируй всё подряд и не тестируй внутренности.

Порядок: один тест — реализация — следующий тест. Не пиши тесты пачкой заранее:
написанные впрок, они проверяют воображаемое поведение и перестают реагировать
на реальные изменения.

Тест утверждает через публичный интерфейс и остаётся зелёным после рефакторинга.
Если он ломается, когда внутренности переехали, а поведение то же, — он проверяет
не то.

Ожидаемое значение бери откуда угодно, кроме кода под тестом: известная величина,
разобранный вручную пример, строка из спецификации. Утверждение, которое считает
ответ тем же способом, что и код, не может с ним не согласиться — и не находит
ошибок никогда.

Пустой catch, захардкоженный happy path и тест, подтверждающий сам себя, —
это невыполненный критерий приёмки, а не выполненный."""

#: Контракт возврата. Без него нечем обновить состояние и нечего передать
#: следующему таску — то есть таск формально сделан и практически потерян.
RETURN_CONTRACT = """STATUS: DONE | DONE_WITH_CONCERNS | HANDOFF | BLOCKED | NEEDS_CONTEXT
FILES: созданные и изменённые — только пути
TESTS: команда → результат (например, `npm test` → 34 passed)
INTERFACES: публичные сигнатуры, схемы, форматы событий, которые ты выставил
REQUIREMENTS: R01 done | R01.1 placeholder — чего не хватило
HANDOFF: только при передаче — на чём остановился и что делать следующему
CONCERNS: что сделано с оговоркой и почему
BLOCKERS: чего не хватило (зависимость, решение, доступ)

Не больше 25 строк. Без кода, без диффов, без пересказа хода работы."""

#: Потолок контекста. Считается не токенами, которых исполнитель не видит, а
#: вызовами инструментов — единственной величиной, которую он может посчитать
#: сам. Порядок цены известен: один вызов обходится примерно в две тысячи
#: токенов, полсотни складываются в шестизначное число.
#:
#: Смысл правила не в экономии, а в честности исхода. Раньше исполнитель,
#: у которого кончалось место, выбирал между «сдать недоделанное как готовое»
#: и «вернуть отказ». Первое врёт о готовности, второе о причине: он не
#: «не смог», он не поместился. Третий исход — передача — стоит следующему
#: одного контекста вместо повторения всей работы с нуля.
CEILING = """Считай свои вызовы инструментов. Их около пятидесяти на контекст —
это не запрет, а граница, за которой ты начнёшь забывать начало собственной
работы.

Подходишь к полусотне и конца не видно — доведи до ЗЕЛЁНОГО прогона, остановись
и верни HANDOFF: строкой скажи, что уже работает и с чего начинать следующему.
Красное не передавай: тот, кто получит твою работу, потратит своё место на
разбор поломки, которой не делал. Красное — это BLOCKED.

Передать можно дважды. Если работа не помещается и в третий контекст, это не
длинная работа, а неверно нарезанная задача — так и напиши."""

#: Что исполнителю запрещено. Не вежливость, а границы его зоны: всё, что он
#: тронет за их пределами, придётся разбирать тому, кто этого не писал.
BOUNDS = """Пиши только внутри своей зоны. Файл за её пределами не трогай —
верни BLOCKED с тем, чего не хватило.

Не добавляй зависимостей сам: не хватает пакета — это BLOCKED с названием.
Не переписывай то, что уже описано в «Что уже построено», — зови готовое.
Не придумывай фактов о человеке: цена, адрес, текст, телефон — видимая
заглушка `[ВПИШИ: ...]`, а не правдоподобное значение."""


#: Разбор заголовка ADR — минимальный и НАМЕРЕННО свой.
#:
#: Проверка решений живёт в `adr.py` соседнего пакета, и импортировать её
#: отсюда значит закладываться на то, как маркетплейс разложит плагины рядом.
#: Такого допущения этот проект себе не позволяет: сломается оно молча, при
#: установке у человека, а не здесь.
#:
#: Поэтому дублируется только тривиальный разбор — зона и тело; вся логика
#: суждения остаётся в одном месте. Расхождение двух читателей ловится тестом,
#: который сверяет их на одних и тех же файлах.
_ADR_NAME = re.compile(r"^(\d{4})-[a-z0-9][a-z0-9-]*\.md$")
_ADR_FM = re.compile(r"\A---\n(.*?)\n---\n(.*)\Z", re.S)


def read_adrs(d: "Path | None") -> list:
    if d is None or not d.is_dir():
        return []
    out = []
    for f in sorted(d.glob("*.md")):
        if not _ADR_NAME.match(f.name):
            continue
        m = _ADR_FM.match(f.read_text("utf-8", errors="replace"))
        if not m:
            continue
        head = {}
        for line in m.group(1).splitlines():
            if ":" not in line:
                continue
            k, v = line.split(":", 1)
            v = v.strip()
            head[k.strip()] = ([x.strip() for x in v[1:-1].split(",") if x.strip()]
                               if v.startswith("[") and v.endswith("]") else v)
        out.append({"file": f.name, "zone": head.get("zone") or [],
                    "status": head.get("status") or "accepted",
                    "body": m.group(2)})
    return out


def governing_adrs(adrs: list, zone: list) -> list:
    """Решения, правящие зоной этого таска.

    Вот здесь ADR перестаёт быть надеждой. У AutoPilot про них сказано
    «прочитай, когда решение вот-вот отменят» — то есть надо вспомнить о папке
    ровно в тот момент, когда ты уверен, что папка не нужна.

    Тут решение вкладывается в промпт того, кто собирается писать в его зоне.
    Не увидеть его нельзя: оно приходит вместе с заданием.
    """
    out = []
    for a in adrs:
        if not str(a["status"]).startswith("accepted"):
            continue
        for x in a["zone"]:
            for y in zone or []:
                nx, ny = x.rstrip("/") + "/", y.rstrip("/") + "/"
                if nx == ny or nx.startswith(ny) or ny.startswith(nx):
                    out.append(a)
                    break
            else:
                continue
            break
    return out


def rows(state: dict) -> list:
    return [t for w in (state.get("waves") or {}).values() for t in w]


def find_task(state: dict, tid: str) -> "dict | None":
    return next((t for t in rows(state) if t["id"] == tid), None)


def extract_sections(spec: str, named: list) -> str:
    """Только НАЗВАННЫЕ разделы спеки, а не спека целиком.

    Передача отдавала исполнителю весь файл. Это не просто лишний контекст:
    исполнитель, видящий всю спеку, перестаёт быть исполнителем одного таска —
    он начинает решать за соседние, а его зона решает, что ему можно трогать.
    Пустой список названных разделов означает «ничего», а не «всё».
    """
    if not named:
        return ""
    want = {_norm(n) for n in named if n}
    out, keep = [], False
    for line in spec.splitlines():
        if line.startswith("#"):
            keep = _norm(line.lstrip("# ")) in want
        if keep:
            out.append(line)
    return "\n".join(out).strip()


def sections_present(spec: str, named: list) -> list:
    """Какие названные разделы спеки в ней не находятся."""
    return [s for s in named if s and _norm(s) not in _norm(spec)]


def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip().lower()


def blockers(state: dict, task: dict, interfaces: str, spec: str,
             test_cmd: str, adr_dir: "Path | None" = None) -> list:
    """Почему этот таск передавать НЕЛЬЗЯ. Пустой список — можно."""
    bad = []
    if not (task.get("requirements") or []):
        bad.append("таск не служит ни одному требованию — это работа, которую "
                   "никто не заказывал; либо привяжи, либо срежь")
    if not (task.get("acceptance") or []):
        bad.append("нет критериев приёмки — исполнитель не узнает, когда "
                   "закончил, и вернёт то, что показалось достаточным")
    if not test_cmd:
        bad.append("не задана команда тестов — «зелёный прогон» будет означать "
                   "«я не запускал»")
    if not (task.get("zone") or []):
        bad.append("нет зоны — границы, за которые нельзя, не названы")

    first = not any(rows(state)) or task["id"] == min(t["id"] for t in rows(state))
    if not interfaces.strip() and not first:
        bad.append("interfaces.md пуст, а таск не первый — архитектуру задаст "
                   "тот, кто увидел одну восьмую задачи, и остальные будут её "
                   "обходить")

    missing = sections_present(spec, task.get("spec_sections") or [])
    if missing:
        bad.append("названы разделы спеки, которых в ней нет: "
                   + ", ".join(missing[:5]))

    # Лазейка, которую надо закрыть явно: проект объявил каталог решений, а
    # передача идёт без него. Тогда исполнитель пишет в зоне, чьё архитектурное
    # решение принято и записано, — и не видит его. Это ровно тот случай, ради
    # которого решения и заводились, и «просто забыли флаг» здесь означает то же
    # самое, что «решения нет».
    declared = state.get("adr_dir")
    if declared and adr_dir is None:
        bad.append(f"проект объявил решения в `{declared}`, а передача идёт без "
                   "них — исполнитель будет писать в зоне, чьё решение принято "
                   "и записано, не увидев его")
    return bad


def holdout_leak(task: dict, prompt: str) -> list:
    """Скрытые проверки, ПРОСОЧИВШИЕСЯ в промпт исполнителя.

    Зачем скрытые проверки вообще. Всё, что исполнитель видит, находится внутри
    его оптимизационной петли: имея критерий, он со временем удовлетворит
    ИМЕННО его — и это не жульничество, а работа по заданию. Значит часть
    проверок обязана остаться снаружи петли, иначе «критерий выполнен» и
    «сделано то, что нужно» перестают быть разными утверждениями.

    Зачем проверять протечку кодом. Скрытность здесь — свойство ТЕКСТА, который
    уходит агенту, а текст собирается из полей таска; одна неосторожная правка
    сборщика — и скрытое поле поедет в промпт, оставаясь скрытым по названию.
    Отказ при этом молчит: прогон зелёный, holdout «прошёл», и никто не узнает,
    что проверка была подсказкой.
    """
    out = []
    for h in (task.get("holdout") or []):
        core = h.strip()
        if len(core) >= 12 and core.lower() in prompt.lower():
            out.append(core[:80])
    return out


def build(state: dict, task: dict, interfaces: str, spec_excerpt: str,
          test_cmd: str, adrs: list = None) -> str:
    """Промпт исполнителю. Обязательные куски вложены здесь, а не вспомнены.

    Поле `holdout` сюда НЕ попадает намеренно: см. `holdout_leak`.
    """
    reqs = ", ".join(task.get("requirements") or [])
    zone = " · ".join(task.get("zone") or [])
    crit = "\n".join(f"- [ ] {c}" for c in (task.get("acceptance") or []))
    quotes = "\n".join(f"> «{q}»" for q in (task.get("quotes") or []))

    parts = [
        f"# Таск {task['id']} — {task.get('name', '')}",
        "",
        f"**Требования:** {reqs}",
        f"**Зона:** {zone}",
        "",
        "## Что должно заработать",
        "",
        task.get("goal") or task.get("name", ""),
    ]
    if quotes:
        # Дословные слова человека стоят около сорока токенов и стоят между
        # свежим контекстом и правдоподобным перетолкованием заказа.
        parts += ["", "## Из брифа, дословно", "", quotes]
    parts += ["", "## Критерии приёмки", "", crit or "—"]
    ruling = governing_adrs(adrs or [], task.get("zone") or [])
    if ruling:
        # Решения идут ДО разделов спеки и до кода: они очерчивают, внутри чего
        # вообще позволено решать. Прочитанные после — уже оправдание сделанного.
        parts += ["", "## Решения, которые правят твоей зоной — отменять нельзя", ""]
        for a in ruling:
            parts += [a["body"].strip(), ""]
    if spec_excerpt.strip():
        parts += ["", "## Разделы спецификации", "", spec_excerpt.strip()]
    parts += [
        "", "## Что уже построено — прочти до начала", "",
        interfaces.strip() or "(пусто — ты первый; границы задаёшь ты)",
        "", "## Как запускать", "", f"Тесты: `{test_cmd}`",
        "", "## Тесты — обязательное", "", TESTING_CONTRACT,
        "", "## Границы", "", BOUNDS,
        "", "## Сколько тебя хватит", "", CEILING,
        "", "## Чем закончить — обязательное", "",
        "Верни ровно этот блок, ничего к нему не добавляя:", "",
        "```", RETURN_CONTRACT, "```",
    ]
    return "\n".join(parts) + "\n"


def halt_if_paused() -> None:
    if os.environ.get("SUPERSTACK_IGNORE_PAUSE") == "1":
        return
    if (Path.home() / ".claude" / "superstack" / "PAUSE").exists():
        print("ОСТАНОВЛЕНО: система на паузе", file=sys.stderr)
        raise SystemExit(10)


def _flag(argv: list, name: str, default=None):
    if name in argv and argv.index(name) + 1 < len(argv):
        return argv[argv.index(name) + 1]
    return default


def main() -> int:
    halt_if_paused()
    argv = sys.argv[1:]
    takes = {"--interfaces", "--spec", "--test-cmd", "--adr"}
    plain, skip = [], False
    for a in argv:
        if skip:
            skip = False
            continue
        if a in takes:
            skip = True
        elif not a.startswith("--"):
            plain.append(a)
    if len(plain) != 2:
        print("вызов: handoff.py <состояние.json> <id> --interfaces X.md "
              "[--spec Y.md] [--test-cmd \"npm test\"]", file=sys.stderr)
        return 3

    try:
        state = json.loads(Path(plain[0]).read_text("utf-8"))
    except (OSError, ValueError) as e:
        print(f"НЕ УДАЛОСЬ: состояние не прочитано: {e}", file=sys.stderr)
        return 3
    task = find_task(state, plain[1])
    if task is None:
        print(f"НЕ УДАЛОСЬ: нет таска {plain[1]}", file=sys.stderr)
        return 3

    def _read(p):
        try:
            return Path(p).read_text("utf-8") if p else ""
        except OSError:
            return ""

    interfaces = _read(_flag(argv, "--interfaces"))
    spec = _read(_flag(argv, "--spec"))
    test_cmd = _flag(argv, "--test-cmd", state.get("test_cmd", ""))

    adr_arg = _flag(argv, "--adr")
    adr_dir = Path(adr_arg) if adr_arg else None
    bad = blockers(state, task, interfaces, spec, test_cmd, adr_dir)
    if bad:
        print("ПЕРЕДАВАТЬ НЕЧЕГО", file=sys.stderr)
        for b in bad:
            print(f"  ! {b}", file=sys.stderr)
        print(json.dumps({"task": task["id"], "status": "fail", "blockers": bad},
                         ensure_ascii=False, indent=1))
        return 1

    prompt = build(state, task, interfaces,
                   extract_sections(spec, task.get("spec_sections") or []),
                   test_cmd, read_adrs(adr_dir))

    # Скрытые проверки сверяются с готовым текстом, а не с намерением его
    # автора: скрытность — свойство того, что уехало агенту.
    leaked = holdout_leak(task, prompt)
    if leaked:
        print("СКРЫТЫЕ ПРОВЕРКИ ПРОСОЧИЛИСЬ", file=sys.stderr)
        for x in leaked:
            print(f"  ! в промпте: «{x}»", file=sys.stderr)
        print("  всё, что исполнитель видит, попадает внутрь его петли: он "
              "удовлетворит именно это, и проверка перестанет быть проверкой",
              file=sys.stderr)
        print(json.dumps({"task": task["id"], "status": "fail",
                          "holdout_leaked": leaked}, ensure_ascii=False, indent=1))
        return 1

    if "--json" in argv:
        print(json.dumps({"task": task["id"], "status": "pass", "prompt": prompt},
                         ensure_ascii=False, indent=1))
    else:
        print(prompt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
