#!/bin/sh
# SUPERSTACK — вход для того, кто не знает, что такое команда.
#
# Целевой человек работает в десктопном приложении и никогда не напечатает
# «/superstack»: он не знает, что такая строка существует. README из четырёх
# строк — тоже мёртвый вход, туда не заходят. Значит первым должен заговорить
# не человек, а система.
#
# Четыре ограничения, без которых напоминание превращается в спам:
#   · не более трёх раз ЗА ВСЁ ВРЕМЯ, потом никогда;
#   · явное «нет» выключает навсегда, не дожидаясь третьего раза;
#   · счётчик не удалось записать -> НЕ печатаем. Напоминание, которое некому
#     сосчитать, повторяется каждую сессию вечно — это худший исход из всех;
#   · только matcher startup: возобновление сессии и компакция — не новый
#     человек, а тот же самый посреди работы.
#
# Хук ничего не запускает и ничего не меняет. Он предлагает. Проверка идёт по
# согласию человека, а не по факту открытия приложения: иначе это не вход,
# а перехват.
#
# Проверить руками:  sh first-run.sh status
# Выключить совсем:  sh first-run.sh done
set -u

MAX=3
STATE="${SUPERSTACK_STATE_DIR:-$HOME/.claude/superstack}"
COUNT="$STATE/first-run.count"
DONE="$STATE/first-run.done"
# Замок на чтение-изменение-запись счётчика. Каталог, а не файл: mkdir —
# единственная атомарная операция, доступная POSIX-оболочке без внешних
# программ. Зачем: несколько окон приложения стартуют одновременно, и без
# замка каждое читает «0», каждое пишет «1» и каждое печатает. Замеряли:
# 8 параллельных стартов давали до 24 предложений вместо трёх.
LOCK="$STATE/first-run.lock"

# Аварийный выключатель — первой строкой, до любой работы. Общее правило для
# всех хуков системы: один экспорт гасит всё разом.
if [ "${SUPERSTACK_DISABLE:-}" = "1" ]; then
  exit 0
fi

read_count() {
  # Нечитаемый или кривой счётчик считается ИСЧЕРПАННЫМ, а не нулевым.
  # Прежняя версия обнуляла лимит на любом мусоре: одна строка «3 sessions»
  # в файле — и человек получал ещё три напоминания, и так каждый раз, пока
  # мусор лежит. Лучше не предложить ни разу, чем предлагать без конца.
  if [ ! -f "$COUNT" ]; then
    printf '0'
    return
  fi
  n=$(cat "$COUNT" 2>/dev/null) || { printf '%s' "$MAX"; return; }
  case "$n" in
    '' | *[!0-9]*) printf '%s' "$MAX"; return ;;
  esac
  printf '%s' "$n"
}

case "${1:-offer}" in
  done)
    # Человек сказал «нет» — это решение, а не пропуск. Подтверждаем только
    # после того, как флаг реально лёг на диск.
    mkdir -p "$STATE" 2>/dev/null || {
      echo "НЕ УДАЛОСЬ: нет доступа к $STATE" >&2
      exit 1
    }
    # 2>/dev/null стоит ПЕРЕД перенаправлением в файл намеренно: оболочка
    # применяет перенаправления слева направо, и жалоба на неудавшееся
    # открытие файла ушла бы человеку раньше, чем её успели заглушить.
    # Своё сообщение мы печатаем сами — чужое «Permission denied» лишнее.
    date -u +%Y-%m-%dT%H:%M:%SZ 2>/dev/null > "$DONE" || {
      echo "НЕ УДАЛОСЬ записать $DONE" >&2
      exit 1
    }
    [ -s "$DONE" ] || {
      echo "НЕ УДАЛОСЬ: флаг пуст после записи" >&2
      exit 1
    }
    echo "больше не предложу"
    exit 0
    ;;

  status)
    if [ -f "$DONE" ]; then
      echo "выключено с $(cat "$DONE" 2>/dev/null)"
    else
      # Кривой счётчик показывается как исчерпанный — ровно так он и
      # трактуется в решении печатать. Показывать «0 из 3» там, где
      # предложений больше не будет, значит врать человеку в лицо.
      echo "предложено $(read_count) из $MAX"
    fi
    exit 0
    ;;
esac

# --- обычный ход: предложить, если ещё можно ------------------------------

if [ -f "$DONE" ]; then
  exit 0
fi

mkdir -p "$STATE" 2>/dev/null || exit 0

# Замок берётся ДО чтения счётчика: проверка и запись обязаны быть одним
# неделимым шагом, иначе лимит держится только на удаче планировщика.
# Не взяли замок — МОЛЧИМ. Заодно это правильное поведение и для застрявшего
# замка (процесс убили между mkdir и rmdir): вечное молчание лучше вечного
# напоминания, а стоимость ошибки — одно непоказанное предложение.
mkdir "$LOCK" 2>/dev/null || exit 0
trap 'rmdir "$LOCK" 2>/dev/null || true' EXIT INT TERM HUP

n=$(read_count)
if [ "$n" -ge "$MAX" ]; then
  exit 0
fi

next=$((n + 1))
# 2>/dev/null снова ПЕРЕД перенаправлением: без этого человек видел
# «Permission denied» на каждом старте сессии — stdout при этом чист,
# то есть хук молчал ровно там, где его слышно, и шумел там, где нет.
printf '%s\n' "$next" 2>/dev/null > "$COUNT" || exit 0

# Печатаем ТОЛЬКО убедившись, что счётчик пережил запись. Успешный вызов
# записи ещё ничего не значит: если файл ведёт в никуда, команда вернёт ноль,
# а счётчик останется прежним — и хук будет предлагать проверку каждую
# сессию до конца времён. Лучше не предложить ни разу.
saved=$(cat "$COUNT" 2>/dev/null || printf '')
if [ "$saved" != "$next" ]; then
  exit 0
fi

# Путь к самому скрипту едет сразу в двух грамматиках, и в обеих ломается
# молча.
#   · ОБОЛОЧКА: каталог этого проекта содержит пробел. Без кавычек
#     напечатанная команда отказа даёт «No such file or directory», rc=127 —
#     то есть единственный способ отказаться от напоминаний мёртв, а человек
#     об этом узнаёт, только попробовав.
#   · JSON: кавычка или обратный слэш в пути ломают разбор ВСЕГО вывода, и
#     хук перестаёт существовать для Claude Code целиком, тоже без единого
#     сообщения.
# Поэтому путь сначала оборачивается в одиночные кавычки для оболочки
# (внутренняя ' -> '\''), а потом экранируется для JSON (\ и ").
# Не обрабатывается: перевод строки внутри пути — такой путь сломает JSON,
# и это здесь не решено.
self_sh=$(printf '%s' "$0" | sed "s/'/'\\\\''/g")
self_sh="'$self_sh'"
self_json=$(printf '%s' "$self_sh" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')

# additionalContext, а не initialUserMessage. initialUserMessage завёл бы
# разговор сам — то есть приписал человеку слова, которых он не говорил,
# и запустил бы работу до согласия. Здесь система получает право заговорить
# первой ровно один раз за сессию и обязана спросить.
#
# JSON собирается вручную: ни python3, ни jq не гарантированы в момент
# старта сессии, а хук, падающий на старте, хуже отсутствующего хука.
printf '{"hookSpecificOutput":{"hookEventName":"SessionStart","additionalContext":"'
printf 'SUPERSTACK (напоминание %s из %s): настройку Claude Code на этом ' "$next" "$MAX"
printf 'компьютере ещё ни разу не проверяли. Сначала ответь на то, с чем '
printf 'пришёл человек, а затем добавь ровно одну строку: могу заодно '
printf 'посмотреть, как настроен твой Claude Code — это минута, менять ничего '
printf 'не буду. Согласится — вызови скилл superstack. Откажется — выполни '
printf 'sh %s done, и больше не предлагай никогда. Без согласия проверку ' "$self_json"
printf 'не запускай и этот текст не пересказывай дословно."}}\n'
exit 0
