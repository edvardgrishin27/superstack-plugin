#!/bin/sh
# SUPERSTACK — страховка памяти на компакции (событие PreCompact).
#
# Момент, в который срабатывает этот хук, — ЕДИНСТВЕННЫЙ шанс что-то спасти.
# Compaction сжимает контекст необратимо: после него детали, которые не были
# сохранены ДО, не восстановить ничем — ни повторным чтением транскрипта
# (его тоже переписывают), ни просьбой «вспомни». Значит хук обязан не
# анализировать и не решать, что важно, а просто скопировать сырой
# транскрипт сессии в сторону, пока он ещё цел. Восстановление из копии —
# задача другого хука (SessionStart), не этого.
#
# ЧТО ХУК ДЕЛАЕТ. Читает JSON события PreCompact со stdin (session_id,
# transcript_path, trigger), копирует файл транскрипта в каталог состояния
# под именем сессии и пишет одну строку метаданных в журнал. Больше ничего:
# не резюмирует, не решает, что «важно», не трогает сам транскрипт на месте.
#
# ЧЕГО ХУК НЕ ДЕЛАЕТ.
#   · Не печатает содержимое разговора ни в stdout, ни в stderr, ни в
#     журнал — только session_id, trigger, время и статус копирования.
#     Разговор пользователя (в том числе секреты, которые он мог туда
#     вставить) уже лежит на диске открытым текстом в transcript_path —
#     это файл самого Claude Code. Хук создаёт вторую копию РЯДОМ, внутри
#     того же каталога состояния пользователя ($SUPERSTACK_STATE_DIR),
#     а не выносит её за пределы этой границы доверия и не печатает её
#     содержимое туда, откуда его мог бы прочитать кто-то посторонний.
#   · Не блокирует компакцию и не может её замедлить дольше отведённого:
#     хук, который думает, превращает сжатие контекста в зависание.
#
# ЧЕТЫРЕ ОГРАНИЧЕНИЯ, общих для всех хуков этой системы:
#   · SUPERSTACK_DISABLE=1 гасит хук ПЕРВОЙ строкой, до чтения stdin и до
#     любой записи на диск;
#   · хук ВСЕГДА выходит кодом 0: PreCompact, уронивший компакцию, хуже
#     отсутствующего хука — человек потерял бы не только память, но и
#     саму компакцию;
#   · ни python3, ни jq не предполагаются установленными в момент
#     компакции — разбор JSON держится на sed по плоской строке;
#   · каталог состояния берётся из SUPERSTACK_STATE_DIR (тесты не должны
#     задевать настоящий ~/.claude), а не хардкодится.
#
# ЧЕГО ЭТОТ ПАРСЕР JSON НЕ УМЕЕТ (и это осознанный пропуск, не забытый):
# экранированные кавычки/бэкслеши внутри значения поля собьют извлечение.
# Реальные поля PreCompact (session_id, transcript_path, trigger) — простые
# идентификаторы и пути без вложенных кавычек, так что это не задевается,
# но полноценным JSON-парсером эта строка не является.
#
# Проверить руками:
#   printf '{"session_id":"s1","transcript_path":"/tmp/t.jsonl","trigger":"auto"}' \
#     | SUPERSTACK_STATE_DIR=/tmp/ss-state sh precompact.sh
set -u

# Аварийный выключатель — до stdin, до диска, до всего.
if [ "${SUPERSTACK_DISABLE:-}" = "1" ]; then
  exit 0
fi

STATE="${SUPERSTACK_STATE_DIR:-${HOME:-/nonexistent}/.claude/superstack}"
DIR="$STATE/precompact"
LOG="$DIR/log"

# Сколько последних снимков сессий держим. Без потолка каталог растёт вечно:
# у активного пользователя компакции идут постоянно, и год работы оставил бы
# на диске сотни забытых копий транскриптов. Оставляем свежие — старые
# сессии восстанавливать всё равно уже некому.
KEEP="${SUPERSTACK_PRECOMPACT_KEEP:-20}"
case "$KEEP" in
  '' | *[!0-9]*) KEEP=20 ;;
esac

# Сколько строк держим в журнале метаданных — тот же довод, что и для KEEP,
# только для журнала: он растёт по одной строке на компакцию бесконечно.
LOG_KEEP="${SUPERSTACK_PRECOMPACT_LOG_KEEP:-500}"
case "$LOG_KEEP" in
  '' | *[!0-9]*) LOG_KEEP=500 ;;
esac

# stdin читаем только если это не терминал: при ручном запуске без
# перенаправления `cat` повис бы навсегда, выглядя как зависший хук.
INPUT=''
if [ ! -t 0 ]; then
  INPUT=$(cat 2>/dev/null || printf '')
fi

# Переносы строк убираются заранее: sed по многострочному вводу ведёт себя
# по-разному в BSD- и GNU-сборках (macOS против Linux), а PreCompact может
# в теории прийти отформатированным. Плоская строка снимает разницу.
FLAT=$(printf '%s' "$INPUT" | tr '\n' ' ')

field() {
  printf '%s' "$FLAT" | sed -n 's/.*"'"$1"'"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p'
}

SESSION_ID=$(field session_id)
TRANSCRIPT=$(field transcript_path)
TRIGGER=$(field trigger)

[ -n "$SESSION_ID" ] || SESSION_ID="unknown"
[ -n "$TRIGGER" ] || TRIGGER="unknown"

# Имя файла на диске собирается из session_id — а он приходит СНАРУЖИ, по
# цепочке из данных, которые не мы порождали. Без очистки значение вроде
# "../../etc/passwd" вывело бы запись за пределы каталога состояния.
# Оставляем только буквы, цифры, дефис и подчёркивание.
SAFE_ID=$(printf '%s' "$SESSION_ID" | tr -cd 'A-Za-z0-9_-')
[ -n "$SAFE_ID" ] || SAFE_ID="unknown"

# Каталог состояния недоступен для записи — молчим и выходим нулём. Хуже
# уронить компакцию из-за диска, которым мы не управляем, не бывает: лучше
# не сохранить снимок один раз, чем сломать ход сессии.
mkdir -p "$DIR" 2>/dev/null || exit 0

TS=$(date -u +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || printf 'unknown')

STATUS="no-transcript"
if [ -n "$TRANSCRIPT" ] && [ -f "$TRANSCRIPT" ] && [ -r "$TRANSCRIPT" ]; then
  DEST="$DIR/$SAFE_ID.jsonl"
  # Пишем во временный файл и переименовываем атомарно: копия, оборванная
  # посреди записи (диск кончился, процесс убили), не должна лечь на место
  # прежнего валидного снимка и выглядеть целой.
  TMP="$DEST.tmp.$$"
  if cp "$TRANSCRIPT" "$TMP" 2>/dev/null; then
    if mv "$TMP" "$DEST" 2>/dev/null; then
      STATUS="saved"
    else
      rm -f "$TMP" 2>/dev/null
      STATUS="write-failed"
    fi
  else
    rm -f "$TMP" 2>/dev/null
    STATUS="copy-failed"
  fi
fi

# Журнал — только метаданные, без содержимого разговора: сам разговор уже
# лежит рядом файлом-копией, дублировать его текст в журнал значит держать
# один и тот же секрет в двух местах вместо одного без всякой пользы.
printf '%s %s %s %s\n' "$TS" "$SAFE_ID" "$TRIGGER" "$STATUS" >> "$LOG" 2>/dev/null || true

# Журнал подрезается тем же приёмом temp+rename, что и снимок выше.
if [ -f "$LOG" ]; then
  n=$(wc -l < "$LOG" 2>/dev/null || printf 0)
  case "$n" in '' | *[!0-9]*) n=0 ;; esac
  if [ "$n" -gt "$LOG_KEEP" ]; then
    LOG_TMP="$LOG.tmp.$$"
    if tail -n "$LOG_KEEP" "$LOG" > "$LOG_TMP" 2>/dev/null; then
      mv "$LOG_TMP" "$LOG" 2>/dev/null || rm -f "$LOG_TMP" 2>/dev/null
    else
      rm -f "$LOG_TMP" 2>/dev/null
    fi
  fi
fi

# Старые снимки чужих (или прошлых) сессий вычищаются — остаются последние
# KEEP по времени изменения. `ls -t` не POSIX, но есть везде, где есть этот
# хук (macOS, Linux); первая строка sed-диапазона — это (KEEP+1)-й файл и
# далее, то есть всё, что старше порога.
if [ -d "$DIR" ]; then
  # shellcheck disable=SC2012
  ls -1t "$DIR"/*.jsonl 2>/dev/null | sed -n "$((KEEP + 1)),\$p" | \
    while IFS= read -r old; do
      [ -n "$old" ] && rm -f "$old" 2>/dev/null
    done
fi

exit 0
