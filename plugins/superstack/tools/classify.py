#!/usr/bin/env python3
"""SUPERSTACK — что это за продукт: выводится из файлов, а не спрашивается.

Зачем это считает машина.

Набор проверок безопасности зависит от вида продукта: магазину нужны деньги и
возвраты, ИИ-продавцу — граница между данными и инструкциями, сайту — формы и
заголовки. Спросить у человека «это SaaS или магазин?» можно, но неразработчик
отвечает наугад — он не знает, чем они различаются ЗДЕСЬ, и его ответ становится
основанием для того, что будет проверено, а что нет.

Ответ уже лежит в его же словах: в документе идеи, в спеке, в зависимостях
проекта. Вопрос, ответ на который есть в файлах, задавать нельзя — это
перекладывание работы на того, кто пришёл за помощью.

Три правила, ради которых это код:

  1. КАЖДЫЙ ВЫВОД НАЗЫВАЕТ УЛИКУ. Не «похоже на магазин», а «слово „оплата“ в
     спеке и stripe в зависимостях». Классификация без улики — гадание с
     уверенным лицом.
  2. СЛАБЫЕ СИГНАЛЫ — ЭТО «НЕ ЗНАЮ». Один намёк видом не делает: код 2 и
     честный вопрос человеку. Угаданный вид тише пропущенного: по нему молча
     не проверят половину.
  3. НАЙДЕНО НЕСКОЛЬКО — ЗНАЧИТ НЕСКОЛЬКО. Магазин с ИИ-помощником это и
     магазин, и ИИ-продавец; выбирать «главный» не нужно, проверки
     складываются.

  python3 classify.py <корень проекта> [--json]

  код 0 — вид определён, 2 — сигналов мало, 3 — ошибка вызова
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

ЧИТАЕМ = (".superstack/idea.md", ".superstack/spec.md", "README.md",
          "package.json", "requirements.txt", "pyproject.toml")

#: Вид → (слова в текстах, имена в зависимостях). Слова подобраны так, чтобы
#: их писал ЧЕЛОВЕК, описывая своё дело, а не разработчик, описывая архитектуру.
ПРИЗНАКИ = {
    "магазин": (("товар", "корзин", "заказ", "оплат", "доставк", "возврат",
                 "чек", "цена"), ("stripe", "yookassa", "cloudpayments", "paddle")),
    "ии-продавец": (("бот", "ассистент", "чат", "подсказыва", "отвеча",
                     "нейросет", "ии-"), ("openai", "anthropic", "langchain",
                                          "llama", "gigachat")),
    "saas": (("подписк", "тариф", "аккаунт", "команда", "личный кабинет",
              "регистрац"), ("supabase", "clerk", "auth0", "nextauth")),
    "приложение": (("мобильн", "андроид", "iphone", "приложение в сторе",
                    "push"), ("react-native", "expo", "flutter", "capacitor")),
    "сайт": (("страниц", "лендинг", "форма", "заявк", "запись", "портфолио",
              "сайт"), ("next", "astro", "vite", "gatsby", "nuxt")),
}

#: Сколько ВЕСА улик нужно, чтобы назвать вид. Одно слово в прозе — намёк:
#: «заказ» встречается и у сайта с формой заявки. Зависимость весит вдвое:
#: библиотеку оплаты не ставят случайно, это поступок, а не слово.
ПОРОГ = 2
ВЕС_ЗАВИСИМОСТИ = 2
ВЕС_СЛОВА = 1


def _тексты(root: Path) -> dict:
    собрано = {}
    for имя in ЧИТАЕМ:
        p = root / имя
        if p.is_file():
            try:
                собрано[имя] = p.read_text("utf-8", errors="replace").lower()
            except OSError:
                continue
    return собрано


def evidence(тексты: dict) -> dict:
    """{вид: [улики]}. Улика — это слово И файл, где оно найдено."""
    найдено: dict = {}
    for вид, (слова, пакеты) in ПРИЗНАКИ.items():
        улики = []
        for имя, текст in тексты.items():
            зависимость = имя in ("package.json", "requirements.txt",
                                  "pyproject.toml")
            словарь = пакеты if зависимость else слова
            for w in словарь:
                if re.search(re.escape(w), текст):
                    улики.append({"word": w, "file": имя,
                                  "вес": ВЕС_ЗАВИСИМОСТИ if зависимость
                                  else ВЕС_СЛОВА})
        # Одно и то же слово в трёх файлах — это одна улика, а не три.
        уникальные, видели = [], set()
        for u in улики:
            if u["word"] in видели:
                continue
            видели.add(u["word"])
            уникальные.append(u)
        if уникальные:
            найдено[вид] = уникальные
    return найдено


def run(root: Path) -> dict:
    тексты = _тексты(root)
    if not тексты:
        return {"status": "unknown",
                "detail": "читать нечего: ни идеи, ни спеки, ни зависимостей",
                "next": "начать с документа идеи — вид продукта выводится из "
                        "слов человека, а не спрашивается у него"}
    улики = evidence(тексты)
    виды = sorted(в for в, у in улики.items()
                  if sum(u["вес"] for u in у) >= ПОРОГ)
    if not виды:
        # Угаданный вид тише пропущенного: по нему молча не проверят половину.
        return {"status": "unknown", "evidence": улики,
                "detail": "сигналов мало — вид продукта не определён",
                "next": "спросить человека прямо: это единственный случай, когда "
                        "вопрос честнее догадки"}
    return {"status": "pass", "kinds": виды,
            "evidence": {в: улики[в] for в in виды},
            "detail": "вид: " + ", ".join(виды),
            "next": "проверки безопасности складываются по всем найденным видам"}


def human(v: dict) -> str:
    if v["status"] != "pass":
        строки = [f"ВИД НЕ ОПРЕДЕЛЁН: {v['detail']}"]
    else:
        строки = [f"ВИД ПРОДУКТА: {v['detail']}"]
        for вид, улики in v["evidence"].items():
            слова = ", ".join(f"«{u['word']}» ({u['file']})" for u in улики[:4])
            строки.append(f"  + {вид}: {слова}")
    if v.get("next"):
        строки.append(f"  дальше: {v['next']}")
    return "\n".join(строки)


def halt_if_paused() -> None:
    if os.environ.get("SUPERSTACK_IGNORE_PAUSE") == "1":
        return
    if (Path.home() / ".claude" / "superstack" / "PAUSE").exists():
        print("ОСТАНОВЛЕНО: система на паузе", file=sys.stderr)
        raise SystemExit(10)


def main() -> int:
    halt_if_paused()
    argv = sys.argv[1:]
    plain = [a for a in argv if not a.startswith("--")]
    if len(plain) != 1:
        print("вызов: classify.py <корень проекта> [--json]", file=sys.stderr)
        return 3
    root = Path(plain[0]).resolve()
    if not root.is_dir():
        print(f"НЕ УДАЛОСЬ: нет каталога {root}", file=sys.stderr)
        return 3
    v = run(root)
    if "--json" not in argv:
        print(human(v), file=sys.stderr)
    print(json.dumps(v, ensure_ascii=False, indent=1))
    return 0 if v["status"] == "pass" else 2


if __name__ == "__main__":
    sys.exit(main())
