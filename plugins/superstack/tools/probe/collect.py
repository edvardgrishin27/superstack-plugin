#: Имена, которые подменяют СНАРУЖИ присваиванием на модуле: `doctor.py`
#: (мод.CLAUDE, мод.CLAUDE_SOURCE, мод.HOME) и около шестидесяти мест в
#: tests/. Впрыснуть такое имя в часть значило бы завести ВТОРОЕ мнение об
#: одном каталоге: подмена дошла бы до ядра и не дошла бы до части — молча, с
#: виду измеренным докладом про чужой профиль. Части берут их через
#: `ЯДРО.<имя>`, то есть читают глобал ядра в момент обращения.
ПОДМЕНЯЕМЫЕ = ("CLAUDE", "CLAUDE_SOURCE", "HOME", "config_dir", "sh",
               "global_config_path", "_settings_files", "TEXT_ASSET_LIMIT",
               "DESKTOP_ASAR")


class _Ядро:
    """Доступ к глобалам ЭТОЙ копии ядра, а не к их значениям на момент импорта."""

    __slots__ = ()

    def __getattr__(self, имя):
        try:
            return globals()[имя]
        except KeyError:
            raise AttributeError(имя) from None


_ЯДРО = _Ядро()


def _подключить(имя: str):
    """Загрузить часть сборщика ПО ПУТИ и поднять её имена к себе.

    Почему не обычный `import`, как двумя каталогами выше у `apply.py`. Этот
    модуль живёт в процессе НЕСКОЛЬКИМИ независимыми копиями: `doctor.py`,
    `what.py`, `settings_copy.py`, `checkpoint.py` и семь загрузчиков в
    tests/ грузят его через `spec_from_file_location`, не регистрируя в
    `sys.modules`, и каждая копия читает свой каталог настроек. Общая запись
    в `sys.modules` склеила бы части между копиями: последняя загруженная
    копия ядра стала бы ЯДРОм для всех, и подмена каталога в одной копии
    молча доехала бы до соседней. Поэтому часть грузится так же — по пути и
    без регистрации.

    Отказ здесь — `SystemExit`, а не пропуск: `main` глушит исключение пробы
    в факт `error.*` и НЕ трогает код возврата, то есть недополученное имя
    дало бы отчёт без нескольких проверок при нулевом коде. Третьего
    состояния — «часть загрузилась, но чего-то не получила» — не бывает.
    """
    путь = Path(__file__).resolve().parent / (имя + ".py")
    спец = importlib.util.spec_from_file_location("ss_probe_" + имя, путь)
    часть = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(часть)
    часть.ЯДРО = _ЯДРО
    for н in часть.НУЖНО_ИЗ_ЯДРА:
        if н in ПОДМЕНЯЕМЫЕ:
            raise SystemExit(f"ОТКАЗ: {имя} просит впрыском подменяемое имя "
                             f"{н} — такое берут только через ЯДРО.{н}")
        if н not in globals():
            raise SystemExit(f"ОТКАЗ: {имя} просит {н}, которого в ядре нет")
        setattr(часть, н, globals()[н])
    for н in часть.ОТДАЁТ:
        if not hasattr(часть, н):
            raise SystemExit(f"ОТКАЗ: {имя} обещал отдать {н}, но не отдал")
        globals()[н] = getattr(часть, н)
    return часть


