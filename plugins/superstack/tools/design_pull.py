#!/usr/bin/env python3
"""SUPERSTACK — дизайн ПОДТЯГИВАЕТСЯ в код, а не пересказывается словами.

Что этот инструмент закрывает.

Фаза 2.5 требовала: человек уходит в дизайн-инструмент, возвращается с
результатом, агент переводит результат в токены. Последний шаг держался на
честности агента. Он читал дизайн глазами и писал в спеку четыре цвета — и
никто, включая человека, не мог отличить цвет, ВЗЯТЫЙ из дизайна, от цвета,
подобранного агентом «примерно такой же». Ровно эта подмена уже случалась
живьём: палитру `#0a0a0c / #f2f2f4 / #86868f / #6355d9` выбрал строитель, она
случайно вышла похожей на ориентир, и это заметили только потому, что смотрели.

Теперь дизайн живёт файлами в рабочем дереве — артбордами `*.dc.html` холста
Claude Design, — и значение, объявленное в спеке, обязано БУКВАЛЬНО ВСТРЕЧАТЬСЯ
в артборде. Не встречается — его выбрал не человек, и передача интерфейсного
таска не состоится. Это и есть разница между «дизайн принесён» как утверждением
и как кодом возврата.

Что здесь проверяется и почему именно это.

  ОТКАЗ (код 1) — только там, где код знает больше человека:
    · объявлен цвет, которого в дизайне нет — значит он придуман;
    · ролей не четыре или они не те — «ровно четыре с ролями» перестаёт быть
      критерием, как только роли необязательны;
    · контраст текста к фону ниже 4.5:1, приглушённого — ниже 3:1: это
      вычисленный факт, а не вкус;
    · семейств шрифта больше двух — счётная величина из той же таблицы.

  НАБЛЮДЕНИЕ (печатается, но не валит) — там, где спорить с утверждённым
  дизайном не наше дело: ступеней кегля больше пяти, ритм не кратен 4px,
  картинки без размеров. Эти числа идут в спеку как есть; решает человек.

  ЧЕГО ВОРОТА НЕ ПРОВЕРЯЮТ — печатается ВСЕГДА, даже на зелёном. Артборд
  статичен: наведение, фокус и нажатие в нём нарисованы отдельными досками, а
  движение не существует вовсе. Зелёный, прочитанный как «дизайн проверен
  целиком», хуже красного: он закрывает вопрос, который не открывали.

  ПРОВЕРЯТЬ НЕЧЕМ (код 2) — артбордов нет. Так выглядит второй путь фазы:
  человек принёс дизайн из внешнего инструмента скриншотами. Тогда числа в
  спеке держатся на слове агента, и это обязано быть сказано, а не выглядеть
  как пройденная проверка.

  python3 design_pull.py <каталог>              величины из дизайна — в спеку
  python3 design_pull.py <каталог> --check      гейт: годен / не годен
  python3 design_pull.py <каталог> --check --tokens <файл.json>
  python3 design_pull.py <каталог> --json       машинный вывод
  python3 design_pull.py <каталог> --record extract|утверждён --canvas <url>
                                               откуда взялись доски

  коды: 0 — годен, 1 — не годен, 2 — проверять нечем, 3 — ошибка вызова
"""
from __future__ import annotations

import json
import math
import re
import sys
from pathlib import Path

#: Роли ровно эти и ровно столько. Пятая роль — это шестая, седьмая и палитра
#: без иерархии; четвёртой недостающей роли не бывает: у фона, текста,
#: приглушённого и акцента разные работы, и лишившись одной, её работу делает
#: соседняя наугад.
РОЛИ = ("фон", "текст", "приглушённый", "акцент")

#: ОТКУДА взялись доски. Черновик агента и дизайн, утверждённый человеком,
#: выглядят на диске одинаково — оба лежат файлами в рабочем дереве. Разница
#: невосстановима задним числом, поэтому она записывается в момент, когда
#: известна, и без неё гейт не зелёный: «нарисовал сам и сам себе одобрил» не
#: имеет права быть неотличимым от «человек открыл холст и поправил руками».
ОТКУДА = {
    "extract": "прочитано обратно из холста ПОСЛЕ правок человека",
    "утверждён": "человек открыл опубликованный холст и принял как есть",
}

КОНТРАСТ_ТЕКСТ = 4.5
КОНТРАСТ_ПРИГЛУШЁННЫЙ = 3.0
СЕМЕЙСТВ = 2
СТУПЕНЕЙ = 5
РИТМ = 4

#: Родовые имена не считаются семейством: `sans-serif` в хвосте стека — это
#: запасной вариант, а не выбор дизайнера. Считать их значило бы валить ворота
#: на каждом честном стеке шрифтов.
РОДОВЫЕ = {
    "sans-serif", "serif", "monospace", "cursive", "fantasy", "system-ui",
    "ui-sans-serif", "ui-serif", "ui-monospace", "ui-rounded", "math",
    "emoji", "fangsong", "-apple-system", "blinkmacsystemfont",
    "inherit", "initial", "unset", "revert", "currentcolor",
}

ЧЕГО_НЕ_ПРОВЕРЯЕМ = (
    "состояния (наведение, фокус, нажатие) — на статичном артборде их видно "
    "только если нарисованы отдельной доской",
    "движение и его гашение при prefers-reduced-motion — в артборде движения нет",
    "как это поведёт себя вживую: артборд не верстка, а картинка разметкой",
)

_HEX = re.compile(r"#[0-9a-fA-F]{3,8}(?![0-9a-fA-F])")
_ФУНК = re.compile(r"\b(?:rgba?|hsla?|oklch|oklab)\(\s*[^()]*?\)", re.I)
# Кавычки внутри значения НЕ исключаются из захвата: имя шрифта с
# пробелом пишется в кавычках (`'Söhne', sans-serif`), и класс,
# запрещающий кавычку, обрывал захват на первом же таком имени —
# семейств оказывалось ноль там, где их два. Обрывают захват `;`,
# `}`, `>` и конец строки: дальше идёт уже не значение свойства.
_СЕМЬЯ = re.compile(r"font-family\s*:\s*([^;}>\n]+)", re.I)
_КЕГЛЬ = re.compile(r"font-size\s*:\s*([0-9.]+)(px|rem|em)", re.I)
_ОТСТУП = re.compile(
    r"(?:padding|margin|gap|row-gap|column-gap)[a-z-]*\s*:\s*([^;}\"']+)", re.I)
_ЧИСЛО_PX = re.compile(r"(-?[0-9.]+)px")
_КАРТИНКА = re.compile(r"<img\b[^>]*>", re.I)


def нормальный(цвет: str) -> str:
    """Одно и то же значение, записанное по-разному, — одно значение.

    `#0A0A0C` и `#0a0a0c`, `rgb(10, 10, 12)` и `rgb(10 10 12)` различаются
    только записью. Без нормализации проверка «объявленное встречается в
    дизайне» проваливалась бы на регистре — то есть ровно там, где всё верно.
    """
    c = цвет.strip().lower()
    if c.startswith("#"):
        h = c[1:]
        if len(h) in (3, 4):
            h = "".join(ch * 2 for ch in h)
        return "#" + h
    c = re.sub(r"[\s,]+", " ", c)
    return c.replace("( ", "(").replace(" )", ")")


def _канал(v: float) -> float:
    v = max(0.0, min(255.0, v)) / 255.0
    return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4


def _из_oklch(L: float, C: float, H: float) -> float:
    """OKLCH → яркость по WCAG. Переход точный, а не приблизительный.

    Токены в oklch — не экзотика: так их пишут в свежих проектах. Отказ считать
    их означал бы, что контраст не проверяется ровно там, где палитра новее.
    """
    h = math.radians(H)
    a, b = C * math.cos(h), C * math.sin(h)
    l_ = L + 0.3963377774 * a + 0.2158037573 * b
    m_ = L - 0.1055613458 * a - 0.0638541728 * b
    s_ = L - 0.0894841775 * a - 1.2914855480 * b
    l, m, s = l_ ** 3, m_ ** 3, s_ ** 3
    r = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    bl = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
    зажать = lambda x: 0.0 if x < 0 else (1.0 if x > 1 else x)   # noqa: E731
    return 0.2126 * зажать(r) + 0.7152 * зажать(g) + 0.0722 * зажать(bl)


def _из_hsl(H: float, S: float, L: float) -> "tuple | None":
    """HSL → sRGB. Формат живой: так пишут палитры в половине шаблонов.

    Без перевода контраст на таком токене остался бы «не вычислен» — то есть
    самый частый случай попадал бы в непроверенные.
    """
    c = (1 - abs(2 * L - 1)) * S
    x = c * (1 - abs(((H / 60.0) % 2) - 1))
    m = L - c / 2
    сектор = int((H % 360) // 60)
    таблица = ((c, x, 0), (x, c, 0), (0, c, x), (0, x, c), (x, 0, c), (c, 0, x))
    r, g, b = таблица[сектор]
    return ((r + m) * 255, (g + m) * 255, (b + m) * 255)


def _части(внутри: str) -> list:
    return [p for p in re.split(r"[ /]+", внутри.strip()) if p and p != "/"]


def _вещественное(s: str, из_ста: bool = False) -> "float | None":
    s = s.strip().rstrip("deg").strip()
    try:
        if s.endswith("%"):
            v = float(s[:-1])
            return v / 100.0 if из_ста else v * 255.0 / 100.0
        return float(s)
    except ValueError:
        return None


def яркость(цвет: str) -> "float | None":
    """Относительная яркость по WCAG. Не смогли разобрать — None, а не ноль.

    Ноль вместо «не знаю» — это чёрный: контраст к белому фону вышел бы 21:1, и
    непонятый цвет проезжал бы ворота с лучшим возможным результатом.
    """
    c = нормальный(цвет)
    if c.startswith("#"):
        h = c[1:]
        if len(h) not in (6, 8):
            return None
        try:
            r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
        except ValueError:
            return None
        return 0.2126 * _канал(r) + 0.7152 * _канал(g) + 0.0722 * _канал(b)
    m = re.match(r"rgba?\((.*)\)$", c)
    if m:
        ч = _части(m.group(1))
        if len(ч) < 3:
            return None
        n = [_вещественное(x) for x in ч[:3]]
        if any(x is None for x in n):
            return None
        return 0.2126 * _канал(n[0]) + 0.7152 * _канал(n[1]) + 0.0722 * _канал(n[2])
    m = re.match(r"hsla?\((.*)\)$", c)
    if m:
        ч = _части(m.group(1))
        if len(ч) < 3:
            return None
        H = _вещественное(ч[0])
        S = _вещественное(ч[1], из_ста=True)
        L = _вещественное(ч[2], из_ста=True)
        if H is None or S is None or L is None:
            return None
        rgb = _из_hsl(H, S, L)
        return (0.2126 * _канал(rgb[0]) + 0.7152 * _канал(rgb[1])
                + 0.0722 * _канал(rgb[2]))
    m = re.match(r"oklch\((.*)\)$", c)
    if m:
        ч = _части(m.group(1))
        if len(ч) < 3:
            return None
        L = _вещественное(ч[0], из_ста=True)
        C = _вещественное(ч[1])
        H = _вещественное(ч[2])
        if L is None or C is None or H is None:
            return None
        return _из_oklch(L, C, H)
    return None


def контраст(a: str, b: str) -> "float | None":
    la, lb = яркость(a), яркость(b)
    if la is None or lb is None:
        return None
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def артборды(каталог: Path) -> dict:
    """Доски холста. Порядок устойчивый: вывод не должен плясать между запусками."""
    if not каталог.is_dir():
        return {}
    out = {}
    for f in sorted(каталог.glob("*.dc.html")):
        try:
            out[f.name] = f.read_text("utf-8", errors="replace")
        except OSError:
            continue
    return out


def цвета(текст: str) -> list:
    найдено = [нормальный(x) for x in _HEX.findall(текст)]
    найдено += [нормальный(x) for x in _ФУНК.findall(текст)]
    видели, итог = set(), []
    for c in найдено:
        if c not in видели:
            видели.add(c)
            итог.append(c)
    return итог


def семейства(текст: str) -> list:
    итог = []
    for стек in _СЕМЬЯ.findall(текст):
        первое = стек.split(",")[0].strip().strip("'\"").lower()
        if первое and первое not in РОДОВЫЕ and первое not in итог:
            итог.append(первое)
    return итог


def кегли(текст: str) -> list:
    шаги = set()
    for величина, единица in _КЕГЛЬ.findall(текст):
        try:
            v = float(величина)
        except ValueError:
            continue
        шаги.add(round(v * 16 if единица.lower() in ("rem", "em") else v, 2))
    return sorted(шаги)


def мимо_ритма(текст: str) -> list:
    """Отступы, не кратные шагу. Ноль и отрицательные — не нарушение."""
    плохие = set()
    for кусок in _ОТСТУП.findall(текст):
        for ч in _ЧИСЛО_PX.findall(кусок):
            try:
                v = float(ч)
            except ValueError:
                continue
            if v > 0 and v % РИТМ != 0:
                плохие.add(v)
    return sorted(плохие)


def картинки_без_размеров(текст: str) -> int:
    сколько = 0
    for тег in _КАРТИНКА.findall(текст):
        if not (re.search(r"\bwidth\s*=", тег, re.I)
                and re.search(r"\bheight\s*=", тег, re.I)):
            сколько += 1
    return сколько


def величины(доски: dict) -> dict:
    весь = "\n".join(доски.values())
    return {
        "артборды": sorted(доски),
        "цвета": цвета(весь),
        "семейства": семейства(весь),
        "ступени_кегля": кегли(весь),
        "мимо_ритма": мимо_ритма(весь),
        "картинки_без_размеров": картинки_без_размеров(весь),
    }


def _токены(каталог: Path, путь: "Path | None") -> "dict | None":
    f = путь or (каталог / "tokens.json")
    if not f.is_file():
        return None
    try:
        d = json.loads(f.read_text("utf-8"))
    except (OSError, ValueError):
        return None
    return d if isinstance(d, dict) else None


def отметка(каталог: Path) -> "dict | None":
    f = каталог / "pulled.json"
    if not f.is_file():
        return None
    try:
        d = json.loads(f.read_text("utf-8"))
    except (OSError, ValueError):
        return None
    return d if isinstance(d, dict) else None


def правились_после(каталог: Path) -> list:
    """Доски, изменённые ПОЗЖЕ отметки.

    Отметка стареет молча: агент записал «человек утвердил», потом поправил
    доску — и гейт продолжает подтверждать одобрение того, чего человек не
    видел. Сравнение времён стоит один вызов stat и ловит ровно это.
    """
    f = каталог / "pulled.json"
    try:
        порог = f.stat().st_mtime
    except OSError:
        return []
    поздние = []
    for д in sorted(каталог.glob("*.dc.html")):
        try:
            if д.stat().st_mtime > порог + 1:
                поздние.append(д.name)
        except OSError:
            continue
    return поздние


def записать_отметку(каталог: Path, откуда: str, холст: str) -> int:
    """Отметка ставится КОДОМ и только с названным холстом.

    Ссылка обязательна: без неё «человек утвердил» — утверждение ни о чём,
    проверить которое нельзя даже вручную.
    """
    if откуда not in ОТКУДА:
        print("НЕ ЗАПИСАНО: --record принимает только "
              + " или ".join(ОТКУДА), file=sys.stderr)
        return 3
    if not холст.strip():
        print("НЕ ЗАПИСАНО: не назван холст (--canvas <ссылка>) — без него "
              "«человек видел» проверить нечем", file=sys.stderr)
        return 3
    if not каталог.is_dir():
        print(f"НЕ ЗАПИСАНО: нет каталога {каталог}", file=sys.stderr)
        return 3
    import datetime as dt
    когда = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    (каталог / "pulled.json").write_text(
        json.dumps({"откуда": откуда, "когда": когда, "холст": холст.strip()},
                   ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"отмечено: {откуда} — {ОТКУДА[откуда]}; холст {холст.strip()}")
    return 0


def проверить(каталог: Path, путь_токенов: "Path | None" = None) -> dict:
    """Вердикт. Отказ — только там, где код знает больше человека."""
    доски = артборды(каталог)
    if not доски:
        return {"код": 2, "отказы": [], "наблюдения": [],
                "величины": {}, "токены": None, "отметка": None,
                "почему": f"артбордов *.dc.html в {каталог} нет — "
                          "дизайн сюда не подтянут, и числа в спеке держатся "
                          "на слове агента"}

    v = величины(доски)
    отказы, наблюдения = [], []

    if "Main.dc.html" not in доски:
        отказы.append("нет Main.dc.html — главной доски холста; какой экран "
                      "главный, читатель определит на глаз, и определит иначе")

    if len(v["семейства"]) > СЕМЕЙСТВ:
        отказы.append(
            f"семейств шрифта {len(v['семейства'])} при потолке {СЕМЕЙСТВ}: "
            + ", ".join(v["семейства"]))

    отм = отметка(каталог)
    if отм is None:
        отказы.append(
            "нет pulled.json — неизвестно, откуда доски: твой черновик и "
            "дизайн, утверждённый человеком, на диске выглядят одинаково")
    elif отм.get("откуда") not in ОТКУДА:
        отказы.append(
            f"откуда доски — «{отм.get('откуда')}»; так не бывает: "
            + " или ".join(ОТКУДА))
    elif not str(отм.get("холст") or "").strip():
        отказы.append("в pulled.json не назван холст — «человек видел» "
                      "проверить нечем")
    else:
        поздние = правились_после(каталог)
        if поздние:
            отказы.append(
                "доски правились ПОСЛЕ отметки: " + ", ".join(поздние[:5])
                + " — человек утвердил не это")

    токены = _токены(каталог, путь_токенов)
    if токены is None:
        отказы.append("нет tokens.json с ролями цветов — цвет без роли не "
                      "переносится в код: его каждый раз выбирают заново")
    else:
        лишние = [k for k in токены if k not in РОЛИ]
        нет = [r for r in РОЛИ if r not in токены]
        if нет or лишние:
            отказы.append(
                "роли не те: нужно ровно " + ", ".join(РОЛИ)
                + ("; не хватает: " + ", ".join(нет) if нет else "")
                + ("; лишние: " + ", ".join(лишние) if лишние else ""))
        в_дизайне = set(v["цвета"])
        for роль in РОЛИ:
            значение = токены.get(роль)
            if not isinstance(значение, str):
                continue
            if нормальный(значение) not in в_дизайне:
                отказы.append(
                    f"объявлен цвет, которого в дизайне НЕТ: {роль} "
                    f"{значение} — его выбрал не человек")
        пары = ((("текст", "фон"), КОНТРАСТ_ТЕКСТ),
                (("приглушённый", "фон"), КОНТРАСТ_ПРИГЛУШЁННЫЙ))
        for (а, б), порог in пары:
            если = контраст(str(токены.get(а, "")), str(токены.get(б, "")))
            if если is None:
                наблюдения.append(
                    f"контраст {а}/{б} не вычислен: значение в записи, которую "
                    "не разобрать — проверено НЕ БЫЛО")
            elif если < порог:
                отказы.append(
                    f"контраст {а} к фону {если:.2f}:1 при пороге {порог}:1")

    if len(v["ступени_кегля"]) > СТУПЕНЕЙ:
        наблюдения.append(
            f"ступеней кегля {len(v['ступени_кегля'])} при критерии {СТУПЕНЕЙ}: "
            + ", ".join(f"{x:g}" for x in v["ступени_кегля"]))
    if v["мимо_ритма"]:
        наблюдения.append(
            f"отступы мимо шага {РИТМ}px: "
            + ", ".join(f"{x:g}" for x in v["мимо_ритма"][:8]))
    if v["картинки_без_размеров"]:
        наблюдения.append(
            f"картинок без width/height: {v['картинки_без_размеров']} — "
            "на верстке это сдвиг вёрстки при загрузке")

    return {"код": 1 if отказы else 0, "отказы": отказы,
            "наблюдения": наблюдения, "величины": v, "токены": токены,
            "отметка": отм, "почему": ""}


def _печать(итог: dict, каталог: Path) -> None:
    if итог["код"] == 2:
        print(f"ПРОВЕРЯТЬ НЕЧЕМ: {итог['почему']}", file=sys.stderr)
        return
    v = итог["величины"]
    print(f"дизайн: {каталог}")
    print(f"  досок: {len(v['артборды'])} — " + ", ".join(v["артборды"]))
    print(f"  цветов в дизайне: {len(v['цвета'])} — " + ", ".join(v["цвета"][:12]))
    print(f"  семейств шрифта: {len(v['семейства'])} — "
          + (", ".join(v["семейства"]) or "не объявлены"))
    print(f"  ступеней кегля: {len(v['ступени_кегля'])} — "
          + ", ".join(f"{x:g}" for x in v["ступени_кегля"]))
    отм = итог.get("отметка") or {}
    if отм.get("откуда") in ОТКУДА:
        print(f"  откуда: {отм['откуда']} — {ОТКУДА[отм['откуда']]}")
        print(f"  холст: {отм.get('холст', '—')}")
    if итог["токены"]:
        for роль in РОЛИ:
            print(f"  {роль}: {итог['токены'].get(роль, '—')}")
    for н in итог["наблюдения"]:
        print(f"  наблюдение: {н}")
    # Печатается ВСЕГДА, в том числе на зелёном: зелёный, прочитанный как
    # «дизайн проверен целиком», закрывает вопрос, который не открывали.
    print("  НЕ ПРОВЕРЕНО здесь:")
    for x in ЧЕГО_НЕ_ПРОВЕРЯЕМ:
        print(f"    · {x}")
    for о in итог["отказы"]:
        print(f"ОТКАЗ: {о}", file=sys.stderr)


def main(argv: list) -> int:
    аргументы = [a for a in argv if not a.startswith("--")]
    if not аргументы:
        print("вызов: design_pull.py <каталог> [--check] [--tokens f.json] "
              "[--json]", file=sys.stderr)
        return 3
    каталог = Path(аргументы[0])
    путь = None
    if "--tokens" in argv:
        i = argv.index("--tokens")
        if i + 1 >= len(argv):
            print("--tokens без файла", file=sys.stderr)
            return 3
        путь = Path(argv[i + 1])
        if not путь.is_file():
            print(f"нет файла токенов: {путь}", file=sys.stderr)
            return 3

    if "--record" in argv:
        i = argv.index("--record")
        откуда = argv[i + 1] if i + 1 < len(argv) else ""
        холст = ""
        if "--canvas" in argv:
            j = argv.index("--canvas")
            холст = argv[j + 1] if j + 1 < len(argv) else ""
        return записать_отметку(каталог, откуда, холст)

    итог = проверить(каталог, путь)
    if "--json" in argv:
        print(json.dumps(итог, ensure_ascii=False, indent=1))
    else:
        _печать(итог, каталог)
    return итог["код"] if "--check" in argv else (2 if итог["код"] == 2 else 0)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
