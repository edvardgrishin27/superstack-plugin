#!/usr/bin/env python3
"""SUPERSTACK — слепая приёмка: сделали ли ТО, о чём просили.

Чего не делает ни один другой гейт. Верификация отвечает «работает ли»,
мутации — «держатся ли тесты», планка — «построено ли». Ни один не отвечает
на вопрос «то ли это». Безупречно сделанное НЕ ТО проходит все шесть ворот.

Почему судью надо ослепить. Спека, план и тикеты — это уже ПЕРЕСКАЗ просьбы,
сделанный тем, кто её понял. Если расхождение возникло на этом шаге, оно
одинаково живёт и в спеке, и в коде: судья, читающий спеку, сверяет пересказ
с пересказом и всегда находит совпадение. Единственный способ поймать дрейф —
дать судье ИСХОДНУЮ просьбу и результат, и больше ничего.

Здесь слепота — свойство ПАКЕТА, а не обещание в инструкции. Скрипт собирает
ровно две вещи и вырезает из изменений сами артефакты пересказа. Инструкция
«не подглядывай в спеку» механизмом не является: подглядывание нечем проверить,
а невключённое нечем прочитать.

Три правила, без которых приёмка становится театром:

  1. НЕТ ИСХОДНОЙ ПРОСЬБЫ — НЕТ ПРИЁМКИ. Не «прошло» и не «провалено», а
     «не смог проверить», код 2. Судить соответствие нечему, если не сохранено,
     о чём просили.
  2. ВЫРЕЗАННОЕ НАЗЫВАЕТСЯ. Пакет перечисляет, какие файлы не показаны судье
     и почему. Молча урезанный вход — это чужой вердикт о чужой работе.
  3. СКРИПТ ГАРАНТИРУЕТ СЛЕПОТУ, НЕ ПРАВОТУ. Вердикт выносит модель, и он
     остаётся мнением. Механизм отвечает лишь за то, что мнение сформировано
     не по пересказу.

  python3 blind_accept.py pack <просьба.txt> <изменения.diff>   -> пакет судье
  python3 blind_accept.py pack --json ...                       -> только JSON

  код 0 — пакет собран, 1 — слепота нарушена, 2 — нечем судить, 3 — вызов
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

MAX_DIFF = 200_000        # знаков изменений: длиннее судья не читает, а листает

#: Артефакты ПЕРЕСКАЗА. Их судья не видит никогда — в них живёт то же
#: расхождение, что и в коде, и совпадение с ними ничего не доказывает.
RETELLING = (
    re.compile(r"(?:^|/)\.claude/specs?/", re.I),
    re.compile(r"(?:^|/)(?:SPEC|ТЗ|PLAN|ПЛАН|ROADMAP)[\w.-]*\.md$", re.I),
    re.compile(r"(?:^|/)\.planning/", re.I),
    re.compile(r"(?:^|/)(?:tasks?|tickets?|issues?)/[\w.-]+\.(?:md|json|ya?ml)$", re.I),
    re.compile(r"(?:^|/)PLAN\.md$", re.I),
    re.compile(r"(?:^|/)REVIEW\.md$", re.I),
    # Наш собственный рабочий каталог. Он попал сюда позже остальных и по самому
    # неприятному поводу: список ловил чужие форматы пересказа — `.planning/`,
    # `PLAN.md`, тикеты — и не ловил СВОЙ. Манифест требований, состояние плана,
    # границы модулей и отчёты ревью лежат в `.superstack/`, все они являются
    # пересказом просьбы, и ни один под прежние правила не подпадал. Судья
    # получил бы моё прочтение брифа и сверял бы пересказ с пересказом — то
    # есть ровно то, против чего написан весь этот файл.
    re.compile(r"(?:^|/)\.superstack/", re.I),
)

#: Следы пересказа в ТЕЛЕ изменений, а не в путях. Файл может называться как
#: угодно и нести внутри идентификаторы манифеста или куски спеки — например,
#: тест, в комментарии которого выписан критерий приёмки словами спецификации.
#:
#: Слова-маркеры пересказа. Используются дважды: как самостоятельный след
#: (см. LEAKS ниже) и как контекст, отличающий идентификатор манифеста от
#: случайного совпадения формы — см. _MANIFEST_ID.
_RETELLING_PHRASE = re.compile(
    r"(?:манифест требований|критери[йи] приёмк|acceptance criteri|"
    r"из спеки|по спецификации)", re.I)

#: Идентификатор строки манифеста: буква R/G/A/D, две цифры и необязательный
#: суффикс уточнения `i`. Та же самая форма встречается и вне манифеста —
#: кубик в настолке (D20), место в брони (A12), hex-цвет в CSS (#A00, #D12),
#: номер релиза (R02). Отличить их нечем, КРОМЕ контекста, поэтому это
#: совпадение засчитывается протечкой только если рядом, В ТОЙ ЖЕ СТРОКЕ
#: diff-а, действительно звучит пересказ: фраза-маркер выше или путь
#: `.superstack`. Строка — минимальная единица «рядом», которую можно
#: проверить детерминированно, без НЛП и догадок; без этого сужения любое
#: приложение с собственной буквенно-цифровой нотацией не собрало бы пакет
#: ни разу. Проверка контекста — в leaks_in(), а не здесь: паттерну самому
#: по себе взять строку целиком неоткуда.
_MANIFEST_ID = re.compile(r"\b[RGAD]\d{2}i?\b")

#: Путь рабочего каталога прогона. Само упоминание — протечка почти всегда,
#: КРОМЕ игнор-файлов вроде `.gitignore` (см. _IGNORE_FILE) — там ему точно
#: положено быть, и это не пересказ просьбы, а техническая строка.
_RUN_DIR = re.compile(r"\.superstack/")

LEAKS = (
    (_RUN_DIR, "путь рабочего каталога прогона"),
    (_MANIFEST_ID, "идентификатор строки манифеста"),
    (_RETELLING_PHRASE, "ссылка на пересказ просьбы"),
)

#: Файлы-списки исключений: путь-паттерн на строку, без прозы. Описать в них
#: манифест или критерии приёмки словами физически нечем — формат файла это
#: не поддерживает. Сборщик продукта сам вписывает туда `.superstack/`, как
#: и любой другой служебный каталог, поэтому такое упоминание — не протечка
#: пересказа, а обычная строка настройки. Исключение — по ИМЕНИ ФАЙЛА и
#: только для пути `.superstack/`: остальные LEAKS внутри `.gitignore`
#: (например, случайная фраза-маркер в комментарии) по-прежнему ловятся.
_IGNORE_FILE = re.compile(r"(?:^|/)\.gitignore$")

#: Служебное начало строки-границы между файлами. Ловится ЛЮБАЯ такая
#: строка, включая ту, которую разобрать не удалось: неопознанная граница
#: обязана остаться видимой, а не слиться с телом предыдущего файла.
_HEADER = "diff --git "
_HEADER_LINE = re.compile(r"^diff --git .*$", re.M)

#: Путь в кавычках. Git берёт половину заголовка в кавычки, как только в
#: имени есть кавычка, обратный слэш или управляющий символ, — а по
#: умолчанию ещё и любая не-ASCII буква, и тогда её байты печатаются
#: восьмеричными последовательностями: `"a/\320\242\320\227.md"`. Кириллица
#: попадает под последнее правило ВСЕГДА, а здесь и у тех, для кого продукт
#: написан, кириллическое имя — норма: `ТЗ.md`, `Спека.md`, `Требования.md`.
_QUOTED = re.compile(r'"(?:[^"\\]|\\.)*"')

#: Однобуквенные обозначения, которыми git печатает управляющие символы.
#: Всё остальное он печатает восьмеричным `\nnn` — ПО БАЙТУ, а не по букве.
_ESCAPE = {"a": 7, "b": 8, "t": 9, "n": 10, "v": 11, "f": 12, "r": 13,
           '"': 34, "\\": 92}
_OCTAL = "01234567"


def is_retelling(path: str) -> bool:
    """Является ли файл пересказом просьбы, а не результатом работы."""
    return any(rx.search(path) for rx in RETELLING)


def unquote_name(token: str) -> "str | None":
    """Имя файла из того, как его напечатал git, — или None, если не вышло.

    Восстанавливаются БАЙТЫ, и только из них собирается строка: `\\320\\242` —
    это два байта одной буквы «Т», и по отдельности ни один из них буквой
    не является.

    None здесь — не мелочь и не «почти получилось». Догадка об имени,
    которое не разобралось, тише отказа и дороже него: под угаданным именем
    кусок либо покажут судье, либо вырежут, и оба решения будут приняты
    вслепую.
    """
    if len(token) < 2 or not token.startswith('"') or not token.endswith('"'):
        return None
    байты = bytearray()
    i, конец = 1, len(token) - 1
    while i < конец:
        if token[i] != "\\":
            байты.extend(token[i].encode("utf-8"))
            i += 1
            continue
        i += 1
        знак, тройка = token[i:i + 1], token[i:i + 3]
        if знак in _ESCAPE:
            байты.append(_ESCAPE[знак])
            i += 1
        elif len(тройка) == 3 and all(c in _OCTAL for c in тройка):
            байты.append(int(тройка, 8))
            i += 3
        else:
            return None
    try:
        return байты.decode("utf-8")
    except UnicodeDecodeError:
        return None


def _half(token: str, приставка: str) -> "str | None":
    """Половина заголовка: путь без служебной приставки `a/` или `b/`."""
    if token.startswith('"'):
        token = unquote_name(token)
        if token is None:
            return None
    if not token.startswith(приставка):
        return None
    return token[len(приставка):]


def _halves(хвост: str) -> list:
    """Кандидаты на пару «было / стало» — в том порядке, в каком их пробуют.

    Пробел в имени git не экранирует вовсе, поэтому границей половин служит
    не первый пробел, а начало второй половины. Кавычки же ставятся у каждой
    половины НЕЗАВИСИМО: смешанную строку `"a/…" b/…` git печатает на каждом
    переименовании файла с не-ASCII именем.
    """
    m = _QUOTED.match(хвост)
    if m and хвост[m.end():m.end() + 1] == " ":
        return [(m.group(0), хвост[m.end() + 1:])]
    return [(хвост[:i], хвост[i + 1:]) for i, знак in enumerate(хвост)
            if знак == " " and (хвост[i + 1:i + 2] == '"'
                                or хвост[i + 1:i + 3] == "b/")]


def parse_file_line(line: str) -> "tuple | None":
    """Пара путей (было, стало) из строки-границы — или None, не разобрано."""
    line = line.rstrip("\r")
    if not line.startswith(_HEADER):
        return None
    годные = []
    for было, стало in _halves(line[len(_HEADER):]):
        a, b = _half(было, "a/"), _half(стало, "b/")
        if a is not None and b is not None:
            годные.append((a, b))
    for a, b in годные:
        # Файл переименовывают редко, а правят постоянно: совпавшие половины
        # и есть верный разрез, даже когда пробел в имени оставил несколько
        # мест, где резать.
        if a == b:
            return a, b
    # Половины разные и мест для разреза больше одного — это переименование,
    # о котором нечем судить. Выбрать любое значит выбрать вслепую.
    return годные[0] if len(годные) == 1 else None


def split_diff(diff: str) -> tuple:
    """Разложить diff на куски по файлам: (было, стало, текст куска).

    Разбор по строкам-границам `diff --git`. Текст до первой границы — не
    файл, а шапка, и он отбрасывается вместе с остальным неопознанным:
    показать судье кусок неизвестной принадлежности значит нарушить слепоту
    вслепую.

    Третьим возвращается список границ, разобрать которые НЕ УДАЛОСЬ. Кусок
    за такой границей не достаётся предыдущему файлу и не показывается ни
    под чьим именем. Раньше он именно приклеивался: строка вида
    `diff --git "a/\\320\\242\\320\\227.md" "b/\\320\\242\\320\\227.md"` не
    узнавалась, второй файл не начинался — и весь его текст ехал судье под
    именем первого, при пустом списке скрытого и слове «готов».

    Что границей НЕ считается, и это ограничение названо, а не замаскировано:
    сводный вид `diff --cc`, которым git показывает слияние. Команда фазы
    приёмки его не печатает никогда, а разбор такой формы — отдельная работа
    с отдельным доказательством, и делать вид, что она сделана, хуже, чем
    сказать, что не сделана.
    """
    границы = [(m.start(), parse_file_line(m.group(0)))
               for m in _HEADER_LINE.finditer(diff)]
    куски, неразобрано = [], []
    for i, (нач, пути) in enumerate(границы):
        кон = границы[i + 1][0] if i + 1 < len(границы) else len(diff)
        if пути is None:
            неразобрано.append(diff[нач:кон].split("\n", 1)[0][:120])
            continue
        куски.append((пути[0], пути[1], diff[нач:кон]))
    return куски, bool(куски), неразобрано


def build_packet(request: str, diff: str) -> dict:
    """Собрать то, и только то, что увидит судья."""
    chunks, parsed, unparsed = split_diff(diff)
    shown, hidden = [], []
    for было, стало, text in chunks:
        # Переименование судится по ОБЕИМ сторонам: спека, переехавшая под
        # нейтральным именем, остаётся пересказом просьбы, а её текст — тем
        # же самым текстом. Иначе переезд файла становится способом провести
        # пересказ мимо вырезания.
        скрыть = is_retelling(было) or is_retelling(стало)
        (hidden if скрыть else shown).append((стало, text))

    body = "".join(t for _, t in shown)
    truncated = len(body) > MAX_DIFF
    if truncated:
        body = body[:MAX_DIFF]

    return {
        "gate": "blind-acceptance",
        "request": request.strip(),
        "changes": body,
        "shown_files": [p for p, _ in shown],
        # Вырезанное НАЗЫВАЕТСЯ: молча урезанный вход превращает вердикт
        # в суждение о работе, которой судья не видел.
        "hidden_files": [{"path": p, "why": "пересказ просьбы, а не результат"}
                         for p, _ in hidden],
        "diff_parsed": parsed,
        # Границы, которые разобрать не удалось. Список тут не для красоты
        # отчёта: пока он не пуст, утверждать, что пересказ вырезан, не из
        # чего — а именно это утверждение и продаёт вся слепая приёмка.
        "unparsed": unparsed,
        "truncated": truncated,
    }


def leaks_in(text: str) -> list:
    """Следы пересказа, ОСТАВШИЕСЯ в теле пакета.

    Зачем проверять то, что уже вырезано. Вырезание — механизм, и он работает
    по путям; следы пересказа умеют приезжать внутри файлов, которые пройти
    обязаны. Свойство независимости, которое никто не проверяет, — это
    свойство независимости, которого нет: пока проверки не было, слепота
    держалась на полноте одного списка регулярок, а список молчит, когда
    в нём чего-то не хватает.

    Идёт ПОСТРОЧНО и следит за текущим файлом по заголовкам `diff --git`,
    которые остаются внутри `text` (split_diff режет по ним, но не вырезает
    саму строку заголовка — см. build_packet). Это даёт ровно то, что нужно
    двум узким правилам: _MANIFEST_ID — протечка только при маркере пересказа
    В ТОЙ ЖЕ СТРОКЕ, а _RUN_DIR — не протечка внутри _IGNORE_FILE. Без знания
    «что за строка и какого она файла» ни то, ни другое правило не
    сформулировать детерминированно — а без них любое приложение с
    собственной буквенно-цифровой нотацией или список исключений вроде
    `.gitignore` не собрали бы пакет ни разу.
    """
    out = []
    current_file = ""
    for line in text.split("\n"):
        пути = parse_file_line(line)
        if пути is not None:
            current_file = пути[1]
            continue  # заголовок diff — служебная строка, не тело правки
        if line.startswith(_HEADER):
            # Граница есть, но не разобрана: под чьим именем идут следующие
            # строки — неизвестно, и послабление по имени файла к ним
            # применять нельзя. Пустое имя не совпадает ни с одним из них.
            current_file = ""
            continue

        for rx, why in LEAKS:
            m = rx.search(line)
            if not m:
                continue
            if rx is _RUN_DIR and _IGNORE_FILE.search(current_file):
                continue  # .gitignore — путь-паттерн, а не пересказ
            if rx is _MANIFEST_ID and not (_RETELLING_PHRASE.search(line)
                                            or ".superstack" in line):
                continue  # форма совпала, но пересказа рядом нет
            out.append({"match": m.group(0)[:60], "why": why})
    return out


def verdict(packet: dict) -> dict:
    """Можно ли вообще судить — и если нет, то почему именно."""
    if not packet["request"]:
        return {**packet, "status": "unknown",
                "next": "исходная просьба не сохранена — судить соответствие нечему; "
                        "сохраняй первое сообщение проекта дословно"}
    if packet["unparsed"]:
        # Неопознанная граница — это НЕ «файлов нет» и НЕ «всё показано».
        # Пока неизвестно, где кончается один файл и начинается следующий,
        # вырезание пересказа подтвердить нечем. Молчаливое склеивание —
        # худший из исходов: показанным числится один путь, скрытых нет,
        # пакет объявлен готовым, а спека едет судье внутри чужого файла.
        return {**packet, "status": "unknown",
                "next": "границу между файлами разобрать не удалось, а значит "
                        "нечем подтвердить, что пересказ просьбы вырезан: "
                        + "; ".join(packet["unparsed"][:3])
                        + ". Собери изменения заново так, чтобы имена файлов "
                          "приходили как есть, без кодирования"}
    if not packet["diff_parsed"]:
        return {**packet, "status": "unknown",
                "next": "изменения не разобраны как diff — судья увидел бы текст "
                        "неизвестной принадлежности"}
    if not packet["shown_files"]:
        why = ("все изменения — пересказ просьбы (спеки, планы, тикеты): "
               "результата работы в них нет"
               if packet["hidden_files"] else "изменений нет вовсе")
        return {**packet, "status": "unknown", "next": why}
    leaked = leaks_in(packet["changes"])
    if leaked:
        # Протечка — ПРОВАЛ сборки пакета, а не пометка в отчёте: судья,
        # увидевший пересказ, вынесет вердикт о совпадении пересказа с кодом,
        # и вердикт будет выглядеть точно как настоящий.
        return {**packet, "status": "leaked", "leaks": leaked,
                "next": "в результате остались служебные пометки процесса, "
                        "а не то, что было сделано: "
                        + "; ".join(f"«{x['match']}» — {x['why']}" for x in leaked)
                        + ". Перепиши эти места своими словами — без "
                          "идентификаторов и ссылок на план или спецификацию "
                          "— и собери пакет заново"}
    return {**packet, "status": "ready", "leaks": [],
            "next": "отдать пакет агенту blind-acceptance: он видит просьбу и "
                    "изменения, и НИЧЕГО больше"}


EXIT = {"ready": 0, "leaked": 1, "unknown": 2}


def human(v: dict) -> str:
    head = {"ready": "ПАКЕТ ГОТОВ", "leaked": "СЛЕПОТА НАРУШЕНА",
            "unknown": "СУДИТЬ НЕЧЕМ"}
    lines = [head[v["status"]]]
    lines.append(f"  просьба: {len(v['request'])} знаков")
    lines.append(f"  показано файлов: {len(v['shown_files'])}")
    for строка in v["unparsed"][:3]:
        lines.append(f"  ! граница между файлами не разобрана: {строка}")
    for x in v.get("leaks", []):
        lines.append(f"  ! протекло: «{x['match']}» — {x['why']}")
    for h in v["hidden_files"][:8]:
        lines.append(f"  скрыто: {h['path']} — {h['why']}")
    if v["truncated"]:
        lines.append(f"  изменения обрезаны до {MAX_DIFF} знаков")
    lines.append(f"  дальше: {v['next']}")
    return "\n".join(lines)


def halt_if_paused() -> None:
    if os.environ.get("SUPERSTACK_IGNORE_PAUSE") == "1":
        return
    if (Path.home() / ".claude" / "superstack" / "PAUSE").exists():
        print("ОСТАНОВЛЕНО: система на паузе", file=sys.stderr)
        raise SystemExit(10)


def main() -> int:
    halt_if_paused()
    argv = [a for a in sys.argv[1:] if a != "--json"]
    quiet = "--json" in sys.argv[1:]
    if len(argv) != 3 or argv[0] != "pack":
        print("вызов: blind_accept.py pack [--json] <просьба.txt> <изменения.diff>",
              file=sys.stderr)
        return 3
    req_p, diff_p = Path(argv[1]), Path(argv[2])
    for p in (req_p, diff_p):
        if not p.is_file():
            print(f"НЕ УДАЛОСЬ: нет файла — {p}", file=sys.stderr)
            return 3
    v = verdict(build_packet(req_p.read_text("utf-8", errors="replace"),
                             diff_p.read_text("utf-8", errors="replace")))
    if not quiet:
        print(human(v), file=sys.stderr)
    print(json.dumps(v, ensure_ascii=False, indent=1))
    return EXIT.get(v["status"], 2)


if __name__ == "__main__":
    sys.exit(main())
