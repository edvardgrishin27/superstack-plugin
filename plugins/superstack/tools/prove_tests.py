#!/usr/bin/env python3
"""SUPERSTACK — доказать, что тесты ПРОЕКТА могли быть красными.

Зачем это, если тесты уже зелёные.

Зелёный прогон отвечает на вопрос «сколько тестов выполнилось». Вопрос, ради
которого их пишут, — «мог ли хоть один упасть», — он не отвечает никогда, и
разница между этими двумя видна только когда что-то ломаешь нарочно.

Механизм найден на живом прогоне, не выведен. Исполнитель вернул `3 passed
(0 failed)`, тесты стояли на названном шве, ожидаемые значения были литералами.
Я заменил зависимость `notify.send` на заглушку, возвращающую ту же форму и НЕ
ОТПРАВЛЯЮЩУЮ НИЧЕГО, — прогон остался `3 passed, 0 failed`. Критерий «форма
отправляется» был выполнен по букве и обойдён по сути: тест утверждал
`result.ok === true`, а `ok` выставляет вызывающий код, а не факт доставки.

Два режима, и оба намеренно НЕ выдумывают поломок.

  · ЗАМЕНА — `find`/`replace` в файле. Точная, переносимая, пишется под
    конкретный критерий приёмки.
  · ЗАГЛУШКА — `stub`: файл целиком заменяется телом, которое возвращает ту же
    форму и ничего не делает. Ровно тот случай с `notify`, и он не зависит от
    языка: убить зависимость всегда можно, подменив её целиком.

Четыре правила, без которых это превратится в театр:

  1. КРАСНЫЙ НАБОР ДО МУТАЦИЙ — НЕ ИЗМЕРЕНИЕ. Если проект красный сам по себе,
     любая мутация «поймана», и отчёт будет блестящим. Сначала зелёный, потом
     ломаем.
  2. НОЛЬ ЗАРЕГИСТРИРОВАННЫХ ПОЛОМОК — «НЕ ПРОВЕРЯЛИ», А НЕ «ТЕСТЫ КРЕПКИЕ».
     Пустой набор мутаций не имеет права выглядеть успехом.
  3. ФАЙЛ ВОССТАНАВЛИВАЕТСЯ БАЙТ-В-БАЙТ И ДО ЛЮБОЙ ДРУГОЙ РАБОТЫ. Мутация,
     пережившая прогон, отравляет все следующие — это уже случалось трижды
     в нашем собственном репозитории.
  4. ПРОГОН, КОТОРЫЙ НЕ СОСТОЯЛСЯ, — НЕ ОТВЕТ ТЕСТОВ. Исход поломки трёхзначен:
     поймана, выжила и НЕИЗВЕСТНО. Третье не считается ни первым, ни вторым, и
     при ненулевом числе неизвестных чистого успеха не бывает.

  .superstack/mutations.json:
    {"test_cmd": "npm test",
     "mutations": [{"id": "...", "file": "...", "why": "...",
                    "find": "...", "replace": "..."},
                   {"id": "...", "file": "...", "why": "...", "stub": "..."}]}

  python3 prove_tests.py <корень проекта> [--set файл.json] [--json]

  код 0 — все поломки пойманы, 1 — есть выжившие, 2 — измерить не смог, 3 — вызов
"""
from __future__ import annotations

import json
import os
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

TIMEOUT = 900

#: Коды, которыми `run_tests` отвечает «прогон НЕ СОСТОЯЛСЯ»: 124 — тесты не
#: уложились в отведённое время, 127 — команду не удалось запустить вовсе.
#: Раньше обе аварии возвращали 127, а исход поломки считался одной строкой
#: `caught = rc != 0` — то есть и подвешенный прогон, и ненайденная команда шли
#: в зачёт пойманной поломкой. Человек читал «твои тесты ловят подмену» ровно
#: там, где у него не выполнилось ни одного теста: то самое враньё умолчанием,
#: против которого весь инструмент и написан. Имя одно на весь файл, чтобы
#: различие не разошлось между базовым прогоном и прогонами с подменой.
НЕ_СОСТОЯЛСЯ = (124, 127)


def почему(code: int, хвост: str = "") -> str:
    """За что прогон не считается ответом тестов — словами, а не кодом.

    Обе аварии означают «мерить нечем», но чинит человек в них разное:
    подвешенный прогон — это про время, ненайденная команда — про саму
    команду. Одно слово на оба случая отправляло бы искать не там.
    """
    слова = ("тесты не уложились в отведённое время" if code == 124
             else "команду тестов не удалось запустить")
    return f"{слова}: {хвост.strip()[-200:]}" if хвост.strip() else слова


def _lock(root: Path) -> Path:
    return root / ".superstack" / ".mutation-lock"


def _alive(pid: int) -> bool:
    if os.name == "nt":
        # На Windows сигнала 0 нет: `os.kill` там убивает процесс по-настоящему.
        # Спросить «жив ли он» нечем, и выбор направления ошибки здесь не
        # технический, а по цене: счесть чужой замок мёртвым значит сломать
        # дерево тому, кто как раз меряет. Поэтому «не знаю» = «жив».
        return True
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except (PermissionError, OSError):
        return True
    return True


def acquire(root: Path) -> "str | None":
    """Занять право ломать дерево. Мёртвый замок снимается сам."""
    p = _lock(root)
    if p.is_file():
        try:
            pid = int(p.read_text("utf-8").split()[0])
        except (OSError, ValueError, IndexError):
            pid = None
        if pid and pid != os.getpid() and _alive(pid):
            return (f"дерево уже ломает процесс {pid} — второй прогон увидит "
                    "чужую поломку и отнесёт её на свой счёт")
    try:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(f"{os.getpid()}\n", encoding="utf-8")
    except OSError as e:
        return f"замок не поставлен ({e}) — ломать вслепую нельзя"
    return None


def release(root: Path) -> None:
    try:
        _lock(root).unlink()
    except OSError:
        pass


def purge_bytecode(root: Path) -> int:
    """Снести кэш байткода в дереве проекта. Не гигиена, а условие измерения.

    Python признаёт кэш устаревшим по паре «размер + время последней правки с
    точностью до секунды». Подмена ТОГО ЖЕ РАЗМЕРА, внесённая в ту же секунду,
    для инвалидации неотличима от отсутствия правки: прогон идёт по прежнему
    `.pyc`, тесты закономерно зеленеют — и поломка объявляется ВЫЖИВШЕЙ, ни
    разу не исполнившись. Человек читает «твои тесты не ловят вот эту подмену»
    ровно там, где подмены в прогоне не было вовсе: ложное обвинение чужим
    тестам, зеркало того, что несостоявшийся прогон числился пойманной.

    Дерево ЧУЖОЕ, поэтому сносится только то, что восстанавливается само:
    каталоги `__pycache__` и ничего кроме них. Внутрь ссылок не заходим —
    чужая ссылка ведёт куда угодно, — а неудавшееся удаление проглатываем:
    один неподатливый каталог не повод отказаться мерить.

    Чего это НЕ достаёт, и это названо, а не замаскировано: кэш, унесённый из
    дерева переменной `PYTHONPYCACHEPREFIX`. Рядом с исходником его нет, и
    найти его отсюда нечем.
    """
    снесено = 0
    for каталог, подкаталоги, _ in os.walk(root, followlinks=False):
        if "__pycache__" not in подкаталоги:
            continue
        # Из обхода каталог убирается сразу: заходить внутрь того, что
        # удаляется целиком, незачем.
        подкаталоги.remove("__pycache__")
        try:
            shutil.rmtree(Path(каталог) / "__pycache__")
            снесено += 1
        except OSError:
            pass
    return снесено


def run_tests(root: Path, cmd: str) -> tuple:
    # Два пояса против прогона по СТАРОМУ байткоду. Нужны оба: они ловят разное.
    #
    #   · Кэш сносится ПЕРЕД КАЖДЫМ прогоном, а не один раз на запуск
    #     инструмента. Кладёт его туда не наш прогон, а сам проект — прошлые
    #     прогоны человека, сборка, команда тестов, поднимающая свой
    #     интерпретатор со своим окружением. Любой из них оставляет под
    #     следующей подменой чужой `.pyc`.
    #   · Записывать байткод в прогоне запрещено: то, чего не записали, не
    #     устареет под следующей подменой и не останется в чужом дереве после
    #     нас. До процессов, которые чистят себе окружение сами, запрет не
    #     доезжает — их и ловит первый пояс.
    #
    # Снос идёт и перед базовым прогоном: единственной разницей между базовым
    # и прогонами с подменой обязана оставаться сама подмена.
    purge_bytecode(root)
    try:
        # posix=False на Windows: в POSIX-режиме обратный слэш считается
        # экранированием, и `C:\проект\npm.cmd` разбирается в `C:проектnpm.cmd`.
        # Команда не найдётся, а сообщение будет про отсутствующий файл — то
        # есть человек пойдёт искать поломку не там.
        p = subprocess.run(shlex.split(cmd, posix=os.name != "nt"),
                           cwd=str(root), capture_output=True,
                           text=True, timeout=TIMEOUT,
                           env={**os.environ, "NO_COLOR": "1", "CI": "1",
                                "PYTHONDONTWRITEBYTECODE": "1"})
    except subprocess.TimeoutExpired:
        return 124, f"не завершилось за {TIMEOUT} с"
    except OSError as e:
        return 127, str(e)
    return p.returncode, ((p.stdout or "") + (p.stderr or ""))[-600:]


def apply(path: Path, m: dict) -> "bytes | None":
    """Внести поломку. Возвращает исходные байты либо None, если не вышло."""
    orig = path.read_bytes()
    if "stub" in m:
        path.write_text(m["stub"], encoding="utf-8")
        return orig
    text = orig.decode("utf-8", errors="replace")
    if m.get("find") not in text:
        return None
    path.write_text(text.replace(m["find"], m["replace"], 1), encoding="utf-8")
    return orig


def _baseline(root: Path, cmd: str) -> "str | None":
    """Набор проекта ДО первой подмены: причина, по которой исходы читать
    нельзя, — или None, если читать можно.

    Красный набор делает «пойманными» все поломки разом: он падал и без
    подмены. По числам отчёта такой прогон неотличим от честного, и это самый
    дешёвый способ получить «всё поймано», не проверив ничего.

    Прогон идёт той же командой, что и прогоны с подменой: единственная
    разница между базовым и остальными — сама подмена, иначе разницу исходов
    не на что относить.
    """
    code, out = run_tests(root, cmd)
    if code == 0:
        return None
    if code in НЕ_СОСТОЯЛСЯ:
        # Прогон не состоялся — это НЕ «набор красный»: тесты не сказали
        # ничего. Слить эти два ответа значило бы отправить человека искать
        # несуществующее падение.
        return f"прогон тестов не состоялся — {почему(code, out)}"
    return (f"набор красный ДО поломок (код {code}) — тогда любая поломка "
            f"«поймана», и отчёт будет блестящим: {out.strip()[-200:]}")


def run(root: Path, spec: dict) -> dict:
    cmd = spec.get("test_cmd", "")
    muts = spec.get("mutations") or []
    if not cmd:
        return {"status": "unknown",
                "detail": "не задана команда тестов — ломать нечего и мерить нечем"}
    if not muts:
        # Пустой набор не имеет права выглядеть успехом: «не проверяли» и
        # «тесты крепкие» — разные утверждения, и второе тут не доказано ничем.
        return {"status": "unknown",
                "detail": "ни одной поломки не зарегистрировано — это «не "
                          "проверяли», а не «тесты держат»",
                "next": "на каждый критерий приёмки завести поломку, которая "
                        "обязана его уронить; для интеграции — заглушку, "
                        "возвращающую ту же форму и не делающую ничего"}

    # Базовый прогон ДО первой подмены: см. `_baseline`. Причина, по которой
    # исходы не читаются, НАЗЫВАЕТСЯ, а не подразумевается.
    причина = _baseline(root, cmd)
    if причина:
        return {"status": "unknown",
                "detail": f"исходы поломок не читаются — {причина}",
                "registered": len(muts), "checked": 0, "executed": 0,
                "caught": 0, "survived": [], "inconclusive": [],
                "baseline": причина}

    survived, checked, broken, неясные = [], 0, [], []
    for m in muts:
        f = root / m.get("file", "")
        if not f.is_file():
            broken.append(f"{m.get('id')}: нет файла {m.get('file')}")
            continue
        orig = None
        try:
            orig = apply(f, m)
            if orig is None:
                broken.append(f"{m.get('id')}: якорь не найден в {m['file']}")
                continue
            rc, _ = run_tests(root, cmd)
            if rc in НЕ_СОСТОЯЛСЯ:
                # Авария ОКРУЖЕНИЯ, а не ответ тестов. Пока обе засчитывались
                # за пойманную поломку, сорванный запуск давал человеку
                # «твои тесты держат» там, где не выполнилось ни одного теста.
                исход = "неизвестно"
            elif rc == 0:
                исход = "выжила"
            else:
                исход = "поймана"
        finally:
            if orig is not None:
                # Восстановление ДО любой другой работы: поломка, пережившая
                # прогон, отравляет все следующие.
                f.write_bytes(orig)
        checked += 1
        if исход == "выжила":
            survived.append({"id": m.get("id"), "file": m.get("file"),
                             "why": m.get("why", "")})
        elif исход == "неизвестно":
            неясные.append({"id": m.get("id"), "file": m.get("file"),
                            "code": rc, "why": почему(rc)})

    # Четыре числа вместо одного громкого. «Все поломки пойманы» не различает
    # «набор покраснел на подмене» и «прогон не состоялся», а разница между
    # ними — это разница между проверкой и её видимостью.
    выполнено = checked - len(неясные)
    поймано = выполнено - len(survived)
    числа = (f"зарегистрировано {len(muts)}, выполнено {выполнено}, "
             f"поймано {поймано}, неизвестно {len(неясные)}")
    итог = {"checked": checked, "survived": survived, "inconclusive": неясные,
            "registered": len(muts), "executed": выполнено, "caught": поймано,
            "baseline": "зелёный"}
    if broken:
        return {"status": "unknown",
                "detail": "поломки не применились: " + "; ".join(broken[:5]),
                **итог}
    if survived:
        return {"status": "fail",
                "detail": f"выжило {len(survived)} из {выполнено} — тесты "
                          f"остались зелёными при внесённой поломке; {числа}",
                "next": "тест обязан падать, когда это ломается; пока не падает, "
                        "критерий выполнен по букве и обойдён по сути",
                **итог}
    if неясные:
        # Ни «поймана», ни «выжила»: прогон не состоялся, и сказать по нему
        # нечего. Чистый успех здесь был бы тем самым враньём умолчанием.
        return {"status": "unknown",
                "detail": числа + " — прогон не состоялся у "
                          + ", ".join(x["id"] for x in неясные[:5]),
                "next": "про эти поломки сейчас не известно ничего — повторить, "
                        "когда тесты снова запускаются",
                **итог}
    return {"status": "pass", "detail": числа, **итог}


def halt_if_paused() -> None:
    if os.environ.get("SUPERSTACK_IGNORE_PAUSE") == "1":
        return
    if (Path.home() / ".claude" / "superstack" / "PAUSE").exists():
        print("ОСТАНОВЛЕНО: система на паузе", file=sys.stderr)
        raise SystemExit(10)


def _utf8_stdio() -> None:
    """Печать по-русски не должна зависеть от локали.

    В окружении без UTF-8 — минимальный контейнер, cron с урезанным env,
    `PYTHONCOERCECLOCALE=0` — кодировка вывода оказывается ascii, и первый же
    русский символ роняет инструмент целиком. Человек получает не «проверка не
    прошла», а трейсбек вместо любого ответа. На macOS по умолчанию это не
    воспроизводится: интерпретатор сам приводит локаль C к C.UTF-8.
    """
    for поток in (sys.stdout, sys.stderr):
        кодировка = (getattr(поток, "encoding", "") or "").lower().replace("-", "")
        if кодировка != "utf8" and hasattr(поток, "reconfigure"):
            поток.reconfigure(encoding="utf-8", errors="replace")


def main() -> int:
    _utf8_stdio()
    halt_if_paused()
    argv = sys.argv[1:]
    takes = {"--set"}
    plain, skip = [], False
    for a in argv:
        if skip:
            skip = False
            continue
        if a in takes:
            skip = True
        elif not a.startswith("--"):
            plain.append(a)
    if len(plain) != 1:
        print("вызов: prove_tests.py <корень проекта> [--set файл.json]",
              file=sys.stderr)
        return 3
    root = Path(plain[0]).resolve()
    if not root.is_dir():
        print(f"НЕ УДАЛОСЬ: нет каталога {root}", file=sys.stderr)
        return 3

    src = Path(argv[argv.index("--set") + 1]) if "--set" in argv \
        else root / ".superstack" / "mutations.json"
    if not src.is_file():
        print(f"НЕ УДАЛОСЬ: нет набора поломок: {src}", file=sys.stderr)
        return 3
    try:
        spec = json.loads(src.read_text("utf-8"))
    except ValueError as e:
        print(f"НЕ УДАЛОСЬ: набор поломок не разобран: {e}", file=sys.stderr)
        return 3

    held = acquire(root)
    if held:
        print(f"НЕ УДАЛОСЬ: {held}", file=sys.stderr)
        return 2
    try:
        v = run(root, spec)
    finally:
        release(root)

    if "--json" not in argv:
        head = {"pass": "ТЕСТЫ ДЕРЖАТ", "fail": "ТЕСТЫ НЕ ДЕРЖАТ",
                "unknown": "ИЗМЕРИТЬ НЕ СМОГ"}
        print(f"{head[v['status']]}: {v['detail']}", file=sys.stderr)
        for s in v.get("survived", []):
            print(f"  ! выжила: {s['id']} ({s['file']}) — {s['why']}",
                  file=sys.stderr)
        for x in v.get("inconclusive", []):
            print(f"  ? не проверена: {x['id']} ({x['file']}) — {x['why']}",
                  file=sys.stderr)
        if v.get("next"):
            print(f"  дальше: {v['next']}", file=sys.stderr)
    print(json.dumps(v, ensure_ascii=False, indent=1))
    return {"pass": 0, "fail": 1, "unknown": 2}[v["status"]]


if __name__ == "__main__":
    sys.exit(main())
