#!/usr/bin/env python3
"""SUPERSTACK — образец, с которым сверяют доводку: «как вот это» получает адрес.

Зачем это отдельный инструмент.

Приёмка отвечает на вопрос «сделали ли то, о чём просили». Она не отвечает на
второй вопрос, который человек задаёт сразу после неё: «а почему оно выглядит
не так, как я хотел». Причина обычно одна и та же — ориентир он называл словами
(«чтобы как у linear», «тон посуше», «чтобы открывалось быстрее, чем сейчас»),
а слова к концу прогона остались в переписке и никуда не переехали.

Доводка без записанного ориентира вырождается предсказуемо. Ведущий смотрит на
свою же работу, не находит различий (он их и не мог найти — сравнивать не с
чем), объявляет «стало лучше» и делает круг за кругом, пока не кончится
терпение или деньги. Это не доводка, а бесплатное блуждание за счёт человека.

Поэтому здесь два жёстких правила, и оба закрыты кодом возврата:

  1. НЕТ ОБРАЗЦА — НЕТ ЦИКЛА. Пустой ориентир даёт код 1, а не «ну попробуем».
     Доводка «сделай красивее» — это просьба к вкусу модели, и результат её
     человек увидит впервые на сдаче, ровно как и в тот раз, когда палитру
     молча выбрал строитель.
  2. КРУГИ СЧИТАЕТ КОД, А НЕ СОВЕСТЬ. Потолок объявлен числом и достигается
     механически. «Ещё один круг, и точно всё» — это не измерение, а
     намерение, и оно исполняется столько раз, сколько ему позволят.

Холст дизайна — тоже образец, и его не нужно переписывать словами: доски
`*.dc.html`, которые человек правил руками, засчитываются сами. Пересказ
холста текстом был бы третьей копией одного факта и разошёлся бы с ним первым.

  python3 reference.py <корень> add --kind <вид> --what "<что именно>"
  python3 reference.py <корень> list
  python3 reference.py <корень> check

  виды: ссылка · снимок · тон · число · холст · круг

  код 0 — образец есть, круг разрешён (для `list` — есть что показать),
  1 — цикл не идёт: образца нет либо потолок кругов достигнут,
  3 — ошибка вызова, 10 — система на паузе
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

ФАЙЛ = ".superstack/reference.md"

#: Сколько кругов доводки допускается за прогон. Число тут не священное —
#: священно то, что оно ЕСТЬ: правило без числа не нарушается никогда, а
#: доводка без потолка кончается не результатом, а усталостью человека.
ПОТОЛОК_КРУГОВ = 3

#: Виды образца. Список закрытый намеренно: свободное поле «прочее» через
#: неделю наполняется строками вида «сделать посимпатичнее», и цикл снова
#: сверяется с настроением.
ВИДЫ = ("ссылка", "снимок", "тон", "число", "холст")

#: Где лежат доски холста дизайна. Фаза 2.5 кладёт их сюда, и они образец
#: наравне с названной ссылкой: человек правил их своей рукой.
ХОЛСТ = ".superstack/design"

_ОБРАЗЕЦ = re.compile(r"^- \*\*(" + "|".join(ВИДЫ) + r")\*\* — (.+)$", re.M)
_КРУГ = re.compile(r"^- \*\*круг (\d+)\*\* — (.+)$", re.M)

_ШАПКА = """# Образец — с чем сверяется доводка

Файл ведёт `tools/reference.py`. Правь его через `add`: строки ниже читает
код, и переписанные руками он не увидит.

## Образцы

## Круги
"""

_ВЫЗОВ = ("вызов: reference.py <корень> add --kind <ссылка|снимок|тон|число|"
          "холст|круг> --what \"<что именно>\" | list | check")


def _текст(root: Path) -> str:
    p = root / ФАЙЛ
    try:
        return p.read_text("utf-8") if p.is_file() else ""
    except OSError:
        return ""


def доски(root: Path) -> list:
    """Артборды холста. Пустой список — не отказ, а «холста не было»."""
    d = root / ХОЛСТ
    if not d.is_dir():
        return []
    return sorted(str(p.relative_to(root)) for p in d.rglob("*.dc.html"))


def образцы(root: Path) -> list:
    """Всё, с чем вообще можно сравнивать: записанное словами плюс холст."""
    из_файла = [{"вид": k, "что": v.strip()}
                for k, v in _ОБРАЗЕЦ.findall(_текст(root))]
    из_файла += [{"вид": "холст", "что": б} for б in доски(root)]
    return из_файла


def круги(root: Path) -> list:
    return [{"номер": int(n), "что": v.strip()}
            for n, v in _КРУГ.findall(_текст(root))]


def проверить(root: Path) -> dict:
    """Можно ли делать круг доводки. Отказ здесь — это код, а не совет."""
    есть = образцы(root)
    сделано = круги(root)
    if not есть:
        return {"код": 1, "статус": "нет-образца", "образцов": 0,
                "кругов": len(сделано), "потолок": ПОТОЛОК_КРУГОВ,
                "линия": "образца нет — доводить не с чем: попроси человека "
                         "дать ссылку, снимок, нужный тон или число, которое "
                         "надо побить"}
    if len(сделано) >= ПОТОЛОК_КРУГОВ:
        return {"код": 1, "статус": "потолок", "образцов": len(есть),
                "кругов": len(сделано), "потолок": ПОТОЛОК_КРУГОВ,
                "линия": f"кругов доводки {len(сделано)} из {ПОТОЛОК_КРУГОВ} — "
                         "дальше решает человек, а не ещё один круг"}
    return {"код": 0, "статус": "есть", "образцов": len(есть),
            "кругов": len(сделано), "потолок": ПОТОЛОК_КРУГОВ,
            "линия": f"образцов {len(есть)}, кругов {len(сделано)} из "
                     f"{ПОТОЛОК_КРУГОВ} — круг разрешён"}


def _строка(вид: str, что: str, номер: int = 0) -> str:
    имя = f"круг {номер}" if вид == "круг" else вид
    return f"- **{имя}** — {что}"


def добавить(root: Path, вид: str, что: str) -> dict:
    """Записать образец или закрытый круг. Успех печатается ПОСЛЕ перечитки."""
    что = (что or "").strip()
    if not что:
        return {"код": 3, "статус": "пусто", "линия": "нечего записывать: --what пуст"}
    if вид == "число" and not re.search(r"\d", что):
        return {"код": 1, "статус": "не-число",
                "линия": "число, которое надо побить, обязано быть числом: "
                         "«быстрее» нельзя ни проверить, ни опровергнуть"}
    if вид == "ссылка" and "://" not in что and not re.search(r"\w\.\w", что):
        return {"код": 1, "статус": "не-ссылка",
                "линия": "в ссылке нет адреса — открыть по ней нечего"}

    номер = 0
    if вид == "круг":
        сделано = круги(root)
        if len(сделано) >= ПОТОЛОК_КРУГОВ:
            return {"код": 1, "статус": "потолок", "кругов": len(сделано),
                    "потолок": ПОТОЛОК_КРУГОВ,
                    "линия": f"круг {len(сделано) + 1} не записан: потолок "
                             f"{ПОТОЛОК_КРУГОВ} уже достигнут"}
        номер = len(сделано) + 1

    p = root / ФАЙЛ
    try:
        p.parent.mkdir(parents=True, exist_ok=True)
        текст = p.read_text("utf-8") if p.is_file() else _ШАПКА
        заголовок = "## Круги" if вид == "круг" else "## Образцы"
        строка = _строка(вид, что, номер)
        if вид == "круг":
            # Круги дописываются в конец: порядок кругов — это ход доводки,
            # и перевёрнутый список читается как «сначала третий».
            текст = текст.rstrip("\n") + "\n" + строка + "\n"
        elif заголовок in текст:
            место = текст.index(заголовок) + len(заголовок)
            текст = текст[:место] + "\n\n" + строка + текст[место:]
        else:
            текст = текст.rstrip("\n") + f"\n\n{заголовок}\n\n{строка}\n"
        p.write_text(текст, encoding="utf-8")
    except OSError as e:
        return {"код": 1, "статус": "не-записан",
                "линия": f"запись не удалась: {e}"}

    # Перечитка с диска, а не доверие своей же переменной. Успех, напечатанный
    # до проверки результата, — самый дорогой вид зелёного в этой системе:
    # человек уходит спать, считая ориентир записанным.
    записано = круги(root) if вид == "круг" else образцы(root)
    if not any(z["что"] == что for z in записано):
        return {"код": 1, "статус": "не-записан",
                "линия": "строка не читается обратно из файла — образец не "
                         "записан, хотя файл изменён"}
    return {"код": 0, "статус": "записан", "вид": вид, "что": что,
            "номер": номер, "файл": ФАЙЛ,
            "линия": f"записано в {ФАЙЛ}: {_строка(вид, что, номер)}"}


def показать(root: Path) -> dict:
    есть, сделано = образцы(root), круги(root)
    if not есть and not сделано:
        return {"код": 1, "статус": "пусто", "образцы": [], "круги": [],
                "линия": f"в {ФАЙЛ} пусто и холста нет — показывать нечего"}
    return {"код": 0, "статус": "есть", "образцы": есть, "круги": сделано,
            "потолок": ПОТОЛОК_КРУГОВ,
            "линия": f"образцов {len(есть)}, кругов {len(сделано)} из "
                     f"{ПОТОЛОК_КРУГОВ}"}


def halt_if_paused() -> None:
    if os.environ.get("SUPERSTACK_IGNORE_PAUSE") == "1":
        return
    if (Path.home() / ".claude" / "superstack" / "PAUSE").exists():
        print("ОСТАНОВЛЕНО: система на паузе", file=sys.stderr)
        raise SystemExit(10)


def main() -> int:
    halt_if_paused()
    argv = sys.argv[1:]
    тихо = "--json" in argv
    берут = {"--kind", "--what"}
    plain, ключи, ждём = [], {}, None
    for a in argv:
        if ждём:
            ключи[ждём] = a
            ждём = None
        elif a in берут:
            ждём = a
        elif not a.startswith("--"):
            plain.append(a)
    if ждём or len(plain) != 2 or plain[1] not in ("add", "list", "check"):
        print(_ВЫЗОВ, file=sys.stderr)
        return 3
    root, cmd = Path(plain[0]), plain[1]
    if not root.is_dir():
        print(f"НЕ УДАЛОСЬ: нет каталога {root}", file=sys.stderr)
        return 3

    if cmd == "add":
        вид = ключи.get("--kind", "")
        if вид not in ВИДЫ + ("круг",):
            print(_ВЫЗОВ, file=sys.stderr)
            return 3
        v = добавить(root, вид, ключи.get("--what", ""))
    elif cmd == "list":
        v = показать(root)
    else:
        v = проверить(root)

    if not тихо:
        print(v["линия"], file=sys.stderr)
    print(json.dumps(v, ensure_ascii=False, indent=1))
    return v["код"]


if __name__ == "__main__":
    sys.exit(main())
