#!/usr/bin/env python3
"""SUPERSTACK — снимки папки продукта: у «верни как было» появляется адрес.

Зачем это отдельный инструмент.

Сборка /go пишет в папку продукта файлы — код, страницы, настройки — и не
заводит там ни одной точки, к которой можно вернуться. Откат в системе был
ровно один (`tools/oops.py` поверх `tools/apply.py`) и возвращал он ТОЛЬКО
настройки Claude Code. То есть на просьбу «верни как было» человек слышал
«откатывать нечего», хотя вчерашний код лежал переписанным. Проверка отката
данных (`tools/data_rollback.py`) при этом исходит из «у кода откат есть» —
предпосылка, которую конвейер сам не создавал.

Здесь она создаётся: папка продукта берётся под снимки, и на границе каждого
этапа снимок делается сам.

  python3 checkpoint.py <папка> init             взять папку под снимки
  python3 checkpoint.py <папка> snap "<этап>"    снимок на границе этапа
  python3 checkpoint.py <папка> list             какие снимки есть
  python3 checkpoint.py <папка> back <sha|этап>  вернуть файлы к снимку

  код 0 — сделано (для `list` — снимки есть), 1 — не смог (нет git в системе,
  папка не под снимками, git отказал), 3 — ошибка вызова, 10 — система на паузе

Три решения, каждое из которых можно было принять иначе:

  · ВОЗВРАТ НЕ СТИРАЕТ ИСТОРИЮ. `back` кладёт файлы поверх (`git checkout <sha>
    -- .`), а не отматывает историю (`reset --hard`). Отмотанная история
    уносит с собой сами снимки — и следующая просьба «верни как было» опять
    остаётся без адреса, только теперь молча.
  · СНИМОК НЕ ДЕЛАЕТСЯ ВПУСТУЮ. Без проверки «а изменилось ли что-нибудь»
    десять границ этапов дают десять пустых записей, и найти среди них ту, где
    работа ещё была цела, нельзя.
  · КЛЮЧИ В СНИМОК НЕ ПОПАДАЮТ. Файл `.env` со значением, похожим на живой
    ключ, в снимок не берётся: снимок хранится вечно, а ключ, попавший в него,
    оттуда уже не убрать. Проверка берётся у сборщика фактов, своей второй
    здесь нет. Решается это ПО ЗНАЧЕНИЮ, а не по тому, попадал ли раньше сам
    файл: новый ключ в давно отслеживаемом файле останавливает снимок, и ни
    рабочий файл, ни прежние снимки при этом не переписываются.
  · СНИМОК ЖИВЁТ В СВОЕЙ ОБЛАСТИ. Фиксируется только папка, о которой просили.
    Подготовленное человеком за её пределами в снимок не уезжает, и его индекс
    остаётся в том же состоянии, в каком был.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

#: С чего начинается подпись снимка. По ней снимки прогона отличаются от
#: собственных сохранений человека: его работа в этой же папке нашей не
#: считается и в `list` не показывается.
ПРЕФИКС = "superstack: "

#: Подпись первого снимка. Он снимается при заведении — до того, как система
#: запишет в папку хоть один свой файл, — и это единственный снимок, который
#: показывает папку такой, какой её принесли.
НАЧАЛО = "как было до начала"

#: Минимальный список того, что в снимок не берётся. Список короткий
#: намеренно: снимок нужен, чтобы вернуть работу, и лишняя строка здесь
#: означает файл, который не вернётся. Поэтому тут только то, что либо
#: пересобирается само, либо вообще не должно было попадать в снимок.
БАЗОВЫЙ_ИГНОР = (
    "# Что в снимки не берётся. Файл создан один раз при заведении;",
    "# дальше правь его как хочешь — снимки его перечитывают, а не переписывают.",
    ".superstack/*.bak",
    "node_modules/",
    "__pycache__/",
    ".venv/",
    "venv/",
    ".DS_Store",
    "*.log",
)

#: Как выглядит файл с настройками окружения. Именно в нём ключи и живут, и
#: именно он чаще всего попадает в снимок по недосмотру.
#:
#: Оговорка названа вслух, а не замаскирована: ключ, лежащий в `config.json`
#: или `settings.yaml`, этой проверкой НЕ ловится. Расширять её на все файлы
#: подряд значило бы выкидывать из снимка чужие файлы по догадке — а снимок,
#: из которого молча пропал файл, хуже снимка с находкой: он выглядит целым.
_ФАЙЛ_ОКРУЖЕНИЯ = re.compile(r"(?i)^\.env(\.[^/]*)?$|^\.envrc$|\.env$")

#: Сколько байт файла окружения читаем. Настоящий `.env` — это десятки строк;
#: всё, что больше, — уже не он, и вычитывать его целиком незачем.
ЧИТАЕМ_БАЙТ = 200_000

СНИМКОВ_В_СПИСКЕ = 50


class НетGit(Exception):
    """В системе нет git. Не поломка прогона — отсутствие снимков."""


class ПроверкаНедоступна(Exception):
    """Нечем проверить файлы на ключи. Снимок в этом случае НЕ делается.

    Направление отказа выбрано намеренно. Молча снять снимок без проверки
    значит однажды положить в него живой ключ навсегда; отказаться от снимка
    значит потерять одну точку возврата и СКАЗАТЬ об этом.
    """


