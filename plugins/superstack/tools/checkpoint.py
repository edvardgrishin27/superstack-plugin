def halt_if_paused() -> None:
    if os.environ.get("SUPERSTACK_IGNORE_PAUSE") == "1":
        return
    if (Path.home() / ".claude" / "superstack" / "PAUSE").exists():
        print("ОСТАНОВЛЕНО: система на паузе", file=sys.stderr)
        raise SystemExit(10)


# --------------------------------------------------------------------------
# git
# --------------------------------------------------------------------------
def _git(root: Path, *args: str, timeout: int = 120):
    """Вызов git в этой папке. Отсутствие самого git — отдельный случай.

    `core.quotepath=false` — иначе нелатинские имена возвращаются в
    восьмеричных последовательностях, и путь, который мы потом читаем с диска,
    просто не находится (тот же разбор уже стоил тишины в проверке отката
    данных).
    """
    try:
        return subprocess.run(["git", "-c", "core.quotepath=false", *args],
                              cwd=str(root), capture_output=True, text=True,
                              timeout=timeout)
    except FileNotFoundError as e:
        raise НетGit(str(e)) from e


def _хвост(p) -> str:
    return " ".join(((p.stderr or p.stdout or "").strip()).split())[-200:]


def _привязка(root: Path) -> "dict | None":
    """Корень хранилища и место папки внутри него. None — хранилища нет.

    Считается ОДИН раз на снимок и служит единственной нормализацией путей.
    Причина — цена прежнего отсутствия такой нормализации: `git status
    --porcelain` печатает пути от КОРНЯ хранилища, а не от папки, в которой
    его позвали, и эти пути присоединялись к самой папке. Снимок из `product`
    искал `product/product/.env`, файла по такому адресу нет — и проверка на
    ключи молча пропускала его, отчитавшись «ключей нет». Корень при этом
    умели считать здесь же, но для путей не использовали.

    `--show-prefix` — путь папки внутри хранилища с косой чертой на конце
    (пусто, когда папка и есть корень). Приставка берётся у самого git, а не
    вычисляется из двух путей: на пути через ссылки и на регистронезависимой
    файловой системе такое вычитание расходится с тем, что видит git.
    """
    p = _git(root, "rev-parse", "--show-toplevel", "--show-prefix")
    if p.returncode != 0:
        return None
    строки = (p.stdout or "").splitlines()
    верх = строки[0] if строки else ""
    if not верх:
        return None
    return {"верх": верх, "приставка": строки[1] if len(строки) > 1 else ""}


def под_снимками(root: Path) -> "str | None":
    """Корень хранилища, которому принадлежит папка. None — его нет.

    Возвращается ИМЕННО корень, а не «да/нет»: папка может лежать ВНУТРИ
    чужого хранилища, и тогда заводить своё поверх нельзя — снимки ушли бы
    в чужую историю.
    """
    п = _привязка(root)
    return п["верх"] if п else None


def _обеспечить_имя(root: Path) -> None:
    """Снимок подписывается кем-то. Если имени нет ни в машине, ни в папке —
    ставим его для ЭТОЙ папки.

    Без этого `commit` отказывает строкой «скажи, кто ты», и отказ приходит
    в момент, когда снимок уже был обещан. Настройки всей машины не трогаем:
    имя ставится локально, в этой папке, и только когда своего нет вовсе.
    """
    p = _git(root, "config", "user.email")
    if p.returncode == 0 and (p.stdout or "").strip():
        return
    _git(root, "config", "user.email", "superstack@local")
    _git(root, "config", "user.name", "SUPERSTACK")


# --------------------------------------------------------------------------
# ключи — проверка берётся у сборщика фактов, своей второй нет
# --------------------------------------------------------------------------
_СБОРЩИК = None


def _найти_ключи(текст: str) -> list:
    """Пары (почему, значение) — тем же прибором, каким система смотрит
    настройки Claude Code.

    Своя вторая проверка разошлась бы с первой при первой же правке, и тогда
    на один вопрос «это ключ?» в продукте было бы два ответа.

    Ловится узко и говорится вслух: широкий `except` вокруг чужого модуля в
    этом проекте уже однажды выключил проверку, и она отвечала «всё чисто».
    """
    global _СБОРЩИК
    if _СБОРЩИК is None:
        import importlib.util
        путь = Path(__file__).resolve().parent / "probe" / "collect.py"
        spec = importlib.util.spec_from_file_location("ss_checkpoint_keys", путь)
        if spec is None or spec.loader is None:
            raise ПроверкаНедоступна(f"{путь}: не читается")
        mod = importlib.util.module_from_spec(spec)
        try:
            spec.loader.exec_module(mod)
        except (OSError, ImportError, SyntaxError, ValueError) as e:
            raise ПроверкаНедоступна(f"{путь}: {e}") from e
        if not hasattr(mod, "_secrets_in_text"):
            raise ПроверкаНедоступна(f"{путь}: проверки на ключи в нём нет")
        _СБОРЩИК = mod
    return _СБОРЩИК._secrets_in_text(текст)


def _изменённое(root: Path, приставка: str = "") -> list:
    """Пути, которые попадут в следующий снимок, — ОТ ПАПКИ СНИМКА.

    Два решения, и оба уже стоили тишины.

    Разбор идёт по разделителям NUL (`-z`), а не по печатной строке. Печатная
    строка — не путь: имя с кириллицей, пробелом или кавычкой git берёт в
    кавычки и кодирует восьмеричными последовательностями, а `ТЗ.md` и
    `Требования.md` тут норма, а не редкость. Такой путь с диска уже не
    читается, и файл рядом с ним выпадает молча.

    Приставка снимается здесь же, один раз на все места сразу: дальше путь
    годится и для чтения с диска, и для области git, и для строки исключений
    рядом с папкой, и для показа человеку.
    """
    p = _git(root, "status", "--porcelain", "-z", "-uall", "--", ".")
    if p.returncode != 0:
        return []
    поля = (p.stdout or "").split("\0")
    пути, i = [], 0
    while i < len(поля):
        запись, i = поля[i], i + 1
        if len(запись) < 4:
            continue
        if "R" in запись[:2] or "C" in запись[:2]:
            # Следующее поле — ОТКУДА переехало. Берём, куда легло.
            i += 1
        путь = запись[3:]
        # Область `-- .` не печатает ничего снаружи папки; проверка стоит на
        # случай, если это когда-нибудь перестанет быть правдой — чужой путь
        # в снимке папки хуже пропущенного.
        if not путь.startswith(приставка):
            continue
        пути.append(путь[len(приставка):])
    return пути


def _отслеживается(root: Path, путь: str) -> bool:
    p = _git(root, "ls-files", "--error-unmatch", "--", путь)
    return p.returncode == 0


def _в_прошлом_снимке(root: Path, путь_от_корня: str) -> str:
    """Содержимое файла в последнем снимке. Пусто — снимка с ним не было.

    Пусто и тогда, когда прочитать не вышло: направление ошибки выбрано так,
    чтобы неизвестное значение считалось НОВЫМ и останавливало снимок, а не
    проезжало в него под видом старого.
    """
    try:
        p = _git(root, "show", f"HEAD:{путь_от_корня}")
    except UnicodeDecodeError:
        return ""
    return (p.stdout or "")[:ЧИТАЕМ_БАЙТ] if p.returncode == 0 else ""


def _ключи_в_окружении(root: Path, приставка: str = "") -> list:
    """Файлы окружения с живыми на вид ключами. Само значение НЕ возвращается.

    Значение не выходит за пределы этой функции нарочно: инструмент, который
    печатает найденный ключ, чтобы предупредить о ключе, — это утечка с
    хорошим намерением. Поэтому сравнение с прошлым снимком тоже живёт здесь,
    а наружу уходит одно число.

    Про каждый файл считается ДВА разных ответа, и это главное здесь. Первый —
    попадал ли в снимки САМ ФАЙЛ. Второй — есть ли в нём ЗНАЧЕНИЕ, которого в
    прошлом снимке не было. Прежде спрашивали только первое, а решали про
    второе: `.env` с безобидным `MODE=development` живёт в снимках месяцами,
    в него ВПЕРВЫЕ дописывают ключ — и «файл отслеживается» пропускало его
    внутрь навсегда.
    """
    out = []
    for путь in _изменённое(root, приставка):
        if not _ФАЙЛ_ОКРУЖЕНИЯ.search(Path(путь).name):
            continue
        f = root / путь
        if not f.is_file():
            continue
        try:
            текст = f.read_text("utf-8", errors="replace")[:ЧИТАЕМ_БАЙТ]
        except OSError:
            continue
        находки = _найти_ключи(текст)
        if not находки:
            continue
        отслеживается = _отслеживается(root, путь)
        было = (_найти_ключи(_в_прошлом_снимке(root, приставка + путь))
                if отслеживается else [])
        out.append({"файл": путь,
                    "почему": находки[0][0],
                    "сколько": len(находки),
                    "уже_в_снимках": отслеживается,
                    "новых": len({з for _, з in находки} - {з for _, з in было})})
    return out


def _про_ключи(пропущено: list) -> str:
    """Что стало с файлами окружения — В ТОЙ ЖЕ строке, что и сам снимок.

    Отдельным полем это уже было и молчало: строку читает человек, а поле —
    никто. Снимок, из которого тихо выпал файл, выглядит полным.
    """
    не_взяты = [n["файл"] for n in пропущено
                if n["что_сделали"] == "в снимок не взят"]
    были_раньше = [n["файл"] for n in пропущено
                   if n["что_сделали"] == "оставлен как был"]
    куски = []
    if не_взяты:
        куски.append(f"в снимок не взято из-за похожего на живой ключа: "
                     f"{', '.join(не_взяты)} — файлы остались на месте, но "
                     f"вернуть их снимком нельзя")
    if были_раньше:
        # Сказано ровно то, что проверено. Прежняя строка утверждала про
        # прошлые снимки то, чего никто не смотрел: она звучала одинаково и
        # для старого ключа, и для нового, впервые дописанного сегодня.
        куски.append(f"эти же ключи уже лежат в прошлом снимке "
                     f"({', '.join(были_раньше)}) — оттуда их этим не убрать")
    return (". " + "; ".join(куски)) if куски else ""


def _в_игнор(root: Path, строки: list) -> None:
    """Дописать строки в список исключений, не тронув того, что там уже есть."""
    f = root / ".gitignore"
    было = f.read_text("utf-8", errors="replace") if f.is_file() else ""
    новые = [s for s in строки if s not in было.splitlines()]
    if not новые:
        return
    хвост = "" if (not было or было.endswith("\n")) else "\n"
    f.write_text(было + хвост + "\n".join(новые) + "\n", encoding="utf-8")


# --------------------------------------------------------------------------
# снимок
# --------------------------------------------------------------------------
def снимок(root: Path, этап: str) -> dict:
    """Снимок границы этапа. Пустой снимок не делается.

    Ничего не подтверждается заранее: sha берётся ПОСЛЕ записи, из самой
    папки, а не из того, что мы собирались сделать.
    """
    этап = " ".join(этап.split())
    if not этап:
        return {"снято": False, "код": 3, "линия": "у снимка нет названия этапа"}

    привязка = _привязка(root)
    if привязка is None:
        return {"снято": False, "код": 1,
                "линия": "папка не под снимками — снимать нечем"}
    приставка = привязка["приставка"]

    находки = _ключи_в_окружении(root, приставка)
    # Сначала смотрим на ВСЕ файлы разом и только потом что-то меняем: иначе
    # снимок, который всё равно не состоится, успел бы дописать человеку файл
    # исключений — правку, о которой он не просил, ради снимка, которого нет.
    новый_ключ = [н for н in находки if н["уже_в_снимках"] and н["новых"]]
    if новый_ключ:
        # Отслеживаемость отвечает про ФАЙЛ, а решение принимается про
        # ЗНАЧЕНИЕ. Ключ, впервые появившийся в давно отслеживаемом файле, в
        # прежних снимках не лежит — значит, этот снимок положил бы его туда
        # навсегда. Ни рабочий файл, ни прежние снимки не переписываем: выбор
        # между ключом и точкой возврата принадлежит человеку, а не нам.
        имена = ", ".join(н["файл"] for н in новый_ключ)
        return {"снято": False, "код": 1, "этап": этап, "ключи": находки,
                "линия": f"снимок не сделан: в {имена} впервые появился ключ, "
                         f"которого в прошлом снимке не было. Снимок хранится "
                         f"вечно, и убрать ключ из него потом нельзя. Ни файл, "
                         f"ни прежние снимки я не трогал — решаешь ты: пока "
                         f"ключ лежит в этом файле, снимка этого этапа не будет"}

    пропущено = []
    for находка in находки:
        if находка["уже_в_снимках"]:
            # Те же ключи уже лежат в прошлом снимке — своей историей мы этого
            # не изменим, а выкинуть файл сейчас значило бы записать в снимок
            # его удаление и стереть человеку рабочий файл при возврате.
            пропущено.append({**находка, "что_сделали": "оставлен как был"})
            continue
        _в_игнор(root, [находка["файл"]])
        пропущено.append({**находка, "что_сделали": "в снимок не взят"})

    if not _изменённое(root, приставка):
        return {"снято": False, "код": 0, "этап": этап, "ключи": пропущено,
                "линия": "нечего фиксировать"}

    _обеспечить_имя(root)
    p = _git(root, "add", "-A", "--", ".")
    if p.returncode != 0:
        return {"снято": False, "код": 1, "этап": этап, "ключи": пропущено,
                "линия": f"снимок не сделан: git add отказал — {_хвост(p)}"}

    # Отдельный вопрос после add, а не до него: изменения могли целиком
    # состоять из файла окружения, который мы только что исключили.
    #
    # Область здесь обязательна. Без неё вопрос звучал «есть ли в индексе хоть
    # что-нибудь», и подготовленный человеком соседний файл отвечал на него
    # «да» — снимок шёл дальше, не имея ни одного своего изменения.
    if _git(root, "diff", "--cached", "--quiet", "--", ".").returncode == 0:
        return {"снято": False, "код": 0, "этап": этап, "ключи": пропущено,
                "линия": "нечего фиксировать"}

    # Коммит строго по своей области. Прежде `add` ограничивался ею, а `commit`
    # фиксировал ВЕСЬ индекс — и снимок уносил в свою историю то, что человек
    # подготовил к собственному коммиту рядом, оставляя его с пустым индексом.
    # `--only` берёт содержимое рабочего дерева по названным путям и не трогает
    # подготовленное за их пределами: и записи «намерен добавить», которые
    # ставит слепая приёмка, и чужая подготовленная работа переживают снимок.
    p = _git(root, "commit", "-q", "--only", "-m", ПРЕФИКС + этап, "--", ".")
    if p.returncode != 0:
        return {"снято": False, "код": 1, "этап": этап, "ключи": пропущено,
                "линия": f"снимок не сделан: git commit отказал — {_хвост(p)}"}

    got = _git(root, "rev-parse", "--short", "HEAD")
    if got.returncode != 0:
        return {"снято": False, "код": 1, "этап": этап, "ключи": пропущено,
                "линия": "снимок как будто сделан, но найти его не удалось — "
                         "считать снятым нельзя"}
    sha = (got.stdout or "").strip()
    return {"снято": True, "код": 0, "этап": этап, "sha": sha,
            "ключи": пропущено,
            "линия": f"снимок {sha} — {этап}" + _про_ключи(пропущено)}


# --------------------------------------------------------------------------
# заведение
# --------------------------------------------------------------------------
def завести(root: Path) -> dict:
    """Взять папку под снимки. Уже взятую — не трогать."""
    верх = под_снимками(root)
    if верх is not None:
        свой = Path(верх).resolve() == root.resolve()
        return {"код": 0, "завели": False, "корень": верх,
                "линия": ("прежние версии файлов здесь уже хранятся — ничего "
                          "не менял" if свой else
                          f"эта папка лежит внутри «{верх}», где прежние "
                          f"версии уже хранятся — ничего не менял")}

    p = _git(root, "init", "-q")
    if p.returncode != 0:
        return {"код": 1, "завели": False,
                "линия": f"снимки завести не вышло — {_хвост(p)}"}

    if not (root / ".gitignore").is_file():
        _в_игнор(root, list(БАЗОВЫЙ_ИГНОР))

    # Первый снимок — до того, как система запишет сюда свой первый файл.
    # Без него «верни как было» упирается в самый ранний снимок, который УЖЕ
    # содержит нашу работу, то есть возвращает не то, о чём просили.
    первый = снимок(root, НАЧАЛО)
    линия = "папка взята под снимки"
    if первый["снято"]:
        линия += f"; первый снимок {первый['sha']} — {НАЧАЛО}"
    elif первый["код"] != 0:
        линия += f"; первый снимок не снят: {первый['линия']}"
    else:
        линия += "; папка пустая, снимать было нечего"
    return {"код": 0, "завели": True, "корень": str(root.resolve()),
            "первый": первый, "линия": линия}


# --------------------------------------------------------------------------
# список
# --------------------------------------------------------------------------
def список(root: Path) -> dict:
    """Снимки прогона, свежий первым. Чужие сохранения сюда не попадают."""
    if под_снимками(root) is None:
        return {"код": 1, "снимки": [],
                "линия": "папка не под снимками — возвращать не к чему"}
    p = _git(root, "log", f"-{СНИМКОВ_В_СПИСКЕ}", "--format=%h%x1f%cI%x1f%s")
    if p.returncode != 0:
        # Пустое хранилище: истории нет, и это не поломка.
        return {"код": 1, "снимки": [],
                "линия": "снимков пока нет — возвращать не к чему"}
    снимки = []
    for строка in (p.stdout or "").splitlines():
        части = строка.split("\x1f")
        if len(части) != 3 or not части[2].startswith(ПРЕФИКС):
            continue
        снимки.append({"sha": части[0], "когда": части[1],
                       "этап": части[2][len(ПРЕФИКС):]})
    if not снимки:
        return {"код": 1, "снимки": [],
                "линия": "снимков пока нет — возвращать не к чему"}
    п = снимки[0]
    return {"код": 0, "снимки": снимки, "последний": п,
            "линия": f"снимков {len(снимки)}; последний {п['sha']} — "
                     f"«{п['этап']}», {п['когда']}"}


# --------------------------------------------------------------------------
# возврат
# --------------------------------------------------------------------------
def _найти_снимок(root: Path, куда: str) -> tuple:
    """(sha, этап, причина отказа). Сначала по названию этапа, потом по sha."""
    все = список(root)
    for s in все["снимки"]:
        if s["этап"] == куда:
            return s["sha"], s["этап"], None
    p = _git(root, "rev-parse", "--verify", "--quiet", f"{куда}^{{commit}}")
    if p.returncode == 0 and (p.stdout or "").strip():
        sha = (p.stdout or "").strip()[:9]
        этап = next((s["этап"] for s in все["снимки"]
                     if sha.startswith(s["sha"]) or s["sha"].startswith(sha)),
                    куда)
        return sha, этап, None
    имена = ", ".join(f"«{s['этап']}»" for s in все["снимки"][:6])
    return None, None, (f"снимка «{куда}» нет" +
                        (f"; есть: {имена}" if имена else " — снимков нет вовсе"))


def откат(root: Path, куда: str) -> dict:
    """Вернуть файлы к снимку. История при этом остаётся целой.

    Порядок: сперва снимок текущего состояния (иначе несохранённая работа
    исчезнет без следа), потом возврат файлов, потом снимок самого возврата.

    Чего возврат НЕ делает, и это названо, а не замаскировано: файлы,
    появившиеся ПОСЛЕ снимка, остаются на месте — возврат кладёт поверх, а не
    вычищает папку.
    """
    if под_снимками(root) is None:
        return {"код": 1, "вернули": False,
                "линия": "папка не под снимками — возвращать не к чему"}

    sha, этап, почему = _найти_снимок(root, куда)
    if sha is None:
        return {"код": 1, "вернули": False, "линия": почему}

    до = снимок(root, f"перед возвратом к {этап}")
    if до["код"] != 0:
        return {"код": 1, "вернули": False, "до": до,
                "линия": f"возврат не начат: текущую работу сохранить не вышло "
                         f"— {до['линия']}"}

    p = _git(root, "checkout", sha, "--", ".")
    if p.returncode != 0:
        return {"код": 1, "вернули": False, "до": до,
                "линия": f"файлы не вернулись — {_хвост(p)}"}

    после = снимок(root, f"откат к {этап}")
    if после["код"] != 0:
        return {"код": 1, "вернули": True, "до": до, "после": после,
                "линия": f"файлы вернулись к {sha}, но отметить сам откат не "
                         f"вышло — {после['линия']}"}
    return {"код": 0, "вернули": True, "sha": sha, "этап": этап,
            "до": до, "после": после,
            "линия": f"файлы вернулись к снимку {sha} — «{этап}»; появившееся "
                     f"после снимка осталось на месте"}


# --------------------------------------------------------------------------
# CLI
# --------------------------------------------------------------------------
_ВЫЗОВ = ("вызов: checkpoint.py <папка> init|snap \"<этап>\"|list|"
          "back <sha|этап> [--json]")

#: Одной фразой и без жаргона — ровно то, что скажут человеку, когда снимков
#: не будет вовсе. Отдельной константой, потому что это единственное место,
#: где отсутствие возможности объясняется тому, кто не пишет код.
БЕЗ_GIT = ("Снимки делать нечем: на этом компьютере нет программы, которая "
           "хранит прежние версии файлов. Работа пойдёт дальше, но вернуть "
           "проект к прежнему состоянию будет нельзя.")


def main() -> int:
    halt_if_paused()
    args = [a for a in sys.argv[1:] if a != "--json"]
    тихо = "--json" in sys.argv[1:]
    if len(args) < 2:
        print(_ВЫЗОВ, file=sys.stderr)
        return 3
    root, cmd, rest = Path(args[0]), args[1], args[2:]
    if cmd not in ("init", "snap", "list", "back"):
        print(_ВЫЗОВ, file=sys.stderr)
        return 3
    if not root.is_dir():
        print(f"папки «{root}» нет", file=sys.stderr)
        return 3
    if cmd in ("snap", "back") and len(rest) != 1:
        print(_ВЫЗОВ, file=sys.stderr)
        return 3
    if cmd in ("init", "list") and rest:
        print(_ВЫЗОВ, file=sys.stderr)
        return 3

    try:
        if cmd == "init":
            v = завести(root)
        elif cmd == "snap":
            v = снимок(root, rest[0])
        elif cmd == "list":
            v = список(root)
        else:
            v = откат(root, rest[0])
    except НетGit:
        v = {"код": 1, "нет_git": True, "линия": БЕЗ_GIT}
    except ПроверкаНедоступна as e:
        v = {"код": 1, "линия": f"снимок не сделан: проверить файлы на ключи "
                                f"нечем — {e}"}
    except (OSError, subprocess.TimeoutExpired) as e:
        v = {"код": 1, "линия": f"снимок не сделан: git не отработал — {e}"}

    код = v.get("код", 1)
    if not тихо:
        print(v["линия"], file=sys.stderr)
    print(json.dumps(v, ensure_ascii=False, indent=1))
    return код


if __name__ == "__main__":
    sys.exit(main())
