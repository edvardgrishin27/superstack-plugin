_ВЫЗОВ = ("вызов: checkpoint.py <папка> init|snap \"<этап>\"|list|"
          "back <sha|этап> [--json]")

#: Одной фразой и без жаргона — ровно то, что скажут человеку, когда снимков
#: не будет вовсе. Отдельной константой, потому что это единственное место,
#: где отсутствие возможности объясняется тому, кто не пишет код.
БЕЗ_GIT = ("Снимки делать нечем: на этом компьютере нет программы, которая "
           "хранит прежние версии файлов. Работа пойдёт дальше, но вернуть "
           "проект к прежнему состоянию будет нельзя.")


def main() -> int:
    halt_if_paused()
    args = [a for a in sys.argv[1:] if a != "--json"]
    тихо = "--json" in sys.argv[1:]
    if len(args) < 2:
        print(_ВЫЗОВ, file=sys.stderr)
        return 3
    root, cmd, rest = Path(args[0]), args[1], args[2:]
    if cmd not in ("init", "snap", "list", "back"):
        print(_ВЫЗОВ, file=sys.stderr)
        return 3
    if not root.is_dir():
        print(f"папки «{root}» нет", file=sys.stderr)
        return 3
    if cmd in ("snap", "back") and len(rest) != 1:
        print(_ВЫЗОВ, file=sys.stderr)
        return 3
    if cmd in ("init", "list") and rest:
        print(_ВЫЗОВ, file=sys.stderr)
        return 3

    try:
        if cmd == "init":
            v = завести(root)
        elif cmd == "snap":
            v = снимок(root, rest[0])
        elif cmd == "list":
            v = список(root)
        else:
            v = откат(root, rest[0])
    except НетGit:
        v = {"код": 1, "нет_git": True, "линия": БЕЗ_GIT}
    except ПроверкаНедоступна as e:
        v = {"код": 1, "линия": f"снимок не сделан: проверить файлы на ключи "
                                f"нечем — {e}"}
    except (OSError, subprocess.TimeoutExpired) as e:
        v = {"код": 1, "линия": f"снимок не сделан: git не отработал — {e}"}

    код = v.get("код", 1)
    if not тихо:
        print(v["линия"], file=sys.stderr)
    print(json.dumps(v, ensure_ascii=False, indent=1))
    return код


if __name__ == "__main__":
    sys.exit(main())
