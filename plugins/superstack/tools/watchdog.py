from datetime import datetime, timezone
from pathlib import Path

# Сиблинг-импорт тем же приёмом, что и в live_panel.py: `_here` добавляется в
# sys.path, а не пишется относительным `..`, потому что инструмент грузят и
# как скрипт, и через importlib из тестов — второе не наследует sys.path[0]
# автоматически. `tools/gauntlet.py` из корня репозитория НЕ импортируется:
# он в поставку плагина не входит, а watchdog.py обязан работать и там, куда
# gauntlet.py никогда не попадёт.
_here = Path(__file__).resolve().parent
if str(_here) not in sys.path:
    sys.path.insert(0, str(_here))
import stall  # noqa: E402
# Запись — общим модулем: замок, уникальный временный сосед и режим
# доступа, который от записи не расширяется. Сторож по замыслу живёт
# РЯДОМ с другими процессами, и «пишет только он» тут допущение, а не
# свойство: цена ошибки в нём — молча потерянная чужая правка.
import atomic_store  # noqa: E402

#: Как часто опрашивать журналы. Компромисс, а не круглое число: разбор
#: журнала волны стоит миллисекунды (несколько файлов на тысячи строк), так
#: что опрос каждые 90 секунд обходится прогону практически бесплатно — и при
#: этом застревание видно не позже чем через пару опросов после того, как
#: `stall.разобрать` впервые о нём скажет. Реже — часовая волна успевала бы
#: простоять большую часть часа незамеченной; чаще — цена такая же, а пользы
#: не прибавляется: признаки петли и слепой работы считаются по количеству
#: шагов, а не по секундам, и между соседними шагами агента обычно проходит
#: заметно больше времени, чем секунды.
ИНТЕРВАЛ_ПО_УМОЛЧАНИЮ = 90

#: Бюджет и шаг опроса для `--check`/`--stop`: сторож стартует отвязанным
#: (`nohup … &`) и мог не успеть записать pid-файл за первые миллисекунды —
#: тот же зазор, что закрывает `CHECK_BUDGET_SECONDS` в live_panel.py, только
#: своей константой: сторож проверяет процесс, а не порт, и делить с панелью
#: число, означающее разное, значило бы притвориться, что это одна величина.
CHECK_BUDGET_SECONDS = 3.0
CHECK_POLL_SECONDS = 0.25

#: Сколько ждать чистого выхода после SIGTERM, прежде чем прибрать pid-файл
#: самостоятельно. Обработчик сигнала прерывает `time.sleep` немедленно, так
#: что в норме процесс укладывается в первые же доли секунды; бюджет —
#: страховка на случай, если он как раз посреди записи снимка на диск.
STOP_BUDGET_SECONDS = 5.0

#: Каталог состояния переопределяется той же переменной, что и реестр проектов
#: в `enable.py`: без неё тесты писали бы в настоящий ~/.claude человека.
STATE_ENV = "SUPERSTACK_STATE_DIR"
WATCH_DIR = "watch"
SNAPSHOT = "stall-watch.json"
LOG = "stall-watch.log"
PID_FILE = "stall-watch.pid"
STOP_FILE = "stall-watch.stop"

КОД_НОРМА = 0
КОД_ЗАСТРЯЛ = 1
КОД_НЕЧЕМ = 2
КОД_ВЫЗОВ = 3
КОД_ЗАНЯТО = 4

#: Собственная добавка к дисциплине честности `stall.py`: то, чего не знает
#: именно ОПРОС НА ТАЙМЕРЕ, а не разовая проверка журнала.
СВОЁ_ЧЕГО_НЕ_ЗНАЕМ = (
    f"событие короче интервала опроса ({ИНТЕРВАЛ_ПО_УМОЛЧАНИЮ} с) могло "
    "начаться и закончиться между двумя срезами — незамеченным",
    "если сам сторож упал (не хватило памяти, процесс убили), это увидит "
    "только следующий --check или --stop — до тех пор тишина в логе "
    "неотличима от того, что застреваний не было",
)


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _состояние(проект: Path) -> Path:
    """Где лежат файлы сторожа. ВНЕ дерева проекта — намеренно.

    Причина названа в заголовке файла: наблюдатель, который каждые 90 секунд
    правит наблюдаемое дерево, ломает измерения того, за кем следит. Подпапка
    по имени проекта нужна, чтобы два проекта не делили один pid-файл.
    """
    корень = os.environ.get(STATE_ENV) or str(Path.home() / ".claude" / "superstack")
    return Path(корень) / WATCH_DIR / stall.слаг(проект)


def _поиск(проект: Path) -> dict:
    """Сколько журналов субагентов видно и в КАКИХ каталогах их искали.

    Без второй половины первая ничего не значит: «агентов волны: 0» неотличимо
    от «журналы лежат не там, где я смотрю», а ночью было именно второе —
    сторож честно печатал ноль по каталогу, которого сессия не заполняла.
    """
    return {"журналов": len(stall.подагенты(проект)),
            "искал_в": [str(d) for d in stall.каталоги_журналов(проект)]}


def _сказать_где_искали(поиск: dict) -> None:
    print(f"  журналов субагентов найдено: {поиск['журналов']}", file=sys.stderr)
    for d in поиск["искал_в"]:
        print(f"    искал в: {d}", file=sys.stderr)


def _alive(pid: int) -> bool:
    """Жив ли процесс с этим pid.

    Тот же приём, что у `_alive()` в корневом `tools/gauntlet.py`, но не
    импортирован оттуда, а повторён: `gauntlet.py` — инструмент разработки
    и в поставку плагина не входит, а `watchdog.py` обязан работать именно
    в поставке. Риск повторения тот же, что там уже назван и принят: если
    pid переиспользован другим процессом ОС в узком окне жизни одной волны,
    сторож примет чужой процесс за своего. Цена ошибки в другую сторону —
    два сторожа поверх одного проекта — выше, поэтому сомнение решается в
    пользу «жив».

    Повторение копией опасно ещё и тем, что расходится молча: охрана Windows
    в двух других копиях этого кода была, а здесь — в единственной копии,
    которая едет к людям, — отсутствовала. Теперь фраза «риск тот же»
    описывает то, что есть, а не то, что имелось в виду.
    """
    if os.name == "nt":
        # На Windows сигнала 0 нет, и `os.kill` там не спрашивает, а УБИВАЕТ:
        # проверка «жив ли сторож» убила бы сторожа. Спросить нечем, поэтому
        # «не знаю» читается как «жив» — как и в двух соседних копиях.
        return True
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except OSError:
        return True
    return True


def _pid_читать(pid_путь: Path) -> "int | None":
    """Жив ли записанный в файле сторож. Чистит файл, оставшийся от мёртвого
    процесса, — иначе следующий `--serve` унаследует чужую «занятость»."""
    if not pid_путь.is_file():
        return None
    try:
        pid = int(pid_путь.read_text("utf-8").strip())
    except (OSError, ValueError):
        return None
    if _alive(pid):
        return pid
    try:
        pid_путь.unlink()
    except OSError:
        pass
    return None


def _атомарная_запись(путь: Path, текст: str) -> None:
    """Запись общим модулем — целиком или никак.

    Обычная `write_text` на файле, который читают `--check`/`--stop` в
    параллель с работающим `--serve`, оставляет окно, где на диске лежит
    половина JSON. Замена файла закрывает его целиком, а не «в среднем».

    Своя копия этих трёх строк здесь была, и в ней жили те же три дефекта,
    что у соседей: общее на всех имя временного соседа, режим доступа по umask
    вместо приватного и никакого замка между двумя сторожами одного проекта.
    """
    with atomic_store.Lock(путь):
        atomic_store.записать(путь, текст)


def _текущие(проект: Path) -> dict:
    """Имя файла -> путь, для всех журналов субагентов проекта ПРЯМО СЕЙЧАС."""
    return {f.name: f for f in stall.подагенты(проект)}


def _срез(проект: Path, зоны: list, вне_волны: set) -> dict:
    """Один опрос: вердикт по каждому журналу, которого не было ДО запуска
    сторожа. Форма результата — та же, что у `stall.проверить_все`."""
    волна = sorted((f for имя, f in _текущие(проект).items()
                    if имя not in вне_волны), key=lambda p: p.name)
    агенты = [stall.вердикт_журнала(f, зоны) for f in волна]
    return {"код": stall.агрегировать(агенты), "агенты": агенты}


def _обновить_историю(история: dict, срез_агенты: list, лог_путь: Path) -> dict:
    """Новая история поверх старой; строки в лог — только там, где код
    агента ИЗМЕНИЛСЯ, а не на каждый опрос.

    Не мутирует `история` — строится новый словарь, а не правится старый на
    месте: сторож живёт часами, и дисциплина «новый объект вместо правки
    старого» здесь стоит копейки (агентов — единицы), а не только принцип.

    Первое появление агента (`было is None`) в лог не идёт: это не переход,
    а начало наблюдения, и отмечать его как событие значило бы шуметь на
    каждую новую задачу волны.
    """
    новая, строки = dict(история), []
    for a in срез_агенты:
        # Раздельно, а не одним `а, б, в = x, y, история.get(а)`: `имя` — цель
        # ЭТОГО ЖЕ присваивания, и Python считает её локальной переменной уже
        # на этапе разбора; чтение до завершения строки роняет UnboundLocalError.
        имя, код = a["агент"], a["код"]
        было = история.get(имя)
        когда_либо_1 = код == 1 or bool(было and было["когда_либо_1"])
        новая[имя] = {"код": код, "когда_либо_1": когда_либо_1}
        if было is None or было["код"] == код:
            continue
        if код == 1:
            п = "; ".join(a["причины"])[:200]
            строки.append(f"{_now_iso()} ЗАСТРЯЛ {имя}: {п}")
        elif было["код"] == 1:
            строки.append(f"{_now_iso()} БОЛЬШЕ НЕ ЗАСТРЯЛ {имя}: "
                          "в последнем срезе причин нет")
    if строки:
        with лог_путь.open("a", encoding="utf-8") as f:
            f.write("\n".join(строки) + "\n")
    return новая


def _итоговый_код(история: dict) -> int:
    """Код по ВСЕЙ истории наблюдения, а не по последнему срезу.

    Агент, который был застрявшим и позже сдвинулся, обязан остаться
    видимым как «застревал»: если считать только последний срез, починка
    прямо перед `--stop` стирает из отчёта ровно то происшествие, ради
    которого сторожа и заводили.
    """
    if any(h["когда_либо_1"] for h in история.values()):
        return КОД_ЗАСТРЯЛ
    if история:
        return stall.агрегировать([{"код": h["код"]} for h in история.values()])
    return КОД_НЕЧЕМ


def _записать_снимок(путь: Path, проект: Path, интервал: int, встал: str,
                      срез: dict, история: dict) -> None:
    данные = {
        "инструмент": "stall-watchdog", "проект": str(проект),
        "pid": os.getpid(), "интервал_с": интервал,
        "встал": встал, "обновлён": _now_iso(),
        "код": _итоговый_код(история),
        "агенты": срез["агенты"],
        "когда_либо_застревали": sorted(n for n, h in история.items()
                                        if h["когда_либо_1"]),
        "чего_не_знаем": list(stall.ЧЕГО_НЕ_ЗНАЕМ) + list(СВОЁ_ЧЕГО_НЕ_ЗНАЕМ),
    }
    _атомарная_запись(путь, json.dumps(данные, ensure_ascii=False, indent=1))


def _cmd_serve(проект: Path, интервал: int, зоны: list) -> int:
    сс = _состояние(проект)
    сс.mkdir(parents=True, exist_ok=True)
    pid_путь, стоп_путь = сс / PID_FILE, сс / STOP_FILE
    снимок_путь, лог_путь = сс / SNAPSHOT, сс / LOG

    занят = _pid_читать(pid_путь)
    if занят:
        print(f"НЕ УДАЛОСЬ: сторож для {проект} уже запущен (pid {занят}) — "
              f"сначала: python3 watchdog.py {проект} --stop", file=sys.stderr)
        return КОД_ЗАНЯТО

    try:
        стоп_путь.unlink()  # хвост прошлого запуска — новый не наследует его
    except OSError:
        pass
    pid_путь.write_text(str(os.getpid()), encoding="utf-8")

    def _на_termинал(signum, frame):  # noqa: ARG001 — сигнатура обработчика фиксирована
        raise SystemExit(0)

    signal.signal(signal.SIGTERM, _на_termинал)

    вне_волны = set(_текущие(проект))
    встал = _now_iso()
    история: dict = {}
    try:
        while not стоп_путь.is_file():
            срез = _срез(проект, зоны, вне_волны)
            история = _обновить_историю(история, срез["агенты"], лог_путь)
            _записать_снимок(снимок_путь, проект, интервал, встал, срез, история)
            time.sleep(интервал)
    except SystemExit:
        pass
    finally:
        try:
            pid_путь.unlink()
        except OSError:
            pass
        try:
            стоп_путь.unlink()
        except OSError:
            pass
    return 0


def _cmd_check(проект: Path) -> int:
    """Только живучесть — жив ли процесс. Ни слова о содержимом волны: это
    вопрос `--stop`, а не `--check` (см. заголовок файла)."""
    pid_путь = _состояние(проект) / PID_FILE
    дедлайн = time.monotonic() + CHECK_BUDGET_SECONDS
    pid = None
    while True:
        pid = _pid_читать(pid_путь)
        if pid or time.monotonic() >= дедлайн:
            break
        time.sleep(CHECK_POLL_SECONDS)
    if not pid:
        print(f"НЕ УДАЛОСЬ: сторож для {проект} не отвечает — не запущен, "
              "не успел подняться или упал", file=sys.stderr)
        return КОД_ЗАНЯТО
    print(f"сторож жив: pid {pid}", file=sys.stderr)
    снимок_путь = _состояние(проект) / SNAPSHOT
    if снимок_путь.is_file():
        try:
            данные = json.loads(снимок_путь.read_text("utf-8"))
            print(f"  последний срез: {данные.get('обновлён', '?')}, "
                  f"агентов волны: {len(данные.get('агенты') or [])}",
                  file=sys.stderr)
        except (OSError, ValueError):
            pass
    поиск = _поиск(проект)
    _сказать_где_искали(поиск)
    print(json.dumps({"живой": True, "pid": pid, **поиск}, ensure_ascii=False))
    return 0


def _cmd_stop(проект: Path) -> int:
    сс = _состояние(проект)
    pid_путь, стоп_путь = сс / PID_FILE, сс / STOP_FILE
    снимок_путь, лог_путь = сс / SNAPSHOT, сс / LOG

    pid = _pid_читать(pid_путь)
    был_жив = bool(pid)
    if был_жив:
        стоп_путь.write_text(_now_iso(), encoding="utf-8")
        try:
            os.kill(pid, signal.SIGTERM)
        except OSError:
            pass
        дедлайн = time.monotonic() + STOP_BUDGET_SECONDS
        while pid_путь.is_file() and time.monotonic() < дедлайн:
            time.sleep(CHECK_POLL_SECONDS)
        try:
            pid_путь.unlink()  # не дождались чистого выхода — прибираем сами
        except OSError:
            pass
        try:
            стоп_путь.unlink()
        except OSError:
            pass

    код, застревали = КОД_НЕЧЕМ, []
    if снимок_путь.is_file():
        try:
            данные = json.loads(снимок_путь.read_text("utf-8"))
            код = данные.get("код", КОД_НЕЧЕМ)
            застревали = данные.get("когда_либо_застревали") or []
        except (OSError, ValueError):
            pass

    поиск = _поиск(проект)
    if not был_жив:
        detail = "сторож для этого проекта не был запущен — останавливать нечего"
        if застревали:
            detail += f" (по оставшемуся снимку застревал(и): {', '.join(застревали)})"
        код = КОД_ЗАСТРЯЛ if застревали else КОД_НЕЧЕМ
    elif застревали:
        detail = f"застревал(и) хотя бы раз за волну: {', '.join(застревали)}"
    elif код == КОД_НОРМА:
        detail = "никто не был замечен застрявшим"
    else:
        # «Судить нечем» без числа читалось как «волна прошла тихо». Это не
        # одно и то же: ноль найденных журналов означает, что смотреть было
        # не на что, и отличить это от «смотрел и не нашёл причин» обязано
        # само сообщение, а не последующие раскопки.
        detail = ("ни по одному агенту не набралось шагов, чтобы судить; "
                  f"журналов субагентов видно {поиск['журналов']}")

    голова = {КОД_НОРМА: "СТОРОЖ ОСТАНОВЛЕН",
              КОД_ЗАСТРЯЛ: "СТОРОЖ ОСТАНОВЛЕН — БЫЛО ЗАСТРЕВАНИЕ",
              КОД_НЕЧЕМ: "СТОРОЖ ОСТАНОВЛЕН — СУДИТЬ НЕЧЕМ"}[код]
    print(f"{голова}: {detail}", file=sys.stderr)
    _сказать_где_искали(поиск)
    print(f"  лента: {лог_путь}", file=sys.stderr)
    print(json.dumps({"код": код, "detail": detail, "застревали": застревали,
                      "лента": str(лог_путь), **поиск}, ensure_ascii=False))
    return код


def main(argv: list) -> int:
    зоны, интервал, простые, режим = [], ИНТЕРВАЛ_ПО_УМОЛЧАНИЮ, [], None
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--zone" and i + 1 < len(argv):
            зоны.append(argv[i + 1]); i += 2; continue
        if a == "--interval" and i + 1 < len(argv):
            try:
                интервал = int(argv[i + 1])
            except ValueError:
                print(f"неверный --interval: {argv[i + 1]}", file=sys.stderr)
                return КОД_ВЫЗОВ
            i += 2; continue
        if a in ("--serve", "--check", "--stop"):
            режим = a; i += 1; continue
        if a.startswith("--"):
            print(f"неизвестный флаг: {a}", file=sys.stderr)
            return КОД_ВЫЗОВ
        простые.append(a); i += 1

    if len(простые) != 1 or режим is None:
        print("вызов: watchdog.py <каталог проекта> "
              "(--serve [--interval сек] [--zone путь]... | --check | --stop)",
              file=sys.stderr)
        return КОД_ВЫЗОВ

    проект = Path(простые[0]).resolve()
    if режим == "--serve":
        return _cmd_serve(проект, интервал, зоны)
    if режим == "--check":
        return _cmd_check(проект)
    return _cmd_stop(проект)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
