#!/usr/bin/env python3
"""SUPERSTACK — сторож волны: следит, пока оркестратор занят и спросить некому.

Зачем это отдельный процесс, а не ещё один флаг у `stall.py`.

Волна уходит одним сообщением, по вызову агента на таск — так поймано в
`4-работа.md`. Пока параллельные помощники не вернулись, оркестратор занят
ровно этим одним ходом и не может вызвать ни `stall.py`, ни что-либо ещё:
инструмент, который проверял бы волну, обязан быть ДРУГИМ процессом, вставшим
ДО волны, а не ещё одной командой в том же ходу. Panel.html уже показал этот
приём — `live_panel.py --serve` поднимается в фоне `nohup … &` из фазы 0 и
живёт весь прогон, — но задача здесь другая, и часть решений это меняет:

  · панель живёт ВЕСЬ прогон, сторож — ровно одну волну. Волна кончилась —
    сторож обязан умереть вместе с ней, а не висеть в фоне до перезапуска
    машины и не путать следующую волну с этой.
  · панель ничего не решает сама — читает `state.json`, который пишут другие.
    Сторож сам считает: он вызывает ту же обнаруживающую логику, что и
    `stall.py` (`вердикт_журнала`, `агрегировать`), просто на таймере.
  · у панели нет вопроса «что было раньше»: она всегда показывает текущее
    состояние. У сторожа есть — см. `подагенты()` в `stall.py`: одна сессия
    может успеть прогнать несколько волн подряд, и без точки отсчёта сторож
    накануне волны судил бы вперемешку с задачами позапрошлого часа. Поэтому
    сторож на старте запоминает, какие журналы субагентов УЖЕ существуют
    (`_текущие`), и дальше судит только то, что появилось ПОСЛЕ.

Живучесть сторожа проверяется тем же приёмом, что и у панели, — отдельной
синхронной командой (`--check`) с честным кодом возврата, а не косвенно по
тому, что успел напечатать отвязанный (`nohup … &`) процесс: весь его вывод
летит в /dev/null, и узнать оттуда о сбое старта неоткуда. Механизм при этом
проще панели: там `panel_is_live` сверяет ответ порта побайтово с файлом на
диске — риск в том, что НА ТОМ ЖЕ ПОРТУ отвечает чужой процесс. У сторожа нет
порта и нет соседей: pid-файл сторожа либо называет живой процесс, либо нет,
и это снимается проверкой `os.kill(pid, 0)` без сетевого раунда.

КУДА УХОДИТ ТРЕВОГА. Панель не трогается этим файлом (её код правит другой
человек в другую сторону), а её JS читает только известные ей поля
`state.json` — просто дописать туда лишнее ничего не покажет. Поэтому у
сторожа СВОИ файлы, и лежат они ВНЕ дерева проекта — в
`~/.claude/superstack/watch/<имя проекта>/`:

  · stall-watch.json — снимок ПОСЛЕДНЕГО среза, перезаписывается целиком;
  · stall-watch.log  — человекочитаемая лента: одна строка на КАЖДУЮ смену
    состояния агента (стал застрявшим / перестал), а не на каждый опрос —
    иначе часовая волна оставила бы сорок повторов одной и той же находки.

Раньше эти файлы писались в `.superstack/` самого проекта, и это была ошибка
не стиля, а измерения. Сторож переписывает их каждые 90 секунд — то есть ПОД
идущим прогоном планки: отпечаток рабочего дерева расходился сам собой, и
ворота «набор» дважды за ночь дали «упало 1 из N» там, где прямой прогон сразу
следом был зелёным. Наблюдатель, меняющий наблюдаемое, — не наблюдатель.

Это не «увидели немедленно»: пока волна идёт, читать файлы всё равно некому —
оркестратор занят тем же ходом, что и сторож наблюдает. Выигрыш другой: когда
ход возвращается, история уже на диске, и «застряло в 12:03, отпустило в
12:11» видно сразу, а не восстанавливается по памяти задним числом. Вывести
это на панель в реальном времени — законное продолжение, но чужими руками:
`live_panel.py` в границах этой правки только читается.

ЧЕСТНОСТЬ. Сторож, как и `stall.py`, видит ДВИЖЕНИЕ, а не правильность: он
не имеет права утверждать, что работа идёт ВЕРНО — только что журнал растёт
и не похож на петлю. Каждый снимок несёт список того, чего он не знает
(`ЧЕГО_НЕ_ЗНАЕМ` из `stall.py`), и добавляет к нему собственные два пункта
(`СВОЁ_ЧЕГО_НЕ_ЗНАЕМ` ниже).

  python3 watchdog.py <каталог проекта> --serve [--interval сек] [--zone п]...
  python3 watchdog.py <каталог проекта> --check
  python3 watchdog.py <каталог проекта> --stop

  `--serve` запускают отвязанным (`nohup … >/dev/null 2>&1 &`) ПЕРЕД волной;
  `--check` сразу следом — отдельная синхронная команда, её код и решает,
  считать ли сторожа поднятым. `--stop` — сразу ПОСЛЕ волны, до всего
  остального: у неё же код возврата говорит, застревал ли кто-то за время
  наблюдения, даже если к моменту остановки это уже прошло.

  код 0 — --check: жив; --stop: жив был, но никто не застревал
  код 1 — --stop: хотя бы один агент волны замечен застрявшим (когда-либо)
  код 2 — --stop: наблюдений не набралось ни по одному агенту; либо сторож
          не был запущен вовсе — останавливать нечего
  код 3 — ошибка вызова
  код 4 — --serve: для этого проекта уже есть живой сторож; --check: не
          отвечает — не запущен, не успел подняться, или упал
"""
