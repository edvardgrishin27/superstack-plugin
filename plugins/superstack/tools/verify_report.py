#!/usr/bin/env python3
"""SUPERSTACK — что о своём наборе сказал САМ прогонщик.

Отдельный файл, потому что это отдельный вопрос. Гейт (`verify.py`) решает,
закрывать ли ход; здесь решается более раннее и более узкое: чем ЯВЛЯЕТСЯ
уже состоявшийся прогон — провалом, пустотой, настоящим прогоном или отчётом,
который разобрать не вышло.

Разделение ИСТОЧНИКОВ и есть механизм. Слова, которые печатает о своём наборе
сам прогонщик, и слова, которые печатает содержимое чужого теста, — разные
утверждения; пока они лежали одной кучей текста, красный прогон с неудачной
фразой в теле assert читался как «проверять было нечего», и гейт отдавал 2
вместо 1.

Здесь ничего не запускается и ничего не пишется: на входе команда проверки,
код возврата и текст её вывода, на выходе — одно из четырёх слов.
"""
from __future__ import annotations

import re
from typing import TYPE_CHECKING

if TYPE_CHECKING:                                    # только ради аннотации
    from verify import Check                         # noqa: F401


# Признаки «инструмент отработал, но не проверил ничего». Формально успех —
# фактически пусто. Самая тихая форма зелёного, который ничего не стоит.
#
# Граница перед нулём (?<!\d) — не украшение. Без неё «0 passing» находится
# внутри «10 passing», и зелёный mocha-прогон на 10, 20, 100 тестах объявляется
# пустым: проект с настоящими тестами получает «проверять нечем» и гейт для
# него не зеленеет никогда.
EMPTY_MARKERS = (
    re.compile(r"no tests ran", re.I),
    re.compile(r"No tests found", re.I),
    re.compile(r"collected 0 items"),
    re.compile(r"Tests:\s+0 total", re.I),
    re.compile(r"(?<!\d)0 passing", re.I),
    re.compile(r"no test files", re.I),
    re.compile(r"\[no test files\]", re.I),
    re.compile(r"testing: warning: no tests to run", re.I),
    # Русскоязычный прогонщик — их пишут в проектах, которые собирает эта же
    # система, и её собственный совет «пусто ≠ зелено» приводит ровно к такой
    # строке рядом с ненулевым кодом.
    re.compile(r"тестов не найдено", re.I),
)

# Заглушка, которую `npm init` кладёт в каждый второй пакет:
#   "test": "echo \"Error: no test specified\" && exit 1"
# Она отличается от прочих пустых прогонов НЕНУЛЕВЫМ кодом, поэтому и читается
# как «тесты есть и они красные». Диагноз ложный: тестов нет вовсе, чинить
# нечего, а ход при этом блокируется требованием починить несуществующее.
# Поэтому маркер действует при ЛЮБОМ коде возврата, в отличие от EMPTY_MARKERS.
STUB_MARKERS = (
    re.compile(r"no test specified", re.I),
)


def _nothing_was_checked(code: int, out: str) -> bool:
    """Прогон был, но проверять оказалось нечего."""
    if code == 5:                       # pytest: тестов не найдено
        return True
    if any(rx.search(out) for rx in STUB_MARKERS):
        return True
    # Пустота узнаётся по ВЫВОДУ, а не по коду возврата — при любом коде.
    #
    # Первая попытка этой починки читала код 2 как «нечего проверять», потому
    # что 2 означает это во всей системе. Правило оказалось шире правды: у make
    # код 2 — «сборка провалилась», и красная объявленная проверка перестала
    # блокировать ход. Поймал это тест, который гоняет настоящий make с целью
    # `exit 1`, — то есть чужая семантика кода была измерена, а не додумана.
    #
    # Живой повод для самой починки остаётся: исполнителю было велено вернуть 2
    # на пустом наборе, чтобы «пусто» не выглядело «зелено»; при чтении по коду
    # гейт объявлял это провалом и отправлял чинить работающий код. Правильный
    # признак — строка, которую прогонщик печатает сам: она принадлежит ему, а
    # код возврата принадлежит соглашению, которого у всех разное.
    return any(rx.search(out) for rx in EMPTY_MARKERS)


# --------------------------------------------------------------------------
# адаптер pytest: что о своём наборе сказал САМ прогонщик
# --------------------------------------------------------------------------
# Признаки пустоты выше ищутся во ВСЁМ выводе проверки — а в него попадает
# тело чужого теста. `assert "No tests found" == "Unexpected error"` честно
# падает, pytest печатает «1 failed» и отдаёт единицу, но фраза из ТЕЛА теста
# срабатывает как признак пустого набора: красный прогон читается как
# «проверять было нечего», гейт отдаёт 2 вместо 1, и Stop-хук разрешает
# закрыть ход «без доказательства». Достаточно неудачного слова в сообщении
# assert, в имени файла или в исходнике — и красное перестаёт быть красным.
#
# Чинится это НЕ чтением кода возврата вместо вывода: так уже пробовали, и
# красный make (у него 2 — «сборка провалилась») перестал блокировать ход.
# Чинится разделением ИСТОЧНИКОВ. Слова, которые печатает о своём наборе сам
# прогонщик, и слова, которые печатает содержимое чужого теста, — разные
# утверждения, а до сих пор это была одна куча текста. Первые перевешивают
# вторые.
#
# Адаптер ровно один — для pytest, чью сводку мы знаем. Общего фреймворка
# адаптеров тут нет намеренно: выдумывать форму чужой сводки значило бы снова
# считать желаемое, поэтому для остальных прогонщиков поведение прежнее (см.
# `_nothing_was_checked`), и это ограничение названо, а не замаскировано.

#: Как прочитан прогон. Ответа четыре, а не два: «отчёт не разобран» обязано
#: отличаться и от «пусто», и от «прогон был», иначе непрочитанное молча
#: превращается в доказательство.
REPORT_FAILED = "failed"
REPORT_EMPTY = "empty"
REPORT_RAN = "ran"
REPORT_UNCLEAR = "unclear"

#: Итоговая строка pytest — единственное место, где он говорит о СВОЁМ
#: наборе: «1 failed, 2 passed in 0.12s», в обычном режиме ещё и в рамке из
#: `=`. Форма привязана к строке ЦЕЛИКОМ и не терпит отступа: в разборе
#: падения строки чужого теста идут с приставкой («E   », «>   », отступ) и
#: под неё не подходят.
_PYTEST_SUMMARY = re.compile(
    r"^=*\s?(?P<msg>no tests ran|\d+[0-9a-z ,]*?) in \d[\d.]*s"
    r"(?: \([^)]*\))?\s?=*$")

#: Пары «число — слово» из этой строки: решение принимают ЧИСЛА, а не
#: вхождение подстроки где-то в выводе.
_PYTEST_COUNT = re.compile(r"(\d+) ([a-z]+)")

#: Сколько тестов pytest собрал — второй его машинный ответ, который остаётся
#: и там, где итоговой строки в выводе не оказалось. Тоже с начала строки:
#: `collected 0 items` из тела чужого теста печатается с отступом.
_PYTEST_COLLECTED = re.compile(r"^collected (\d+) items?")

#: Сколько строк с конца просматривается в поисках сводки. Своё pytest
#: печатает последним, но stdout и stderr здесь склеены, и предупреждение,
#: ушедшее в stderr, встаёт ПОСЛЕ сводки. Окно закрытое и небольшое: чем оно
#: шире, тем ближе поиск подходит к телу чужого теста — то есть к тому, ради
#: чего сужение и заводилось.
_SUMMARY_TAIL_LINES = 25

#: Слова, которыми pytest называет падение. Ненулевое число при любом из них
#: — приговор, и он перевешивает любой признак пустоты в остальном тексте.
_FAILED_WORDS = ("failed", "error", "errors")

#: Слова, означающие «тест реально выполнили».
_RAN_WORDS = ("passed", "failed", "error", "errors",
              "xpassed", "xfailed", "skipped")

#: Слова, которые про набор говорят, но выполнением не являются: сводка из
#: одних только них означает, что не проверено ничего.
_IDLE_WORDS = ("deselected", "warning", "warnings")


def _pytest_summary(out: str) -> "dict | None":
    """Числа из итоговой строки pytest. None — её в выводе нет."""
    for line in reversed(out.splitlines()[-_SUMMARY_TAIL_LINES:]):
        m = _PYTEST_SUMMARY.match(line)
        if m:
            return {w: int(n) for n, w in _PYTEST_COUNT.findall(m.group("msg"))}
    return None


def _pytest_collected(out: str) -> "int | None":
    """Сколько тестов pytest собрал. None — он этого не печатал.

    Берётся последнее вхождение: при параллельном прогоне строка печатается
    не один раз, и итоговым остаётся последнее число.
    """
    found = None
    for line in out.splitlines():
        m = _PYTEST_COLLECTED.match(line)
        if m:
            found = int(m.group(1))
    return found


def _pytest_report(out: str) -> "str | None":
    """Что pytest сказал о СВОЁМ наборе. None — вывод не его, судить нечем.

    Порядок ответов и есть правило «отчёт перевешивает подстроку»: сначала
    названные прогонщиком падения, и только потом всё остальное.
    """
    counts = _pytest_summary(out)
    if counts is None:
        # Сводки нет — но собранное число он печатает отдельной строкой, и
        # ноль в ней такой же машинный ответ, как и она сама.
        return REPORT_EMPTY if _pytest_collected(out) == 0 else None
    if any(counts.get(w, 0) for w in _FAILED_WORDS):
        return REPORT_FAILED
    if any(counts.get(w, 0) for w in _RAN_WORDS):
        return REPORT_RAN
    if all(w in _IDLE_WORDS for w in counts):
        # Сюда же попадает «no tests ran»: слов в ней нет вовсе.
        return REPORT_EMPTY
    # Сводка есть, а слова в ней незнакомые (плагин, чужая сборка pytest).
    # Считать нечего — и это НАЗЫВАЕТСЯ, а не округляется до пустоты.
    return REPORT_UNCLEAR


def _is_pytest(check: Check) -> bool:
    """Наш ли это прогонщик — по команде, которую мы сами и собрали.

    Тот же признак, что в `_why_unrunnable`: строку `check.id` подаёт кто
    угодно, команду — только `_all_checks`.
    """
    return check.cmd[:3] == ("python3", "-m", "pytest")


def _read_the_run(check: Check, code: int, out: str) -> str:
    """Как прочитан прогон: пусто / провал / прогон был / отчёт не разобран.

    Порядок тут не косметика. У pytest коды 5 и 0 — его СОБСТВЕННОЕ машинное
    утверждение о наборе («не собрал ни одного» и «собрал и все прошли»), и
    внутри его адаптера читать их правильно: чужое соглашение о кодах здесь
    ни при чём, а без нуля прогонщик, которому велено молчать (`-q` поверх
    `-q` в настройках проекта), остался бы непрочитанным на пустом месте.
    Дальше слово берёт сводка — она есть и там, где pytest запущен чужой
    командой: целью Makefile, скриптом пакета. И только если своего
    прогонщика прочитать не вышло, это называется отдельным словом. Для
    незнакомых прогонщиков — общие признаки пустоты, как было.
    """
    if _is_pytest(check):
        if code == 5:
            return REPORT_EMPTY
        if code == 0:
            return REPORT_RAN
    report = _pytest_report(out)
    if report is not None:
        return report
    if _is_pytest(check):
        return REPORT_UNCLEAR
    return REPORT_EMPTY if _nothing_was_checked(code, out) else REPORT_RAN
