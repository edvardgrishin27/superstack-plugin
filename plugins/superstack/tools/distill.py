#!/usr/bin/env python3
"""SUPERSTACK — чужое знание входит скиллами по задачам, а не документом целиком.

Зачем нарезать, если можно положить как есть.

Внешний корпус — методичка, статья, чужой репозиторий — приходит документом:
одна большая тема, внутри которой перемешаны десять задач. Положить его в
скилл целиком просто и почти бесполезно: скилл выбирается по описанию «когда
меня брать», а у документа такого ответа нет. Он подтягивается либо всегда,
либо никогда, и оба исхода одинаково плохи.

Поэтому чужое режется ПО ЗАДАЧАМ: один скилл — одна задача, которую человек
может назвать своими словами. Творческая часть — где проходят швы — работа
модели. Здесь проверяется форма, которую иначе теряют.

Три правила:

  1. ИМЯ НЕСЁТ ПРЕФИКС ИСТОЧНИКА. Не ради красоты: без него чужой скилл
     сталкивается с твоим по имени, и выигрывает случайный. Плюс через месяц
     видно, откуда это взялось.
  2. ОДИН СКИЛЛ — ОДНА ЗАДАЧА. Описание, перечисляющее «и то, и это, и ещё»,
     означает, что документ положили целиком и нарезку не делали.
  3. ПРОИСХОЖДЕНИЕ НАЗВАНО ВНУТРИ. Через полгода нельзя будет отличить
     выстраданное на своих прогонах от переписанного из чужой статьи — а это
     разного веса знание.

  python3 distill.py <каталог скиллов> --source <имя источника> [--json]
  python3 distill.py --template <источник> <задача>

  код 0 — форма соблюдена, 1 — есть нарушения, 2 — читать нечего,
  3 — ошибка вызова
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

ИМЯ = re.compile(r"(?m)^name:\s*(.+?)\s*$")
ОПИСАНИЕ = re.compile(r"(?m)^description:\s*(.+?)\s*$")
ИСТОЧНИК = re.compile(r"(?mi)^источник:\s*(.+?)\s*$")

#: Признаки того, что документ положили целиком: описание обещает несколько
#: задач разом. Список короткий и грубый намеренно — он ловит форму, а не смысл.
МНОГОЗАДАЧНОСТЬ = (" и ещё", ", а также", "всё о ", "полное руководство",
                   "методология", "справочник по")

#: Сколько задач может обещать одно описание. Две — уже документ.
СОЮЗОВ = 2


def template(источник: str, задача: str) -> str:
    имя = f"{источник}-{задача}".lower().replace(" ", "-")
    return "\n".join([
        "---",
        f"name: {имя}",
        f"description: Когда нужно {задача}. Одна задача, а не тема целиком.",
        "---",
        "",
        f"Источник: {источник}",
        "",
        "## Когда брать",
        "",
        "[Как человек назовёт эту задачу своими словами.]",
        "",
        "## Что делать",
        "",
        "[Шаги. Из чужого документа — только то, что относится к ЭТОЙ задаче.]",
        "",
        "## Чем это отличается от нашего",
        "",
        "[Если противоречит нашему подходу — сказать вслух и объяснить, что взяли.]",
        "",
    ])


def check(каталог: Path, источник: str) -> dict:
    """Форма дистиллированных скиллов. Проверяется то, что теряют."""
    if not каталог.is_dir():
        return {"status": "unknown", "detail": f"нет каталога скиллов: {каталог}"}
    свои = sorted(d for d in каталог.iterdir() if (d / "SKILL.md").is_file())
    из_источника = [d for d in свои if d.name.startswith(источник + "-")]
    if not из_источника:
        return {"status": "unknown",
                "detail": f"скиллов с префиксом «{источник}-» нет — "
                          "дистиллировать ещё нечего"}

    находки = []
    for d in из_источника:
        текст = (d / "SKILL.md").read_text("utf-8", errors="replace")
        имя = ИМЯ.search(текст)
        описание = (ОПИСАНИЕ.search(текст) or [None, ""])[1] \
            if ОПИСАНИЕ.search(текст) else ""
        if not имя or not имя.group(1).startswith(источник + "-"):
            находки.append({"skill": d.name, "id": "no-source-prefix",
                            "why": "имя без префикса источника: столкнётся с "
                                   "твоим скиллом, и выиграет случайный"})
        if not описание.strip():
            находки.append({"skill": d.name, "id": "no-description",
                            "why": "скилл без описания не выбирается никогда"})
        else:
            союзы = sum(1 for м in МНОГОЗАДАЧНОСТЬ if м in описание.lower())
            if союзы >= СОЮЗОВ or len(описание) > 400:
                находки.append({"skill": d.name, "id": "document-not-a-task",
                                "why": "описание обещает тему целиком — документ "
                                       "положили как есть, нарезки не было"})
        if not ИСТОЧНИК.search(текст):
            находки.append({"skill": d.name, "id": "no-provenance",
                            "why": "происхождение не названо: через полгода не "
                                   "отличить выстраданное от переписанного"})
    return {"status": "fail" if находки else "pass", "findings": находки,
            "skills": [d.name for d in из_источника],
            "detail": (f"нарушений формы: {len(находки)}" if находки
                       else f"форма соблюдена: скиллов {len(из_источника)}")}


def halt_if_paused() -> None:
    if os.environ.get("SUPERSTACK_IGNORE_PAUSE") == "1":
        return
    if (Path.home() / ".claude" / "superstack" / "PAUSE").exists():
        print("ОСТАНОВЛЕНО: система на паузе", file=sys.stderr)
        raise SystemExit(10)


def main() -> int:
    halt_if_paused()
    argv = sys.argv[1:]
    if "--template" in argv:
        i = argv.index("--template")
        if len(argv) < i + 3:
            print("вызов: distill.py --template <источник> <задача>",
                  file=sys.stderr)
            return 3
        print(template(argv[i + 1], argv[i + 2]))
        return 0

    берут = {"--source"}
    plain, пропуск = [], False
    for a in argv:
        if пропуск:
            пропуск = False
            continue
        if a in берут:
            пропуск = True
        elif not a.startswith("--"):
            plain.append(a)
    if len(plain) != 1 or "--source" not in argv:
        print("вызов: distill.py <каталог скиллов> --source <имя источника>",
              file=sys.stderr)
        return 3
    v = check(Path(plain[0]).expanduser(), argv[argv.index("--source") + 1])
    if "--json" not in argv:
        голова = {"pass": "ФОРМА СОБЛЮДЕНА", "fail": "ФОРМА НАРУШЕНА",
                  "unknown": "ПРОВЕРЯТЬ НЕЧЕГО"}
        print(f"{голова[v['status']]}: {v['detail']}", file=sys.stderr)
        for f in v.get("findings", []):
            print(f"  ! {f['skill']}: {f['why']}", file=sys.stderr)
    print(json.dumps(v, ensure_ascii=False, indent=1))
    return {"pass": 0, "fail": 1, "unknown": 2}[v["status"]]


if __name__ == "__main__":
    sys.exit(main())
