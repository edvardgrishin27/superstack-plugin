#!/usr/bin/env python3
"""SUPERSTACK — обречённый прогон рвётся рано, а не доигрывается до конца.

Что было. Исполнитель доходил до конца, гейт говорил «нет», и круг повторялся
целиком. Прогон, обречённый на третьем шаге, оплачивался полностью — вместе с
разбором его результата и следующим заходом.

Почему это код, а не модель-судья. Признаки застревания читаются механически и
не требуют мнения: одна и та же команда, упавшая трижды, — это петля, а не
трудность. Двадцать шагов без единого запуска проверок — это работа вслепую,
что бы исполнитель о ней ни писал. Судить это моделью значит платить токенами
за то, что видно из журнала бесплатно.

На чём держится. Claude Code пишет журнал субагента отдельным файлом и
дописывает его ПО ХОДУ — установлено измерением: журнал прерванного субагента
содержит его шаги, значит записи ложатся не в конце. Поэтому проверять можно
на ходу, а не после раунда.

  · ПЕТЛЯ — один и тот же вызов упал трижды подряд;
  · ВСЛЕПУЮ — шагов много, запусков проверок ноль;
  · НЕЗАКРЫТАЯ ОШИБКА — хвост журнала в ошибках, успеха после них нет;
  · РАЗГОВОР — за последние шаги ни одной правки файла;
  · ЧУЖАЯ ЗОНА — правки за границами, объявленными таску.

ВТОРОЙ ДЕФЕКТ, свой собственный, а не унаследованный. Волна из N параллельных
помощников пишет N журналов. Пока `--agent` не задан, выбор шёл функцией
`max(mtime)` — «самый свежий» решает файловый кэш, а не то, кто застрял.
Проверка одного случайного журнала из пяти молчала про четыре непроверенных, и
застрявшим мог оказаться любой из них. По умолчанию (без `--agent`) инструмент
теперь смотрит ВСЕ журналы текущей волны — субагентов той же сессии, что и
самый свежий, — и называет застрявшего, даже если его файл не самый свежий.
`--agent <id>` по-прежнему проверяет один конкретный журнал, как раньше.

ЧЕГО ЭТОТ ИНСТРУМЕНТ НЕ ЗНАЕТ (печатается всегда): идёт ли работа В ВЕРНУЮ
СТОРОНУ. Прогон может двигаться бодро и строить не то. Здесь видно только
движение, и «идёт» значит «не застрял», а не «делает правильно». Это верно и
для волны целиком: массовое «идёт» не означает «делают то, что нужно», а
массовое «судить нечем» — что не делают ничего.

ТРЕТИЙ ЗАЗОР эта проверка не закрывает и не притворяется, что закрывает: она
смотрит журналы уже ПОСЛЕ волны, когда оркестратор снова свободен. Пока волна
идёт, вызвать её некому — оркестратор занят ровно до её возврата. Для этого
интервала рядом стоит `watchdog.py`: отдельный процесс, встающий ДО волны и
опрашивающий те же журналы, пока стенограмма занята.

  python3 stall.py <каталог проекта> [--agent <id>] [--zone src/a/] [--json]

  без --agent  -> вся волна: каждый журнал своим вердиктом, общий код — по
                  худшему из них (см. `агрегировать`)
  --agent <id> -> один конкретный журнал, вывод и код — как раньше

  коды: 0 — идёт (никто не застрял), 1 — застрял хотя бы один (названа
        причина), 2 — судить нечем ни по одному журналу
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

#: Сколько раз одна и та же команда должна упасть, чтобы это была петля, а не
#: обычная вторая попытка. Два падения подряд — норма отладки; три — признак,
#: что пробуют то же самое.
ПЕТЛЯ = 3

#: Ниже этого числа шагов судить нечего: прогон ещё не начался.
МИНИМУМ_ШАГОВ = 6

#: На скольких последних шагах смотрится незакрытая ошибка.
ХВОСТ = 8

#: Сколько ходов подряд БЕЗ ЕДИНОГО вызова инструмента считается разговором.
#: Мерилось не «нет правок»: первая редакция валила на этом честный прогон,
#: который час гонял проверки и ничего не правил, — read-only работа работой
#: быть не перестаёт. Разговор — это когда агент пишет, а не действует.
ХОЛОСТЫХ = 4

#: Шагов, после которых отсутствие проверок перестаёт быть нормой.
ВСЛЕПУЮ_ПОСЛЕ = 12

#: Что считается запуском проверки. Список ЗАКРЫТЫЙ: угадывание «похоже на
#: тест» ошибается в обе стороны, а закрытый список можно прочитать и оспорить.
ЗАПУСК_ПРОВЕРКИ = ("pytest", "unittest", "npm test", "npm run test", "yarn test",
                   "pnpm test", "go test", "cargo test", "phpunit", "rspec",
                   "verify.py", "gauntlet.py", "vitest", "jest", "swift test",
                   "gradle test", "mvn test", "dotnet test")

ЧЕГО_НЕ_ЗНАЕМ = (
    "идёт ли работа в верную сторону — видно движение, а не правильность",
    "нужна ли пауза: длинная сборка выглядит как молчание",
)


def слаг(путь: Path) -> str:
    """Имя каталога журналов для пути: всё, кроме букв и цифр, — дефис.

    Та же схема, что у `measure_run.py`: считается, а не угадывается.
    """
    return re.sub(r"[^A-Za-z0-9]", "-", str(путь.resolve()))


def каталог_журналов(проект: Path) -> Path:
    """Каталог журналов, отвечающий САМОЙ папке проекта."""
    return Path.home() / ".claude" / "projects" / слаг(проект)


def каталоги_журналов(проект: Path) -> list:
    """Все каталоги, где могут лежать журналы работы НАД ЭТИМ проектом.

    Найдено измерением, а не выведено из документации. Сессия, которая строит
    подкаталог репозитория, сплошь и рядом открыта ЭТАЖОМ ВЫШЕ — и журналы
    ложатся в каталог по имени ТОЙ папки, а не этой. Каталог по имени самой
    папки проекта при этом существует и пуст: поиск ровно по нему находил ноль
    журналов и всю ночь печатал «агентов волны: 0», хотя журналы лежали через
    папку — на этом репозитории счёт был 0 против 68.

    Поэтому смотрятся папка проекта И ЕЁ ПРЕДКИ. Граница — домашний каталог:
    он и всё, что выше, накрывают все проекты машины разом, и сессия, открытая
    в доме, к этой работе отношения не имеет. Та же граница, по которой
    `enable.py` отказывается заводить слишком широкий каталог; повторена здесь,
    а не позаимствована, потому что этот инструмент обязан работать в поставке
    в одиночку.

    ЧЕГО ЭТО НЕ РАЗЛИЧАЕТ: сессию соседнего проекта, открытую в той же
    родительской папке. Её журналы попадут в список наравне со своими —
    сузить это без обращения к самой сессии нечем, поэтому `--check` и
    `--stop` печатают, где именно искали, а не одно молчаливое число.

    Порядок — от самой папки вверх: ближний каталог первым.
    """
    p = проект.resolve()
    дом = Path.home().resolve()
    корень = Path(p.anchor) if p.anchor else p
    каталоги, кандидат = [], p
    while True:
        каталоги.append(каталог_журналов(кандидат))
        родитель = кандидат.parent
        if родитель in (кандидат, корень, дом) or родитель in дом.parents:
            break
        кандидат = родитель
    return каталоги


def _верхние(проект: Path) -> list:
    """Журналы верхнего уровня — запасной вариант там, где субагентских нет."""
    out = []
    for корень in каталоги_журналов(проект):
        if корень.is_dir():
            out.extend(корень.glob("*.jsonl"))
    return sorted(out, key=lambda p: p.name)


def журнал(проект: Path, agent: str = "") -> "Path | None":
    """Журнал прогона. По умолчанию — самый свежий журнал субагента.

    Субагент выбирается раньше сессии намеренно: строит он, а оркестратор
    только раздаёт. Мерить оркестратора значило бы мерить не того.
    """
    свои = []
    for корень in каталоги_журналов(проект):
        if not корень.is_dir():
            continue
        for сессия in корень.glob("*/subagents/agent-*.jsonl"):
            if agent and agent not in сессия.name:
                continue
            свои.append(сессия)
    if not свои and not agent:
        свои = _верхние(проект)
    if not свои:
        return None
    try:
        return max(свои, key=lambda p: p.stat().st_mtime)
    except OSError:
        return None


def подагенты(проект: Path) -> list:
    """Журналы субагентов проекта, по всем сессиям сразу, БЕЗ выбора «того
    самого» и без запасного варианта на одиночные сессии.

    Сырой список нужен `watchdog.py`: он снимает с него слепок ДО волны и
    сравнивает с ним каждый следующий срез, чтобы судить только новое. Смешать
    сюда журналы верхнего уровня (не-субагентские) было бы неверно — их
    появление никак не связано с волной субагентов, а с любым другим
    разговором в этом проекте.
    """
    свои = []
    for корень in каталоги_журналов(проект):
        if корень.is_dir():
            свои.extend(корень.glob("*/subagents/agent-*.jsonl"))
    return sorted(свои, key=lambda p: p.name)


def все_журналы(проект: Path) -> list:
    """Журналы ТЕКУЩЕЙ волны: субагенты той же сессии, что и самый свежий.

    Ровно второй дефект. Раньше `журнал()` брал ЕДИНСТВЕННЫЙ файл — тот,
    что последним тронул файловый кэш, а не тот, что застрял. У волны из пяти
    помощников пять журналов, и «самый свежий» — случайный из них: застрявший
    мог лежать среди четырёх непроверенных. Здесь смотрятся ВСЕ файлы
    `subagents/` той сессии, где лежит самый свежий, — ровно те, кого позвал
    один и тот же оркестраторский ход.

    ЧЕГО ЭТО НЕ РАЗЛИЧАЕТ. Одна сессия может успеть прогнать несколько волн
    подряд — их журналы лежат в той же папке `subagents/` и здесь неотличимы
    от текущей волны: и уже сданная задача, и никогда не начинавшаяся заново
    попадут в один список. Точную границу волны знает только `watchdog.py` —
    он помнит, что было ДО его запуска, и судит лишь то, что появилось после.

    Запасной вариант (все `*.jsonl` верхнего уровня) остаётся для проекта, где
    субагентских журналов нет вовсе — тот же случай, что был у одиночной
    проверки раньше, просто теперь проверяются все найденные, а не один.
    """
    свои = подагенты(проект)
    if свои:
        свежайший = max(свои, key=lambda p: p.stat().st_mtime)
        return sorted(свежайший.parent.glob("agent-*.jsonl"), key=lambda p: p.name)
    return _верхние(проект)


def холостые_ходы(f: Path) -> int:
    """Сколько ПОСЛЕДНИХ ходов помощника прошли без единого вызова инструмента.

    Признак разговора вместо работы. Считается по ходам, а не по правкам:
    прогон, который читает и запускает проверки, ничего не меняя, работает —
    и первая редакция этого инструмента валила именно такой, живой.
    """
    ходы = []
    try:
        строки = f.read_text("utf-8", errors="replace").splitlines()
    except OSError:
        return 0
    for строка in строки:
        try:
            o = json.loads(строка)
        except ValueError:
            continue
        if o.get("type") != "assistant":
            continue
        блоки = (o.get("message") or {}).get("content") or []
        ходы.append(any(isinstance(b, dict) and b.get("type") == "tool_use"
                        for b in блоки))
    сколько = 0
    for был_вызов in reversed(ходы):
        if был_вызов:
            break
        сколько += 1
    return сколько


def шаги(f: Path) -> list:
    """Шаги прогона: вызов инструмента и то, чем он кончился.

    Читается ФОРМА записи, а не текст: `is_error` стоит в самом результате, и
    его не приходится угадывать по словам в выводе — угадывание ошибалось бы
    на каждом тесте, который печатает слово «error» в своём же отчёте.
    """
    out, ожидают = [], {}
    try:
        строки = f.read_text("utf-8", errors="replace").splitlines()
    except OSError:
        return []
    for строка in строки:
        try:
            o = json.loads(строка)
        except ValueError:
            continue
        for блок in ((o.get("message") or {}).get("content") or []):
            if not isinstance(блок, dict):
                continue
            if блок.get("type") == "tool_use":
                шаг = {"инструмент": блок.get("name", "?"),
                       "команда": _команда(блок.get("input") or {}),
                       "путь": str((блок.get("input") or {}).get("file_path") or ""),
                       "упал": None}
                ожидают[блок.get("id")] = шаг
                out.append(шаг)
            elif блок.get("type") == "tool_result":
                шаг = ожидают.pop(блок.get("tool_use_id"), None)
                if шаг is not None:
                    шаг["упал"] = bool(блок.get("is_error"))
    return out


def _команда(вход: dict) -> str:
    c = вход.get("command") or ""
    return re.sub(r"\s+", " ", str(c)).strip()[:200]


def _проверка(команда: str) -> bool:
    н = команда.lower()
    return any(з in н for з in ЗАПУСК_ПРОВЕРКИ)


def разобрать(шаги_: list, зоны: list, холостых: int = 0) -> dict:
    причины = []
    всего = len(шаги_)

    # Петля: одна и та же команда, упавшая подряд ПЕТЛЯ раз.
    подряд, прежняя = 0, None
    for ш in шаги_:
        ключ = ш["команда"] or ш["инструмент"]
        if ш["упал"] and ключ == прежняя:
            подряд += 1
        elif ш["упал"]:
            подряд, прежняя = 1, ключ
        else:
            подряд, прежняя = 0, None
        if подряд >= ПЕТЛЯ:
            причины.append(f"петля: «{ключ[:60]}» упало {подряд} раз подряд")
            break

    проверок = sum(1 for ш in шаги_ if _проверка(ш["команда"]))
    if всего >= ВСЛЕПУЮ_ПОСЛЕ and not проверок:
        причины.append(f"вслепую: {всего} шагов и ни одного запуска проверок")

    хвост = шаги_[-ХВОСТ:]
    первое = next((i for i, ш in enumerate(хвост) if ш["упал"]), None)
    упавшие = [ш for ш in хвост if ш["упал"]]
    if первое is not None and not any(ш["упал"] is False for ш in хвост[первое:]):
        причины.append(
            f"незакрытая ошибка: последние {len(хвост)} шагов кончаются "
            f"падением «{упавшие[-1]['команда'][:50] or упавшие[-1]['инструмент']}»")

    if холостых >= ХОЛОСТЫХ:
        причины.append(f"разговор: {холостых} ходов подряд без единого "
                       "вызова инструмента")

    if зоны:
        чужие = sorted({ш["путь"] for ш in шаги_
                        if ш["путь"] and not any(ш["путь"].startswith(z)
                                                 or z in ш["путь"] for z in зоны)})
        if чужие:
            причины.append("чужая зона: правки вне границ задачи — "
                           + ", ".join(x[-40:] for x in чужие[:3]))

    return {"шагов": всего, "проверок": проверок, "причины": причины}


def вердикт_журнала(f: Path, зоны: list) -> dict:
    """Вердикт по ОДНОМУ уже найденному журналу.

    Общее место для одиночной проверки (`--agent`) и проверки волны: обе
    обязаны судить по одним и тем же правилам, иначе «застрял» для одной и
    той же формы журнала значило бы разное в зависимости от того, как его
    нашли. Имя журнала и агента подмешаны в результат, чтобы вызывающий
    (волна, `watchdog.py`) мог сказать, ЧЕЙ это вердикт, не разбирая путь сам.
    """
    ш = шаги(f)
    if len(ш) < МИНИМУМ_ШАГОВ:
        return {"код": 2, "причины": [], "шагов": len(ш), "проверок": 0,
                "журнал": f.name, "агент": f.stem,
                "почему": f"шагов {len(ш)}, меньше {МИНИМУМ_ШАГОВ} — прогон "
                          "ещё не начался, судить рано"}
    р = разобрать(ш, list(зоны), холостые_ходы(f))
    return {"код": 1 if р["причины"] else 0, "причины": р["причины"],
            "шагов": р["шагов"], "проверок": р["проверок"],
            "журнал": f.name, "агент": f.stem, "почему": ""}


def агрегировать(агенты: list) -> int:
    """Общий код волны — по ХУДШЕМУ известному, а не по большинству и не по
    среднему.

    «Застрял хотя бы один» обязан остаться видимым и тогда, когда четверо из
    пяти в порядке: большинство или средний код спрятали бы его за общим
    «идёт» — ровно та потеря, ради которой волну вообще стали смотреть
    целиком. «Судить нечем» — код, который волна получает только тогда,
    когда сказать нечего НИ ПО ОДНОМУ журналу; агент, для которого рано
    судить (мало шагов), не мешает остальным быть засчитанными как идущие
    или застрявшие — ранний старт одного не должен маскировать петлю другого.
    """
    коды = {a["код"] for a in агенты}
    if 1 in коды:
        return 1
    if 0 in коды:
        return 0
    return 2


def проверить(проект: Path, agent: str = "", зоны: list = ()) -> dict:
    f = журнал(проект, agent)
    if f is None:
        return {"код": 2, "причины": [], "шагов": 0, "проверок": 0,
                "журнал": "", "агент": "",
                "почему": f"журналов прогона для {проект} нет — судить нечем"}
    return вердикт_журнала(f, list(зоны))


def проверить_все(проект: Path, зоны: list = ()) -> dict:
    """Вердикт по ВСЕЙ волне: каждый журнал — своей строкой в «агенты»,
    общий код — по `агрегировать`.

    Один вызов `stall.py` без `--agent` раньше видел РОВНО ОДИН журнал — тот,
    что последним тронул файловый кэш, а не тот, что застрял. При пяти
    параллельных помощниках это пять журналов, и «самый свежий» получал
    вердикт по чистой случайности файловой системы, пока остальные четыре
    молчали. Здесь судятся все.
    """
    файлы = все_журналы(проект)
    if not файлы:
        где = ", ".join(str(d) for d in каталоги_журналов(проект))
        return {"код": 2, "агенты": [],
                "почему": f"журналов прогона для {проект} нет — судить нечем; "
                          f"искал в: {где}"}
    агенты = [вердикт_журнала(f, list(зоны)) for f in файлы]
    return {"код": агрегировать(агенты), "агенты": агенты, "почему": ""}


def _печать(итог: dict) -> None:
    if итог["код"] == 2:
        print(f"СУДИТЬ НЕЧЕМ: {итог['почему']}", file=sys.stderr)
        return
    print(f"журнал: {итог['журнал']}")
    print(f"  шагов: {итог['шагов']}, запусков проверок: {итог['проверок']}")
    print("  ЧЕГО НЕ ЗНАЕМ:")
    for x in ЧЕГО_НЕ_ЗНАЕМ:
        print(f"    · {x}")
    for п in итог["причины"]:
        print(f"ЗАСТРЯЛ: {п}", file=sys.stderr)


def _печать_волны(итог: dict) -> None:
    """Волна: по журналу в строке плюс сводка, где «застряло N» не спрятать.

    Число застрявших стоит В ЗАГОЛОВКЕ сводки, а не только в перечне ниже —
    так оно не теряется среди строк про тех, кто идёт нормально, даже если
    их читают по диагонали. Сами находки — в stderr и последними, как и в
    одиночной проверке: их место замыкать вывод, а не растворяться в начале.
    """
    агенты = итог["агенты"]
    if not агенты:
        print(f"СУДИТЬ НЕЧЕМ: {итог['почему']}", file=sys.stderr)
        return
    застряли = [a for a in агенты if a["код"] == 1]
    идут = [a for a in агенты if a["код"] == 0]
    рано = [a for a in агенты if a["код"] == 2]
    print(f"волна: {len(агенты)} журналов — идёт {len(идут)}, "
          f"застряло {len(застряли)}, судить рано {len(рано)}")
    for a in рано:
        print(f"  · {a['агент']}: {a['почему']}")
    for a in идут:
        print(f"  · {a['агент']}: шагов {a['шагов']}, запусков проверок {a['проверок']}")
    if итог["код"] != 2:
        print("  ЧЕГО НЕ ЗНАЕМ:")
        for x in ЧЕГО_НЕ_ЗНАЕМ:
            print(f"    · {x}")
    for a in застряли:
        for п in a["причины"]:
            print(f"ЗАСТРЯЛ [{a['агент']}]: {п}", file=sys.stderr)


def main(argv: list) -> int:
    зоны, agent, простые = [], "", []
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--zone" and i + 1 < len(argv):
            зоны.append(argv[i + 1]); i += 2; continue
        if a == "--agent" and i + 1 < len(argv):
            agent = argv[i + 1]; i += 2; continue
        if a == "--json":
            i += 1; continue
        if a.startswith("--"):
            print(f"неизвестный флаг: {a}", file=sys.stderr)
            return 3
        простые.append(a); i += 1
    if len(простые) != 1:
        print("вызов: stall.py <каталог проекта> [--agent id] [--zone src/a/] "
              "[--json]", file=sys.stderr)
        return 3

    проект = Path(простые[0])
    if agent:
        итог, печать = проверить(проект, agent, зоны), _печать
    else:
        итог, печать = проверить_все(проект, зоны), _печать_волны
    if "--json" in argv:
        print(json.dumps(итог, ensure_ascii=False, indent=1))
    else:
        печать(итог)
    return итог["код"]


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
