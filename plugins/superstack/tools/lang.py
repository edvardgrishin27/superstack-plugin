#!/usr/bin/env python3
"""SUPERSTACK — на каком языке говорить с человеком.

Зачем это код, а не «пиши на языке собеседника».

Продукт объясняется человеку по-русски: отчёт, ответ на «где я», подписи
панели, отказы инструментов. Человек, поставивший плагин с английской
страницы, получал ту же стройку и русский текст в конце — то есть продукт,
которым нельзя пользоваться, не зная языка автора.

Договориться об этом словами нельзя по двум причинам. Первая: язык решается
один раз, в самом начале, а печатают текст десять инструментов в разное время
и в разных процессах — им нужен общий ответ, а не общая договорённость.
Вторая: модель, которой велено «отвечай на языке человека», исполняет это
ровно до первой строки, собранной инструментом, — а инструменты и печатают
почти всё, что человек читает.

Поэтому язык — ЗАПИСЬ на диске, поле `lang` в `.superstack/state.json`, рядом
с этапом и держателем хода. Пишется один раз в фазе 0 по первой фразе
человека, меняется его же словами («по-английски», «in Russian»), читается
всеми инструментами через `read()`.

Записи нет — русский. Это не догадка о человеке, а сохранение прежнего
поведения: проект, заведённый до этой записи, не имеет права менять язык на
середине прогона.

Надписи лежат в `data/plain-ru.json`, раздел `tools` — оба языка в одном
файле и по одним и тем же ключам, как и надписи панели. Второй файл рядом
разъезжается молча: в один надпись добавили, во второй забыли, и человек
видит пустое место вместо текста.

  python3 lang.py detect "<первая фраза человека>"   -> ru | en
  python3 lang.py read <папка проекта>               -> записанный язык

  код 0 — язык назван, 3 — ошибка вызова
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import plain_ru  # noqa: E402

RU, EN = "ru", "en"
LANGS = (RU, EN)

#: Язык по умолчанию. Не «язык системы» и не язык окружения: умолчание обязано
#: совпадать с тем, как продукт вёл себя до этой записи, иначе прогон, начатый
#: вчера, заговорит сегодня иначе.
DEFAULT = RU

#: Папка прогона /go внутри проекта. То же имя, что у what.py и панели.
RUN = ".superstack"

_КИРИЛЛИЦА = re.compile(r"[а-яёА-ЯЁ]")


def detect(text: str) -> str:
    """Язык первой фразы человека.

    Кириллица — русский, всё прочее — английский. Прибор нарочно грубый:
    определять язык точно здесь незачем, а ошибиться в сторону «непонятного
    человеку языка» можно только одним способом — промолчать и оставить
    русский всем подряд.
    """
    return RU if _КИРИЛЛИЦА.search(text or "") else EN


def from_state(state: dict) -> str:
    """Язык из уже прочитанного состояния прогона.

    Чужое значение в поле не принимается: `lang: "de"` — это не «немецкий», а
    опечатка, и говорить с человеком на языке, надписей для которого нет,
    значит показать ему пустые строки.
    """
    got = (state or {}).get("lang")
    return got if got in LANGS else DEFAULT


def read(where: "Path | str") -> str:
    """Записанный язык прогона. Принимает и корень проекта, и папку прогона.

    Инструменты зовут это из разных мест: отчёт знает папку прогона, /what и
    канал доставки — корень проекта, откат — текущую папку. Требовать от
    каждого своего пути значило бы завести четыре способа ошибиться.

    Нечитаемое состояние — это `ru`, а не поломка: язык не то, ради чего стоит
    ронять последний шаг прогона.
    """
    p = Path(where)
    for f in (p / "state.json", p / RUN / "state.json"):
        try:
            return from_state(json.loads(f.read_text("utf-8")))
        except (OSError, ValueError):
            continue
    return DEFAULT


def words(lang: str = DEFAULT, data: dict = None) -> dict:
    """Надписи инструментов на нужном языке, с русской подстраховкой.

    Нет английской строки — возвращается русская. Это ВИДНО: человек читает
    английский отчёт и натыкается на русскую строку, идёт и спрашивает. Пустое
    место на её месте выглядело бы как «здесь ничего и не должно быть».
    """
    data = data or plain_ru.load()
    ru = data["tools"]["map"]
    if lang != EN:
        return ru
    en = (plain_ru.english(data).get("tools") or {})
    return {**ru, **{k: v for k, v in en.items() if v}}


def t(key: str, lang: str = DEFAULT, data: dict = None, **fmt) -> str:
    """Надпись по ключу. Ключа нет — падаем здесь, а не молчим.

    Отсутствие ключа — ошибка того, кто пишет код, и она обязана найтись на
    первом же прогоне теста. Тихая пустая строка вместо заголовка отчёта
    прошла бы все проверки и нашлась бы только человеком.
    """
    text = words(lang, data)[key]
    return text.format(**fmt) if fmt else text


def role_word(owner: str, lang: str = DEFAULT, data: dict = None) -> str:
    """Держатель хода словами — теми же, что показывает панель."""
    data = data or plain_ru.load()
    if lang == EN:
        said = (plain_ru.english(data).get("roles") or {}).get(owner)
        if said:
            return said
    return plain_ru.role_word(owner, data)


def phase_name(name: str, lang: str = DEFAULT, data: dict = None) -> str:
    """Название этапа. Ключ этапа русский всегда — он же ключ состояния."""
    data = data or plain_ru.load()
    if lang == EN:
        return (plain_ru.english(data).get("names") or {}).get(name) or name
    return name


def main() -> int:
    plain_ru.halt_if_paused()
    argv = sys.argv[1:]
    if len(argv) != 2 or argv[0] not in ("detect", "read"):
        print("вызов: lang.py detect «фраза» | read <папка>", file=sys.stderr)
        return 3
    print(detect(argv[1]) if argv[0] == "detect" else read(argv[1]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
