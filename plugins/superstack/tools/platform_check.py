#!/usr/bin/env python3
"""SUPERSTACK — на какой платформе это проверяли, а на какой нет.

Зачем отдельный инструмент.

Проверялось всё только на macOS. На чужой платформе человек получит не отказ,
а НЕПОНЯТНЫЕ ошибки — и решит, что сломан его компьютер. Худший из возможных
исходов не «не работает», а «непонятно, что происходит».

Зависимость от оболочки к 20.08 снята полностью: тормоз и все четыре
автозапуска переехали на Python. Осталась одна зависимость — сам python3, без
которого не работает ни один инструмент, то есть продукт целиком.

Сколько их — считается измерением, а не переписывается сюда числом. Число в
тексте устаревает молча: в этом файле рядом стояли «65» и «67» при настоящих
семидесяти с лишним, и обе цифры выглядели одинаково уверенно.

Поэтому платформа называется вслух и НА СТАРТЕ, вместе со списком того, что
именно не работает. «Возможны проблемы» — не сообщение: под ним нельзя принять
ни одного решения.

Чем это НЕ является. Это не поддержка Windows. Порт скриптов может быть написан
и лежать рядом, но пока никто не прогонял его на живой Windows, статус у него
один — НЕ ПРОВЕРЕНО, и инструмент говорит именно это. «Должно работать» здесь
запрещено ровно так же, как везде.

  python3 platform_check.py [--json]

  код 0 — платформа проверена, 2 — не проверена (работает частично), 3 — вызов
"""
from __future__ import annotations

import json
import os
import platform
import shutil
import sys
from pathlib import Path

#: Платформы, на которых прогон делался живьём. Список короткий намеренно:
#: сюда попадают только те, где кто-то реально прошёл прогон от начала до конца.
ПРОВЕРЕНЫ = ("Darwin", "Linux")

#: Что перестаёт работать без POSIX-оболочки. Список поимённый, потому что
#: «возможны проблемы» не сообщение: под ним нельзя принять ни одного решения.
#:
#: Прежде здесь стоял ОДИН пункт — про права в тестах, с припиской «сам продукт
#: это не задевает». Приписка была верна для того пункта и превращалась во
#: враньё для всего списка: три вещи ниже задевают продукт напрямую, и человек
#: узнавал о них не отсюда, а по тишине вместо работы.
ЗАВИСИТ_ОТ_ОБОЛОЧКИ = (
    ("самозапуск на старте и в конце сеанса",
     "система зовёт себя строкой «python3»; там, где толкователь языка "
     "назван иначе — «python» или «py», — эти запуски не срабатывают МОЛЧА: "
     "ошибки не будет, работы тоже"),
    ("русские буквы в окне команд",
     "почти все инструменты не переключают вывод на UTF-8, и в окне команд "
     "Windows отказы и отчёты выходят нечитаемым набором знаков — прочесть "
     "то, что система говорит, будет нечем"),
    ("однострочные обёртки .sh рядом с инструментами",
     "их запускает оболочка, которой здесь нет; сами инструменты на Python "
     "работают, а обёртки — нет, и вызов через них молча ничего не делает"),
    ("права на папку",
     "проверка прав в наборе опирается на POSIX-модель: часть проверок здесь "
     "будет пропущена — это про измерение продукта, а не про сам продукт"),
)


def сколько_инструментов() -> int:
    """Сколько инструментов рядом. Измерением: число в тексте устаревает молча."""
    return len(list(Path(__file__).resolve().parent.glob("*.py")))


def работает_везде() -> list:
    """Что работает всюду, где есть Python 3.9+.

    Обратная половина списка нужна не для утешения: без неё человек решит, что
    не работает ВСЁ, и это тоже неправда.
    """
    return [
        f"все инструменты продукта (сейчас их {сколько_инструментов()}): "
        "проверка перед «готово», доказательство тестов поломкой, планка "
        "проекта, осмотр хранилища кода, отчёт",
        "скиллы и агенты — это текст, платформа им безразлична",
    ]


def degraded() -> list:
    """Что именно деградирует здесь и сейчас. Пусто — значит ничего.

    Проверяется НАЛИЧИЕ оболочки, а не имя системы: Windows с установленным
    Git Bash ведёт себя иначе, чем без него, и объявлять их одинаково значило
    бы врать половине людей.
    """
    if shutil.which("sh"):
        return []
    return [{"что": имя, "почему": why} for имя, why in ЗАВИСИТ_ОТ_ОБОЛОЧКИ]


def verdict() -> dict:
    сейчас = platform.system()
    сломано = degraded()
    проверена = сейчас in ПРОВЕРЕНЫ

    if проверена and not сломано:
        return {"status": "pass", "platform": сейчас,
                "detail": f"{сейчас} — платформа, на которой прогон делали живьём"}

    причины = []
    if not проверена:
        причины.append(f"{сейчас} не входит в проверенные ({', '.join(ПРОВЕРЕНЫ)}): "
                       "живого прогона здесь не было ни одного")
    if сломано:
        причины.append("POSIX-оболочки (`sh`) нет в системе")

    return {"status": "unknown", "platform": сейчас,
            "detail": "; ".join(причины),
            "broken": сломано,
            "works": работает_везде(),
            "next": "пользоваться можно — но зная, что именно не работает. "
                    "Прогон на этой платформе никто не делал, и пока не сделает, "
                    "честный статус один: не проверено"}


def human(v: dict) -> str:
    if v["status"] == "pass":
        return f"ПЛАТФОРМА ПРОВЕРЕНА: {v['detail']}"
    строки = [f"ПЛАТФОРМА НЕ ПРОВЕРЕНА ({v['platform']}): {v['detail']}"]
    if v.get("broken"):
        строки.append("  не работает:")
        строки += [f"    ! {b['что']} — {b['почему']}" for b in v["broken"]]
    строки.append("  работает:")
    строки += [f"    + {w}" for w in v.get("works", [])]
    строки.append(f"  дальше: {v['next']}")
    return "\n".join(строки)


def halt_if_paused() -> None:
    if os.environ.get("SUPERSTACK_IGNORE_PAUSE") == "1":
        return
    if (Path.home() / ".claude" / "superstack" / "PAUSE").exists():
        print("ОСТАНОВЛЕНО: система на паузе", file=sys.stderr)
        raise SystemExit(10)


def _utf8_stdio() -> None:
    for поток in (sys.stdout, sys.stderr):
        кодировка = (getattr(поток, "encoding", "") or "").lower().replace("-", "")
        if кодировка != "utf8" and hasattr(поток, "reconfigure"):
            поток.reconfigure(encoding="utf-8", errors="replace")


def main() -> int:
    _utf8_stdio()
    halt_if_paused()
    argv = sys.argv[1:]
    if [a for a in argv if not a.startswith("--")]:
        print("вызов: platform_check.py [--json]", file=sys.stderr)
        return 3
    v = verdict()
    if "--json" not in argv:
        print(human(v), file=sys.stderr)
    print(json.dumps(v, ensure_ascii=False, indent=1))
    return 0 if v["status"] == "pass" else 2


if __name__ == "__main__":
    sys.exit(main())
