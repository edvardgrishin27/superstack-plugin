#!/usr/bin/env python3
"""SUPERSTACK — какая модель под какую ЗАДАЧУ. Выбор считает код.

Зачем это отдельный инструмент.

Модель была свойством РОЛИ: исполнитель — средний тир, советчики — свой. Размер
и риск задачи на выбор не влияли вообще, и правка на две строки уезжала той же
моделью, что переписывание схемы данных. Дорогое не тратилось там, где ошибка
стоит переделки, и тратилось там, где хватило бы дешёвого. Раскладку по тирам
система уже мерила у человека — а решать не умела нигде.

Почему решает КОД, а не суждение модели. Судить о собственной задаче «дорогая
она или нет» — это самооценка внутри той же петли: дешёвый ответ всегда выгоден
тому, кто торопится, а дорогой — тому, кто не уверен. Признак, названный в
исходнике, одинаков в понедельник и в пятницу, и его можно оспорить, показав
пальцем. Ещё он ничего не стоит: скрипт считает его за ноль токенов.

Признаков четыре, и каждый объясняется одной фразой:

  · ЗОНУ НАКРЫВАЕТ ПРИНЯТОЕ РЕШЕНИЕ — дорого. Ошибка внутри архитектурного
    решения отменяет решение, а не строчку: чинить придётся всё, что на нём
    стоит. Список решений над зоной уже считает передача таска.
  · ЭТО НЕ ПЕРВЫЙ ЗАХОД — дорого. Первый не сошёлся; та же модель той же
    дорогой придёт туда же. Счётчик берётся у самой проверки: второй счётчик
    попыток разошёлся бы с первым на второй же неделе.
  · ЗОНА ТРОГАЕТ ДАННЫЕ ЧЕЛОВЕКА — дорого. У кода откат — git, у данных его нет
    ни у кого; список признаков такой зоны уже назван проверкой отката данных.
  · ОДИН ФАЙЛ И НИ ОДНОГО ТРЕБОВАНИЯ — дёшево. Переименование, формат, правка
    в одном месте: разъезжаться нечему, а ошибка ловится тестом и стоит одного
    повтора, который всё равно дешевле разницы тиров.

Границы выбраны так, а не иначе, и вот почему:

  · дорогое ПЕРЕВЕШИВАЕТ дешёвое. Миграция в одном файле без требований по
    форме механическая, по существу — потеря данных. Ошибка в эту сторону
    стоит одного лишнего дорогого прогона; в обратную — восстановления
    того, чего не восстановить;
  · «признаков нет» — это ОБЫЧНЫЙ тир, а не дешёвый. Неизвестное не повод
    удешевлять: маршрутизатор, отвечающий одно и то же, — прежняя жёсткая
    раскладка под новым именем;
  · каталог в зоне не считается одним файлом: это неизвестное число файлов,
    и удешевлять по нему значит звать дешёвый тир на всё, что назвали папкой;
  · признаков ровно четыре и они называются словами. Веса и пороги по десятку
    признаков нельзя ни объяснить человеку, ни оспорить — их можно только
    подкрутить до нужного ответа.

Выбор и его причина ложатся в ход стройки. Без записи вопрос «окупился ли
дорогой тир» не имеет источника данных: остаётся верить на слово тому, кто
тратил.

Доедет ли выбор до исполнителя — отдельный вопрос, и ответ на него честный.
Поле модели в файле агента статично, зато модель, названную В МОМЕНТ ВЫЗОВА,
хост берёт первой — раньше поля в файле. Мешают этому три вещи, и все три
названы в документации хоста: версия ниже порога, при которой выбор модели у
субагента не действует вовсе; включённый запрет, при котором хост гонит всех
субагентов одной моделью и игнорирует обе двери; и старый порядок разрешения,
где переменная умолчания шла раньше вызова. В каждом случае инструмент говорит
это словами и ненулевым кодом, вместо того чтобы отчитаться выбором, которого
не было.

  python3 model_route.py <ход-стройки.json> <id> [--adr docs/adr]
                         [--attempt N] [--host-version 2.1.170]
                         [--facts facts.json] [--project .] [--now ISO]
                         [--dry-run] [--json]

  код 0 — тир выбран и доедет до исполнителя,
  1 — тир выбран, но до исполнителя НЕ доедет: причина названа,
  2 — доставку проверить нечем: версия хоста никем не измерена,
  3 — ошибка вызова
"""
from __future__ import annotations

import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

# Соседи по пакету и проба. Путь добавляется явно: каталог скрипта при импорте
# из теста в sys.path не попадает — так же, как у соседних инструментов.
sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent / "probe"))

import atomic_store  # noqa: E402
import collect  # noqa: E402
import data_rollback  # noqa: E402
import handoff  # noqa: E402
import progress  # noqa: E402
import verify  # noqa: E402

#: Тиры. Имена — те, которые понимает хост в поле модели и в вызове субагента.
ДОРОГОЙ = "opus"
ОБЫЧНЫЙ = "sonnet"
ДЕШЁВЫЙ = "haiku"

#: Где живёт ход стройки, там же и выбор: отдельный файл решений разошёлся бы
#: с состоянием при первой же перенарезке, и разошёлся бы молча.
ЖУРНАЛ = "model_routing"

#: С какого захода задача считается повторной. Второй заход — уже повтор:
#: ждать третьего значит оплатить ещё один круг тем же способом.
ПОВТОР = 2

#: Переменная, которой хосту велят гнать всех субагентов одной моделью. Пока
#: она включена, выбор модели не действует ни из файла агента, ни из вызова.
СИЛОЙ = "CLAUDE_CODE_SUBAGENT_MODEL_FORCE"

#: Переменная, задающая модель субагентов по умолчанию.
УМОЛЧАНИЕ = "CLAUDE_CODE_SUBAGENT_MODEL"

#: Версия, с которой модель, названная В МОМЕНТ ВЫЗОВА, идёт раньше этой
#: переменной. До неё порядок был обратный: переменная перекрывала и вызов, и
#: поле в файле агента — то есть выбор доезжал не до исполнителя, а до неё.
ВЫЗОВ_РАНЬШЕ_УМОЛЧАНИЯ = (2, 1, 251)

ДОЕДЕТ, НЕ_ДОЕДЕТ, НЕИЗВЕСТНО = "доезжает", "не доезжает", "неизвестно"


def _версия(тройка: tuple) -> str:
    return ".".join(str(x) for x in тройка)


def порог() -> str:
    """Версия хоста, ниже которой выбор модели у субагента не действует.

    Число живёт у пробы в единственном экземпляре. Переписать его сюда значило
    бы завести второй порог, который разойдётся с первым и будет спорить с ним
    в отчётах.
    """
    return _версия(collect.MODEL_ROUTING_FLOOR)


def механическая(задача: dict) -> bool:
    """Правка, у которой нечему разъехаться: один файл и ни одного требования.

    Каталог в зоне сюда не годится: это неизвестное число файлов. Требование на
    задаче — тоже: за ним стоит обещание человеку, и его цена не в строчках.
    """
    зона = задача.get("zone") or []
    if len(зона) != 1 or зона[0].rstrip().endswith("/"):
        return False
    return not (задача.get("requirements") or [])


def решить(задача: dict, решения: list, заход_номер: int) -> dict:
    """Тир и ПРИЧИНА выбора. Причина возвращается всегда, в том числе обычная.

    Признак без причины следующий читатель сдвинет наугад — поэтому каждый
    сработавший признак несёт свою фразу, а не только имя.
    """
    зона = задача.get("zone") or []
    дорого = []

    правят = handoff.governing_adrs(решения, зона)
    if правят:
        дорого.append({
            "признак": "под решением",
            "почему": "зону накрывают принятые решения ("
                      + ", ".join(a["file"] for a in правят)
                      + "): ошибка здесь отменяет решение, а не строчку"})

    if заход_номер >= ПОВТОР:
        дорого.append({
            "признак": "повторный заход",
            "почему": f"заход №{заход_номер}: первый не сошёлся, и та же "
                      "модель той же дорогой придёт туда же"})

    данные = data_rollback.touches_data(зона)
    if данные:
        дорого.append({
            "признак": "данные человека",
            "почему": f"зона трогает данные ({данные[0]}): у кода откат — git, "
                      "у данных его нет ни у кого"})

    if дорого:
        return {"tier": ДОРОГОЙ, "signals": дорого,
                "why": "дорогой тир — ошибка здесь дорого стоит: "
                       + "; ".join(с["признак"] for с in дорого)}

    if механическая(задача):
        признак = {
            "признак": "механическая правка",
            "почему": f"один файл ({зона[0]}) и ни одного требования: "
                      "разъезжаться нечему, ошибка ловится тестом"}
        return {"tier": ДЕШЁВЫЙ, "signals": [признак],
                "why": "дешёвый тир — " + признак["почему"]}

    return {"tier": ОБЫЧНЫЙ, "signals": [],
            "why": "обычный тир — ни одного признака дорогого и ни одного "
                   "признака механического: неизвестное не повод удешевлять"}


def заход(проект: Path) -> tuple:
    """Который это заход по счёту и откуда взято число.

    Счётчик берётся у ПРОВЕРКИ — у той самой, что уже считает подряд идущие
    провалы одного проекта. Свой второй счётчик разошёлся бы с ним на второй
    неделе, и спорить они стали бы в тот момент, когда нужен точный ответ.
    """
    записи = verify._load_attempts(verify._state_path())
    серия = записи.get(str(Path(проект).expanduser().resolve())) or {}
    try:
        число = int(серия.get("attempt", 0))
    except (TypeError, ValueError):
        число = 0
    return число + 1, f"счётчик проверки: подряд идущих провалов {число}"


def _включено(значение) -> bool:
    return str(значение or "").strip().lower() not in ("", "0", "false", "no")


def доставка(версия: "str | None", маршрутизация: "bool | None",
             окружение: dict) -> dict:
    """Доедет ли выбор до исполнителя. «Не смог проверить» — не «доедет».

    Три исхода вместо двух намеренно. Молчаливое «всё в порядке» на неизмеренной
    версии — это ровно тот отказ, ради которого инструмент писался: дорогая
    задача уезжает моделью сессии, а отчёт утверждает обратное.
    """
    if _включено(окружение.get(СИЛОЙ)):
        return {"состояние": НЕ_ДОЕДЕТ,
                "почему": f"{СИЛОЙ} включён: хост гонит всех субагентов одной "
                          "моделью и выбор игнорирует — ни из файла агента, "
                          "ни из вызова"}
    if маршрутизация is None and версия:
        маршрутизация = collect._at_least(версия, collect.MODEL_ROUTING_FLOOR)
    if маршрутизация is False:
        return {"состояние": НЕ_ДОЕДЕТ,
                "почему": f"версия хоста {версия or 'неизвестна'} ниже "
                          f"{порог()}: выбор модели у субагента там не "
                          "действует, и он исполнится моделью сессии"}
    if маршрутизация is None:
        return {"состояние": НЕИЗВЕСТНО,
                "почему": f"версию хоста никто не измерял (порог {порог()}): "
                          "доедет ли выбор до исполнителя — неизвестно, и это "
                          "не то же самое, что «доедет»"}
    старый = collect._at_least(версия, ВЫЗОВ_РАНЬШЕ_УМОЛЧАНИЯ)
    if окружение.get(УМОЛЧАНИЕ) and старый is False:
        # Узкий, но настоящий случай: версия выше порога, поле модели работает,
        # а порядок ещё обратный — переменная перекрывает и вызов, и файл.
        # Промолчать тут значит доложить выбор, которого не будет.
        return {"состояние": НЕ_ДОЕДЕТ,
                "почему": f"{УМОЛЧАНИЕ} задана, а версия хоста {версия} ниже "
                          f"{_версия(ВЫЗОВ_РАНЬШЕ_УМОЛЧАНИЯ)}: там переменная "
                          "идёт раньше и вызова, и поля в файле агента"}
    return {"состояние": ДОЕДЕТ,
            "почему": f"версия хоста {версия or 'по осмотру'} не ниже "
                      f"{порог()}: модель, названная в момент вызова, идёт "
                      "первой — раньше поля в файле агента"}


def вписать(путь: Path, запись: dict, когда: str) -> None:
    """Выбор и причина — туда же, где живёт ход стройки.

    Дописывается, а не затирается: «окупился ли дорогой тир» — вопрос про
    ИСТОРИЮ выборов, и снимок последнего на него не отвечает.

    Замок на весь цикл «прочитал, изменил, записал» — общий, как у всех, кто
    пишет этот файл: волна из двух помощников иначе теряет чужую правку молча.

    Читается СЫРОЙ разбор, а не мягкое чтение хода стройки: то возвращает
    пустое состояние на нечитаемом файле, и запись выбора поверх него стёрла бы
    волны, критерии и отметки — целую стройку ради одной строчки журнала.
    Нечитаемый файл здесь обязан уронить запись, а не заменить её собой.
    """
    with atomic_store.Lock(путь):
        состояние = json.loads(путь.read_text("utf-8"))
        состояние[ЖУРНАЛ] = list(состояние.get(ЖУРНАЛ) or []) + [запись]
        progress.save(путь, состояние, когда)


def факты_осмотра() -> "Path | None":
    """Факты последнего осмотра, если человек уже смотрел на свою машину.

    Каталог настроек берётся у пробы, а не собирается литералом: на машине с
    назначенным профилем «домашний каталог» — не тот каталог, который читает
    хост, и файл нашёлся бы в чужом профиле или не нашёлся вовсе.
    """
    p = collect.CLAUDE / "superstack" / "run" / "facts.json"
    return p if p.is_file() else None


def факт_маршрутизации(путь: "str | None") -> tuple:
    """Ответ осмотра про маршрутизацию субагентов, если он уже собран.

    Осмотр считает этот факт по тому же порогу. Взять готовый ответ дешевле и
    честнее, чем считать второй раз: два счёта одной величины расходятся.
    """
    if not путь:
        return None, None
    try:
        факты = json.loads(Path(путь).read_text("utf-8"))
    except (OSError, ValueError) as e:
        print(f"факты не прочитаны ({e}) — считаю доставку по версии",
              file=sys.stderr)
        return None, None

    def значение(ключ):
        v = факты.get(ключ)
        return v.get("value") if isinstance(v, dict) else v

    маршрутизация = значение("rt.subagent_model_routing")
    if not isinstance(маршрутизация, bool):
        маршрутизация = None
    версия = значение("rt.active_version")
    return маршрутизация, (версия if isinstance(версия, str) else None)


def человеку(v: dict) -> str:
    строки = [f"ТИР {v['tier'].upper()} — таск {v['task']}: {v['why']}"]
    for с in v["signals"]:
        строки.append(f"  · {с['признак']}: {с['почему']}")
    д = v["delivery"]
    строки.append(f"  доставка: {д['состояние']} — {д['почему']}")
    if д["состояние"] == НЕ_ДОЕДЕТ:
        строки.append("  зови исполнителя как прежде и не выдавай дешёвое за "
                      "дорогое: выбор до него не доехал")
    elif д["состояние"] == НЕИЗВЕСТНО:
        # «Не смог проверить» и «не доехал» — разные утверждения, и второе тут
        # не доказано. Считать неизмеренное доехавшим — тоже нельзя.
        строки.append("  доехал ли выбор — проверить нечем: сначала осмотр, "
                      "иначе тир назван, но не подтверждён")
    return "\n".join(строки)


def halt_if_paused() -> None:
    if os.environ.get("SUPERSTACK_IGNORE_PAUSE") == "1":
        return
    if (Path.home() / ".claude" / "superstack" / "PAUSE").exists():
        print("ОСТАНОВЛЕНО: система на паузе", file=sys.stderr)
        raise SystemExit(10)


def _flag(argv: list, name: str, default=None):
    if name in argv and argv.index(name) + 1 < len(argv):
        return argv[argv.index(name) + 1]
    return default


def main() -> int:
    halt_if_paused()
    argv = sys.argv[1:]
    берут = {"--adr", "--attempt", "--host-version", "--facts", "--project",
             "--now"}
    простые, пропуск = [], False
    for a in argv:
        if пропуск:
            пропуск = False
            continue
        if a in берут:
            пропуск = True
        elif not a.startswith("--"):
            простые.append(a)
    if len(простые) != 2:
        print("вызов: model_route.py <ход-стройки.json> <id> [--adr docs/adr] "
              "[--attempt N] [--host-version 2.1.170] [--facts facts.json]",
              file=sys.stderr)
        return 3

    путь = Path(простые[0]).expanduser()
    try:
        состояние = json.loads(путь.read_text("utf-8"))
    except (OSError, ValueError) as e:
        print(f"НЕ УДАЛОСЬ: ход стройки не прочитан: {e}", file=sys.stderr)
        return 3
    задача = handoff.find_task(состояние, простые[1])
    if задача is None:
        print(f"НЕ УДАЛОСЬ: нет задачи {простые[1]}", file=sys.stderr)
        return 3

    # Корень проекта: рядом с ходом стройки, если он лежит в своей папке.
    # Он нужен ровно затем, чтобы спросить счётчик попыток тем же ключом,
    # каким его пишет проверка.
    по_умолчанию = (путь.resolve().parent.parent
                    if путь.resolve().parent.name == ".superstack"
                    else Path.cwd())
    проект = Path(_flag(argv, "--project", str(по_умолчанию))).expanduser()

    явный = _flag(argv, "--attempt")
    if явный is not None:
        try:
            номер, откуда = int(явный), "назван вызовом"
        except ValueError:
            print(f"НЕ УДАЛОСЬ: --attempt не число: {явный}", file=sys.stderr)
            return 3
    else:
        номер, откуда = заход(проект)

    решения = handoff.read_adrs(Path(_flag(argv, "--adr")).expanduser()
                               if _flag(argv, "--adr") else None)
    выбор = решить(задача, решения, номер)

    где_факты = _flag(argv, "--facts") or факты_осмотра()
    маршрутизация, версия_из_фактов = факт_маршрутизации(где_факты)
    версия = _flag(argv, "--host-version") or версия_из_фактов
    как_доедет = доставка(версия, маршрутизация, os.environ)

    когда = _flag(argv, "--now") or datetime.now(timezone.utc).isoformat(
        timespec="seconds")
    запись = {"task": задача["id"], "tier": выбор["tier"], "why": выбор["why"],
              "signals": выбор["signals"], "attempt": номер,
              "delivery": как_доедет, "at": когда}
    сухой = "--dry-run" in argv
    if not сухой:
        try:
            вписать(путь, запись, когда)
        except (OSError, ValueError) as e:
            # Незаписанный выбор — это не мелочь: без записи потом нечем
            # ответить, окупился ли дорогой тир. Молча вернуть тир, сделав вид,
            # что он записан, значит соврать в единственном поле, ради
            # которого запись затевалась.
            print(f"НЕ УДАЛОСЬ: выбор не записан в ход стройки: {e}",
                  file=sys.stderr)
            return 3

    статус = {ДОЕДЕТ: "pass", НЕ_ДОЕДЕТ: "fail",
              НЕИЗВЕСТНО: "unknown"}[как_доедет["состояние"]]
    v = {"status": статус, "task": задача["id"], "tier": выбор["tier"],
         "why": выбор["why"], "signals": выбор["signals"], "attempt": номер,
         "attempt_source": откуда, "delivery": как_доедет,
         "recorded": not сухой,
         "detail": f"{выбор['tier']}: {выбор['why']}"}
    if "--json" not in argv:
        print(человеку(v), file=sys.stderr)
    elif статус != "pass":
        # Отказ обязан быть слышен и в машинном режиме: иначе он живёт только
        # в поле JSON, которое читают глазами через раз.
        print(человеку(v), file=sys.stderr)
    print(json.dumps(v, ensure_ascii=False, indent=1))
    return {"pass": 0, "fail": 1, "unknown": 2}[статус]


