#!/usr/bin/env python3
"""SUPERSTACK — запись файлов, которые пишет не один процесс.

Зачем это отдельный модуль, а не по четыре строки в каждом инструменте.

Запись «во временный файл рядом и переименовать» выглядела правильной и была
неправильной одинаково во всех инструментах сразу — размноженная копипастом
ошибка чинится по одному файлу и возвращается в остальных. Внешняя проверка
нашла в этих четырёх строках три дефекта:

  · имя временного файла одно на всех. Два процесса, пишущих один и тот же
    файл настроек, брали один и тот же `settings.json.tmp`: один падал «нет
    такого файла», и одна из двух записей пропадала — при этом обе операции
    завершались и обе возвращали ноль;

  · атомарной замены мало. Оба процесса читают старое состояние, каждый меняет
    СВОЮ часть и пишет ЦЕЛИКОМ; записавший вторым затирает чужую правку. Дыра
    не в записи, а МЕЖДУ чтением и записью, и закрывает её только замок,
    который держится весь цикл;

  · замена файла не наследует режим доступа. Файл с правами 0600 после записи
    получал 0644 при обычном umask 022 — то есть настройки человека
    становились читаемыми другим локальным пользователям машины.

Замок пришёл сюда из хода стройки, где появился после живого случая: в девятой
волне так исчезла отметка «проверено» — один процесс закрыл часть кодом
возврата, а параллельный вернул ей «в работе», молча и с нулём у обоих.
Заметить это можно было только глазами.

Модуль ничего не печатает в stdout и не имеет командной строки: он библиотека,
а не инструмент. В stderr уходят две вещи, и обе обязательны: отказ по замку
(молчаливая работа без замка есть молчаливая потеря чужой правки) и фраза об
остановке на повреждённом файле состояния (см. `прочитать_состояние`).
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import stat
import sys
import tempfile
import time
from pathlib import Path

#: Сколько байт файла-замка запирается там, где замок берётся не на весь
#: дескриптор, а на область файла. Область у всех процессов одна и та же,
#: поэтому одного байта достаточно, и файл при этом может быть пустым.
_ОБЛАСТЬ_ЗАМКА = 1

#: Предел ожидания замка, секунды. Своя операция короткая — прочитать,
#: изменить, записать, — поэтому за этот срок замок успевает освободиться
#: почти всегда. Число тут не священное; священно то, что предел ЕСТЬ:
#: безусловное ожидание вешало запись навсегда, без ошибки и без вывода, а
#: молчаливое ожидание неотличимо от работы.
ПРЕДЕЛ_ОЖИДАНИЯ = 10.0

#: Пауза между попытками взять замок.
_ШАГ_ОЖИДАНИЯ = 0.02

#: Режим НОВОГО файла. Настройки человека создаются приватными, а не по umask:
#: при обычном umask 022 файл рождался бы читаемым для всех, кто есть на этой
#: машине, — и никто бы этого не заметил, потому что читать его никто не
#: пробовал.
ПРИВАТНЫЙ = 0o600

#: Сказано ли уже, что замка нет. Предупреждение печатается ОДИН раз за
#: запуск: строка на каждый шаг волны превратилась бы в шум, который
#: перестают читать вместе со всем остальным.
_БЕЗ_ЗАМКА_СКАЗАНО = False


def _сказать_без_замка(причина: object) -> None:
    global _БЕЗ_ЗАМКА_СКАЗАНО
    if _БЕЗ_ЗАМКА_СКАЗАНО:
        return
    _БЕЗ_ЗАМКА_СКАЗАНО = True
    print(f"ВНИМАНИЕ: файл пишется без замка ({причина}). Если по этой папке "
          "прямо сейчас работает второй помощник, его правка может пропасть "
          "без единой ошибки — запускай по одному.", file=sys.stderr)


def _запереть(fh, предел: float) -> bool:
    """Запереть файл на время «прочитал, изменил, записал».

    Вызов запирания у Windows и у POSIX разный, и `fcntl` на Windows просто
    нет: безусловный импорт валил бы инструмент, которым пишется каждый шаг
    волны, — то есть весь ход стройки, на ровном месте.

    Возвращает False, если замка взять не удалось: работа продолжается, но об
    этом сказано вслух. Молчаливая работа без замка — это молчаливая потеря
    чужой правки, ради которой замок и заводился.

    У ожидания есть предел, и это вторая половина того же правила. Безусловный
    `flock` ждал вечно: процесс, погибший с невыпущенным замком, вешал
    следующую запись навсегда — без ошибки, без вывода и без признака поломки.
    «Висит» и «работает» выглядят одинаково, а отказ по времени — состояние,
    которое можно назвать.
    """
    if os.name == "nt":
        import msvcrt
        fh.seek(0)
        try:
            msvcrt.locking(fh.fileno(), msvcrt.LK_LOCK, _ОБЛАСТЬ_ЗАМКА)
        except OSError as e:
            # Занятую область здесь ждут около десяти секунд, и только потом
            # это исключение — предел ожидания у платформы уже свой.
            _сказать_без_замка(e)
            return False
        return True
    import fcntl
    срок = time.monotonic() + предел
    while True:
        try:
            fcntl.flock(fh.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
            return True
        except OSError as e:
            if time.monotonic() >= срок:
                _сказать_без_замка(f"ждали {предел:g} с, файл держит "
                                   f"кто-то другой: {e}")
                return False
            time.sleep(_ШАГ_ОЖИДАНИЯ)


def _отпереть(fh) -> None:
    """Снять то, что было взято. Зовётся только после удачного запирания."""
    if os.name == "nt":
        import msvcrt
        fh.seek(0)
        msvcrt.locking(fh.fileno(), msvcrt.LK_UNLCK, _ОБЛАСТЬ_ЗАМКА)
        return
    import fcntl
    fcntl.flock(fh.fileno(), fcntl.LOCK_UN)


class Lock:
    """Замок на файл — на всё время «прочитал, изменил, записал».

    Атомарной замены файла мало. Волна из двух помощников означает два
    процесса, которые читают состояние, меняют СВОЮ часть и пишут ЦЕЛИКОМ:
    тот, кто записал вторым, затирает чужую правку, и оба выходят с кодом 0.

    Это не теория. 18.08.2026 в девятой волне так исчезла отметка «проверено» у
    части 10: один процесс закрыл её кодом возврата, а параллельный вернул ей
    «в работе» — молча, без единой ошибки. Заметить можно было только глазами.

    Замок берётся на всю операцию, а не на запись: между чтением и записью и
    находится дыра.

    Запирается СОСЕДНИЙ файл, а не сам целевой: цель переименовывается при
    каждой записи, и замок, взятый на неё, достался бы уже несуществующему
    файлу — то есть не достался бы никому.
    """

    def __init__(self, path: Path, ждать: float = ПРЕДЕЛ_ОЖИДАНИЯ):
        path = Path(path)
        self.path = path.with_suffix(path.suffix + ".lock")
        self.ждать = ждать
        self.fh = None
        self.заперто = False

    def __enter__(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.fh = self.path.open("a+")
        self.заперто = _запереть(self.fh, self.ждать)
        return self

    def __exit__(self, *exc):
        try:
            # Отпирается только взятое: снимать замок, которого не брали,
            # значит получить вторую ошибку поверх первой и потерять её.
            if self.заперто:
                _отпереть(self.fh)
        finally:
            self.fh.close()
        return False


def _временный(path: Path) -> Path:
    """Уникальный временный сосед целевого файла.

    Имя `settings.json.tmp` было одно на всех: два процесса брали один и тот
    же путь, один затирал файл другого на полуслове, второй падал «нет такого
    файла» — и одна из двух записей пропадала при обеих завершившихся
    операциях. Уникальное имя убирает не последствие, а саму встречу.

    Сосед создаётся ПРИВАТНЫМ (так делает mkstemp) и лежит рядом с целью:
    переименование атомарно только в пределах одной файловой системы.
    """
    fd, имя = tempfile.mkstemp(dir=str(path.parent),
                               prefix=path.name + ".", suffix=".tmp")
    os.close(fd)
    return Path(имя)


def _режим_цели(path: Path, режим_нового: int) -> int:
    """Какие права обязан иметь файл ПОСЛЕ записи.

    Замена файла режим не наследует: 0600 превращался в 0644 при обычном
    umask 022, и настройки человека становились читаемыми другим локальным
    пользователям машины. Существовавший файл сохраняет СВОЙ режим — в обе
    стороны: назначать чужому файлу приватность значит так же менять решение
    человека, просто в другую сторону.
    """
    try:
        return stat.S_IMODE(path.stat().st_mode)
    except OSError:
        return режим_нового


def записать(path: Path, текст: str, *, режим_нового: int = ПРИВАТНЫЙ) -> None:
    """Записать текст одним движением, не расширив прав.

    Запись поверх оставляет обрезанный файл, если процесс погиб на середине, —
    то есть настройки человека в состоянии, которого не было ни до, ни после.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    режим = _режим_цели(path, режим_нового)
    врем = _временный(path)
    try:
        врем.write_text(текст, encoding="utf-8")
        os.chmod(врем, режим)
        os.replace(врем, path)
    except BaseException:
        # Оборвалось на середине — мусор не остаётся лежать рядом с
        # настройками человека. Ошибку записи это не прячет: она летит дальше.
        try:
            врем.unlink()
        except OSError:
            pass
        raise


def скопировать(откуда: Path, куда: Path, *,
                режим_нового: int = ПРИВАТНЫЙ) -> None:
    """Положить на место КОПИЮ чужого файла — тем же движением и правами.

    Копия транскрипта разговора создавалась прямым `copyfile` и получала права
    по umask: при обычном 022 весь разговор человека оказывался читаемым
    любому, кто есть на этой машине, — и никто бы этого не заметил, потому что
    читать его никто не пробовал.

    Через `записать` это не сделать: транскрипт бывает большим и не обязан
    быть текстом, а читать его в память ради одной замены значит менять цену
    операции. Поэтому копирование идёт файл-в-файл, а уникальный сосед, режим
    и атомарная замена берутся отсюда — теми же, что у остальной записи.
    """
    куда = Path(куда)
    куда.parent.mkdir(parents=True, exist_ok=True)
    режим = _режим_цели(куда, режим_нового)
    врем = _временный(куда)
    try:
        shutil.copyfile(откуда, врем)
        os.chmod(врем, режим)
        os.replace(врем, куда)
    except BaseException:
        # Оборвалось на середине — недокопированный кусок не остаётся лежать
        # рядом и не подменяет собой прежнюю целую копию.
        try:
            врем.unlink()
        except OSError:
            pass
        raise


def записать_json(path: Path, data, *, indent: int = 1,
                  режим_нового: int = ПРИВАТНЫЙ) -> None:
    """То же для набора полей. Отступ — параметр: файлы разных инструментов
    читает человек, и переформатировать их заодно с починкой значит выдать
    правку одного поля за правку всего файла."""
    записать(path, json.dumps(data, ensure_ascii=False, indent=indent),
             режим_нового=режим_нового)


#: Код остановки «файл состояния есть, но не читается». Ни один из пяти
#: инструментов, читающих состояние, этим числом не занят: 3 у них — ошибка
#: вызова, 4 — «уже начато». Одно событие для человека — одно число.
ПОВРЕЖДЁН = 5


class ФайлПовреждён(Exception):
    """Файл состояния лежит на месте, но прочитать его нельзя.

    Раньше этот случай читался как «пусто», и следующая запись клала пустое
    поверх: исчезал весь ход стройки или все слова человека — без ошибки и
    с кодом 0. Отдельное исключение нужно, чтобы его не поймал ни один
    `except ValueError` по дороге: такая ловушка снова превратила бы
    остановку в «пусто».
    """

    def __init__(self, path: Path, что: str, копия: "Path | None"):
        self.path, self.что, self.копия = Path(path), что, копия
        if копия is not None:
            фраза = f"{что} повреждён, копия сохранена, ничего не стёрто: {копия}"
        else:
            # Копию положить не вышло — обещать её нельзя.
            фраза = (f"{что} повреждён и не читается, ничего не стёрто: "
                     f"{self.path}")
        super().__init__(фраза)


def отложить_копию(path: Path, вид: str) -> "tuple[Path, bool]":
    """Копия рядом, с отпечатком содержимого в имени: (путь, новая ли).

    Отпечаток, а не время: повторное чтение того же файла находит уже
    положенную копию и не плодит вторую, а изменившееся содержимое получает
    свою. Копия кладётся тем же движением и с теми же правами, что и любая
    запись здесь.
    """
    path = Path(path)
    отпечаток = hashlib.sha256(path.read_bytes()).hexdigest()[:12]
    копия = path.with_name(f"{path.name}.{вид}-{отпечаток}.bak")
    if копия.is_file():
        return копия, False
    скопировать(path, копия)
    return копия, True


def _отложить_битый(path: Path) -> "Path | None":
    try:
        return отложить_копию(path, "broken")[0]
    except OSError:
        return None


def прочитать_состояние(path: Path, пустое: dict, что: str, *,
                        поверх_битого: bool = False) -> dict:
    """Прочитать файл состояния, не выдавая нечитаемое за пустое.

    Файла нет (или в нём нет ни одного знака) — законное начало: беречь
    нечего, отдаётся копия `пустое`. Файл есть, но не разбирается или это не
    набор полей — рядом кладётся копия, и поднимается `ФайлПовреждён`.

    `поверх_битого` — явная просьба начать заново: копия уже лежит рядом,
    стирать больше нечего, и упираться в остановку было бы тупиком.
    """
    path = Path(path)
    if not path.is_file():
        return json.loads(json.dumps(пустое))
    try:
        raw = path.read_bytes()
        if not raw.strip():
            return json.loads(json.dumps(пустое))
        d = json.loads(raw.decode("utf-8"))
        if not isinstance(d, dict):
            raise ValueError("не набор полей")
    except (OSError, ValueError):
        копия = _отложить_битый(path)
        if поверх_битого and копия is not None:
            return json.loads(json.dumps(пустое))
        raise ФайлПовреждён(path, что, копия) from None
    for k, v in пустое.items():
        d.setdefault(k, json.loads(json.dumps(v)))
    return d


def запустить(main) -> int:
    """Запустить `main` инструмента; на повреждённом файле — фраза и код 5.

    Ловится здесь, у самого входа, а не в каждой команде: команда, забывшая
    поймать, отдала бы человеку трассировку вместо одной фразы.
    """
    try:
        return main()
    except ФайлПовреждён as e:
        print(f"ОСТАНОВЛЕНО: {e}", file=sys.stderr)
        return ПОВРЕЖДЁН
