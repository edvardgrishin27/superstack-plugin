#!/usr/bin/env python3
"""SUPERSTACK — окупился ли дорогой тир. Один вопрос, ответ числом.

Зачем это существует.

Числа в системе собирались честно и никуда не вели. Цена прогона считалась по
журналам сессий. Выбор тира со всеми признаками ложился в ход стройки. Счётчик
заходов вёлся проверкой. Ни один из трёх никто не читал, чтобы в следующий раз
решить иначе, — и это записано в докстрингах обоих измерителей как
предупреждение самим себе: самоулучшение без обратной связи есть накопление.

Здесь петля замыкается, и ровно на один вопрос: ОКУПАЕТСЯ ЛИ ПРИЗНАК, ПО
КОТОРОМУ МЫ ПЛАТИМ ДОРОЖЕ. Не прогноз, не подбор весов, не оценка качества
работы — на них нет данных, и выдуманный ответ здесь стоил бы дороже
отсутствующего.

Как считается, и почему именно так.

  · ИСХОД ЗАХОДА берётся из журнала выбора: заход, после которого у той же
    задачи есть заход с бо́льшим номером, не сошёлся. Третий счётчик попыток
    не заводится — два счётчика расходятся, и расходятся молча.
  · ЗАДАЧА, КОТОРАЯ ЕЩЁ НЕ ДОКАЗАНА, исходом не считается вовсе. «Пока
    неизвестно» — не «сошлось»: красить незаконченное в зелёное значит
    получить окупаемость у любого признака.
  · ЦЕНА берётся у измерителя прогона. Второго источника расхода нет и не
    будет: два разойдутся ровно тогда, когда понадобится точный ответ.
  · СРАВНИВАЕТСЯ признак с выборами, где ни одного дорогого признака не было.
    Без второй группы разницы не существует, и «стало лучше» не с чем
    сопоставить.

Три вещи, которых этот инструмент НЕ делает, и все три намеренно.

  1. НИЧЕГО НЕ ВЫКЛЮЧАЕТ. Признак, который стоит дорого и ничего не меняет,
     называется вслух вместе с числами. Выключить его — решение владельца.
     Скрипт, правящий правила выбора по собственному замеру, меняет следующий
     прогон без ведома того, кто за него платит.
  2. НЕ ПРАВИТ ПРАВИЛА ВЫБОРА ТИРА. Он на них СМОТРИТ. Ход стройки читается и
     не переписывается.
  3. НЕ УГАДЫВАЕТ НА ТОНКИХ ДАННЫХ. Ниже порога ответ — «мерить нечем».
     Осторожная догадка выглядит как измерение и потому опаснее молчания.

  python3 tier_payoff.py <ход-стройки.json> [--project .] [--json]

  код 0 — сведено, подозрительных признаков нет
       1 — есть подозрительный признак: показан, но НЕ выключен
       2 — мерить нечем: журнала выбора нет или записей меньше порога
       3 — ошибка вызова
"""
from __future__ import annotations

import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

# Соседи по пакету и проба. Путь добавляется явно: каталог скрипта при импорте
# из теста в sys.path не попадает — так же, как у соседних инструментов.
sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent / "probe"))

import handoff  # noqa: E402
import measure_run  # noqa: E402
import model_route  # noqa: E402
import progress  # noqa: E402

#: Ключ журнала выбора и имена тиров берутся у самого маршрутизатора.
#: Переписать их сюда литералами значило бы завести вторую копию, которая
#: разойдётся с первой при первой же правке — и разойдётся молча, потому что
#: оба места выглядят верными.
ЖУРНАЛ = model_route.ЖУРНАЛ
ДОРОГОЙ = model_route.ДОРОГОЙ
ОБЫЧНЫЙ = model_route.ОБЫЧНЫЙ

#: Сколько закрытых заходов нужно, чтобы вообще открывать рот про признак.
#:
#: Число выбрано, а не измерено, и потому названо. Обоснование одно: при N
#: записях одна запись двигает долю на 1/N. Вывод «признак ничего не меняет»
#: обязан пережить одну запись, ушедшую в другую сторону; на пяти записях она
#: двигает ответ на пятую часть — то есть на всю разницу целиком. Десять —
#: наименьшее круглое число, при котором одна запись ответ не переворачивает.
#: Ниже порога инструмент молчит, и это не осторожность, а честность: тонкие
#: данные дают уверенный на вид ответ ровно так же, как толстые.
ПОРОГ_ЗАПИСЕЙ = 10

#: Слова, которыми называется отсутствие замера расхода. Отдельной строкой,
#: потому что путать «нечего мерить» с «ничего не потратили» нельзя: первое
#: означает отсутствие данных, второе — измеренный ноль, и на втором строят
#: выводы.
РАСХОД_НЕ_ИЗМЕРЕН = "расход не измерен"

#: Кто решает по найденному признаку. Стоит в каждом вердикте, а не в
#: послесловии: строку отчёта читают вырванной из отчёта.
ВЛАДЕЛЕЦ = "решает владелец: инструмент показывает и ничего не выключает"

#: Как цена сессии превращается в цену захода. Правило названо вслух, чтобы
#: его можно было оспорить: точнее данных нет, и молчаливое деление выглядело
#: бы измерением.
ПРАВИЛО_ЦЕНЫ = ("цена измеренной сессии разнесена поровну между выборами, "
                "сделанными внутри неё: точнее данных нет")

ЗАКРЫЛСЯ, ПЕРЕЗАХОД, НЕ_ИЗВЕСТНО = "закрылся", "перезаход", "не известно"
ОКУПАЕТСЯ, ПОДОЗРИТЕЛЬНЫЙ, НЕЧЕМ = "окупается", "подозрительный", "мерить нечем"

#: С чем сравнивается дорогой признак: с выборами ОБЫЧНОГО тира — там, где мы
#: не доплачивали и не удешевляли. Дешёвый тир из сравнения исключён нарочно:
#: он достаётся механическим правкам, у которых и без всякой доплаты почти не
#: бывает вторых заходов. Считая их «жизнью без признака», инструмент завышал
#: бы подозрение — то есть обвинял бы признаки чужой лёгкостью.
СРАВНЕНИЕ = f"выборы обычного тира ({ОБЫЧНЫЙ})"


def _время(v) -> "datetime | None":
    """Метка времени в UTC. Наивная считается UTC, а не местным временем.

    Местное время сдвинуло бы окна сессий на часы и разнесло цену не тем
    заходам — тихо и правдоподобно.
    """
    if not v:
        return None
    try:
        т = datetime.fromisoformat(str(v).replace("Z", "+00:00"))
    except ValueError:
        return None
    return т if т.tzinfo else т.replace(tzinfo=timezone.utc)


def выборы(состояние: dict) -> list:
    """Журнал выбора — по одной записи на заход.

    Две записи об одном заходе одной задачи считаются ОДНИМ заходом: берётся
    последняя, та, что действовала в момент исполнения. Иначе повторная
    маршрутизация того же захода удваивала бы его вес в числах — и удваивала
    бы его именно там, где кто-то переспрашивал, то есть в самых спорных
    местах.

    ЧТО ЭТО СТОИТ, названо здесь, а не спрятано. Номер захода приходит от
    проверки, и без её прогона он не меняется: задача, перезапущенная в обход
    проверки, приходит сюда вторым выбором с тем же номером и склеивается с
    первым. Перезаход в таком случае недосчитан, то есть признак выглядит
    ЛУЧШЕ, чем он есть. Ошибка склонена в эту сторону намеренно: недообвинить
    признак дешевле, чем обвинить зря — по обвинению владелец выключает то,
    за что платит.
    """
    журнал = состояние.get(ЖУРНАЛ)
    if not isinstance(журнал, list):
        return []
    по_заходам = {}
    for з in журнал:
        if not isinstance(з, dict) or not з.get("task"):
            continue
        try:
            заход = int(з.get("attempt") or 0)
        except (TypeError, ValueError):
            continue
        по_заходам[(str(з["task"]), заход)] = {**з, "task": str(з["task"]),
                                               "attempt": заход}
    return [по_заходам[к] for к in sorted(по_заходам)]


def исходы(записи: list, состояние: dict) -> list:
    """Чем кончился каждый заход. Счётчик заходов — тот, что уже в журнале.

    Признак перезахода один: у той же задачи есть заход с бо́льшим номером.
    Свой счётчик попыток разошёлся бы и с журналом выбора, и со счётчиком
    проверки, из которого журнал заполнялся, — а спорить три числа начали бы
    в тот момент, когда нужен точный ответ.

    Последний заход задачи считается закрывшимся, только если сама задача
    ДОКАЗАНА кодом возврата. Иначе исход неизвестен, и запись выпадает из
    счёта — вместе с объявленным числом таких записей, чтобы выпадение было
    видно, а не тихо улучшало долю.
    """
    предел = {}
    for з in записи:
        предел[з["task"]] = max(предел.get(з["task"], 0), з["attempt"])
    статус = {str(т.get("id")): т.get("status")
              for т in handoff.rows(состояние) if isinstance(т, dict)}
    готово = []
    for н, з in enumerate(записи):
        if з["attempt"] < предел[з["task"]]:
            исход = ПЕРЕЗАХОД
        elif статус.get(з["task"]) == progress.PROVEN:
            исход = ЗАКРЫЛСЯ
        else:
            исход = НЕ_ИЗВЕСТНО
        готово.append({**з, "№": н, "исход": исход})
    return готово


def _без_цен(почему: str) -> dict:
    return {"измерен": False, "почему": почему, "цены": {},
            "без_цены": 0, "разнесено": 0}


def расход(проект: Path, записи: list) -> dict:
    """Цена каждого захода — у СУЩЕСТВУЮЩЕГО измерителя прогона.

    Заход относится к той сессии, в чьё измеренное окно попала его метка
    времени. Цена сессии делится между попавшими в неё выборами поровну:
    данных о том, кто из них съел больше, нет ни у кого, и выдумывать их
    нельзя. Правило названо в ответе, чтобы его читали вместе с числом.

    Журнала сессий нет — так и сказано. Ноль сюда подставлять нельзя: «нечего
    мерить» и «ничего не потратили» — разные утверждения, и второе тут не
    доказано.
    """
    замер = measure_run.measure(проект)
    if замер["status"] != "pass":
        return _без_цен(f"{РАСХОД_НЕ_ИЗМЕРЕН}: {замер['detail']}")

    окна = []
    for с in замер["sessions"]:
        начало, конец = _время(с.get("started")), _время(с.get("finished"))
        if начало and конец:
            окна.append((начало, конец, с["cost"]))

    попал = []
    for з in записи:
        метка = _время(з.get("at"))
        попал.append(next((i for i, (a, b, _) in enumerate(окна)
                           if метка and a <= метка <= b), None))
    сколько = {}
    for i in попал:
        if i is not None:
            сколько[i] = сколько.get(i, 0) + 1
    цены = {з["№"]: окна[i][2] / сколько[i]
            for з, i in zip(записи, попал) if i is not None}
    без_цены = sum(1 for i in попал if i is None)
    if not цены:
        return {**_без_цен(f"{РАСХОД_НЕ_ИЗМЕРЕН} по этим выборам: ни один не "
                           "попал в измеренную сессию"),
                "без_цены": без_цены}
    return {"измерен": True, "цены": цены, "без_цены": без_цены,
            "разнесено": round(sum(цены.values()), 3), "почему": ПРАВИЛО_ЦЕНЫ}


def _признаки(з: dict) -> list:
    return [с.get("признак") for с in (з.get("signals") or [])
            if isinstance(с, dict) and с.get("признак")]


def _счёт(группа: list, цены: dict) -> dict:
    """Числа одной группы заходов. Доля считается только от ЗАКРЫТЫХ.

    Номера заходов возвращаются списком: по ним видно, сравнимы ли две группы
    вообще. Группа, живущая на заходах, которых у второй не бывает, — это
    другой набор задач, а не другая величина.
    """
    закрытые = [з for з in группа if з["исход"] in (ЗАКРЫЛСЯ, ПЕРЕЗАХОД)]
    перезаходов = sum(1 for з in закрытые if з["исход"] == ПЕРЕЗАХОД)
    свои = [цены[з["№"]] for з in группа if з["№"] in цены]
    return {"записей": len(группа), "закрыто": len(закрытые),
            "перезаходов": перезаходов,
            "доля": round(перезаходов / len(закрытые), 3) if закрытые else None,
            "цена": round(sum(свои) / len(свои)) if свои else None,
            "заходы": sorted({з["attempt"] for з in закрытые})}


def свести(записи: list, признак: str, цены: dict) -> dict:
    """Числа одного признака: сколько раз он сработал и чем это кончилось.

    Группа признака — все заходы, где он назван, а не только те, где он
    оказался единственным. Признаки в одном выборе складываются, и делить их
    вклад было бы подбором весов, которого здесь нет.
    """
    свои = [з for з in записи if признак in _признаки(з)]
    return _счёт(свои, цены)


def _вердикт(имя: str, числа: dict, вердикт: str, почему: str) -> dict:
    """Строка свода: числа, вердикт и тот, кто по нему решает."""
    return {"признак": имя, **числа, "вердикт": вердикт, "почему": почему,
            "решает": ВЛАДЕЛЕЦ}


def _про_цену(числа: dict, основа: dict) -> str:
    if числа["цена"] is None or основа["цена"] is None:
        return f"; {РАСХОД_НЕ_ИЗМЕРЕН} — вывод только по заходам"
    return f"; цена захода {числа['цена']} против {основа['цена']} без него"


def подозрение(имя: str, числа: dict, основа: dict) -> dict:
    """Вердикт по признаку: окупается, подозрителен или мерить нечем.

    «Подозрителен» — это утверждение о ЧИСЛАХ, а не приговор признаку: заходов
    после него не меньше, чем без него, а платим мы за него больше. Что с этим
    делать, решает владелец; инструмент не выключает ничего сам, потому что
    выключенный признак меняет следующий прогон, за который платит он.
    """
    if числа["закрыто"] < ПОРОГ_ЗАПИСЕЙ:
        return _вердикт(имя, числа, НЕЧЕМ,
                        f"закрытых заходов {числа['закрыто']} при пороге "
                        f"{ПОРОГ_ЗАПИСЕЙ}: одна запись двигала бы ответ "
                        "сильнее, чем сам признак")
    if основа["закрыто"] < ПОРОГ_ЗАПИСЕЙ:
        return _вердикт(имя, числа, НЕЧЕМ,
                        f"сравнить не с чем: {СРАВНЕНИЕ} дали "
                        f"{основа['закрыто']} закрытых заходов при пороге "
                        f"{ПОРОГ_ЗАПИСЕЙ}")
    if not set(числа["заходы"]) & set(основа["заходы"]):
        # Так устроен признак повторного захода: он срабатывает ровно там, где
        # обычного тира не бывает по определению, — и сравнивать его было бы
        # не с чем. Проверяются НОМЕРА заходов, а не имя признака: имя
        # проверять значит зашить в измеритель знание о конкретном правиле.
        return _вердикт(имя, числа, НЕЧЕМ,
                        f"общих заходов с группой сравнения нет: у признака "
                        f"заходы {числа['заходы']}, у сравнения "
                        f"{основа['заходы']} — это разные наборы задач, и "
                        "вердикт вышел бы формой, а не измерением")

    хвост = _про_цену(числа, основа)
    счёт = (f"перезаходов {числа['перезаходов']} из {числа['закрыто']} против "
            f"{основа['перезаходов']} из {основа['закрыто']} без него")
    if числа["доля"] < основа["доля"]:
        return _вердикт(имя, числа, ОКУПАЕТСЯ,
                        f"{счёт} — заходов меньше{хвост}")
    return _вердикт(имя, числа, ПОДОЗРИТЕЛЬНЫЙ,
                    f"{счёт} — платим дороже, а заходов не меньше{хвост}")


def разобрать(состояние: dict, проект: Path) -> dict:
    """Свод целиком: числа по каждому дорогому признаку и общий вердикт."""
    записи = исходы(выборы(состояние), состояние)
    деньги = расход(проект, записи)
    цены = деньги["цены"]

    основа = _счёт([з for з in записи if з.get("tier") == ОБЫЧНЫЙ], цены)
    основа["группа"] = СРАВНЕНИЕ
    имена = sorted({и for з in записи if з.get("tier") == ДОРОГОЙ
                    for и in _признаки(з)})
    свод = [подозрение(и, свести(записи, и, цены), основа) for и in имена]
    подозрительные = [с["признак"] for с in свод
                      if с["вердикт"] == ПОДОЗРИТЕЛЬНЫЙ]

    if not записи:
        статус = "unknown"
        деталь = ("журнала выбора нет: ни один тир не записан — мерить нечем. "
                  "Это не «дорогой тир не нужен», а отсутствие данных")
    elif not свод:
        статус = "unknown"
        деталь = "дорогой тир ни разу не выбирался — окупаться нечему"
    elif подозрительные:
        статус = "fail"
        деталь = ("признаков, за которые платим дороже без выигрыша: "
                  + ", ".join(подозрительные))
    elif any(с["вердикт"] == ОКУПАЕТСЯ for с in свод):
        статус = "pass"
        деталь = f"дорогих признаков {len(свод)}, подозрительных нет"
    else:
        статус = "unknown"
        деталь = (f"дорогих признаков {len(свод)}, и ни по одному нет "
                  f"{ПОРОГ_ЗАПИСЕЙ} закрытых заходов — мерить нечем")

    return {"status": статус, "threshold": ПОРОГ_ЗАПИСЕЙ,
            "records": len(записи),
            "unresolved": sum(1 for з in записи if з["исход"] == НЕ_ИЗВЕСТНО),
            "spend": {к: v for к, v in деньги.items() if к != "цены"},
            "baseline": основа, "signals": свод,
            "suspicious": подозрительные, "detail": деталь}


def человеку(v: dict) -> str:
    """Одной фразой и числами. Ни одной строки, которую надо набирать."""
    if not v["signals"]:
        return v["detail"]
    о = v["baseline"]
    цена_основы = (f", цена захода {о['цена']}" if о["цена"] is not None else "")
    строки = [
        f"Окупился ли дорогой тир — по {v['records']} выборам; вывод даётся от "
        f"{v['threshold']} закрытых заходов",
        f"Там, где не доплачивали: перезаходов {о['перезаходов']} из "
        f"{о['закрыто']}{цена_основы}",
    ]
    for с in v["signals"]:
        строки.append(f"  · «{с['признак']}» — выборов {с['записей']}, "
                      f"{с['вердикт']}: {с['почему']}")
    if v["unresolved"]:
        строки.append(f"Заходов без известного исхода: {v['unresolved']} — "
                      "они в счёт не пошли")
    if not v["spend"]["измерен"]:
        строки.append(v["spend"]["почему"])
    if v["suspicious"]:
        строки.append("Ничего не выключаю: это твоё решение, а не моё — "
                      "числа выше показывают, за что мы доплачиваем зря")
    return "\n".join(строки)


def halt_if_paused() -> None:
    if os.environ.get("SUPERSTACK_IGNORE_PAUSE") == "1":
        return
    if (Path.home() / ".claude" / "superstack" / "PAUSE").exists():
        print("ОСТАНОВЛЕНО: система на паузе", file=sys.stderr)
        raise SystemExit(10)


def _flag(argv: list, name: str, default=None):
    if name in argv and argv.index(name) + 1 < len(argv):
        return argv[argv.index(name) + 1]
    return default


def main() -> int:
    halt_if_paused()
    argv = sys.argv[1:]
    берут = {"--project"}
    простые, пропуск = [], False
    for a in argv:
        if пропуск:
            пропуск = False
            continue
        if a in берут:
            пропуск = True
        elif not a.startswith("--"):
            простые.append(a)
    if len(простые) != 1:
        print("вызов: tier_payoff.py <ход-стройки.json> [--project .] [--json]",
              file=sys.stderr)
        return 3

    путь = Path(простые[0]).expanduser()
    try:
        состояние = json.loads(путь.read_text("utf-8"))
    except (OSError, ValueError) as e:
        print(f"НЕ УДАЛОСЬ: ход стройки не прочитан: {e}", file=sys.stderr)
        return 3
    if not isinstance(состояние, dict):
        print("НЕ УДАЛОСЬ: ход стройки — не запись, а что-то другое",
              file=sys.stderr)
        return 3

    # Корень проекта: рядом с ходом стройки, если он лежит в своей папке. Он
    # нужен ровно затем, чтобы измеритель прогона нашёл журналы сессий тем же
    # правилом, каким он их ищет везде.
    по_умолчанию = (путь.resolve().parent.parent
                    if путь.resolve().parent.name == ".superstack"
                    else Path.cwd())
    проект = Path(_flag(argv, "--project", str(по_умолчанию))).expanduser()
    if not проект.is_dir():
        print(f"НЕ УДАЛОСЬ: нет каталога {проект}", file=sys.stderr)
        return 3

    v = разобрать(состояние, проект)
    if "--json" in argv:
        if v["status"] != "pass":
            # Находка обязана быть слышна и в машинном режиме: иначе она живёт
            # только в поле, которое читают глазами через раз.
            print(человеку(v), file=sys.stderr)
        print(json.dumps(v, ensure_ascii=False, indent=1))
    else:
        print(человеку(v))
    return {"pass": 0, "fail": 1, "unknown": 2}[v["status"]]


if __name__ == "__main__":
    sys.exit(main())
