#!/usr/bin/env python3
"""SUPERSTACK — чтение файлов настроек человека и очистка их копии.

Отдельный файл, потому что здесь собрано одно утверждение: ЧТО ИМЕННО имеет
право уехать в копию. Копия настроек — второй экземпляр всего, что в них
лежит, включая ключи; «критическая находка про пароль» без этой очистки
превращала бы одну копию пароля в две.

Здесь нет ни одной записи на диск и ни одного пути к профилю. Кто и куда
пишет — соседний `apply.py`; сюда приходят содержимое и находки, отсюда
уходят очищенный текст и причины отказа. Граница проходит по файлу, а не по
внимательности читателя.

Три вещи, ради которых всё написано:

  1. ЧТЕНИЕ ОДНО. Копирование читало `utf-8-sig`, а сборщик фактов — `utf-8`:
     на файле с BOM у них выходили разные ответы о том, что в файле лежит, и
     решение о вырезании принималось по более слепому.
  2. НЕ РАЗОБРАЛОСЬ — ЭТО НЕ ПУСТО. Неудача разбора говорит о разборщике и не
     сообщает о содержимом ничего; прежде из неё выводилось «вырезать нечего»,
     и файл уезжал в копию сырым.
  3. СМОТРИМ НА ТО, ЧТО ПИШЕМ. Список находок собран раньше и, возможно,
     другим чтением; пустой он означает «сканер ничего не увидел», а не «в
     файле ничего нет». Поэтому копия проверяется свежим обходом И тем
     текстом, которым она станет.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path


#: Сборщик фактов, загружаемый по требованию. Из него берутся ОДНО чтение
#: конфигурации, ОДИН сканер секретов и ОДИН резолвер каталога настроек — те
#: же самые, которыми собирались находки. Две копии этой логики разошлись бы
#: молча, и разошлись бы ровно там, где цена расхождения — вторая копия чужого
#: пароля или правка не в том профиле.
_ПРОБА = None


def _проба():
    """Модуль сборщика фактов. Не загрузился — это ОТКАЗ, а не тишина.

    Широкий `except` вокруг этой загрузки выключил бы очистку копии молча, и
    инструмент отчитался бы удачной копией, в которой лежит невырезанный
    секрет. Такое уже случалось с вычиткой подписи этапа: проверка отвалилась
    при переносе зависимости и продолжила отвечать «всё чисто». Поэтому здесь
    говорится вслух и ничего не делается.

    То же правило теперь держит и адрес правки: без сборщика неизвестно, какой
    каталог настроек читает хост. Молчаливый переход на домашний каталог был бы
    вторым резолвером — и включался бы он ровно тогда, когда о нём никто не
    помнит, у того, чей профиль вынесен в сторону.
    """
    global _ПРОБА
    if _ПРОБА is None:
        import importlib.util
        путь = Path(__file__).resolve().parent / "probe" / "collect.py"
        if not путь.is_file():
            raise SystemExit(
                f"ОТКАЗ: сканер секретов не найден ({путь}) — копию настроек "
                f"делать вслепую нельзя: в неё уехали бы незакрытые значения. "
                f"Ничего не менял.")
        спек = importlib.util.spec_from_file_location("ss_collect_for_apply", путь)
        мод = importlib.util.module_from_spec(спек)
        спек.loader.exec_module(мод)
        _ПРОБА = мод
    return _ПРОБА


#: что инструменту вообще разрешено трогать. Всё остальное — не его дело.
WRITABLE = ("settings.json", "settings.local.json")

#: Метка на месте вырезанного секрета. Одна на весь пакет: копия ставит её,
#: откат по ней узнаёт, что возвращать нечего. Две независимые строки
#: разъехались бы при первой же правке, и откат перестал бы узнавать метку.
REDACTION_MARK = "<ВЫРЕЗАНО-SUPERSTACK"


# --------------------------------------------------------------------------
# чтение конфигурации: одно на всех
# --------------------------------------------------------------------------
def _прочитать_конфиг(src: Path) -> tuple:
    """Прочитать файл настроек ТЕМ ЖЕ чтением, каким его читает сборщик фактов.

    Возвращает (разобранное, беда). Беда — строка, если разобрать не удалось;
    она называет причину и НЕ содержит содержимого файла.

    Прежде копирование читало `utf-8-sig`, а сборщик — `utf-8`: на файле с BOM
    у них получались разные ответы о том, что в файле лежит, и решение о
    вырезании принималось по более слепому. Здесь чтение ровно одно.
    """
    try:
        текст = src.read_text(encoding=_проба().CONFIG_ENCODING)
    except OSError as e:
        return None, f"файл не читается ({e})"
    except UnicodeDecodeError as e:
        # Байты, которые не складываются в текст, — тот же случай «не
        # проверено», а не отдельный. Ловится он отдельно потому, что
        # UnicodeDecodeError — это ValueError, и до разбора JSON дело не
        # доходит: без этой ветки настройки, сохранённые в UTF-16 (обычное
        # дело для редакторов Windows), роняли инструмент трейсбеком вместо
        # честного отказа. Наружу идут причина и позиция, но не сами байты.
        return None, (f"не читается как текст ({e.reason}, байт {e.start})")
    try:
        return json.loads(текст), None
    except ValueError as e:
        return None, f"не разбирается как JSON ({e})"


# --------------------------------------------------------------------------
# редактирование секретов в бэкапе
# --------------------------------------------------------------------------
def redact(obj, hits: list[dict], path: str = ""):
    """Убрать из копии значения, помеченные пробой как секреты.

    Совпадения приходят из находок и содержат ПУТЬ, а не значение. Здесь
    путь используется, чтобы заменить значение меткой. Отпечаток остаётся,
    поэтому по бэкапу можно понять, тот ли это был секрет, — но не какой.
    """
    locations = {h.get("location") for h in hits if h.get("location")}
    return _redact_walk(obj, "", locations)


def _redact_walk(obj, path: str, locations: set):
    if isinstance(obj, dict):
        return {k: _redact_walk(v, f"{path}.{k}" if path else str(k), locations)
                for k, v in obj.items()}
    if isinstance(obj, list):
        return [_redact_walk(v, f"{path}[{i}]", locations)
                for i, v in enumerate(obj)]
    if path in locations and isinstance(obj, str):
        fp = hashlib.sha256(obj.encode("utf-8")).hexdigest()[:12]
        return f"{REDACTION_MARK} len={len(obj)} fp={fp}>"
    return obj


def _redact_journal(запись: dict, hits: list[dict]) -> dict:
    """Журнал полей живёт по тому же правилу, что и копия файла.

    Копия файла очищается, а записи «было/стало» лежат рядом, в manifest.json
    того же каталога. Значение, которое действие перезаписало, попало бы туда
    открытым текстом — и находка про пароль снова создала бы вторую копию
    пароля, только этажом ниже и без единого сообщения об этом.

    Места берутся из тех же находок, что и очистка копии: проба сообщает ПУТЬ,
    и здесь он же сравнивается с путём поля.
    """
    места = {h.get("location") for h in hits if h.get("location")}
    if not места:
        return запись
    поле = запись.get("field") or ""
    итог = dict(запись)
    for ключ in ("before", "after"):
        if ключ in итог:
            итог[ключ] = _redact_walk(итог[ключ], поле, места)
    return итог


def _свежие_находки(данные) -> list[dict]:
    """Секреты — в том содержимом, которое СЕЙЧАС ляжет в копию.

    Список находок приходит снаружи: его собрали раньше и, возможно, другим
    чтением. Пустой он означает «сканер ничего не увидел», а не «в файле
    ничего нет» — на файле с BOM он выходил пустым ровно так. Копия не имеет
    права принимать это за разрешение сохранить файл целиком, поэтому она
    смотрит сама и на то самое содержимое, которое пишет.
    """
    находки: list = []
    _проба()._walk_env(данные, "", находки)
    return находки


def _что_вырезать(name: str, данные, внешние: list[dict]) -> list[dict]:
    """Места, которые в копии будут закрыты меткой.

    Свежий обход ДОПОЛНЯЕТ находки, а не заменяет их: правило может знать про
    место, которого сканер не видит, и терять его нельзя. Совпадающие места
    считаются один раз — иначе число «вырезано столько-то» удваивалось бы на
    ровном месте и врало человеку про размер утечки.
    """
    свои = [h for h in внешние if h.get("file") in (name, "user", "user-local")]
    места = {h.get("location") for h in свои}
    return свои + [h for h in _свежие_находки(данные)
                   if h.get("location") not in места]


def _остатки_в_тексте(текст: str) -> list[str]:
    """Что сканер видит в ТЕКСТЕ, который вот-вот будет записан.

    Обход по структуре читает значения, но не ИМЕНА полей: секрет, оказавшийся
    в имени, для него невидим, а в копию уезжает так же открыто. Здесь копия
    проверяется тем, чем она станет, — текстом.

    Возвращаются ПРИЧИНЫ и номера строк. Само найденное наружу не выходит:
    отказ, печатающий значение, сам становится утечкой.
    """
    проба = _проба()
    причины: list[str] = []
    место = 0
    for номер, строка in enumerate(текст.split("\n"), 1):
        # Хвост нужен только приватному ключу: заголовок стоит на этой строке,
        # а тело — на следующих.
        хвост = текст[место:] if проба._PEM_HEADER.search(строка) else None
        место += len(строка) + 1
        for почему, _значение in проба._secrets_in_text(строка, tail=хвост):
            причины.append(f"строка {номер}: {почему}")
    return причины


def _отказ_непроверенное(список: list[dict]) -> str:
    """Почему копия не снята и что именно осталось непроверенным."""
    строки = "\n".join(f"  · {э['file']}: {э['why']}" for э in список)
    return ("ОТКАЗ: копия настроек не снята — эти файлы не разбираются:\n"
            f"{строки}\n"
            "Что в них лежит, я НЕ ПРОВЕРИЛ: неудача разбора ничего не "
            "говорит о содержимом, и там могут быть незакрытые значения, в том "
            "числе ключи. Сырую копию не делаю — она унесла бы их как есть. "
            "Ничего не менял: почини эти файлы или убери их в сторону и "
            "позови снова.")


def _отказ_остатки(name: str, причины: list[str]) -> str:
    """Копия, в которой осталось незакрытое значение, не сохраняется."""
    return (f"ОТКАЗ: копия {name} не сохранена — в ней остались бы незакрытые "
            f"значения ({'; '.join(причины[:3])}). Сами значения не печатаю. "
            f"Ничего не менял: убери их из настроек или закрой ссылкой на "
            f"переменную окружения и позови снова.")
