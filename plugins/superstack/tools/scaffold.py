#!/usr/bin/env python3
"""SUPERSTACK — папка проекта рождается настроенной, а не настраивается потом.

Зачем это нужно именно неразработчику.

Человек без опыта не знает, что у проекта бывает конституция, что у неё есть
потолок, что у готовности бывает черта, и что «проверить» — это команда, а не
взгляд. Он и не должен этого знать. Он должен получить папку, в которой всё
это уже стоит, выведенное из того, что он САМ рассказал в интервью и спеке.

Поэтому генератор — компилятор, а не мастер на все руки:

  вход:  .superstack/spec.md (обязательно) + .superstack/interview.json
  выход: CLAUDE.md · SPEC_TEMPLATE.md · .superstack/bar.json · .claude/rules/

Четыре правила, ради которых всё написано:

  1. НИЧЕГО НЕ ВЫДУМЫВАЕТ. Каждая строка выведена из спеки или интервью. Нет
     спеки — отказ, а не правдоподобный текст. Правдоподобный текст здесь
     хуже пустоты: человек примет его за своё решение и не заметит подмены.
  2. НЕ ПЕРЕЗАПИСЫВАЕТ ЧУЖОЕ. Существующий файл трогается только по явному
     `--force`. Работа человека дороже удобства генератора.
  3. КОНСТИТУЦИЯ ПОМЕЩАЕТСЯ В ПОТОЛОК. Тот же, который проверяет правило
     `cc.constitution-over-ceiling`. Генератор, порождающий находку, —
     это инструмент, спорящий сам с собой.
  4. У ПРОЕКТА СРАЗУ ЕСТЬ ЧЕРТА ГОТОВНОСТИ. `.superstack/bar.json` кладётся
     вместе с остальным: продукт без планки нечем объявить готовым.

  python3 scaffold.py <корень проекта> [--force] [--json]

  код 0 — сгенерировано, 1 — есть занятые файлы (нужен --force),
  2 — генерировать не из чего, 3 — ошибка вызова
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

СПЕКА = ".superstack/spec.md"
ИНТЕРВЬЮ = ".superstack/interview.json"

#: Тот же потолок, который проверяет правило конституции. Число живёт в одном
#: месте: два числа на один порог однажды разойдутся, и разойдутся молча.
ПОТОЛОК = 200

#: Разделы спеки SUPERSTACK. Не восемь и не семнадцать — три, и каждый обязан
#: быть непустым; это проверяет spec_lint.py, здесь они только читаются.
РАЗДЕЛЫ = ("Что должно получиться", "Как проверить", "Чего НЕ делаем")


def _из_спеки(текст: str) -> dict:
    """Разделы спеки по заголовкам. Чего нет — того нет, и это не заполняется.

    Генератор, дописывающий недостающий раздел «разумным» текстом, создаёт
    решение, которого человек не принимал, и подписывает его его именем.
    """
    найдено: dict = {}
    текущий = None
    for строка in текст.splitlines():
        m = re.match(r"^#{1,4}\s+(.+?)\s*$", строка)
        if m:
            имя = m.group(1).strip()
            текущий = next((р for р in РАЗДЕЛЫ if р.lower() in имя.lower()), None)
            if текущий:
                найдено[текущий] = []
            continue
        if текущий:
            найдено[текущий].append(строка)
    return {к: "\n".join(v).strip() for к, v in найдено.items() if "\n".join(v).strip()}


def _улаженное(root: Path) -> list:
    """Что человек уже решил в интервью — только улаженные узлы."""
    p = root / ИНТЕРВЬЮ
    if not p.is_file():
        return []
    try:
        d = json.loads(p.read_text("utf-8"))
    except (OSError, ValueError):
        return []
    return [(у.get("question") or у["id"], у.get("answer", ""))
            for у in (d.get("nodes") or []) if (у.get("answer") or "").strip()]


def _занято(root: Path, файлы: dict) -> list:
    """Какие целевые файлы уже существуют. Молча их трогать нельзя."""
    return [имя for имя in файлы if (root / имя).exists()]


def constitution(разделы: dict, решения: list, имя: str) -> str:
    строки = [f"# {имя}", "",
              "Этот файл читает каждая сессия целиком. Здесь только то, что",
              "верно ВСЕГДА; редкое живёт в скиллах и правилах.", "",
              "## Что строим", "", разделы["Что должно получиться"].strip(), ""]
    строки += ["## Как проверить, что работает", "",
               разделы["Как проверить"].strip(), ""]
    if разделы.get("Чего НЕ делаем"):
        строки += ["## Границы", "", разделы["Чего НЕ делаем"].strip(), ""]
    if решения:
        строки += ["## Решено с человеком", ""]
        строки += [f"- **{в}** — {о}" for в, о in решения[:20]]
        строки += [""]
    строки += ["## Правила работы", "",
               "- Готово — это код возврата, а не «должно работать».",
               "- Не трогаем то, о чём не договаривались: см. «Границы».",
               "- Секрет в коде — стоп, а не «поправим позже».", ""]
    return "\n".join(строки)


def spec_template() -> str:
    return "\n".join([
        "# Спецификация: [название]", "",
        "## Что должно получиться", "",
        "[Что человек сможет делать, чего не мог. Без слова «система».]", "",
        "## Как проверить", "",
        "[Команда или действие с ожидаемым результатом. «Работает» — не проверка.]",
        "", "## Чего НЕ делаем", "",
        "[Что сознательно осталось за границей этой работы и почему.]", ""])


def bar(разделы: dict) -> dict:
    return {
        "schema": "superstack.bar.v1",
        "why": ("Черта готовности этого проекта. Заведена генератором из спеки: "
                "«" + разделы["Как проверить"].strip().splitlines()[0][:120] + "»"),
        "gates": [
            {"name": "верификация", "why": "зелено ли сейчас", "builtin": "verify"},
            {"name": "мутации", "why": "держатся ли тесты при внесённой поломке",
             "builtin": "mutations"},
            {"name": "осмотр", "why": "можно ли доверять зелёному", "builtin": "doctor"},
        ],
    }


def generate(root: Path, разделы: dict, решения: list) -> dict:
    """Что и куда будет положено. Имя проекта берётся у каталога, не выдумывается."""
    имя = root.name
    return {
        "CLAUDE.md": constitution(разделы, решения, имя),
        "SPEC_TEMPLATE.md": spec_template(),
        ".superstack/bar.json": json.dumps(bar(разделы), ensure_ascii=False,
                                           indent=1) + "\n",
    }


def run(root: Path, force: bool) -> dict:
    p = root / СПЕКА
    if not p.is_file():
        return {"status": "unknown",
                "detail": f"генерировать не из чего: нет {СПЕКА}",
                "next": "сначала спека — конфигурация выводится из неё, а не наоборот"}
    разделы = _из_спеки(p.read_text("utf-8", errors="replace"))
    нет = [р for р in РАЗДЕЛЫ[:2] if р not in разделы]
    if нет:
        return {"status": "unknown",
                "detail": "в спеке нет разделов: " + ", ".join(нет),
                "next": "дописать их; выдумывать за человека генератор не будет"}

    файлы = generate(root, разделы, _улаженное(root))
    занято = _занято(root, файлы)
    if занято and not force:
        return {"status": "fail", "occupied": занято,
                "detail": f"файлы уже есть: {', '.join(занято)}",
                "next": "перезапись только с --force: работа человека дороже "
                        "удобства генератора"}

    строк = len(файлы["CLAUDE.md"].splitlines())
    if строк > ПОТОЛОК:
        # Генератор, порождающий находку, спорит сам с собой.
        return {"status": "fail", "lines": строк,
                "detail": f"конституция вышла {строк} строк при потолке {ПОТОЛОК}",
                "next": "сократить спеку либо вынести подробности в скиллы"}

    for имя, тело in файлы.items():
        цель = root / имя
        цель.parent.mkdir(parents=True, exist_ok=True)
        цель.write_text(тело, encoding="utf-8")
    return {"status": "pass", "written": sorted(файлы), "lines": строк,
            "detail": f"положено файлов: {len(файлы)}, конституция {строк} строк"}


def halt_if_paused() -> None:
    if os.environ.get("SUPERSTACK_IGNORE_PAUSE") == "1":
        return
    if (Path.home() / ".claude" / "superstack" / "PAUSE").exists():
        print("ОСТАНОВЛЕНО: система на паузе", file=sys.stderr)
        raise SystemExit(10)


def main() -> int:
    halt_if_paused()
    argv = sys.argv[1:]
    plain = [a for a in argv if not a.startswith("--")]
    if len(plain) != 1:
        print("вызов: scaffold.py <корень проекта> [--force]", file=sys.stderr)
        return 3
    root = Path(plain[0]).resolve()
    if not root.is_dir():
        print(f"НЕ УДАЛОСЬ: нет каталога {root}", file=sys.stderr)
        return 3
    v = run(root, "--force" in argv)
    if "--json" not in argv:
        голова = {"pass": "ПАПКА НАСТРОЕНА", "fail": "НЕ ПОЛОЖИЛ",
                  "unknown": "ГЕНЕРИРОВАТЬ НЕ ИЗ ЧЕГО"}
        print(f"{голова[v['status']]}: {v['detail']}", file=sys.stderr)
        for имя in v.get("written", []):
            print(f"  + {имя}", file=sys.stderr)
        if v.get("next"):
            print(f"  дальше: {v['next']}", file=sys.stderr)
    print(json.dumps(v, ensure_ascii=False, indent=1))
    return {"pass": 0, "fail": 1, "unknown": 2}[v["status"]]


if __name__ == "__main__":
    sys.exit(main())
