#!/usr/bin/env python3
"""SUPERSTACK — критерий приёмки обязан иметь АДРЕС.

Что было. `handoff.py` проверял у критериев ровно одно: что список непуст.
Поэтому «работает корректно» проходило передачу и уезжало исполнителю. Дальше
он сам решал, где смотреть и что считать выполненным, — то есть критерий
приёмки, придуманный ради того, чтобы это решал не он, возвращал решение ему.

Три вещи, без которых критерий не работает, и почему именно они:

  · ГДЕ СМОТРЕТЬ. Критерий без адреса проверяется там, где удобно проверяющему.
    Двое проверят в разных местах и оба будут правы.
  · ЧТО ВЫСОКО И ЧТО НИЗКО. Без нижней границы «почти работает» засчитывается:
    отличить «сделано» от «похоже на сделано» нечем.
  · ЧТО МИМО. Без этого критерии перетекают друг в друга: один и тот же изъян
    роняет три из них, а четвёртый не проверяет никто.

ЧЕГО ЭТОТ ИНСТРУМЕНТ НЕ ДЕЛАЕТ — и это печатается всегда, даже на зелёном.
Он проверяет ФОРМУ, а не правоту: что адрес назван, а не что он верный; что
граница проведена, а не что она в нужном месте. Критерий может быть безупречно
оформлен и проверять не то. Зелёный здесь значит «критерий можно проверить»,
а не «критерий правильный».

Старая форма — строка — принимается и называется безадресной. Проект,
объявивший `"criteria": "строгие"`, дальше с такими не работает; проект без
этого ключа продолжает жить как жил.

  python3 criteria.py <состояние.json> <id>            разбор критериев
  python3 criteria.py <состояние.json> <id> --check    гейт
  python3 criteria.py <состояние.json> <id> --json     машинный вывод
        [--root <каталог проекта>]  где искать пути из «где» (по умолчанию .)

  коды: 0 — у всех есть адрес, 1 — названы безадресные, 2 — критериев нет,
        3 — ошибка вызова
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

#: Поля критерия. «мимо» не обязательно само по себе — оно становится
#: обязательным только там, где два критерия смотрят в одно место: пока адреса
#: разные, разграничивать нечего.
ОБЯЗАТЕЛЬНЫЕ = ("что", "где", "высоко", "низко")
РАЗГРАНИЧЕНИЕ = "мимо"

#: Не адреса, а отговорки. Список ЗАКРЫТЫЙ и коротким остаётся намеренно:
#: порог по длине этих слов не ловит — «в коде» и «app.py» одной длины, — а
#: угадывание «достаточно ли конкретно» валило бы верное. Правило, которое
#: можно прочитать и оспорить, лучше догадки, которую нельзя.
НЕ_АДРЕС = {"в коде", "в тесте", "в тестах", "в проекте", "в приложении",
            "везде", "внутри", "где надо", "по коду", "в системе"}

ЧЕГО_НЕ_ПРОВЕРЯЕМ = (
    "верен ли адрес — только что он назван и, если это путь, что файл есть",
    "в том ли месте проведена граница «высоко/низко» — только что она есть",
    "проверяет ли критерий то, ради чего таск заведён",
    "конкретен ли адрес: названный, но неудачный адрес проезжает",
)

#: Путь узнаётся по форме, а не по существованию: иначе несуществующий файл
#: молча считался бы «не путём» и проезжал бы проверку, ради которой она есть.
_УЗЕЛ = re.compile(r"^(?P<путь>[^\s:]+?)(?:::[^\s]+)?$")
_РАСШИРЕНИЕ = re.compile(r"\.[A-Za-z0-9]{1,6}$")


def похоже_на_путь(где: str) -> "str | None":
    """Адрес, который можно проверить на диске. Не путь — None, а не отказ.

    Команда (`npm test`), эндпоинт и имя экрана — законные адреса, просто
    непроверяемые здесь. Требовать от них существования файла значило бы
    валить верное.
    """
    m = _УЗЕЛ.match(где.strip())
    if not m:
        return None
    путь = m.group("путь")
    if "/" not in путь and not _РАСШИРЕНИЕ.search(путь):
        return None
    return путь


def разобрать(критерий, корень: Path) -> dict:
    """Один критерий: что с ним не так. Пустой список причин — всё на месте."""
    if isinstance(критерий, str):
        return {"вид": "строка", "текст": критерий.strip(),
                "где": "", "причины": [
                    "критерий-строка: адрес не назван, границы нет — "
                    "проверяющий выберет и то и другое сам"]}
    if not isinstance(критерий, dict):
        return {"вид": "мусор", "текст": str(критерий)[:80], "где": "",
                "причины": ["критерий не строка и не объект"]}

    причины = []
    for поле in ОБЯЗАТЕЛЬНЫЕ:
        значение = критерий.get(поле)
        if not (isinstance(значение, str) and значение.strip()):
            причины.append(f"нет поля «{поле}»")
    где = str(критерий.get("где") or "").strip()
    if где.lower().rstrip(".") in НЕ_АДРЕС:
        причины.append(f"«{где}» — не адрес, а отговорка: по нему двое "
                       "проверят в разных местах и оба будут правы")
    путь = похоже_на_путь(где) if где else None
    if путь and not (корень / путь).exists():
        причины.append(f"путь из «где» не существует: {путь}")
    return {"вид": "объект", "текст": str(критерий.get("что") or "")[:120],
            "где": где, "причины": причины}


def проверить(таск: dict, корень: Path) -> dict:
    критерии = таск.get("acceptance") or []
    if not критерии:
        return {"код": 2, "разбор": [], "отказы": [],
                "почему": "у таска нет ни одного критерия приёмки — "
                          "проверять нечего, и это не «прошло»"}

    разбор = [разобрать(к, корень) for к in критерии]

    # Два критерия в одно место без разграничения — это один критерий,
    # записанный дважды: изъян уронит оба, а то, что должен был проверять
    # второй, не проверит никто.
    адреса = {}
    for i, (к, р) in enumerate(zip(критерии, разбор)):
        if not р["где"]:
            continue
        адреса.setdefault(р["где"], []).append((i, к))
    for где, группа in адреса.items():
        if len(группа) < 2:
            continue
        без_границы = [i for i, к in группа
                       if not (isinstance(к, dict)
                               and str(к.get(РАЗГРАНИЧЕНИЕ) or "").strip())]
        for i in без_границы:
            разбор[i]["причины"].append(
                f"тот же адрес, что и у соседнего критерия ({где}), "
                f"и не сказано «{РАЗГРАНИЧЕНИЕ}» — они перетекают друг в друга")

    отказы = []
    for i, р in enumerate(разбор, 1):
        for причина in р["причины"]:
            отказы.append(f"критерий {i}: {причина}")
    return {"код": 1 if отказы else 0, "разбор": разбор, "отказы": отказы,
            "почему": ""}


def строгие(состояние: dict) -> bool:
    """Проект объявил строгие критерии? Умолчание — нет.

    Молчаливое ужесточение сломало бы проекты, начатые до этой проверки, на
    середине волны — и человек увидел бы отказ там, где вчера всё шло.
    """
    return str(состояние.get("criteria") or "").strip() == "строгие"


def _таск(состояние: dict, tid: str) -> "dict | None":
    for волна in (состояние.get("waves") or {}).values():
        for t in волна:
            if str(t.get("id")) == str(tid):
                return t
    return None


def _печать(итог: dict, tid: str) -> None:
    if итог["код"] == 2:
        print(f"ПРОВЕРЯТЬ НЕЧЕГО: {итог['почему']}", file=sys.stderr)
        return
    print(f"таск {tid}: критериев {len(итог['разбор'])}")
    for i, р in enumerate(итог["разбор"], 1):
        адрес = р["где"] or "адреса нет"
        print(f"  {i}. [{адрес}] {р['текст'][:70]}")
    print("  НЕ ПРОВЕРЕНО здесь:")
    for x in ЧЕГО_НЕ_ПРОВЕРЯЕМ:
        print(f"    · {x}")
    for о in итог["отказы"]:
        print(f"ОТКАЗ: {о}", file=sys.stderr)


def main(argv: list) -> int:
    простые = [a for a in argv if not a.startswith("--")]
    флаги = {"--check", "--json"}
    # `--root` забирает следующий аргумент, поэтому убираем его из простых.
    if "--root" in argv:
        i = argv.index("--root")
        if i + 1 >= len(argv):
            print("--root без каталога", file=sys.stderr)
            return 3
        корень = Path(argv[i + 1])
        простые = [a for a in простые if a != argv[i + 1]]
    else:
        корень = Path(".")
    if len(простые) != 2:
        print("вызов: criteria.py <состояние.json> <id> [--check] [--json] "
              "[--root <каталог>]", file=sys.stderr)
        return 3
    неизвестные = [a for a in argv
                   if a.startswith("--") and a not in флаги and a != "--root"]
    if неизвестные:
        print(f"неизвестные флаги: {', '.join(неизвестные)}", file=sys.stderr)
        return 3

    try:
        состояние = json.loads(Path(простые[0]).read_text("utf-8"))
    except (OSError, ValueError) as e:
        print(f"НЕ УДАЛОСЬ: состояние не прочитано: {e}", file=sys.stderr)
        return 3
    таск = _таск(состояние, простые[1])
    if таск is None:
        print(f"НЕ УДАЛОСЬ: нет таска {простые[1]}", file=sys.stderr)
        return 3

    итог = проверить(таск, корень)
    if "--json" in argv:
        print(json.dumps(итог, ensure_ascii=False, indent=1))
    else:
        _печать(итог, простые[1])
    return итог["код"] if "--check" in argv else (2 if итог["код"] == 2 else 0)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
