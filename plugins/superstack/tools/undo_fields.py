#!/usr/bin/env python3
"""SUPERSTACK — откат формата `superstack.undo.v2`: единица возврата — ПОЛЕ.

Отдельный файл, потому что это отдельный контракт. Раньше откат возвращал
файл целиком и вместе со своей правкой стирал всё, что человек успел изменить
после применения: тема, которую он переставил, и поля, которые он добавил,
исчезали молча, а код возврата при этом был нулевой. Инструмент отменял не
своё.

Отсюда всё устройство: путь поля разбирается и проверяется, текущее значение
сравнивается с тем, которое мы оставили, и только совпавшее возвращается.
Разошлось — это чужая правка: она остаётся, а человеку называют поле и то,
что здесь оставлял инструмент. Своя же запись, сделанная вчера, — ВНЕШНИЕ
данные: между записью и чтением она лежала на диске.

Чего этот модуль НЕ знает и знать не должен: где лежит профиль человека и
каким движением в него пишут. И то и другое приходит параметрами от
`apply.py` — единственного места, которое ПИШЕТ в конфигурацию. Так формат
журнала можно прогнать на любом дереве, а писатель настроек остаётся один.

Прежний формат (копия без метки) тоже живёт здесь — `_undo_legacy`. Он рядом
намеренно: контраст «файлом целиком» против «полем» и есть то, ради чего
формат менялся.
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

# Замок — общий для всех, кто пишет одни и те же файлы (tools/atomic_store.py).
# Каталог скрипта при импорте из теста в sys.path не попадает, поэтому
# добавляется явно — как у соседей.
sys.path.insert(0, str(Path(__file__).resolve().parent))
import atomic_store  # noqa: E402
from settings_copy import REDACTION_MARK, WRITABLE  # noqa: E402,F401


class UnsafeName(Exception):
    """Имя из записи отката, которому нельзя верить."""


def _звенья(поле) -> list:
    """Путь поля из записи отката — тоже внешние данные, и тоже проверяется."""
    if not isinstance(поле, str) or not поле:
        raise UnsafeName(f"путь поля «{поле}» не читается")
    куски = поле.split(".")
    if any(not к for к in куски):
        raise UnsafeName(f"путь поля «{поле}» пуст в одном из звеньев")
    return куски


def _взять(документ, куски: list) -> tuple:
    """(есть ли такое поле, что в нём лежит)."""
    узел = документ
    for к in куски:
        if not isinstance(узел, dict) or к not in узел:
            return False, None
        узел = узел[к]
    return True, узел


def _положить(документ: dict, куски: list, значение) -> None:
    узел = документ
    for к in куски[:-1]:
        след = узел.get(к)
        if not isinstance(след, dict):
            след = {}
            узел[к] = след
        узел = след
    узел[куски[-1]] = значение


def _убрать(документ: dict, куски: list, свои: list) -> None:
    """Снять поле и те контейнеры, которые инструмент сам же и завёл.

    Пустой словарь, оставшийся после снятия поля, — след инструмента, но
    только если этот словарь он и создал. Чужой пустой словарь остаётся: он
    был до нас, и убрать его значило бы снова отменить не своё.
    """
    цепочка = [документ]
    for к in куски[:-1]:
        след = цепочка[-1].get(к)
        if not isinstance(след, dict):
            return
        цепочка.append(след)
    цепочка[-1].pop(куски[-1], None)
    for i in range(len(куски) - 2, -1, -1):
        if ".".join(куски[:i + 1]) in свои and not цепочка[i + 1]:
            цепочка[i].pop(куски[i], None)


def _секрет_вырезан(значение) -> bool:
    """Есть ли в значении след вырезанного секрета — на любой глубине.

    То же правило, что защищало файл целиком, теперь держится за ОДНО поле:
    вернуть метку на место живого значения — это потеря данных под видом
    отката. Соседние поля того же файла при этом возвращаются как обычно.
    """
    if isinstance(значение, str):
        return REDACTION_MARK in значение
    if isinstance(значение, dict):
        return any(_секрет_вырезан(v) for v in значение.values())
    if isinstance(значение, list):
        return any(_секрет_вырезан(v) for v in значение)
    return False


def _коротко(значение) -> str:
    """Значение инструмента — коротко.

    Печатается только СВОЁ значение. Живое значение человека здесь не
    показывается никогда: отказ обязан назвать поле, а не вынести на экран
    то, что в нём лежит, — иначе отказ сам станет утечкой.
    """
    текст = json.dumps(значение, ensure_ascii=False)
    return текст if len(текст) <= 60 else текст[:57] + "…"


def _restore_one_field(документ: dict, запись: dict) -> dict:
    """Вернуть ОДНО поле — и только если в нём всё ещё лежит записанное нами.

    Прежде откат возвращал файл целиком и вместе со своей правкой стирал
    всё, что человек успел изменить после применения: тема, которую он
    переставил, и поля, которые он добавил, исчезали молча, а код возврата
    при этом был нулевой. Инструмент отменял не своё.

    Отсюда сравнение вместо записи поверх: текущее значение обязано совпасть
    с тем, которое мы оставили. Разошлось — это чужая правка; она остаётся,
    а человеку называют поле и то, что здесь оставлял инструмент.
    """
    куски = _звенья(запись.get("field"))
    вернём = запись.get("before")
    if _секрет_вырезан(вернём):
        return {"ok": False, "что": запись.get("field"),
                "почему": "в копии на месте этого поля вырезан секрет — "
                          "возврат затёр бы живое значение меткой"}
    есть, текущее = _взять(документ, куски)
    ожидалось = запись.get("after")
    if not есть or текущее != ожидалось:
        return {"ok": False, "что": запись.get("field"),
                "почему": "изменено после применения (я оставлял "
                          f"{_коротко(ожидалось)}) — чужое значение не трогаю"}
    if запись.get("before_present"):
        _положить(документ, куски, вернём)
    else:
        _убрать(документ, куски, запись.get("created_parents") or [])
    return {"ok": True, "что": запись.get("field")}


def _drop_created_file(путь: Path, документ) -> dict:
    """Убрать файл, которого до применения не было, — если в нём нет чужого.

    Создание файла тоже было невозвратным: возвращалось только то, что лежит
    в копии, а копии у несуществовавшего файла нет. Инструмент создавал файл
    настроек, откат отвечал «не вернул ничего», файл оставался.

    Пустым файл становится ровно после того, как поля инструмента сняты выше.
    Осталось хоть что-то — это чужое, и оно важнее пустоты: файл остаётся, а
    человеку говорится, что именно в нём осталось.
    """
    осталось = (sorted(str(k) for k in документ)
                if isinstance(документ, dict) else ["непонятное содержимое"])
    if осталось:
        return {"ok": False, "что": путь.name,
                "почему": "файла до применения не было, но в нём появилось "
                          f"чужое ({', '.join(осталось[:5])}) — оставляю как есть"}
    путь.unlink()
    return {"ok": True, "что": f"{путь.name} (файла до применения не было — убрал)"}


def _undo_journal(manifest: dict, цель, записать) -> tuple:
    """Откат по журналу полей: возвращаем СВОЁ, чужое оставляем на месте.

    Единица отката здесь — поле, а не файл. Поэтому один и тот же откат может
    вернуть часть и отказаться от части, и обе половины называются вслух.

    Каталог копии сюда не передаётся, и это не упущение: возвращаемое берётся
    из журнала, а не из копии файла. Копия остаётся тем, чем была, — тем, что
    человек может прочитать глазами, когда откат от чего-то отказался.

    `цель` (имя -> файл, который откату разрешено трогать) и `записать`
    (файл, документ) приходят снаружи по той же причине: профиль человека
    знает `apply.py`, и он же — единственный, кто в конфигурацию ПИШЕТ. Две
    копии этого знания разъехались бы молча, а разъехались бы ровно там, где
    цена расхождения — правка не в том профиле.
    """
    записи: dict = {}
    for a in manifest.get("applied") or []:
        if isinstance(a, dict) and a.get("changed"):
            записи.setdefault(a.get("file") or WRITABLE[0], []).append(a)
    состояние = manifest["backup"].get("before") or {}
    вернули, отказы = [], []

    for имя in sorted(set(записи) | set(состояние)):
        try:
            путь = цель(имя)
        except UnsafeName as e:
            отказы.append({"что": имя, "почему": str(e)})
            continue
        # Замок на весь цикл «прочитал, изменил, записал»: откат читает
        # файл настроек и пишет его целиком, и параллельный Stop-хук между
        # этими двумя движениями вернул бы в файл то, что откат только что
        # убрал, — молча и с нулём у обоих.
        with atomic_store.Lock(путь):
            мои = записи.get(имя, [])
            было_ли = (состояние.get(имя) or {}).get("before_exists", True)
            if not путь.is_file():
                for a in мои:
                    отказы.append({"что": a.get("field"),
                                   "почему": f"файла {имя} больше нет — "
                                             "возвращать поле некуда"})
                continue
            try:
                документ = json.loads(путь.read_text(encoding="utf-8-sig"))
            except (OSError, ValueError) as e:
                for a in мои:
                    отказы.append({"что": a.get("field"),
                                   "почему": f"{имя} сейчас не разбирается ({e}) — "
                                             "вслепую его не трогаю"})
                continue
            if not isinstance(документ, dict):
                for a in мои:
                    отказы.append({"что": a.get("field"),
                                   "почему": f"в {имя} лежит не набор полей, а "
                                             f"{type(документ).__name__}"})
                continue

            менялось = False
            for a in reversed(мои):
                try:
                    итог = _restore_one_field(документ, a)
                except UnsafeName as e:
                    итог = {"ok": False, "что": a.get("field"), "почему": str(e)}
                if итог["ok"]:
                    вернули.append(f"{имя}: {итог['что']}")
                    менялось = True
                else:
                    отказы.append(итог)
            if мои and not было_ли:
                итог = _drop_created_file(путь, документ)
                if итог["ok"]:
                    вернули.append(итог["что"])
                    continue
                отказы.append(итог)
            if менялось:
                записать(путь, документ)
    return вернули, отказы


def _undo_legacy(bdir: Path, manifest: dict, цель) -> tuple:
    """Откат копии, снятой ПРЕЖНЕЙ версией: файл целиком, полей в ней нет.

    Старая копия не знает ни одного поля — вернуть «только своё» из неё
    физически нечем, а притвориться, что можно, значило бы молча её испортить.
    Поэтому здесь остаётся прежнее поведение вместе с прежним запретом: файл,
    в копии которого вырезаны секреты, не возвращается. Добавлена ровно одна
    вещь — проверка имени, которое и раньше было внешними данными; сама
    проверка приходит параметром `цель` (см. `_undo_journal`).
    """
    вернули, отказы = [], []
    for name in manifest["backup"]["files"]:
        try:
            dst = цель(name)
        except UnsafeName as e:
            отказы.append({"что": name, "почему": str(e)})
            continue
        src = bdir / name
        text = src.read_text(encoding="utf-8")
        if REDACTION_MARK in text:
            # Возврат такого файла затёр бы живой секрет меткой. Это потеря
            # данных под видом отката — поэтому файл не трогаем и говорим об этом.
            отказы.append({"что": name,
                           "почему": "в копии вырезаны секреты — возврат затёр "
                                     "бы живое значение меткой"})
            continue
        shutil.copy2(src, dst)
        вернули.append(name)
    return вернули, отказы


def _формат_копии(manifest) -> "str | None":
    """Каким форматом записана копия. Неизвестный — повод отказаться, а не гадать.

    Копия прежней версии метки не имеет вовсе: это `None`, и откатывается она
    прежним способом. Метка, которой этот инструмент не знает, означает копию
    из будущего — разобрать её по догадке значит молча её испортить, а
    молчаливая порча копии здесь хуже честного отказа.
    """
    if isinstance(manifest, dict) and isinstance(manifest.get("backup"), dict):
        return manifest["backup"].get("format")
    return None
