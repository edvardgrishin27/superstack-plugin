#!/usr/bin/env python3
"""SUPERSTACK — документ идеи: то, что человек рассказывает ДО спеки.

Зачем отдельный документ, если есть спека.

Спека отвечает «что построить и как проверить». Она не отвечает на вопрос, из
которого всё растёт: **зачем и кому**. Без него первая же развилка решается
вкусом исполнителя, а человек узнаёт об этом на сдаче — когда построено не то,
хотя построено по спеке.

Пять разделов, и это не десять. Каждый лишний раздел неразработчик заполняет
шумом, потому что не знает, что туда писать; проверить шум нельзя, а выглядит
он как заполненный документ.

  1. БОЛЬ — с числом. «Людям неудобно» болью не является: по ней нельзя
     понять, стало ли лучше. «Записываю клиентов в блокнот и трачу час в день»
     — является.
  2. КТО — конкретный человек и как он справляется сегодня.
  3. ЧТО ИЗМЕНИТСЯ — первое действие, ради которого всё строится.
  4. ЧЕМ МЕРЯЕМ — как узнаем, что стало лучше. Тоже числом.
  5. ГРАНИЦЫ — чего в этой версии не делаем.

Три правила, ради которых это код, а не чеклист:

  1. ГАЛОЧКУ СТАВИТ НЕ ЧЕЛОВЕК. Чеклист, который отмечает тот, кого проверяют,
     не проверка. Здесь разделы ищутся заголовками, а не упоминанием в прозе.
  2. РАЗДЕЛ БЕЗ ЧИСЛА ТАМ, ГДЕ ЧИСЛО ОБЯЗАНО БЫТЬ, — ПУСТОЙ. Боль и мера без
     цифры — это ощущение, а ощущение нельзя ни проверить, ни опровергнуть.
  3. ПУСТОЙ ДОКУМЕНТ — НЕ «ИДЕЯ ПРОСТАЯ». Отсутствие файла даёт код 2, а не
     разрешение строить.

  python3 idea_lint.py <корень проекта> [--json]
  python3 idea_lint.py --template          напечатать пустой документ

  код 0 — документ годен, 1 — есть провалы, 2 — документа нет,
  3 — ошибка вызова
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

ФАЙЛ = ".superstack/idea.md"

#: (ключ, заголовок, зачем, нужно ли число)
РАЗДЕЛЫ = (
    ("боль", "Боль", "без числа нельзя понять, стало ли лучше", True),
    ("кто", "Кто", "безымянный пользователь — это никто, и решать за него будет вкус", False),
    ("изменится", "Что изменится", "первое действие, ради которого всё строится", False),
    ("мера", "Чем меряем", "«стало удобнее» проверить нельзя", True),
    ("границы", "Границы", "без границы объём растёт молча", False),
)

ЗАГОЛОВОК = re.compile(r"^\s{0,3}#{1,6}\s+(.+?)\s*$")
ЧИСЛО = re.compile(r"\d")

#: Формулировки, которые выглядят ответом и им не являются.
ПУСТЫЕ = ("удобнее", "лучше", "быстрее", "современно", "красиво", "оптимизировать",
          "улучшить процесс", "автоматизировать всё", "как у всех")


def sections(текст: str) -> dict:
    """Разделы по ЗАГОЛОВКАМ, а не по упоминанию в прозе.

    Иначе фраза «боль тут очевидна» посреди абзаца засчиталась бы за раздел, и
    линт превратился бы в поиск подстроки, то есть ни во что.
    """
    найдено: dict = {}
    текущий = None
    for строка in текст.splitlines():
        m = ЗАГОЛОВОК.match(строка)
        if m:
            имя = m.group(1).strip().lower()
            текущий = next((к for к, т, _, _ in РАЗДЕЛЫ if т.lower() in имя), None)
            if текущий:
                найдено[текущий] = []
            continue
        if текущий:
            найдено[текущий].append(строка)
    return {к: "\n".join(v).strip() for к, v in найдено.items()}


def problems(разделы: dict) -> list:
    """Что не так с документом. Каждая находка называет раздел и причину."""
    беды = []
    for ключ, титул, зачем, нужно_число in РАЗДЕЛЫ:
        тело = разделы.get(ключ, "")
        if not тело:
            беды.append({"section": титул, "why": f"раздела нет — {зачем}"})
            continue
        if нужно_число and not ЧИСЛО.search(тело):
            беды.append({"section": титул,
                         "why": f"нет ни одного числа — {зачем}"})
        пустые = [п for п in ПУСТЫЕ if п in тело.lower()]
        if пустые and len(тело) < 200:
            беды.append({"section": титул,
                         "why": "держится на словах, которые нельзя проверить: "
                                + ", ".join(пустые[:3])})
    return беды


def template() -> str:
    строки = ["# Идея", ""]
    подсказки = {
        "боль": "Что не так СЕЙЧАС, с числом. Не «неудобно», а «час в день на то,\nчто должно занимать пять минут».",
        "кто": "Конкретный человек и как он справляется сегодня.",
        "изменится": "Первое действие, ради которого всё строится. Одно.",
        "мера": "Как узнаем, что стало лучше. Тоже числом.",
        "границы": "Чего в этой версии НЕ делаем и почему.",
    }
    for ключ, титул, _, _ in РАЗДЕЛЫ:
        строки += [f"## {титул}", "", подсказки[ключ], ""]
    return "\n".join(строки)


def run(root: Path) -> dict:
    p = root / ФАЙЛ
    if not p.is_file():
        return {"status": "unknown",
                "detail": f"документа идеи нет: {ФАЙЛ}",
                "next": "начать с него: спека отвечает «что построить», а он — "
                        "«зачем и кому»; без второго первая развилка решается вкусом"}
    разделы = sections(p.read_text("utf-8", errors="replace"))
    беды = problems(разделы)
    if беды:
        return {"status": "fail", "problems": беды,
                "detail": f"провалов: {len(беды)} из {len(РАЗДЕЛЫ)} разделов",
                "next": "дописать названное; галочку здесь ставит не человек"}
    return {"status": "pass", "sections": sorted(разделы),
            "detail": f"документ идеи годен: разделов {len(разделы)}"}


def halt_if_paused() -> None:
    if os.environ.get("SUPERSTACK_IGNORE_PAUSE") == "1":
        return
    if (Path.home() / ".claude" / "superstack" / "PAUSE").exists():
        print("ОСТАНОВЛЕНО: система на паузе", file=sys.stderr)
        raise SystemExit(10)


def main() -> int:
    halt_if_paused()
    argv = sys.argv[1:]
    if "--template" in argv:
        print(template())
        return 0
    plain = [a for a in argv if not a.startswith("--")]
    if len(plain) != 1:
        print("вызов: idea_lint.py <корень проекта> [--json] | --template",
              file=sys.stderr)
        return 3
    root = Path(plain[0]).resolve()
    if not root.is_dir():
        print(f"НЕ УДАЛОСЬ: нет каталога {root}", file=sys.stderr)
        return 3
    v = run(root)
    if "--json" not in argv:
        голова = {"pass": "ИДЕЯ ОПИСАНА", "fail": "ИДЕЯ ОПИСАНА НЕ ДО КОНЦА",
                  "unknown": "ИДЕИ НЕТ"}
        print(f"{голова[v['status']]}: {v['detail']}", file=sys.stderr)
        for b in v.get("problems", []):
            print(f"  ! {b['section']}: {b['why']}", file=sys.stderr)
        if v.get("next"):
            print(f"  дальше: {v['next']}", file=sys.stderr)
    print(json.dumps(v, ensure_ascii=False, indent=1))
    return {"pass": 0, "fail": 1, "unknown": 2}[v["status"]]


if __name__ == "__main__":
    sys.exit(main())
