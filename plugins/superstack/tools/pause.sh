#!/bin/sh
# SUPERSTACK — тормоз. Работает, даже когда агент не отвечает.
#
# Печатает "ПАУЗА" ТОЛЬКО после того, как убедился, что флаг реально на диске.
# Раньше сообщение шло безусловно: человек в аварийной ситуации читал
# "остановлено", а система продолжала работать.
set -u
F="$HOME/.claude/superstack/PAUSE"
case "${1:-status}" in
  on)
    mkdir -p "$(dirname "$F")" || { echo "НЕ УДАЛОСЬ: нет доступа к $(dirname "$F")" >&2; exit 1; }
    date -u +%Y-%m-%dT%H:%M:%SZ > "$F" || { echo "НЕ УДАЛОСЬ записать флаг $F" >&2; exit 1; }
    [ -s "$F" ] || { echo "НЕ УДАЛОСЬ: флаг пуст после записи" >&2; exit 1; }
    # Путь печатается В КАВЫЧКАХ: он лежит в каталоге с пробелом и кириллицей,
    # и строка без кавычек копируется в неработающую команду ровно тогда, когда
    # человек торопится больше всего.
    echo "ПАУЗА подтверждена. Флаг: $F"; echo "Снять: \"$0\" off" ;;
  off)
    # «Снято» и «нечего было снимать» — разные события. Одинаковый ответ на оба
    # означает, что подтверждение снятия ничего не подтверждает: человек, снявший
    # чужую паузу или промахнувшийся файлом, читает тот же успех.
    # Имя переменной латиницей: оболочка не принимает кириллицу в именах,
    # и первая же попытка дала «command not found» вместо снятия паузы.
    if [ -f "$F" ]; then had=1; else had=0; fi
    rm -f "$F"
    [ -e "$F" ] && { echo "НЕ УДАЛОСЬ снять паузу: $F на месте" >&2; exit 1; }
    if [ "$had" = 1 ]; then echo "пауза снята"; else echo "паузы не было"; fi ;;
  *)
    if [ -f "$F" ]; then echo "НА ПАУЗЕ с $(cat "$F")"; exit 10; else echo "работает"; fi ;;
esac
