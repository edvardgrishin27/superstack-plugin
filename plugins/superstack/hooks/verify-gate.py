#!/usr/bin/env python3
"""SUPERSTACK — гейт верификации: ход не закрывается без доказательства.

Правило, ради которого хук существует: «должно работать» и «тесты должны
проходить» означают, что работа не сделана. Решение принимает КОД ВОЗВРАТА
`verify.py`, а не формулировка в ответе.

Что хук делает и чего не делает:
  · код 1 — блокирует закрытие хода и кладёт в причину улику из stderr;
  · код 2 («проверять нечем»), смерть по сигналу, отсутствие инструмента —
    НЕ блокируют, но обязаны прозвучать человеку ровно один раз за сессию:
    ход закрыт БЕЗ доказательства, и он должен об этом знать;
  · пауза и повторный заход не блокируют никогда.

Блокировка ровно ОДНА на попытку закрытия. Второй одинаковый блок означает,
что починить не вышло, и дальше гейт перестаёт быть проверкой и становится
ловушкой — каждый круг стоит полного прогона тестов.

Почему на Python. `sh` был лишней зависимостью, а вместе с ним уходит самая
хрупкая часть прежнего скрипта — экранирование JSON руками через tr/sed/awk.
Кавычка или табуляция в выводе проверки ломали разбор ВСЕГО объекта, и хук
переставал существовать для Claude Code целиком, молча. Теперь строку собирает
`json.dumps`.

Чего порт НЕ исправляет: сторож по-прежнему не убивает внуков (pytest, npm),
запущенных внутри `verify.py`. У самого `verify.py` на каждую команду свой
предел, поэтому осиротевший прогон конечен.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

БЮДЖЕТ = 120

#: Сколько строк улики уносим в причину и по сколько знаков. Ограничение не
#: косметика: вывод хука урезается на 10000 знаках, и обрезанный хвост унёс бы
#: закрывающую кавычку вместе с валидностью всего ответа.
СТРОК_УЛИКИ = 40
ЗНАКОВ_В_СТРОКЕ = 300


def состояние() -> Path:
    return Path(os.environ.get("SUPERSTACK_STATE_DIR")
                or Path(os.environ.get("HOME", "/nonexistent")) / ".claude" / "superstack")


def проект() -> Path:
    p = (os.environ.get("SUPERSTACK_PROJECT_DIR")
         or os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd())
    try:
        # Симлинки разрешаются ОБЯЗАТЕЛЬНО: `enable.py` пишет отметку уже
        # разрешённой. На macOS `/var` — симлинк на `/private/var`, и одного
        # этого хватает, чтобы строки не совпали: отметка стоит, гейт её не
        # видит, человек остаётся без проверки и не узнаёт об этом.
        return Path(p).resolve()
    except OSError:
        return Path(p)


def позвали_здесь(корень: Path) -> bool:
    """Здесь цена гейта области выше, чем у остальных хуков.

    Гейт верификации МОЖЕТ НЕ ДАТЬ ЗАКРЫТЬ ХОД в чужом проекте, где нет ни
    тестов, ни плана, и человек не понимает, чего от него хотят.
    """
    список = состояние() / "projects"
    if not список.is_file():
        return False
    try:
        строки = список.read_text("utf-8", errors="replace").splitlines()
    except OSError:
        return False
    свой = str(корень).rstrip("/") + "/"
    for строка in строки:
        строка = строка.strip()
        if not строка:
            continue
        if свой.startswith(строка.rstrip("/") + "/"):
            return True
        try:
            реальный = str(Path(строка).resolve()).rstrip("/") + "/"
        except OSError:
            continue
        if свой.startswith(реальный):
            return True
    return False


def сессия(вход: str) -> str:
    m = re.search(r'"session_id"\s*:\s*"([^"]*)"', вход)
    return re.sub(r"[^A-Za-z0-9._-]", "", m.group(1))[:64] if m else ""


def сказать_один_раз(текст: str, вход: str) -> int:
    """«Не смог проверить» обязано прозвучать — но ровно один раз за сессию.

    `systemMessage` выбран намеренно: `additionalContext` на событии Stop
    ПРОДОЛЖАЕТ разговор, то есть был бы той же блокировкой под другим именем.
    Здесь ход закрывается, а предупреждение уходит человеку, не модели.

    Нечем сосчитать — МОЛЧИМ: напоминание, которое некому сосчитать,
    повторяется вечно, и это хуже, чем не сказать ни разу.
    """
    sid = сессия(вход)
    if not sid:
        return 0
    журнал = состояние() / "gate-noted.sessions"
    try:
        если_уже = журнал.read_text("utf-8", errors="replace").splitlines()
    except OSError:
        если_уже = []
    if sid in если_уже:
        return 0
    # Отметка засчитывается, ТОЛЬКО если легла на диск и перечиталась: успешная
    # запись в никуда вернула бы ноль и не сохранила ничего, а предупреждение,
    # которое не удалось отметить, повторяется каждый ход вечно.
    try:
        состояние().mkdir(parents=True, exist_ok=True)
        with журнал.open("a", encoding="utf-8") as f:
            f.write(sid + "\n")
        if sid not in журнал.read_text("utf-8", errors="replace").splitlines():
            return 0
    except OSError:
        return 0
    print(json.dumps({"systemMessage": текст}, ensure_ascii=False))
    return 0


def улика(stderr: str) -> str:
    строки = stderr.splitlines()[:СТРОК_УЛИКИ]
    return "\n".join(s[:ЗНАКОВ_В_СТРОКЕ] for s in строки)


def заблокировать(код: int, stderr: str) -> int:
    причина = [
        f"ГЕЙТ ВЕРИФИКАЦИИ НЕ ПРОЙДЕН: python3 tools/verify.py вернул код {код}.",
        "Ход не закрывается. «Должно работать» и «тесты должны проходить» "
        "означают, что работа не сделана.",
        "Почини причину и прогони проверку заново. Если чинить нечего — скажи "
        "это человеку словами и назови, что именно осталось непроверенным; "
        "молча ход не закрывай.",
        # Выход называется ЗДЕСЬ, а не в документации. Это единственное место,
        # где человек читает текст в тот момент, когда система его не
        # отпускает, — и это фраза, а не команда: тот, кто застрял, в терминал
        # не пойдёт.
        "Если это мешает человеку — передай ему дословно: чтобы остановить "
        "проверки, достаточно сказать «останови суперстек». Не предлагай ему "
        "переменные окружения и команды оболочки.",
    ]
    хвост = улика(stderr)
    if хвост:
        причина.append(хвост)
    print(json.dumps({"decision": "block", "reason": "\n".join(причина)},
                     ensure_ascii=False))
    return 0


def main() -> int:
    # Аварийный выключатель — первой проверкой: ни stdin, ни диск, ни verify.py
    # не должны быть тронуты, когда систему попросили молчать.
    if os.environ.get("SUPERSTACK_DISABLE") == "1":
        return 0

    корень = проект()
    if not позвали_здесь(корень):
        return 0

    # stdin читаем, только если это не терминал: при ручном запуске без
    # перенаправления чтение повисло бы навсегда, выглядя как зависший хук.
    вход = "" if sys.stdin.isatty() else sys.stdin.read()

    # Пауза — тормоз, который обязан работать, даже когда всё остальное
    # сломано. Остановленная система не имеет права держать человека в ходе,
    # который ему нечем закрыть.
    if os.environ.get("SUPERSTACK_IGNORE_PAUSE") != "1" \
            and (состояние() / "PAUSE").is_file():
        return 0

    # Повторный заход: ход уже продолжен нашим же блоком. Разрыв цикла
    # обязателен — у Claude Code свой предел в восемь подряд, и упереться в
    # него значит восемь полных прогонов набора вместо одного.
    if re.search(r'"stop_hook_active"\s*:\s*true', вход):
        return 0

    # Путь к verify.py считается от САМОГО хука, а не от CLAUDE_PLUGIN_ROOT:
    # переменная может указывать на другую установку плагина, и тогда хук
    # проверял бы чужим кодом.
    verify = Path(__file__).resolve().parent.parent / "tools" / "verify.py"
    if not verify.is_file():
        return сказать_один_раз(
            f"SUPERSTACK: гейт верификации не отработал — нет {verify}. "
            "Ход закрыт БЕЗ доказательства.", вход)

    бюджет = os.environ.get("SUPERSTACK_GATE_TIMEOUT", "")
    бюджет = int(бюджет) if бюджет.isdigit() else БЮДЖЕТ

    # stdout проверки глушим: чужой JSON в нашем stdout сломал бы разбор
    # нашего собственного ответа. Нужен stderr — он короткий и уходит в
    # причину как улика.
    try:
        p = subprocess.run([sys.executable, str(verify), str(корень)],
                           stdout=subprocess.DEVNULL, stderr=subprocess.PIPE,
                           text=True, timeout=бюджет)
        код, stderr = p.returncode, (p.stderr or "")
    except subprocess.TimeoutExpired:
        return сказать_один_раз(
            f"SUPERSTACK: гейт верификации не уложился в {бюджет}с и был "
            "прерван. Ход закрыт БЕЗ доказательства.", вход)
    except OSError as e:
        return сказать_один_раз(
            f"SUPERSTACK: гейт верификации не отработал ({e}). "
            "Ход закрыт БЕЗ доказательства.", вход)

    # Смерть по сигналу — не вердикт. Проверка НЕ СОСТОЯЛАСЬ, а не провалилась:
    # провал чинят кодом, несостоявшуюся проверку — бюджетом или руками.
    if код < 0:
        return сказать_один_раз(
            f"SUPERSTACK: гейт верификации прерван сигналом {-код}. "
            "Ход закрыт БЕЗ доказательства.", вход)

    if код in (0, 10):
        return 0
    if код == 2:
        return сказать_один_раз(
            "SUPERSTACK: проверять нечем — проект не объявил ни одной "
            "проверки. Ход закрыт БЕЗ доказательства.", вход)
    if код != 1:
        return сказать_один_раз(
            f"SUPERSTACK: гейт верификации не смог проверить (код {код}). "
            "Ход закрыт БЕЗ доказательства.", вход)
    return заблокировать(код, stderr)


if __name__ == "__main__":
    # Хук ВСЕГДА выходит нулём: упавший на закрытии хода хук — это ошибка в
    # лицо человеку на каждом ходе.
    try:
        sys.exit(main())
    except Exception:                                        # noqa: BLE001
        sys.exit(0)
