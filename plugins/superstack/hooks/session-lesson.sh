#!/bin/sh
# SUPERSTACK — вопрос в конце сессии: что забрать навсегда.
#
# Зачем хук, а не пункт в инструкции. Журнал находок построен целиком —
# планка из трёх условий, маршрутизация в три адресата, слияние похожего —
# и до этого хука его НИКТО НЕ ВЫЗЫВАЛ. За всё время разработки в нём
# накопилась одна запись, вписанная руками. Механизм без спускового крючка
# не работает ровно так же, как отсутствующий, но выглядит построенным.
#
# Момент выбран не случайно: в конце хода видно и симптом, и починку, и то,
# что НЕ сработало по дороге. Через сессию останется только починка — а без
# отброшенного тупика урок бесполезен, потому что в следующий раз в этот
# тупик зайдут снова.
#
# Почему шум не набежит. Решает не хук, а планка внутри learn.py: запись
# принимается только с пройденной проверкой, названным паттерном отказа и
# хотя бы одним отброшенным тупиком. Не прошло — не записалось. Поэтому
# правильный ответ на этот вопрос ЧАЩЕ ВСЕГО «ничего», и текст говорит об
# этом прямо: хук, вынуждающий что-нибудь записать, наполняет память шумом,
# а шумную память перестают читать — и она умирает тише, чем пустая.
#
# Хук ничего не пишет сам. Он задаёт вопрос.
set -u

# Аварийный выключатель — первой строкой, до любой работы.
if [ "${SUPERSTACK_DISABLE:-}" = "1" ]; then
  exit 0
fi

STATE="${SUPERSTACK_STATE_DIR:-$HOME/.claude/superstack}"
if [ -f "$STATE/PAUSE" ] && [ "${SUPERSTACK_IGNORE_PAUSE:-}" != "1" ]; then
  exit 0
fi

# SUPERSTACK работает ТОЛЬКО там, где его позвали. Плагины ставятся глобально
# (Scope: user), их хуки объявлены без привязки к проекту — и без этого гейта
# хук срабатывает в КАЖДОМ проекте на машине. Найдено заказчиком на живом
# случае: в соседнем каталоге он пишет обучающие материалы, а система
# спрашивала там про уроки. Выключатели у продукта были только глобальные
# («выключить везде»), а нужно обратное — «включить там, где позвали».
# Отметку ставит явный вызов скилла: /go, /superstack, /what, /fix, /oops.
PROJECT="${SUPERSTACK_PROJECT_DIR:-${CLAUDE_PROJECT_DIR:-$PWD}}"
# Симлинки разрешаются ОБЯЗАТЕЛЬНО. Отметку пишет `enable.py` через
# `path.resolve()`, то есть уже разрешённой; сюда путь приходит из окружения,
# а `$PWD` оболочка наследует как есть. На macOS `/var` — симлинк на
# `/private/var`, и одного этого хватает, чтобы строки не совпали: отметка
# стоит, гейт её не видит, и НИ ОДИН хук не срабатывает. Молча — а значит
# человек остаётся без гейта верификации и не узнаёт об этом.
# Не удалось перейти в каталог — оставляем как есть: гейт не имеет права
# падать из-за проверки собственного пути.
PROJECT=$(CDPATH= cd -- "$PROJECT" 2>/dev/null && pwd -P) || \
  PROJECT="${SUPERSTACK_PROJECT_DIR:-${CLAUDE_PROJECT_DIR:-$PWD}}"
[ -n "$PROJECT" ] || PROJECT="$PWD"
enabled_here() {
  [ -f "$STATE/projects" ] || return 1
  while IFS= read -r line; do
    [ -n "$line" ] || continue
    # Совпадение по сегментам пути: /a/bc не заводится записью /a/b.
    case "$PROJECT/" in "$line"/*) return 0 ;; esac
    # ...и то же самое по разрешённым именам. Один и тот же каталог приходит
    # сюда под разными именами: `enable.py` пишет `path.resolve()`, оболочка
    # отдаёт `$PWD` как есть, а на macOS `/var` — симлинк на `/private/var`.
    # Сверять одну сторону мало: промах возможен в обе.
    real=$(CDPATH= cd -- "$line" 2>/dev/null && pwd -P) || real=""
    [ -n "$real" ] || continue
    case "$PROJECT/" in "$real"/*) return 0 ;; esac
  done < "$STATE/projects"
  return 1
}
enabled_here || exit 0

# Ход, в котором ничего не изменилось, не может содержать урок — планка
# требует пройденную проверку, а проверять нечего. Спрашивать всё равно стоит
# ровно один лишний ход: агент обязан ответить, ответ порождает новый Stop,
# и на разговорных ходах это встаёт в петлю коротких реплик. Наблюдалось
# живьём: четыре хода подряд вида «готово к перезапуску», каждый вызванный
# предыдущим.
#
# Критерий точный и дешёвый: изменился ли хоть один файл в рабочем каталоге
# позже, чем был задан прошлый вопрос. `-quit` останавливает обход на первом
# совпадении, поэтому цена не зависит от размера дерева.
#
# «Файл изменился» НЕ ЗНАЧИТ «работал агент». Из обхода исключено то, что
# трогает сама система: прогон мутаций правит и восстанавливает файлы в том же
# дереве десятки минут подряд, и на каждом разговорном ходе критерий давал
# «изменения есть». Наблюдалось живьём: шесть ходов подряд с вопросом об уроке,
# пока в фоне шла планка, и ни в одном не было правки. Сторож считал
# собственный шум работой человека.
STAMP="$STATE/last-lesson-ask"
if [ -f "$STAMP" ]; then
  CHANGED=$(find . -type f -newer "$STAMP" \
    -not -path "*/.git/*" -not -path "*/node_modules/*" \
    -not -path "*/__pycache__/*" -not -path "*/.pytest_cache/*" \
    -not -path "*/.mutation-backup/*" -not -name ".mutation-lock" \
    -print -quit 2>/dev/null)
  # Пока прогон мутаций идёт, любое изменение в дереве принадлежит ему, а не
  # человеку: инструмент правит чужие файлы по всему репозиторию, и исключить
  # их по имени нельзя. Замок — точный признак «система работает сама».
  if [ -f "$STATE/../superstack/.mutation-lock" ] || \
     [ -f "./.mutation-lock" ]; then
    exit 0
  fi
  if [ -z "$CHANGED" ]; then
    exit 0
  fi
fi

# Путь к инструменту вычисляется от самого хука: ${CLAUDE_PLUGIN_ROOT} внутри
# скрипта не разворачивается, а относительный прыжок «..» ломается молча при
# любом перемещении файла.
SELF_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
LEARN=$(CDPATH= cd -- "$SELF_DIR/../tools" 2>/dev/null && pwd)/learn.py
if [ ! -f "$LEARN" ]; then
  # Инструмента нет — вопрос без адреса бесполезен: человек прочитает просьбу
  # записать урок и не найдёт куда. Молчим.
  exit 0
fi

# Экранирование пути для оболочки и для JSON — как в hooks/first-run.sh:
# каталог проекта может содержать пробел, кавычку или обратный слэш, и в
# обеих грамматиках это ломается без единого сообщения.
esc_sh=$(printf '%s' "$LEARN" | sed "s/'/'\\\\''/g")
esc_sh="'$esc_sh'"
esc_json=$(printf '%s' "$esc_sh" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')

# Отметка ставится ровно тогда, когда вопрос задан: она и есть точка отсчёта
# «изменилось ли что-нибудь с прошлого раза». Ранние выходы её не трогают —
# иначе выключенный или приостановленный хук сдвигал бы отсчёт и терял работу,
# сделанную за это время.
mkdir -p "$STATE" 2>/dev/null || true
: > "$STAMP" 2>/dev/null || true

printf '{"hookSpecificOutput":{"hookEventName":"Stop","additionalContext":"'
printf 'SUPERSTACK: ход закончен — реши, есть ли здесь урок НА ВСЕГДА. Планка '
printf 'из трёх условий, и она строгая: пройденная проверка (тест, прогон, '
printf 'наблюдаемый эффект — не «мне кажется»), названный паттерн отказа (что '
printf 'именно ломалось) и хотя бы один отброшенный тупик (что пробовали и не '
printf 'сработало). Все три — тогда: python3 %s add --title ... --check ... ' "$esc_json"
printf '%s' '--failure ... --deadend ... . Не все три — НЕ ЗАПИСЫВАЙ и не упоминай: '
printf 'чаще всего верный ответ именно такой, а шумную память перестают читать. '
printf 'Ничего не спрашивай у человека и не пересказывай этот текст."}}\n'
exit 0
