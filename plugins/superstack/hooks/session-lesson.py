#!/usr/bin/env python3
"""SUPERSTACK — вопрос в конце сессии: что забрать навсегда.

Зачем хук, а не пункт в инструкции. Журнал находок построен целиком — планка
из трёх условий, маршрутизация в три адресата, слияние похожего — и до этого
хука его НИКТО НЕ ВЫЗЫВАЛ. За всё время разработки в нём накопилась одна
запись, вписанная руками. Механизм без спускового крючка не работает ровно так
же, как отсутствующий, но выглядит построенным.

Момент выбран не случайно: в конце хода видно и симптом, и починку, и то, что
НЕ сработало по дороге. Через сессию останется только починка — а без
отброшенного тупика урок бесполезен, потому что в следующий раз в этот тупик
зайдут снова.

Почему шум не набежит. Решает не хук, а планка внутри `learn.py`: запись
принимается только с пройденной проверкой, названным паттерном отказа и хотя бы
одним отброшенным тупиком. Не прошло — не записалось. Поэтому правильный ответ
на этот вопрос ЧАЩЕ ВСЕГО «ничего», и текст говорит об этом прямо: хук,
вынуждающий что-нибудь записать, наполняет память шумом, а шумную память
перестают читать — и она умирает тише, чем пустая.

Хук ничего не пишет сам. Он задаёт вопрос.

Почему на Python, а не на оболочке. `sh` — ЛИШНЯЯ зависимость: питон продукту
нужен в любом случае, на нём все инструменты, а оболочка нужна была только
хукам. Порт убирает вторую, оставляя одну. Заодно исчезает целый класс ошибок:
экранирование для оболочки и для JSON руками — то место, где путь с кавычкой
ломал вывод молча.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

#: Что трогает САМА система. «Файл изменился» не значит «работал агент»: прогон
#: мутаций правит и восстанавливает файлы в том же дереве десятками минут, и на
#: каждом разговорном ходе критерий давал «изменения есть». Наблюдалось живьём:
#: шесть ходов подряд с вопросом об уроке, пока в фоне шла планка.
СВОЙ_ШУМ = (".git", "node_modules", "__pycache__", ".pytest_cache",
            ".mutation-backup")

ТЕКСТ = (
    "SUPERSTACK: ход закончен — реши, есть ли здесь урок НА ВСЕГДА. Планка "
    "из трёх условий, и она строгая: пройденная проверка (тест, прогон, "
    "наблюдаемый эффект — не «мне кажется»), названный паттерн отказа (что "
    "именно ломалось) и хотя бы один отброшенный тупик (что пробовали и не "
    "сработало). Все три — тогда: python3 {} add --title ... --check ... "
    "--failure ... --deadend ... . Не все три — НЕ ЗАПИСЫВАЙ и не упоминай: "
    "чаще всего верный ответ именно такой, а шумную память перестают читать. "
    "Ничего не спрашивай у человека и не пересказывай этот текст."
)


def состояние() -> Path:
    return Path(os.environ.get("SUPERSTACK_STATE_DIR")
                or Path.home() / ".claude" / "superstack")


def выключен() -> bool:
    """Аварийный выключатель — первой проверкой, до любой работы."""
    if os.environ.get("SUPERSTACK_DISABLE") == "1":
        return True
    if (состояние() / "PAUSE").is_file() \
            and os.environ.get("SUPERSTACK_IGNORE_PAUSE") != "1":
        return True
    return False


def проект() -> Path:
    p = (os.environ.get("SUPERSTACK_PROJECT_DIR")
         or os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd())
    try:
        # Симлинки разрешаются ОБЯЗАТЕЛЬНО. Отметку пишет `enable.py` уже
        # разрешённой, а сюда путь приходит из окружения как есть. На macOS
        # `/var` — симлинк на `/private/var`, и одного этого хватает, чтобы
        # строки не совпали: отметка стоит, гейт её не видит, и НИ ОДИН хук
        # не срабатывает. Молча.
        return Path(p).resolve()
    except OSError:
        return Path(p)


def позвали_здесь(корень: Path) -> bool:
    """SUPERSTACK работает ТОЛЬКО там, где его позвали.

    Плагины ставятся глобально, их хуки объявлены без привязки к проекту — и
    без этого гейта хук срабатывает в КАЖДОМ проекте на машине. Найдено на
    живом случае: в соседнем каталоге человек писал обучающие материалы, а
    система спрашивала там про уроки.
    """
    список = состояние() / "projects"
    if not список.is_file():
        return False
    try:
        строки = список.read_text("utf-8", errors="replace").splitlines()
    except OSError:
        return False
    свой = str(корень).rstrip("/") + "/"
    for строка in строки:
        строка = строка.strip()
        if not строка:
            continue
        # Совпадение по СЕГМЕНТАМ пути: /a/bc не заводится записью /a/b.
        if свой.startswith(строка.rstrip("/") + "/"):
            return True
        # ...и то же по разрешённым именам: промах возможен в обе стороны.
        try:
            реальный = str(Path(строка).resolve()).rstrip("/") + "/"
        except OSError:
            continue
        if свой.startswith(реальный):
            return True
    return False


def что_то_менялось(отметка: Path, корень: Path) -> bool:
    """Изменился ли хоть один файл позже прошлого вопроса.

    Ход, в котором ничего не изменилось, не может содержать урок — планка
    требует пройденную проверку, а проверять нечего. Спрашивать всё равно
    стоит ровно один лишний ход: агент обязан ответить, ответ порождает новый
    Stop, и на разговорных ходах это встаёт в петлю коротких реплик.
    Наблюдалось живьём: четыре хода подряд вида «готово к перезапуску».

    Обход останавливается на ПЕРВОМ совпадении — цена не зависит от размера
    дерева.
    """
    try:
        порог = отметка.stat().st_mtime
    except OSError:
        return True
    for каталог, папки, файлы in os.walk(корень):
        папки[:] = [d for d in папки if d not in СВОЙ_ШУМ]
        for имя in файлы:
            if имя == ".mutation-lock":
                continue
            try:
                if (Path(каталог) / имя).stat().st_mtime > порог:
                    return True
            except OSError:
                continue
    return False


def ломают_дерево(корень: Path) -> bool:
    """Пока прогон мутаций идёт, любое изменение принадлежит ему, а не человеку.

    Инструмент правит чужие файлы по всему репозиторию, и исключить их по
    имени нельзя. Замок — точный признак «система работает сама».
    """
    return (состояние() / ".mutation-lock").is_file() \
        or (корень / ".mutation-lock").is_file()


def main() -> int:
    if выключен():
        return 0
    корень = проект()
    if not позвали_здесь(корень):
        return 0

    отметка = состояние() / "last-lesson-ask"
    if отметка.is_file():
        if ломают_дерево(корень) or not что_то_менялось(отметка, корень):
            return 0

    # Путь к инструменту считается от самого хука: `${CLAUDE_PLUGIN_ROOT}`
    # внутри скрипта не разворачивается, а относительный прыжок «..» ломается
    # молча при любом перемещении файла.
    learn = Path(__file__).resolve().parent.parent / "tools" / "learn.py"
    if not learn.is_file():
        # Инструмента нет — вопрос без адреса бесполезен: человек прочитает
        # просьбу записать урок и не найдёт куда. Молчим.
        return 0

    # Отметка ставится ровно тогда, когда вопрос задан: она и есть точка
    # отсчёта. Ранние выходы её не трогают — иначе выключенный хук сдвигал бы
    # отсчёт и терял работу, сделанную за это время.
    try:
        состояние().mkdir(parents=True, exist_ok=True)
        отметка.write_text("", encoding="utf-8")
    except OSError:
        pass

    # Экранирование делает json.dumps, а не printf с sed. Путь с кавычкой,
    # пробелом или обратным слэшем ломал прежний вывод без единого сообщения —
    # в обеих грамматиках сразу.
    # Кавычки ставятся ВСЕГДА, а не по необходимости. `shlex.quote`
    # опускает их, когда пробелов нет, — и форма напечатанной команды
    # начинает зависеть от того, где лежит репозиторий. Тест на это
    # зеленел только потому, что в каталоге автора есть пробел.
    команда = '"%s"' % str(learn).replace('"', '\\"')
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "Stop",
        "additionalContext": ТЕКСТ.format(команда)}}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
