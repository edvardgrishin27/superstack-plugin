#!/usr/bin/env python3
"""SUPERSTACK — первое предложение: система заговаривает первой, но спрашивает.

Вход для того, кто не знает про команды. Человек ставит плагин и не знает, что
дальше; без этого хука продукт молчит, пока его не позовут по имени, — то есть
для новичка не существует.

Право заговорить первым дано ровно один раз за сессию и с потолком: три
напоминания на машину, дальше молчание навсегда. Отказ — это решение, а не
пропуск: он записывается флагом, и после него не предлагается никогда.

Почему `additionalContext`, а не `initialUserMessage`. Второй завёл бы разговор
сам — то есть приписал человеку слова, которых он не говорил, и запустил бы
работу до согласия.

Почему на Python, хотя прежняя версия возражала. В скрипте стояло: «ни python3,
ни jq не гарантированы в момент старта сессии, а хук, падающий на старте, хуже
отсутствующего». Аргумент пересмотрен, и вот чем.

На машине без python3 SUPERSTACK НЕ РАБОТАЕТ ВООБЩЕ: на нём все инструменты,
все гейты и вся проверка. Предложить там «посмотреть, как настроен твой Claude
Code» значит позвать человека в продукт, который у него не запустится, — это
хуже молчания, а не лучше. Зато `sh` был ЛИШНЕЙ зависимостью: он нужен был
только хукам. Порт убирает вторую, оставляя одну — ту, без которой всё равно
ничего нет.

  python3 first-run.py           предложить, если ещё можно
  python3 first-run.py status    сколько предложено
  python3 first-run.py done      больше не предлагать никогда
"""
from __future__ import annotations

import datetime as dt
import json
import os
import sys
from pathlib import Path

#: Потолок напоминаний на машину. Четвёртого не будет никогда: предложение,
#: повторяемое без конца, читается как навязывание и портит отношение к
#: продукту сильнее, чем непоказанное предложение.
ПОТОЛОК = 3

ТЕКСТ = (
    "SUPERSTACK (напоминание {} из {}): настройку Claude Code на этом "
    "компьютере ещё ни разу не проверяли. Сначала ответь на то, с чем пришёл "
    "человек, а затем добавь ровно одну строку: могу заодно посмотреть, как "
    "настроен твой Claude Code — это минута, менять ничего не буду. "
    "Согласится — вызови скилл superstack. Откажется — выполни python3 {} "
    "done, и больше не предлагай никогда. Без согласия проверку не запускай и "
    "этот текст не пересказывай дословно."
)


def состояние() -> Path:
    return Path(os.environ.get("SUPERSTACK_STATE_DIR")
                or Path.home() / ".claude" / "superstack")


def счётчик() -> int:
    """Нечитаемый или кривой счётчик считается ИСЧЕРПАННЫМ, а не нулевым.

    Прежняя версия обнуляла лимит на любом мусоре: одна строка «3 sessions» в
    файле — и человек получал ещё три напоминания, и так каждый раз, пока
    мусор лежит. Лучше не предложить ни разу, чем предлагать без конца.
    """
    f = состояние() / "first-run.count"
    if not f.is_file():
        return 0
    try:
        текст = f.read_text("utf-8").strip()
    except OSError:
        return ПОТОЛОК
    return int(текст) if текст.isdigit() else ПОТОЛОК


def отказались() -> Path:
    return состояние() / "first-run.done"


def больше_не_предлагать() -> int:
    """Отказ — решение. Подтверждаем только после того, как флаг лёг на диск."""
    f = отказались()
    try:
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(dt.datetime.now(dt.timezone.utc)
                     .strftime("%Y-%m-%dT%H:%M:%SZ") + "\n", encoding="utf-8")
    except OSError as e:
        print(f"НЕ УДАЛОСЬ записать {f}: {e}", file=sys.stderr)
        return 1
    if not (f.is_file() and f.stat().st_size):
        print("НЕ УДАЛОСЬ: флаг пуст после записи", file=sys.stderr)
        return 1
    print("больше не предложу")
    return 0


def сколько() -> int:
    f = отказались()
    if f.is_file():
        try:
            когда = f.read_text("utf-8").strip()
        except OSError:
            когда = "?"
        print(f"выключено с {когда}")
    else:
        # Кривой счётчик показывается как исчерпанный — ровно так он и
        # трактуется в решении печатать. Показывать «0 из 3» там, где
        # предложений больше не будет, значит врать человеку в лицо.
        print(f"предложено {счётчик()} из {ПОТОЛОК}")
    return 0


def предложить() -> int:
    if отказались().is_file():
        return 0
    try:
        состояние().mkdir(parents=True, exist_ok=True)
    except OSError:
        return 0

    # Замок берётся ДО чтения счётчика: проверка и запись обязаны быть одним
    # неделимым шагом, иначе лимит держится на удаче планировщика. Каталог, а
    # не файл: создание каталога атомарно везде. Замеряли: восемь параллельных
    # стартов давали до 24 предложений вместо трёх.
    #
    # Не взяли замок — МОЛЧИМ. Это же верно и для застрявшего замка: вечное
    # молчание лучше вечного напоминания, а цена ошибки — одно непоказанное
    # предложение.
    замок = состояние() / "first-run.lock"
    try:
        замок.mkdir()
    except (FileExistsError, OSError):
        return 0
    try:
        было = счётчик()
        if было >= ПОТОЛОК:
            return 0
        стало = было + 1
        файл = состояние() / "first-run.count"
        try:
            файл.write_text(f"{стало}\n", encoding="utf-8")
        except OSError:
            return 0
        # Печатаем, ТОЛЬКО убедившись, что счётчик пережил запись. Успешная
        # запись ещё ничего не значит: если файл ведёт в никуда, вызов вернёт
        # успех, а счётчик останется прежним — и хук будет предлагать каждую
        # сессию до конца времён.
        try:
            if файл.read_text("utf-8").strip() != str(стало):
                return 0
        except OSError:
            return 0

        # Кавычки ВСЕГДА: без пробела в пути `shlex.quote` их опускает,
        # и форма команды начинает зависеть от места установки.
        сам = '"%s"' % str(Path(__file__).resolve()).replace('"', '\\"')
        print(json.dumps({"hookSpecificOutput": {
            "hookEventName": "SessionStart",
            "additionalContext": ТЕКСТ.format(стало, ПОТОЛОК, сам)}},
            ensure_ascii=False))
        return 0
    finally:
        try:
            замок.rmdir()
        except OSError:
            pass


def main() -> int:
    # Аварийный выключатель — первой проверкой, до любой работы. Общее правило
    # для всех хуков: один экспорт гасит всё разом.
    if os.environ.get("SUPERSTACK_DISABLE") == "1":
        return 0
    команда = sys.argv[1] if len(sys.argv) > 1 else "offer"
    return {"done": больше_не_предлагать, "status": сколько}.get(
        команда, предложить)()


if __name__ == "__main__":
    sys.exit(main())
