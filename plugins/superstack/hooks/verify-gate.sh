#!/bin/sh
# SUPERSTACK — принуждение гейта верификации на закрытии хода.
#
# Зачем это отдельный хук, а не строка в инструкции.
#
# В skills/go/SKILL.md написано «либо код возврата 0 — либо не готово». Пока это
# только текст, это пожелание: исполняет его ровно та модель, которую проверяют,
# и неисполнение не видно никому. Правило без принуждения обязано либо получить
# механизм, либо быть удалено. Механизм — здесь: Stop-хук сам зовёт
# tools/verify.py и решает по КОДУ ВОЗВРАТА, дать ли закрыть ход.
#
# ЧЕМ БЛОКИРУЕТСЯ ЗАВЕРШЕНИЕ (документация Claude Code, событие Stop).
# Хук выходит с кодом 0 и печатает в stdout ровно один JSON-объект
# {"decision":"block","reason":"..."}; reason уходит модели следующей
# инструкцией. Ненулевой код возврата самого хука для этого не годится:
# код 1 Claude Code считает НЕблокирующей ошибкой и ход всё равно закроет,
# а код 2 блокирует, но подаёт текст как аварию хука. Поэтому решение
# печатается JSON-ом, а хук всегда выходит нулём.
#
# ЧЕГО ХУК НЕ ДЕЛАЕТ. Он ничего не чинит, не правит и не откатывает: единственное
# его действие — запуск verify.py и печать вердикта. Чинящий хук отнимает у
# человека решение и прячет отказ, вместо того чтобы его показать.
#
# ЧЕТЫРЕ ОГРАНИЧЕНИЯ, без которых этот хук становится вредителем:
#
#   · SUPERSTACK_DISABLE=1 гасит его ПЕРВОЙ строкой, до чтения stdin и до
#     любого запуска. Один экспорт обязан выключать всю систему разом;
#   · пауза (tools/pause.sh) соблюдается: пока система остановлена, хук молчит,
#     иначе тормоз не тормозит, а запирает человека в незакрываемом ходе;
#   · ПРОЕКТ БЕЗ ОБЪЯВЛЕННЫХ ПРОВЕРОК (verify.py даёт код 2) НЕ БЛОКИРУЕТСЯ.
#     Блокировать было бы честнее по духу, но вечная блокировка в чужом
#     репозитории без тестов означает, что закрыть ход нельзя вообще ничем:
#     установка плагина ломает работу, и его сносят в первый же день. Поэтому
#     ход закрывается — но молча этого не происходит: см. note_once ниже,
#     «проверять нечем» называется человеку прямо. «Не нашёл» и «не смог
#     проверить» — разные утверждения, и оба гасят доверие, а не выдаются
#     за пройденный гейт;
#   · таймаут обязателен: Stop-хук стоит на КАЖДОМ закрытии хода, и проверка,
#     которая думает пятнадцать минут, превращает работу в ожидание.
#
# Проверить руками:  sh verify-gate.sh </dev/null
# Выключить совсем:  SUPERSTACK_DISABLE=1 (переменная окружения)
# Свой бюджет:       SUPERSTACK_GATE_TIMEOUT=<секунды>
set -u

# Аварийный выключатель — первой строкой, до любой работы: ни stdin, ни диск,
# ни verify.py не должны быть тронуты, когда систему попросили молчать.
if [ "${SUPERSTACK_DISABLE:-}" = "1" ]; then
  exit 0
fi

STATE="${SUPERSTACK_STATE_DIR:-${HOME:-/nonexistent}/.claude/superstack}"
# Каталог проекта берём из переменной, а не из данных stdin: разбор JSON в
# оболочке спотыкается на экранировании путей, а PWD хука и так равен рабочему
# каталогу сессии.
PROJECT="${SUPERSTACK_PROJECT_DIR:-${CLAUDE_PROJECT_DIR:-$PWD}}"
# Симлинки разрешаются ОБЯЗАТЕЛЬНО. Отметку пишет `enable.py` через
# `path.resolve()`, то есть уже разрешённой; сюда путь приходит из окружения,
# а `$PWD` оболочка наследует как есть. На macOS `/var` — симлинк на
# `/private/var`, и одного этого хватает, чтобы строки не совпали: отметка
# стоит, гейт её не видит, и НИ ОДИН хук не срабатывает. Молча — а значит
# человек остаётся без гейта верификации и не узнаёт об этом.
# Не удалось перейти в каталог — оставляем как есть: гейт не имеет права
# падать из-за проверки собственного пути.
PROJECT=$(CDPATH= cd -- "$PROJECT" 2>/dev/null && pwd -P) || \
  PROJECT="${SUPERSTACK_PROJECT_DIR:-${CLAUDE_PROJECT_DIR:-$PWD}}"
[ -n "$PROJECT" ] || PROJECT="$PWD"

# SUPERSTACK работает ТОЛЬКО там, где его позвали. Плагины ставятся глобально
# (Scope: user), их хуки объявлены без привязки к проекту — и без этого гейта
# хук срабатывает в КАЖДОМ проекте на машине. Здесь цена выше, чем у остальных
# хуков: гейт верификации МОЖЕТ НЕ ДАТЬ ЗАКРЫТЬ ХОД в проекте, где нет ни
# тестов, ни плана, и человек не понимает, чего от него хотят.
# Отметку ставит явный вызов скилла: /go, /superstack, /what, /fix, /oops.
enabled_here() {
  [ -f "$STATE/projects" ] || return 1
  while IFS= read -r line; do
    [ -n "$line" ] || continue
    # Совпадение по сегментам пути: /a/bc не заводится записью /a/b.
    case "$PROJECT/" in "$line"/*) return 0 ;; esac
    # ...и то же самое по разрешённым именам. Один и тот же каталог приходит
    # сюда под разными именами: `enable.py` пишет `path.resolve()`, оболочка
    # отдаёт `$PWD` как есть, а на macOS `/var` — симлинк на `/private/var`.
    # Сверять одну сторону мало: промах возможен в обе.
    real=$(CDPATH= cd -- "$line" 2>/dev/null && pwd -P) || real=""
    [ -n "$real" ] || continue
    case "$PROJECT/" in "$real"/*) return 0 ;; esac
  done < "$STATE/projects"
  return 1
}
enabled_here || exit 0

# Путь к verify.py считается от САМОГО СКРИПТА, а не от CLAUDE_PLUGIN_ROOT:
# переменная может указывать на другую установку плагина, и тогда хук проверял
# бы чужим кодом. Скрипт же всегда знает, где лежит он сам.
VERIFY="$(dirname "$0")/../tools/verify.py"

# Бюджет времени. Мусор вместо числа считается неуказанным: арифметика в
# оболочке на строке «две минуты» роняет хук целиком, а упавший на закрытии
# хода хук — это ошибка в лицо человеку на каждом ходе.
BUDGET="${SUPERSTACK_GATE_TIMEOUT:-120}"
case "$BUDGET" in
  '' | *[!0-9]*) BUDGET=120 ;;
esac

# stdin читаем только если это не терминал: при ручном запуске без
# перенаправления `cat` повис бы навсегда и выглядел как зависший хук.
input=''
if [ ! -t 0 ]; then
  input=$(cat 2>/dev/null || printf '')
fi

# Пауза — это тормоз, который обязан работать даже когда всё остальное сломано.
# На паузе хук не запускает проверку и не блокирует: остановленная система не
# имеет права держать человека в ходе, который нечем закрыть.
if [ "${SUPERSTACK_IGNORE_PAUSE:-}" != "1" ] && [ -f "$STATE/PAUSE" ]; then
  exit 0
fi

# Повторный заход. stop_hook_active=true означает, что ход уже продолжен нашим
# же блоком. Блокируем НЕ БОЛЕЕ ОДНОГО РАЗА на попытку закрытия: второй
# одинаковый блок означает, что модель починить не смогла, и дальше гейт
# перестаёт быть проверкой и становится ловушкой — каждый круг стоит полного
# прогона тестов. Разрыв цикла обязателен: у Claude Code свой предел в 8
# подряд, и упереться в него — это восемь прогонов набора вместо одного.
if printf '%s' "$input" | grep -q '"stop_hook_active"[[:space:]]*:[[:space:]]*true'; then
  exit 0
fi

# --- печать -----------------------------------------------------------------

esc() {
  # Экранирование для строки JSON. Кавычка или обратный слэш в выводе проверки
  # ломают разбор ВСЕГО объекта, и хук перестаёт существовать для Claude Code
  # целиком — молча, без единого сообщения.
  #
  # Управляющие символы вырезаются ВСЕ, включая табуляцию: JSON запрещает их
  # в строке сырыми, и одна табуляция из вывода make роняет разбор ровно так же,
  # как кавычка. Табуляция заменяется пробелом, а не удаляется, чтобы отступы
  # в выводе проверки не слипались в нечитаемое; переводы строк становятся \n.
  # Перевод строки (\012) в списке на удаление отсутствует намеренно: по нему
  # awk ниже режет вывод на строки, и без него всё слипается в одну.
  tr '\011' ' ' \
    | tr -d '\000-\011\013-\037' \
    | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' \
    | awk '{ printf "%s\\n", $0 }'
}

mark_session() {
  # Отметить сессию как уже предупреждённую. Ноль возвращается ТОЛЬКО если
  # отметка реально легла на диск и перечиталась.
  #
  # Три шага и одна общая точка отказа — намеренно: «удалось ли отметить»
  # обязано решаться в одном месте. Успешная запись в никуда (файл ведёт в
  # /dev/null, каталог нечитаем) возвращает ноль и не сохраняет ничего, а
  # предупреждение, которое не удалось отметить, повторяется каждый ход вечно.
  mkdir -p "$STATE" 2>/dev/null || return 1
  printf '%s\n' "$1" 2>/dev/null >> "$notes" || return 1
  grep -qxF "$1" "$notes" 2>/dev/null || return 1
  return 0
}

note_once() {
  # «Не смог проверить» обязано прозвучать человеку — но ровно один раз за
  # сессию. systemMessage выбран намеренно: additionalContext на событии Stop
  # ПРОДОЛЖАЕТ разговор, то есть был бы той же блокировкой под другим именем,
  # а здесь ход закрывается и предупреждение уходит человеку, не модели.
  #
  # Ограничение «раз в сессию» — не украшение. Хук стоит на каждом закрытии
  # хода: без счётчика человек в репозитории без тестов получал бы одну и ту же
  # строку по десять раз за час и перестал бы её читать вовсе.
  #
  # Нечем сосчитать (нет session_id, каталог состояния не пишется) — МОЛЧИМ.
  # Ровно как в hooks/first-run.sh: напоминание, которое некому сосчитать,
  # повторяется вечно, и это хуже, чем не сказать ни разу.
  sid=$(printf '%s' "$input" \
    | sed -n 's/.*"session_id"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' \
    | tr -cd 'A-Za-z0-9._-' | cut -c1-64)
  [ -n "$sid" ] || exit 0
  notes="$STATE/gate-noted.sessions"
  # Файл-журнал, а не файл-на-сессию: удалять здесь ничего нельзя, а тысячи
  # пустых файлов в каталоге состояния — тот же мусор, только незаметный.
  grep -qxF "$sid" "$notes" 2>/dev/null && exit 0
  mark_session "$sid" || exit 0
  printf '{"systemMessage":"'
  printf '%s' "$1" | esc
  printf '"}\n'
  exit 0
}

# --- запуск проверки --------------------------------------------------------

if ! command -v python3 >/dev/null 2>&1; then
  note_once "SUPERSTACK: гейт верификации не отработал — python3 не найден. Ход закрыт БЕЗ доказательства."
fi
if [ ! -f "$VERIFY" ]; then
  note_once "SUPERSTACK: гейт верификации не отработал — нет $VERIFY. Ход закрыт БЕЗ доказательства."
fi

ERRF=/dev/null
TMPD="${TMPDIR:-/tmp}/superstack-gate.$$"
if mkdir "$TMPD" 2>/dev/null; then
  ERRF="$TMPD/err"
  trap 'rm -rf "$TMPD" 2>/dev/null || true' EXIT INT TERM HUP
fi

# verify.py пишет человеческий разбор в stderr, а JSON в stdout. Нам нужен
# stderr: он короткий и уходит в reason как улика. stdout глушим — чужой JSON
# в нашем stdout сломал бы разбор нашего собственного ответа.
python3 "$VERIFY" "$PROJECT" >/dev/null 2>"$ERRF" &
pid=$!

# Сторож вместо опроса `kill -0`: отработавший, но не подобранный потомок
# остаётся зомби, и kill -0 на нём УСПЕШЕН — цикл опроса крутился бы до конца
# бюджета на каждой быстрой проверке. Здесь ожидание одно и честное.
# Вывод сторожа уведён в /dev/null намеренно: унаследованный конец трубы держал
# бы stdout хука открытым, и Claude Code ждал бы EOF весь бюджет.
# Чего сторож НЕ делает: не убивает внуков (pytest, npm), запущенных внутри
# verify.py — группу процессов из POSIX-оболочки без setsid не собрать. У самого
# verify.py на каждую команду свой предел, поэтому осиротевший прогон конечен.
(
  sleep "$BUDGET"
  kill -TERM "$pid" 2>/dev/null
  sleep 2
  kill -KILL "$pid" 2>/dev/null
) >/dev/null 2>&1 &
watchdog=$!

wait "$pid"
rc=$?
kill "$watchdog" 2>/dev/null

# --- решение ----------------------------------------------------------------

# Смерть по сигналу — не вердикт. Значения 0,1,2,3,10 verify.py отдаёт сам;
# всё, что 128 и выше, означает «убит», то есть проверка не состоялась, а не
# провалилась. Путать нельзя: провал чинят кодом, несостоявшуюся проверку —
# бюджетом или руками.
if [ "$rc" -ge 128 ]; then
  note_once "SUPERSTACK: гейт верификации не уложился в ${BUDGET}с и был прерван. Ход закрыт БЕЗ доказательства."
fi

case "$rc" in
  0) exit 0 ;;
  1) ;;
  2) note_once "SUPERSTACK: проверять нечем — проект не объявил ни одной проверки. Ход закрыт БЕЗ доказательства." ;;
  10) exit 0 ;;
  *) note_once "SUPERSTACK: гейт верификации не смог проверить (код $rc). Ход закрыт БЕЗ доказательства." ;;
esac

detail=''
if [ -s "$ERRF" ]; then
  # Ограничение длины — не косметика: вывод хука урезается на 10000 знаках, и
  # обрезанный хвост унёс бы закрывающую кавычку вместе с валидностью JSON.
  detail=$(awk 'NR<=40 { print substr($0, 1, 300) }' "$ERRF" 2>/dev/null || printf '')
fi

printf '{"decision":"block","reason":"'
{
  printf 'ГЕЙТ ВЕРИФИКАЦИИ НЕ ПРОЙДЕН: python3 tools/verify.py вернул код %s.\n' "$rc"
  printf 'Ход не закрывается. «Должно работать» и «тесты должны проходить» означают, что работа не сделана.\n'
  printf 'Почини причину и прогони проверку заново. Если чинить нечего — скажи это человеку словами и назови, что именно осталось непроверенным; молча ход не закрывай.\n'
  # Выход называется ЗДЕСЬ, а не в документации. Это единственное место,
  # где человек читает текст в тот момент, когда система его не отпускает,
  # — и это фраза, а не команда: тот, кто застрял, в терминал не пойдёт.
  printf 'Если это мешает человеку — передай ему дословно: чтобы остановить проверки, достаточно сказать «останови суперстек». Не предлагай ему переменные окружения и команды оболочки.\n'
  if [ -n "$detail" ]; then
    printf '%s\n' "$detail"
  fi
} | esc
printf '"}\n'
exit 0
