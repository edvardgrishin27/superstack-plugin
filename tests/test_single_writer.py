#!/usr/bin/env python3
"""Второго способа записи в поставляемом пакете нет.

Зачем эта проверка отдельным файлом и почему она ищет ФОРМУ.

Запись «во временный файл рядом и переименовать» выглядела правильной и была
неправильной одинаково в двенадцати местах сразу: одно имя временного соседа
на всех, потерянный при замене режим доступа и отсутствие замка на цикл
«прочитал, изменил, записал». Размноженная копипастом ошибка чинится по одному
файлу и возвращается в остальных — четверых починили, восемь остались писать
по-прежнему, и набор при этом был зелёным.

Отсюда единственная форма проверки, которая переживает время. ПЕРЕЧЕНЬ ИМЁН
отвечает только про то, что вспомнили в день починки: он ничего не знает про
файл, который появится завтра, и молча пропустит девятого — так и вышло, в
находке было названо восемь инструментов, а хук сжатия контекста собирал
временного соседа руками и в список не попал. Поэтому здесь спрашивается не
«кто из известных», а «есть ли в дереве ФОРМА»:

  · имя временного соседа, собранное вручную (литерал «.tmp»);
  · подмена файла на месте (`os.replace`, `X.replace(цель)` — у `str.replace`
    аргументов два, у `Path.replace` один);
  · свой уникальный временный файл (`mkstemp`, `NamedTemporaryFile`).

Чего проверка НЕ ловит и это названо, а не замаскировано: `os.rename` и
`Path.rename` не запрещены, потому что переименованием отодвигают СТАРЫЙ файл
(ротация журнала, карантин), а не кладут на место свежесобранный. Свап через
переименование всё равно требует имени для соседа — а имя ловится первой
формой.

Граница дерева: проверяется ПАКЕТ, который ставится человеку. Планка,
выкладка и прочая оснастка лежат в корневом `tools/`, у человека не
оказываются и живут по своим правилам — вписывать их сюда значило бы
проверять не то дерево, о котором утверждение.
"""
from __future__ import annotations

import ast
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from paths import PKG  # noqa: E402

#: Единственное место в пакете, которому эти формы разрешены: оно и ЕСТЬ общий
#: модуль записи. Исключение ровно одно и расти не должно — каждое следующее имя
#: здесь означает второй способ записи, вернувшийся под уважительным предлогом.
ОБЩИЙ_МОДУЛЬ = "tools/atomic_store.py"

#: Ниже этого числа ответ проверки не значит ничего. Проверка, которой нечего
#: смотреть, отвечает «всё чисто» — и это самый дешёвый способ получить зелёное:
#: не найти нарушений в пустом списке файлов. Граница снизу отделяет «посмотрели
#: и не нашли» от «смотреть было не на что».
МИНИМУМ_ФАЙЛОВ = 40

#: Имена методов, которые кладут файл на место. `replace` берётся только с ОДНИМ
#: позиционным аргументом: так выглядит `Path.replace(цель)`, а `str.replace`
#: с одним аргументом — это TypeError, то есть спутать их нельзя.
ПОДМЕНА_МЕТОДОМ = "replace"

#: Функции стандартной библиотеки, которыми делают своего временного соседа.
СВОЙ_ВРЕМЕННЫЙ = ("mkstemp", "NamedTemporaryFile")


def файлы_поставки() -> list:
    """Все .py пакета, который ставится человеку."""
    return sorted(PKG.rglob("*.py"))


def _докстринги(дерево: ast.AST) -> set:
    """Узлы-константы, которые являются докстрингами.

    Проза не код: описание отказа «имя `settings.json.tmp` было одно на всех»
    обязано остаться в файле, который этот отказ починил, и не считаться самим
    отказом. Ровно этой разницы не знал прежний поиск подстрокой.
    """
    из_прозы = set()
    for узел in ast.walk(дерево):
        if not isinstance(узел, (ast.Module, ast.FunctionDef,
                                 ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        тело = getattr(узел, "body", None)
        if not тело:
            continue
        первый = тело[0]
        if (isinstance(первый, ast.Expr)
                and isinstance(первый.value, ast.Constant)
                and isinstance(первый.value.value, str)):
            из_прозы.add(id(первый.value))
    return из_прозы


def нарушения(файл: Path) -> list:
    """Места, где файл пишет мимо общего модуля: (строка, форма).

    Разбор синтаксическим деревом, а не поиском по тексту: подстрока «.tmp»
    находится и в комментарии, а `os.replace` от `строка.replace` текстовым
    поиском не отличается вовсе. Файл, который не разбирается, — это провал
    проверки, а не пустой список: «не смог посмотреть» и «чисто» разные ответы.
    """
    дерево = ast.parse(файл.read_text("utf-8"), filename=str(файл))
    проза = _докстринги(дерево)
    найдено = []
    for узел in ast.walk(дерево):
        if (isinstance(узел, ast.Constant) and isinstance(узел.value, str)
                and id(узел) not in проза and ".tmp" in узел.value):
            найдено.append((узел.lineno, "имя временного соседа вручную"))
        if isinstance(узел, ast.ImportFrom) and узел.module in ("os", "tempfile"):
            for имя in узел.names:
                if имя.name == ПОДМЕНА_МЕТОДОМ or имя.name in СВОЙ_ВРЕМЕННЫЙ:
                    найдено.append((узел.lineno,
                                    f"взят напрямую: {узел.module}.{имя.name}"))
        if not isinstance(узел, ast.Call):
            continue
        что = узел.func
        if isinstance(что, ast.Attribute):
            откуда = getattr(что.value, "id", None)
            if откуда == "os" and что.attr == ПОДМЕНА_МЕТОДОМ:
                найдено.append((узел.lineno, "подмена файла: os.replace"))
            elif откуда == "tempfile" and что.attr in СВОЙ_ВРЕМЕННЫЙ:
                найдено.append((узел.lineno,
                                f"свой временный файл: tempfile.{что.attr}"))
            elif (что.attr == ПОДМЕНА_МЕТОДОМ and len(узел.args) == 1
                  and not узел.keywords):
                найдено.append((узел.lineno, "подмена файла: Path.replace"))
        elif isinstance(что, ast.Name) and что.id in СВОЙ_ВРЕМЕННЫЙ:
            найдено.append((узел.lineno, f"свой временный файл: {что.id}"))
    return sorted(set(найдено))


class ЗаписьВПакетеОдна(unittest.TestCase):
    """Главная проверка: в поставке нет второго способа записи."""

    def test_временный_сосед_нигде_не_собирается_вручную(self):
        грязные = {}
        for файл in файлы_поставки():
            имя = файл.relative_to(PKG).as_posix()
            if имя == ОБЩИЙ_МОДУЛЬ:
                continue
            места = нарушения(файл)
            if места:
                грязные[имя] = места
        self.assertEqual(
            грязные, {},
            "запись мимо общего модуля: временный сосед собирается вручную "
            "или файл кладётся на место в обход tools/atomic_store.py. "
            "Одна и та же ошибка, размноженная копипастом, чинится по одному "
            "файлу и возвращается в остальных — писать надо общим модулем")

    def test_исключение_ровно_одно_и_это_сам_модуль(self):
        """Список исключений — не место для послаблений. Он ровно один, и это
        тот файл, ради которого запрет и заведён."""
        модуль = PKG / ОБЩИЙ_МОДУЛЬ
        self.assertTrue(модуль.is_file(),
                        f"общего модуля записи нет на месте: {модуль}")


class ПрибораХватаетНаВсёДерево(unittest.TestCase):
    """Проверка, которой нечего смотреть, отвечает «всё чисто»."""

    def test_проверке_было_что_смотреть(self):
        файлы = файлы_поставки()
        self.assertGreaterEqual(
            len(файлы), МИНИМУМ_ФАЙЛОВ,
            f"проверка увидела {len(файлы)} файлов пакета — столько их не "
            "бывает: смотреть было не на что, и «нарушений нет» тут значит "
            "только, что список пуст")
        хвосты = {ф.parent.name for ф in файлы}
        self.assertTrue({"tools", "hooks"} <= хвосты,
                        "в обзор не попали и инструменты, и хуки — а девятым "
                        f"оказался как раз хук: {sorted(хвосты)}")

    def test_прибор_видит_сам_общий_модуль(self):
        """Обратный контроль: на файле, где эти формы ЕСТЬ по праву, прибор
        обязан их находить. Иначе «нарушений нет» означало бы сломанный прибор,
        а не чистое дерево."""
        места = нарушения(PKG / ОБЩИЙ_МОДУЛЬ)
        формы = {ф for _, ф in места}
        self.assertIn("имя временного соседа вручную", формы, места)
        self.assertIn("подмена файла: os.replace", формы, места)
        self.assertIn("свой временный файл: tempfile.mkstemp", формы, места)


class ФормаАНеПереченьИмён(unittest.TestCase):
    """Девятый ловится тем же прибором, что и первые восемь.

    Здесь и проверяется главное свойство: файла с таким именем не было ни в
    находке, ни в этом наборе — и он всё равно найден, потому что спрашивают
    про форму, а не про имя.
    """

    def _на_куске(self, текст: str) -> list:
        каталог = tempfile.TemporaryDirectory()
        self.addCleanup(каталог.cleanup)
        файл = Path(каталог.name) / "инструмент_которого_ещё_нет.py"
        файл.write_text(текст, encoding="utf-8")
        return нарушения(файл)

    def test_новый_файл_с_ручной_записью_виден(self):
        места = self._на_куске(
            "import os\n"
            "from pathlib import Path\n"
            "def сохранить(path: Path, текст: str) -> None:\n"
            '    tmp = path.with_suffix(path.suffix + ".tmp")\n'
            '    tmp.write_text(текст, encoding="utf-8")\n'
            "    os.replace(tmp, path)\n")
        формы = {ф for _, ф in места}
        self.assertIn("имя временного соседа вручную", формы, места)
        self.assertIn("подмена файла: os.replace", формы, места)

    def test_подмена_методом_пути_тоже_видна(self):
        """`tmp.replace(цель)` — та же подмена под другим именем: сторож писал
        состояние именно так, и поиск по «os.replace» его не находил."""
        места = self._на_куске(
            "from pathlib import Path\n"
            "def сохранить(путь: Path, текст: str) -> None:\n"
            "    врем = путь.with_name(путь.name + СУФФИКС)\n"
            '    врем.write_text(текст, encoding="utf-8")\n'
            "    врем.replace(путь)\n")
        self.assertIn("подмена файла: Path.replace", {ф for _, ф in места}, места)

    def test_свой_уникальный_сосед_тоже_виден(self):
        """Уникальное имя лечит только столкновение двух процессов. Режим
        доступа и замок на цикл оно не даёт, а выглядит как починка."""
        места = self._на_куске(
            "import tempfile\n"
            "def свой(каталог):\n"
            "    fd, имя = tempfile.mkstemp(dir=каталог)\n"
            "    return имя\n")
        self.assertIn("свой временный файл: tempfile.mkstemp",
                      {ф for _, ф in места}, места)

    def test_проза_про_починенный_отказ_нарушением_не_считается(self):
        """Обратный контроль. Файл, который ПОЧИНИЛ эту ошибку, обязан иметь
        право рассказать о ней словами — иначе проверка вынуждала бы стирать
        объяснение вместе с дефектом."""
        места = self._на_куске(
            '"""Имя `settings.json.tmp` было одно на всех, и os.replace тут\n'
            'не спасал: дыра между чтением и записью."""\n'
            "def ничего() -> None:\n"
            "    return None\n")
        self.assertEqual(места, [], "проза сочтена кодом")


if __name__ == "__main__":
    unittest.main()
