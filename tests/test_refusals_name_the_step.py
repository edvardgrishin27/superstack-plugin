#!/usr/bin/env python3
"""Отказ, который дойдёт до человека, обязан называть следующий шаг.

Продукт читает не разработчик — вывод инструментов ему пересказывает агент.
Отказ, который называет проблему и молчит о выходе, оставляет человека в
тупике: он не знает ни термина, ни устройства системы, ни что теперь делать
руками. Это уже соблюдается в части отказов (design_pull.py про придуманный
цвет, criteria.py про безадресный критерий) — здесь заперто ровно это
свойство, и только для отказов, которые его правда несут.

НАСТОЯЩЕЕ ПРАВИЛО — НЕ «каждый отказ называет шаг». Оно у́же и точнее:

  · отказ, РЕШЕНИЕ по которому принимает ЧЕЛОВЕК, обязан называть шаг сам,
    в собственном тексте;
  · отказ, который разбирает АГЕНТ, идущий по сценарию фазы, может оставить
    шаг фазе вместо того, чтобы повторять его в каждой строке отказа, — но
    тогда фаза ОБЯЗАНА этот шаг называть, и это тоже проверяется здесь.

Почему граница проходит именно так. У `design_pull.py` про контраст и
`crew.py` про пропавшего исполнителя решение принимает человек: цвет в
холсте правит он руками, а знание, что задачу нужно перезапустить, — тоже
его. Текст отказа может оказаться единственным, что он увидит, — без фазы
вокруг, которая объяснила бы остальное. Поэтому шаг обязан ехать вместе
с отказом.

У `criteria.py` про безадресный критерий и `stall.py` про застревание отказ
разбирает агент, идущий по сценарию `go/phases/4-работа.md`, — и шаг для
обоих уже написан ТАМ: для stall.py — «Перережь таск, смени подход или
спроси человека», для критерия без адреса — «Чинится в плане, а не в
передаче». Дублировать эти фразы в тексте самого отказа значило бы держать
одно и то же в двух местах, которые однажды разойдутся.

ЧТО ПРОВЕРЯЕТСЯ. Два класса ниже, каждый — своя половина правила.

  · ЗакрытыйСписокОтказов — закрытый список из четырёх реальных отказов
    (по одному-два на design_pull.py/crew.py/handoff.py), решение по
    которым принимает человек. Инструмент вызван по-настоящему (прямой
    импорт модуля и вызов функции), а не пересказан текстом руками: если
    завтра формулировка в исходнике изменится, тест увидит то же, что
    увидит человек, а не вчерашнюю копию строки. В найденном тексте отказа
    проверено присутствие слова из ЗАКРЫТОГО списка МАРКЕРЫ_ШАГА —
    словоформ повелительного наклонения, которыми в этом проекте уже
    называют действие человека («сделай», «запусти», «привяжи», «срежь»,
    «обоснуй», «раздели»).

  · ФазаНазываетШагТам — для criteria.py и stall.py, чей отказ разбирает
    агент, проверено, что шаг, о котором говорилось выше, ДЕЙСТВИТЕЛЬНО
    записан в тексте фазы дословно, а не только упомянут как факт в
    докстринге этого файла.

criteria.py и stall.py НЕ входят в ЗакрытыйСписокОтказов не потому, что
работа над ними не доделана, а по существу: их отказы разбирает агент по
сценарию фазы, и правило требует шаг ОТ ФАЗЫ, а не от текста самого отказа.
Это проверяет другой класс — ФазаНазываетШагТам, а не этот список.

ЧЕГО ЭТО НЕ ПРОВЕРЯЕТ — честно, а не по умолчанию.

  · НЕ то, что отказы crew.py/handoff.py, не попавшие в закрытый список,
    тоже называют шаг, — они его не называют, переписывать их не входило
    в задачу, и молчание об этом было бы нечестным умолчанием. Расширить
    список — значит вписать новую запись руками, когда для неё появится
    исправленный текст, а не понадеяться, что чужая формулировка попадёт
    под уже существующую догадку.
  · НЕ смысл шага: ведёт ли он к цели, выполним ли он вообще, правда ли
    единственный. Только то, что в тексте есть словоформа из закрытого
    списка (ЗакрытыйСписокОтказов) или дословная фраза из фазы
    (ФазаНазываетШагТам).
  · НЕ грамматическое правило. МАРКЕРЫ_ШАГА — конкретные слова, а не
    правило «есть глагол повелительного наклонения»: формулировка вне
    списка не будет замечена, даже если человек прочтёт её как шаг. По
    той же причине ФазаНазываетШагТам не пытается применить МАРКЕРЫ_ШАГА
    к тексту фазы — шаг для stall.py там держится на трёх повелительных
    глаголах подряд (это совпадение форм, а не общее свойство фразы), а
    шаг для criteria.py — на обороте «чинится в плане», где повелительного
    наклонения нет вовсе. Латать список ради одной фразы значило бы
    подгонять правило под пример, а не проверять правило; вместо этого
    ФазаНазываетШагТам проверяет дословное присутствие уже известной
    фразы — тот же приём, что и в ЗакрытыйСписокОтказов, просто без
    посредника в виде МАРКЕРЫ_ШАГА.
  · НЕ то, что агент, идущий по фазе, реально свяжет код отказа с нужным
    абзацем и дочитает до него, — это вне досягаемости текстового теста.

Список короткий и это не ошибка: правило, которое можно прочитать и
оспорить, лучше догадки, которую нельзя (тот же приём, что и в
criteria.py:НЕ_АДРЕС, откуда он взят).
"""
from __future__ import annotations

import importlib.util
import json
import sys
import tempfile
import unittest
from datetime import datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from paths import PKG, skill_text  # noqa: E402


def _load(имя: str):
    """Модуль инструмента загружен файлом, а не текстом переписан.

    Та же схема, что в test_design_pull.py/test_crew.py/test_handoff.py:
    прямой импорт по пути, без завязки на то, как пакет ставится у человека.
    """
    путь = PKG / "tools" / f"{имя}.py"
    spec = importlib.util.spec_from_file_location(f"ss_refusal_{имя}", путь)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


dp = _load("design_pull")
cr = _load("crew")
ho = _load("handoff")

#: Закрытый список словоформ. Выбран руками по текстам ниже, а не угадан по
#: смыслу: пополнить его для нового отказа значит вписать сюда новое слово
#: явно, а не понадеяться, что чужая формулировка попадёт под уже
#: существующее правило.
МАРКЕРЫ_ШАГА = ("сделай", "запусти", "привяжи", "срежь", "обоснуй", "раздели")


def называет_шаг(текст: str) -> bool:
    return any(маркер in текст for маркер in МАРКЕРЫ_ШАГА)


class ПравилоРазличаетАНеПропускаетВсё(unittest.TestCase):
    """Если бы `называет_шаг` отвечала «да» всегда, весь файл был бы фикцией.

    Эти два случая не отказы реальных инструментов — они проверяют саму
    функцию правила на примере с шагом и без него.
    """

    def test_факт_без_маркера_не_считается_шагом(self):
        self.assertFalse(называет_шаг("контраст 3.10:1 при пороге 4.5:1"))

    def test_повелительное_из_списка_считается_шагом(self):
        self.assertTrue(называет_шаг("сделай текст темнее"))


class ЗакрытыйСписокОтказов(unittest.TestCase):
    """Четыре реальных отказа — не весь набор, а перечисленные здесь."""

    def test_design_pull_контраст_называет_шаг(self):
        """Отказ по контрасту (design_pull.py): правка из этой сессии."""
        с = {"фон": "#0a0a0c", "текст": "#1a1a1e",
             "приглушённый": "#86868f", "акцент": "#6355d9"}
        with tempfile.TemporaryDirectory() as tmp:
            d = Path(tmp)
            (d / "Main.dc.html").write_text(
                "<div style=\"background:{фон};color:{текст}\">"
                "<p style=\"color:{приглушённый}\">т</p>"
                "<button style=\"background:{акцент}\">д</button></div>"
                .format(**с), encoding="utf-8")
            (d / "tokens.json").write_text(
                json.dumps(с, ensure_ascii=False), encoding="utf-8")
            (d / "pulled.json").write_text(json.dumps(
                {"откуда": "extract", "когда": "2026-08-24T10:00:00Z",
                 "холст": "https://claude.ai/public/artifacts/пример"},
                ensure_ascii=False), encoding="utf-8")
            итог = dp.проверить(d)
        отказ = next((о for о in итог["отказы"]
                      if о.startswith("контраст текст")), None)
        self.assertIsNotNone(отказ, итог["отказы"])
        self.assertTrue(называет_шаг(отказ), отказ)

    def test_crew_пропавший_исполнитель_называет_шаг(self):
        """Отказ про застрявшую задачу (crew.py): правка из этой сессии."""
        started = (datetime.now(timezone.utc) - timedelta(minutes=55)).isoformat()
        задача = {"id": "01", "status": "running", "zone": ["src/"],
                  "started": started}
        состояние = {"schema": "superstack.progress.v1", "waves": {"1": [задача]}}
        v = cr.check(состояние)
        отказ = next((p for p in v["problems"] if "молчит" in p), None)
        self.assertIsNotNone(отказ, v["problems"])
        self.assertTrue(называет_шаг(отказ), отказ)

    def test_crew_потолок_яруса_называет_шаг(self):
        """Отказ про потолок тасков (crew.py): не тронут этой сессией,
        уже называл шаг («либо обоснуй в спеке, либо раздели на два
        прогона») — держит планку, чтобы список не проверял только
        собственную правку автора."""
        r = cr.tier_check([{"id": f"{i:02d}"} for i in range(17)])
        self.assertEqual(r["status"], "fail")
        self.assertTrue(называет_шаг(r["detail"]), r["detail"])

    def test_handoff_нет_требований_называет_шаг(self):
        """Отказ про непривязанный таск (handoff.py): не тронут этой
        сессией, уже называл шаг («либо привяжи, либо срежь»)."""
        t = {"id": "01", "name": "x", "goal": "y", "requirements": [],
             "zone": ["src/bot/"], "acceptance": ["критерий"]}
        состояние = {"schema": "superstack.progress.v1", "waves": {"1": [t]}}
        b = ho.blockers(состояние, t, "интерфейсы построены", "", "npm test")
        отказ = next((x for x in b if "не служит ни одному требованию" in x),
                     None)
        self.assertIsNotNone(отказ, b)
        self.assertTrue(называет_шаг(отказ), отказ)


class ФазаНазываетШагТам(unittest.TestCase):
    """Вторая половина правила: где инструмент не называет шаг сам, шаг
    обязана назвать фаза, которая его вызывает и по которой идёт агент.

    Здесь проверяется не текст criteria.py/stall.py, а go/phases/4-работа.md:
    что фраза о шаге, названная в докстринге этого файла, ДЕЙСТВИТЕЛЬНО там
    лежит, дословно, а не только упомянута как факт. Тот же приём, что и у
    ЗакрытыйСписокОтказов выше, — известная строка, найденная в реальном
    источнике, а не эвристика.

    Подстроки — это часть более длинной фразы, а не она целиком: в исходном
    markdown «…или спроси» и «человека.» разнесены переносом строки
    (`…или спроси\\nчеловека.`), и проверка через этот перенос хрупкая — она
    молча перестанет находить фразу после безобидной правки переноса строки,
    которая ничего не меняет по смыслу. Взята часть, целиком лежащая на
    одной строке файла: она переживёт такую правку, а весь абзац — нет.
    """

    @classmethod
    def setUpClass(cls):
        cls.скилл = skill_text("go")

    def test_stall_шаг_записан_в_фазе(self):
        """`stall.py` вызывается в 4-работа.md, и код 1 там же расшифрован:
        не повторять то же самое, а перерезать, сменить подход или спросить
        человека."""
        self.assertIn("stall.py", self.скилл)
        self.assertIn("НЕ отправляй то же самое на второй круг", self.скилл)
        self.assertIn("Перережь таск, смени подход", self.скилл)

    def test_критерий_без_адреса_шаг_записан_в_фазе(self):
        """`criteria.py` вызывается в 3-план.md; последствие отказа — блок
        передачи — и его починка расшифрованы в 4-работа.md, там, где агент
        реально на них натыкается."""
        self.assertIn("criteria.py", self.скилл)
        self.assertIn("Критерий без адреса дальше не едет", self.скилл)
        self.assertIn("Чинится в плане, а не в передаче", self.скилл)


if __name__ == "__main__":
    unittest.main()
