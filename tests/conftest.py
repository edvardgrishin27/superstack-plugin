#!/usr/bin/env python3
"""Отказ стартовать, если в дереве застряла мутация.

Зачем это здесь, а не в планке. Планка уже отказывается идти с застрявшей
поломкой — и всё равно не спасла: набор гоняют и напрямую, `pytest tests/`,
а тогда проверки нет вовсе. Ровно так и вышло дважды. Прерванный прогон
мутаций оставил в `log.py` одну строку `if False:`, и набор показал ВОСЕМЬ
падений в четырёх разных файлах — ни одно из которых не было дефектом.

Цена ошибки не в потерянном времени, а в направлении: восемь красных тестов
читаются как «сломан код» и отправляют чинить работающее. Один раз я так и
начал — искать дефект там, где его не было.

Поэтому проверка стоит на входе В САМ НАБОР и обрывает сессию одной строкой
с причиной и командой починки, вместо россыпи падений без объяснения.

ОБХОД ОБЯЗАТЕЛЕН, и вот почему. Ворота мутаций сами применяют поломку и
запускают этим набором — если бы проверка срабатывала и там, pytest выходил
бы с ненулевым кодом ДО единого теста, а ворота читают ненулевой код как
«мутация поймана». То есть все мутации отчитались бы пойманными, не будучи
проверенными ни разу: механизм против ложного зелёного превратился бы в
источник самого дорогого ложного зелёного в системе. Поэтому ворота ставят
SUPERSTACK_MUTATION_RUN=1, и только там проверка молчит.
"""
from __future__ import annotations

import importlib.util
import os
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent


def _stuck() -> list:
    """Застрявшие мутации — через саму планку, чтобы признак был ОДИН.

    Своя копия распознавания разошлась бы с планкой при первой же правке, и
    тогда набор и планка расходились бы в ответе на один вопрос.
    """
    spec = importlib.util.spec_from_file_location(
        "_supersta" "ck_gauntl" "et_probe", REPO / "tools" / "gauntlet.py")
    if spec is None or spec.loader is None:
        return []
    mod = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(mod)
        return mod.stuck_mutations()
    except Exception:  # noqa: BLE001 — сторож не имеет права ронять чужой набор
        return []


def pytest_sessionstart(session) -> None:
    if os.environ.get("SUPERSTACK_MUTATION_RUN") == "1":
        return
    stuck = _stuck()
    if not stuck:
        return
    names = ", ".join(s["id"] for s in stuck[:5])
    where = ", ".join(sorted({s["file"] for s in stuck})[:5])
    pytest.exit(
        "В ДЕРЕВЕ ЗАСТРЯЛА МУТАЦИЯ — падения ниже были бы не дефектами кода.\n"
        f"  поломок: {len(stuck)} — {names}\n"
        f"  в файлах: {where}\n"
        "  причина: прогон мутаций прерван между применением и восстановлением\n"
        "  починить: python3 tools/gauntlet.py --unstick",
        returncode=3)
