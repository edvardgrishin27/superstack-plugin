#!/usr/bin/env python3
"""Где что лежит.

Зачем отдельный модуль. Тесты — единица РАЗРАБОТКИ, плагин — единица УСТАНОВКИ:
пользователь тесты не ставит, поэтому набор живёт в корне репозитория, а не
внутри пакета. Прежнее `ROOT / "tools" / "verify.py"` из-за этого неверно, и
путь считается отсюда.

Пакет с версии 0.3.0 один. До неё их было семь, и `at()` искал файл по имени
среди всех — иначе каждое перемещение файла между пакетами означало бы правку
двадцати тестовых файлов. Поиск остался: он стоит одну строку и переживёт
любое будущее перемещение внутри пакета, а вот привычка писать полный путь в
каждом тесте — не переживёт.
"""
from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PLUGINS = REPO / "plugins"

#: Корень пакета. Тесты, которым нужен именно он (манифест, раскладка каталогов,
#: проверки упаковки), берут его здесь, а не собирают из строк.
PKG = PLUGINS / "superstack"


def at(*parts: str) -> Path:
    """Путь внутри пакета, а если там нет — в корне репозитория.

    Корень нужен для набора мутаций и карты плана: они не принадлежат пакету,
    потому что не ставятся вместе с ним.
    """
    rel = Path(*parts)
    if (PKG / rel).exists():
        return PKG / rel
    if (REPO / rel).exists():
        return REPO / rel
    raise FileNotFoundError(f"«{rel}» нет ни в пакете, ни в корне репозитория")


def packages() -> list:
    """Все каталоги пакетов. Сейчас один — и проверки на это опираются.

    Функция существует ровно затем, чтобы «пакет один» было УТВЕРЖДЕНИЕМ,
    которое проверяется, а не молчаливым допущением, размазанным по тестам.
    """
    return sorted(d for d in PLUGINS.glob("*")
                  if (d / ".claude-plugin" / "plugin.json").is_file())


def skill_text(name: str) -> str:
    """Скилл ЦЕЛИКОМ: SKILL.md вместе с вынесенными фазами.

    Условные фазы вынесены из `go/SKILL.md` в `go/phases/*.md`: для бота и
    скрипта они не нужны, а контекст занимали каждый прогон. Утверждение
    «в скилле сказано X» после этого перестаёт быть утверждением об одном
    файле — и тесты, читавшие только SKILL.md, покраснели на верном коде.

    ВАЖНО, чем это НЕ является. Склейка отвечает на вопрос «сказано ли»,
    и НЕ отвечает на «прочтёт ли модель вынесенное». Второе держит отдельная
    проверка: каждый файл фазы обязан быть назван в SKILL.md вместе с
    указанием прочесть его целиком. Без неё вынесенное было бы недостижимым —
    той же болезнью, что и инструмент, до которого не дотягивается ни один
    скилл, этажом выше.
    """
    d = PKG / "skills" / name
    куски = [(d / "SKILL.md").read_text("utf-8")]
    куски += [f.read_text("utf-8") for f in sorted(d.glob("phases/*.md"))]
    return "\n".join(куски)
